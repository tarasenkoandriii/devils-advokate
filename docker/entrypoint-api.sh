#!/usr/bin/env bash
# Devil's Advocate — инициализация БД для локального докер-стенда
# (сервис api-init в docker-compose.dev.yml, DOCKER.md).
#
# Отдельный одноразовый контейнер, а не «первые строчки в CMD самого
# api»: если бы схему накатывал сам api-контейнер, то при каждом
# перезапуске (а в dev-режиме он перезапускается от любой правки кода)
# заново гонялись бы push и сид. Одноразовый init с
# `depends_on: service_completed_successfully` — единственная схема, где
# api стартует ПОСЛЕ готовой БД ровно один раз и падает честно, если
# инициализация не удалась.

set -euo pipefail

echo "[api-init] Ожидание Postgres…"
# pg_isready, а не «поспать 5 секунд»: контейнер postgres поднимает
# сокет заметно раньше, чем принимает соединения, и фиксированный sleep
# — это либо флейки на медленной машине, либо потерянное время на
# быстрой. 60 попыток по секунде — верхняя граница, после которой
# честно падаем, а не висим бесконечно в CI/на чужой машине.
for i in $(seq 1 60); do
  if pg_isready -h "${POSTGRES_HOST:-postgres}" -p "${POSTGRES_PORT:-5432}" -U "${POSTGRES_USER:-devils_advocate}" -q; then
    echo "[api-init] Postgres готов (попытка $i)."
    break
  fi
  if [ "$i" -eq 60 ]; then
    echo "[api-init] Postgres не ответил за 60 секунд — прерываюсь." >&2
    exit 1
  fi
  sleep 1
done

# ─────────────────────────────────────────────────────────────────────
# db push, а НЕ migrate deploy — и это не упрощение, а единственный
# рабочий вариант в текущем состоянии репозитория: папки
# apps/api/prisma/migrations в проекте нет вообще (в prisma/ лежат
# только schema.prisma, seed.ts и manual-migrations/ с SQL, который
# применяется руками). `prisma migrate deploy` без единой миграции
# ничего не создаст, и api стартовал бы на пустой БД, падая на первом
# же запросе с невнятной ошибкой Prisma.
#
# Ограничение, которое это накладывает, названо прямо: db push
# синхронизирует схему без истории миграций, то есть ЛОКАЛЬНЫЙ стенд
# не проверяет миграционный путь (порядок, обратимость, данные при
# ALTER). Для дев-стенда это приемлемо; для продакшна нет — там
# по-прежнему нужен нормальный `prisma migrate` (см. VERCEL.md).
# ─────────────────────────────────────────────────────────────────────
echo "[api-init] prisma db push (схема → БД)…"
npx prisma db push --schema prisma/schema.prisma --skip-generate --accept-data-loss

echo "[api-init] Основной сид (провайдеры/модели/промпт/классы хранения)…"
npm run prisma:seed

echo "[api-init] Dev-сид (пользователь dev-${DEV_USER_ID:-123} с правами оператора)…"
npx ts-node prisma/seed-dev.ts

echo "[api-init] Готово."
