'use client';

/** Пункт [decision-basis] 2026-09-04 — сообщение о сбое НЕ уносит с
 * собой страницу.
 *
 * НАЙДЕНО ИЗМЕРЕНИЕМ: десять страниц панели из семнадцати начинались с
 * `if (error) return <div>…</div>`, и на трёх из них — модерация
 * пользователей, библиотеки и заведений — этой же переменной
 * пользовались ОБРАБОТЧИКИ ДЕЙСТВИЙ. То есть неудачная попытка отклонить
 * одну заявку стирала весь список, фильтры и раскрытые детали, и
 * оператор терял ровно то, по чему мог бы проверить, применилось
 * действие или нет. Хуже всего это выглядело на заведениях, где даже
 * сбой загрузки боковой сводки комиссий уносил очередь заявок целиком.
 *
 * РАЗЛИЧЕНИЕ, а не запрет. Ранний возврат честен там, где показывать
 * нечего: если не загрузился сам список, страница пуста по существу.
 * Сбой ДЕЙСТВИЯ — другое: данные на экране остались верными, испортилось
 * только одно действие, и говорить о нём надо рядом с ним.
 *
 * Компонент вынесен отдельно не ради переиспользования, а чтобы сверка
 * его РИСОВАЛА. Урок [render-guards]: проверка на упоминание
 * `role="alert"` в исходнике проходила и тогда, когда баннер был
 * отключён условием `{false && …}` — мутация это показала. */
export function ErrorBanner({ error, onDismiss }: { error: string | null; onDismiss: () => void }) {
  if (!error) return null;
  return (
    <div className="card" style={{ marginBottom: 20, borderColor: 'var(--signal-critical)' }}>
      <p role="alert" style={{ color: 'var(--signal-critical)', margin: 0 }}>{error}</p>
      <button className="btn" style={{ marginTop: 8 }} onClick={onDismiss}>
        Закрыть
      </button>
    </div>
  );
}
