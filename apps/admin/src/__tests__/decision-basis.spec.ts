// Сверка оснований 2026-09-04 — решение о человеке без причины.
//
// ПЕРВЫЕ ТЕСТЫ В ЭТОМ ПРИЛОЖЕНИИ ВООБЩЕ. У `apps/admin` не было ни
// одного: в `package.json` не было даже команды `test`, и раннер сверок
// его не видел — то есть 29 файлов панели, через которую продукт
// действует НА ЛЮДЕЙ, не проверялись ничем, кроме компилятора. Это и
// нашлось первым.
//
// НАЙДЕННОЕ В САМОЙ ПАНЕЛИ:
//
//  1. Ограничение и полная блокировка принимались БЕЗ ПРИЧИНЫ:
//     `note?: string` и в базу `null`. Продукт требует основание везде —
//     позиция без цитаты не создаётся, факт без источника не
//     сохраняется, — а решение отнять у человека девять действий или
//     вход целиком записывалось с пустым «почему». Журнал фиксировал,
//     ЧТО сделано, и мог не знать, за что.
//  2. Человеку причину не показывали никогда, хотя она уже хранилась в
//     базе. Он узнавал только факт: доступ закрыт.
//  3. Оба сообщения отправляли «напишите в поддержку» — ПОДДЕРЖКИ В
//     ПРОДУКТЕ НЕТ: ни адреса, ни формы, ни обработчика в боте (поиск по
//     монорепо находит только сами эти две строки). Названный
//     несуществующий способ хуже неназванного: человек ищет и не
//     находит. Та же форма, что в пункте [candidate-rights].
//  4. Сообщение об ограничении было НА УКРАИНСКОМ при русском остальном
//     интерфейсе — чужой язык ровно в тот момент, когда человеку и так
//     непонятно, что произошло.
//  5. В панели любая ошибка заменяла СОБОЙ ВСЮ СТРАНИЦУ ранним
//     `return`: оператор терял список, фильтры и раскрытые детали и не
//     мог проверить, применилось ли действие. ИЗМЕРЕНО: так делали
//     одиннадцать страниц из семнадцати, и на трёх — модерация
//     пользователей, библиотеки и заведений — этой же переменной
//     пользовались ОБРАБОТЧИКИ ДЕЙСТВИЙ. На заведениях доходило до
//     того, что сбой загрузки боковой сводки комиссий уносил очередь
//     заявок целиком. Правило в проекте УЖЕ понимали: комментарий у
//     поля комиссии объяснял, почему оно не пользуется общей
//     переменной, — но обошли изъян в одном поле вместо того, чтобы
//     починить причину. Знакомая форма: «правило было, просто не
//     везде».
//
// ЧЕСТНАЯ ГРАНИЦА ПОРОГА, и она стоила прогона. Первая версия требовала
// десяти символов — и уронила существующий тест с причиной «спам».
// Причина была права, а порог нет: «спам» — настоящее основание, а не
// отписка. Проверяется НАЛИЧИЕ причины (три буквы: отсекают точку,
// прочерк и «ок»), а не её качество — качество тестом не проверяется, и
// притворяться, что проверяется, нельзя.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ErrorBanner } from '../components/ErrorBanner';
import { hasReason } from '../lib/moderation-reason';

const SRC = join(__dirname, '..');
const API = join(__dirname, '../../../api/src');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

function read(base: string, rel: string): string {
  return readFileSync(join(base, rel), 'utf8');
}

/** Комментарии прочь перед разбором КОДА. За эту сессию проверка ловила
 * собственный объяснительный текст четырежды: здесь она объявила, что
 * сообщение «снова отправляет в поддержку», прочитав фразу в комментарии
 * о том, как было РАНЬШЕ. Ошибка разбора, выданная за находку, — ровно
 * то, чего эти сверки делать не должны. */
function code(base: string, rel: string): string {
  return read(base, rel).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: «спам» — причина, а точка и «ок» — нет', () => {
    // Порог проверяет наличие основания, а не длину мысли. Настоящее
    // короткое слово проходить обязано: на этом первая версия правила и
    // сломалась.
    assert(hasReason('спам'), '«спам» отвергнут — порог снова требует длины, а не причины');
    assert(hasReason('дубли заявок'), 'обычная причина отвергнута');
    assert(!hasReason('.'), 'точка принята за причину');
    assert(!hasReason('—'), 'прочерк принят за причину');
    assert(!hasReason('ок'), '«ок» принято за причину');
    assert(!hasReason(''), 'пустая строка принята за причину');
    assert(!hasReason('   '), 'пробелы приняты за причину');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: панель не даёт ограничить и заблокировать без причины', () => {
    // Сказать оператору ДО нажатия, а не отказом сервера после.
    const src = read(SRC, 'app/moderation/users/page.tsx');
    assert(/from '\.\.\/\.\.\/\.\.\/lib\/moderation-reason'/.test(src),
      'панель больше не пользуется общей проверкой причины — сверка проверяла бы свою копию');
    const disabled = src.match(/disabled=\{!u\.is(Restricted|Blocked) && !hasReason\(/g) ?? [];
    assert(disabled.length === 2, `кнопки без причины должны быть неактивны обе, найдено ${disabled.length}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сервер тоже требует причину — панель не единственная защита', () => {
    // Проверка только на экране защищает от опечатки, а не от прямого
    // запроса к API.
    const src = read(API, 'admin-users/admin-users.service.ts');
    assert(/MIN_MODERATION_REASON_LETTERS/.test(src), 'на сервере нет порога причины');
    assert(/requireReason\(note, 'ограничение'\)/.test(src), 'ограничение ставится без обязательной причины');
    assert(/requireReason\(note, 'блокировка'\)/.test(src), 'блокировка ставится без обязательной причины');
    // Снятие — БЕЗ причины: требовать основание, чтобы вернуть человеку
    // доступ, значило бы мешать исправлять ошибку.
    assert(/isRestricted: false, restrictedAt: null, restrictedNote: null/.test(src), 'снятие ограничения изменилось');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: человеку сообщают ОСНОВАНИЕ, а не только факт', () => {
    const src = read(API, 'telegram-auth/moderation-notice.ts');
    assert(/Основание: \$\{reason\}/.test(src), 'причина не попадает в сообщение человеку');
    assert(/blockedNotice/.test(src) && /restrictedNotice/.test(src), 'нет обоих сообщений');
    // При ограничении важно сказать, что НЕ закрыто, — иначе человек
    // решит, что потерял всё.
    assert(/чтение и выгрузка ваших данных работают/.test(src), 'не сказано, что осталось доступным');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: несуществующая поддержка больше не называется', () => {
    // Названный и несуществующий способ хуже неназванного.
    const notice = code(API, 'telegram-auth/moderation-notice.ts');
    assert(/SUPPORT_CONTACT/.test(notice), 'контакт не берётся из настройки');
    assert(!/напишите в поддержку/.test(notice), 'сообщение снова отправляет в несуществующую поддержку');
    for (const rel of ['telegram-auth/telegram-auth.guard.ts', 'telegram-auth/not-restricted.guard.ts']) {
      const src = code(API, rel);
      assert(!/напишите в поддержку|до підтримки/.test(src), `${rel}: осталась отправка в несуществующую поддержку`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сообщение об ограничении — на языке остального интерфейса', () => {
    // Оно было на украинском при русском продукте: чужой язык ровно
    // тогда, когда человеку и так непонятно, что произошло.
    const src = code(API, 'telegram-auth/not-restricted.guard.ts');
    assert(!/обмежений|Зверніться|підтримки/.test(src), 'в сообщении об ограничении снова украинский текст');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: баннер ошибки РИСУЕТСЯ, а не просто упомянут в исходнике', () => {
    // Урок [render-guards] стоил здесь мутации: проверка на упоминание
    // `role="alert"` в файле проходила и тогда, когда весь баннер был
    // отключён условием `{false && …}`. Проверка на упоминание, а не на
    // поведение. Поэтому компонент вынесен и рисуется по-настоящему.
    const shown = renderToStaticMarkup(
      createElement(ErrorBanner, { error: 'Не удалось отклонить заявку', onDismiss: () => {} }),
    );
    assert(/role="alert"/.test(shown), 'сообщение об ошибке не объявляется вслух');
    assert(/Не удалось отклонить заявку/.test(shown), 'текст ошибки не показан — оператор не узнает, что случилось');
    assert(/<button/.test(shown), 'сообщение нельзя закрыть');

    // И обратная половина: без ошибки баннер не занимает места и не
    // сообщает о несуществующей беде.
    assert(renderToStaticMarkup(createElement(ErrorBanner, { error: null, onDismiss: () => {} })) === '',
      'баннер рисуется, когда ошибки нет');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сбой ДЕЙСТВИЯ не уносит с собой страницу модерации', () => {
    // Ранний `return` уносил список, фильтры и раскрытые детали — и
    // оператор терял ровно то, по чему мог бы проверить, применилось
    // решение или нет. Три страницы модерации пользовались одной
    // переменной и для загрузки, и для действий; теперь они разделены.
    for (const rel of ['app/moderation/users/page.tsx', 'app/moderation/library/page.tsx', 'app/moderation/venues/page.tsx']) {
      const src = code(SRC, rel);
      assert(!/if \(error\) return </.test(src), `${rel}: ошибка снова заменяет собой страницу`);
      assert(/<ErrorBanner/.test(src), `${rel}: сбой действия не показывается баннером`);
      // Баннеру передана НАСТОЯЩАЯ переменная состояния, а не константа:
      // мутация `{false && …}` в прошлой версии проверки проходила.
      assert(/<ErrorBanner error=\{(actionError|error)\}/.test(src), `${rel}: баннеру передана не переменная ошибки`);
      assert(/onDismiss=\{\(\) => set(Action)?Error\(null\)\}/.test(src), `${rel}: сообщение об ошибке нельзя закрыть`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сбой действия не подменяется сбоем загрузки', () => {
    // Мутация показала дыру: достаточно было в обработчике действия
    // написать `setLoadError` вместо `setActionError` — и страница снова
    // исчезала, а проверка на отсутствие `if (error) return` проходила.
    // Поэтому правило теперь о том, ОТКУДА ставится ошибка загрузки:
    // ровно из одного места — из самой загрузки.
    for (const rel of ['app/moderation/library/page.tsx', 'app/moderation/venues/page.tsx']) {
      const src = code(SRC, rel);
      const calls = src.match(/setLoadError\(/g) ?? [];
      assert(calls.length === 1,
        `${rel}: ошибку загрузки ставят из ${calls.length} мест — сбой действия снова может унести страницу`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сбой ЗАГРУЗКИ по-прежнему честно заменяет страницу', () => {
    // Обратная половина правила, иначе «не заменять страницу» станет
    // догмой: если не загрузился сам список, показывать нечего, и
    // рисовать пустую таблицу с баннером наверху — врать о полноте.
    for (const rel of ['app/moderation/library/page.tsx', 'app/moderation/venues/page.tsx']) {
      const src = code(SRC, rel);
      assert(/if \(loadError\) return </.test(src), `${rel}: сбой загрузки перестал показываться`);
      assert(/role="alert"/.test(src), `${rel}: сбой загрузки не объявляется вслух`);
    }
  }],

  ['ИЗМЕРЕНИЕ: панель вообще видна сверкам, и страницы модерации не откатились', () => {
    // Число живёт здесь, чтобы следующая сверка начинала с факта: до
    // этого захода проверок в приложении не было ВООБЩЕ — ни одной, и
    // в `package.json` не было даже команды `test`.
    const pkg = JSON.parse(readFileSync(join(SRC, '../package.json'), 'utf8'));
    assert(typeof pkg.scripts?.test === 'string', 'у панели снова нет команды test — сверки её не увидят');

    // Остальные семь страниц с ранним возвратом НЕ ТРОНУТЫ намеренно:
    // там `error` ставится только при загрузке, и заменить собой
    // страницу — честное поведение. Число зафиксировано, чтобы это
    // осталось решением, а не забытым хвостом.
    const pages: string[] = [];
    (function walk(dir: string) {
      for (const name of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, name.name);
        if (name.isDirectory()) walk(full);
        else if (name.name === 'page.tsx') pages.push(full);
      }
    })(join(SRC, 'app'));
    const earlyReturn = pages.filter((p) => /if \(error\) return </.test(readFileSync(p, 'utf8')));
    assert(earlyReturn.length === 8,
      `страниц с ранним возвратом по error должно остаться 8 (только сбой загрузки), найдено ${earlyReturn.length}: ` +
        earlyReturn.map((p) => p.slice(SRC.length + 1)).join(', '));
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\ndecision-basis: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
