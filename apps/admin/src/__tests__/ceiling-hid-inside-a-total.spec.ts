// Сверка 2026-09-24 — потолок читался как итог.
//
// НАЙДЕНО. Сервер отдавал операторский обзор очередей медиа с
// необъявленным потолком в 200 строк, а этот экран не показывал очереди
// по одной — он их СКЛАДЫВАЛ: «очередей», «роликов», «разобрано»,
// «доля разобранных».
//
// Итог по срезу, подписанный как итог по всему, хуже обрезанного
// списка. Список хотя бы выглядит списком, и человек может заподозрить,
// что видит не всё. Число выглядит ФАКТОМ О СИСТЕМЕ: при девятистах
// очередях оператор читал «200» и долю разобранных среди последних
// двухсот — и принимал по этой доле решение о работоспособности
// конвейера.
//
// СДЕЛАНО. Итоги считает база по всем строкам и приходят отдельным
// полем `totals`; экран их показывает, а не выводит заново. Список
// остаётся с потолком и говорит о нём — но только когда потолок
// сработал: подпись, стоящая всегда, не отвечает на вопрос «мне
// показали всё?».
//
// ПРАВИЛО ЗДЕСЬ ПО МЕСТУ, А НЕ ПО ФОРМЕ, и это выбор, а не небрежность.
// Форма «экран складывает список в число» законна в большинстве
// случаев: полный список сложить можно и нужно. Незаконно складывать
// список, у которого сервер объявил потолок, — а связь «этот массив
// пришёл с потолком» из текста экрана не видна. Поэтому проверяется
// конкретное место, где потолок точно есть; общее правило, которое
// нельзя проверить, было бы утверждением о проверке вместо проверки.

import { readFileSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

function code(rel: string): string {
  return readFileSync(join(SRC, rel), 'utf8')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const SUMMARY_PAGE = 'app/domains/page.tsx';
const LIST_PAGE = 'app/media-review/page.tsx';

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: экран не складывает срез с потолком в итог', () => {
    const src = code(SUMMARY_PAGE);
    assert(
      !/mediaQueues\s*\.\s*reduce\(/.test(src) && !/mediaQueues\.queues\s*\.\s*reduce\(/.test(src),
      `${SUMMARY_PAGE}: итог снова выводится сложением полученных очередей. ` +
        'Сервер отдаёт их с потолком, и сумма среза, подписанная как итог, — ' +
        'уверенно показанное неверное число.',
    );
    assert(
      /mediaQueues\.totals\./.test(src),
      `${SUMMARY_PAGE}: итоги не берутся из ответа сервера. Они должны считаться там, ` +
        'где известно, сколько строк всего, — в базе.',
    );
    // Первая редакция этого теста запрещала только сложение и требовала,
    // чтобы `totals` где-нибудь упоминался. Мутация «взять длину среза»
    // проходила её насквозь: сложения нет, `totals` рядом есть, а число
    // всё равно из среза. Экрану итогов сам срез не нужен ни для чего —
    // значит и обращаться к нему он не должен вовсе.
    assert(
      !/mediaQueues\.queues/.test(src),
      `${SUMMARY_PAGE}: экран итогов читает сам срез. Любое число, выведенное из него, ` +
        'будет числом по последним 200 строкам под подписью «всего» — ' +
        'запрещено не сложение, а вывод итога из среза каким угодно способом.',
    );
  }],

  ['ОБРАТНАЯ ПРОБА: разбор действительно ловит сложение среза', () => {
    const offending = 'const media = mediaQueues.reduce((acc, q) => acc, {});';
    assert(
      /mediaQueues\s*\.\s*reduce\(/.test(offending),
      'Выражение перестало находить сложение — тогда ключевой тест проходит ' +
        'не потому, что сложения нет, а потому, что его не ищут.',
    );
    assert(
      !/mediaQueues\s*\.\s*reduce\(/.test('const media = mediaQueues.totals;'),
      'Выражение находит лишнее: чтение готового итога — не сложение среза.',
    );
  }],

  ['потолок списка назван, и назван только когда сработал', () => {
    const src = code(LIST_PAGE);
    assert(
      /rows\?\.hasMore/.test(src) || /rows\.hasMore/.test(src),
      `${LIST_PAGE}: экран не говорит о потолке вовсе — список выглядит полным.`,
    );
    assert(
      /rows\?\.hasMore\s*&&/.test(src),
      `${LIST_PAGE}: подпись о потолке стоит безусловно. Подпись, стоящая всегда, ` +
        'не отвечает на вопрос «мне показали всё?» — ровно за это её критикует ' +
        'шапка механизма страниц.',
    );
    assert(
      /rows\.totals\.queues/.test(src),
      `${LIST_PAGE}: сказано «показаны не все», но не сказано, сколько всего. ` +
        '«Есть ещё» без числа человек не может сопоставить ни с чем.',
    );
  }],

  ['числа «застряли» в строках не выдаются за итог по системе', () => {
    const src = code(LIST_PAGE);
    assert(
      /totals\.stuckProcessing/.test(src),
      `${LIST_PAGE}: при сработавшем потолке показаны застрявшие только по видимым ` +
        'очередям, а всего по системе — нет. Вопрос «что застряло» не имеет ' +
        'смысла в границах страницы.',
    );
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nceiling-hid-inside-a-total: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
