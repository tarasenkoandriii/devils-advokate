/** Пункт [decision-basis] 2026-09-04 — есть ли у решения основание.
 *
 * Та же проверка, что на сервере (`MIN_MODERATION_REASON_LETTERS`): три
 * буквы. Она не оценивает КАЧЕСТВО причины — этого тестом не сделать
 * (урок [guard-audit]: не притворяться, что проверяешь непроверяемое), —
 * а отсекает точку, прочерк и «ок», не отсекая ни одного настоящего
 * слова: «спам» проходит.
 *
 * Дублируется в панели не ради защиты (защита на сервере, панель её не
 * заменяет), а чтобы сказать оператору ДО нажатия, а не отказом после.
 *
 * Вынесено из страницы отдельным модулем ровно затем, чтобы сверка
 * ВЫЗЫВАЛА эту функцию, а не свою копию. Мутация показала, чего стоила
 * копия: `hasReason` в панели можно было заставить всегда возвращать
 * true, и проверка `/function hasReason/` в исходнике этого не замечала.
 * Снова «проверка написана на упоминание, а не на поведение». */
export const MIN_REASON_LETTERS = 3;

export function hasReason(note: string | undefined): boolean {
  return ((note ?? '').match(/\p{L}/gu) ?? []).length >= MIN_REASON_LETTERS;
}
