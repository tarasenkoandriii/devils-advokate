// Пункт [green-deploy-pointed-at-localhost] 2026-09-30 — вторая копия
// правила из `apps/tma/src/lib/api-base-url.ts`. Копий две, потому что
// это два отдельных приложения Next без общего пакета; что список
// признаков платформы и поведение при отсутствии адреса у них
// совпадают, держит
// `apps/api/src/__tests__/audit-2026-09-30-green-deploy-pointed-at-localhost.spec.ts`.
//
// НАЙДЕННОЕ. Адрес API брался так — в ВОСЬМИ местах одного приложения
// (`api.ts`, `public-api.ts` и пять раз внутри `features.ts`), плюс
// девятый раз в админке:
//
//   process.env.NEXT_PUBLIC_API_BASE_URL ?? 'http://localhost:3000'
//
// Переменная читается на СБОРКЕ (`NEXT_PUBLIC_` вкомпилируется в
// бандл), не в рантайме. Значит если её не выставить в проекте на
// платформе, в бандл уезжает `http://localhost:3000`, сборка проходит,
// деплой зелёный, страницы рисуются — и каждый запрос уходит на
// localhost БРАУЗЕРА ЧЕЛОВЕКА. Ни одной ошибки на нашей стороне: ни в
// сборке, ни в логах функции, потому что до функции ничего не доходит.
// Узнать об этом можно было только от человека, у которого «ничего не
// работает».
//
// Отдельно: дефолт был скопирован восемь раз. Проверять его в восьми
// местах — это и есть «правило было, просто не везде» наоборот: копия
// есть везде, проверки нет нигде.
//
// ПРАВИЛО. Дефолт для разработки остаётся дефолтом для РАЗРАБОТКИ. На
// платформе отсутствие адреса — не «возьми localhost», а красная
// сборка: красная сборка дешевле зелёного деплоя, который не работает,
// и обнаруживается нами, а не человеком.
//
// Признак платформы — `VERCEL`/`VERCEL_ENV`, которые платформа
// выставляет сама на всех сборках (прод и превью), а не `NODE_ENV`:
// `next build` локально и в CI тоже идёт с `NODE_ENV=production`, и по
// нему проверка роняла бы обычную локальную сборку, в которой дефолт
// как раз уместен.

/** Дефолт разработки. Используется ТОЛЬКО когда мы не на платформе. */
export const LOCAL_API_BASE_URL = 'http://localhost:3000';

// ─────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗДЕСЬ СТАТИЧЕСКИЕ `process.env.ИМЯ`, А НЕ ПАРАМЕТР-ОКРУЖЕНИЕ.
//
// Найдено проверкой на живом деплое 2026-09-30, уже ПОСЛЕ того, как
// сборка позеленела. Первая версия этого файла принимала окружение
// параметром — ради тестируемости — и читала `env.NEXT_PUBLIC_API_BASE_URL`.
// На сервере (сборка, пререндер) это работает: там `process.env`
// настоящий, и проверка предела увидела значение, поэтому сборка
// прошла. А в браузере — нет: сборщик подставляет значение только в
// ТЕКСТ `process.env.NEXT_PUBLIC_API_BASE_URL`, буквально; обращение
// через переменную он подставить не может и оставляет как есть, а
// `process.env` в бандле — обрезанный объект. Значит в браузере
// значение снова становилось undefined, и адрес снова падал на
// localhost — ровно тот дефект, который этот файл закрывает.
//
// Урок, который стоит держать при себе: зелёная сборка проверяла
// СЕРВЕРНУЮ половину кода, а ломалась клиентская. Тестируемость,
// купленная за параметр, стоила работоспособности; поэтому значения
// приходят ЗНАЧЕНИЯМИ ПО УМОЛЧАНИЮ — их текст остаётся статическим и
// подставляется сборщиком, а тест по-прежнему может передать своё.
// ─────────────────────────────────────────────────────────────────────

export function resolveApiBaseUrl(
  /** Сырое значение переменной. По умолчанию — статическая ссылка,
   *  которую подставляет сборщик. */
  rawValue: string | undefined = process.env.NEXT_PUBLIC_API_BASE_URL,
  /** Признак сборки на платформе. Обе переменные платформа выставляет
   *  сама; в браузере их нет, и это правильно — проверять предел надо
   *  на сборке, а не у человека на экране. */
  onPlatform: boolean = Boolean(
    (process.env.VERCEL ?? '').trim() || (process.env.VERCEL_ENV ?? '').trim(),
  ),
): string {
  const raw = (rawValue ?? '').trim();
  if (raw) {
    // Хвостовой слэш убирается здесь, а не в восьми местах склейки:
    // `${base}${path}` с ним даёт `//conversations` — путь, которого на
    // API нет, и отказ 404 выглядел бы как «объекта не существует».
    return raw.replace(/\/+$/, '');
  }
  if (onPlatform) {
    throw new Error(
      'NEXT_PUBLIC_API_BASE_URL не выставлена в проекте на платформе. ' +
        'Без неё в бандл уедет http://localhost:3000, и каждый запрос уйдёт на localhost браузера человека: ' +
        'деплой будет зелёным, а приложение — нерабочим. Выставьте адрес API в переменных проекта и пересоберите.',
    );
  }
  return LOCAL_API_BASE_URL;
}

/** Единственный адрес API приложения. */
export const API_BASE_URL = resolveApiBaseUrl();
