-- Пункт [state-not-sent] 2026-09-06 — снятие вакансии с публикации
-- переносится из ТЕКСТА вакансии в колонку.
--
-- ЗАЧЕМ. До этой правки факт снятия хранился единственным способом:
-- перечитывание дописывало в конец `raw_text` строку
-- «[Снята с публикации: источник ответил 404 — ДАТА]». Колонки под
-- состояние источника не было вовсе. Следствия разобраны в
-- src/vacancy-intake/source-availability.ts; здесь важно одно: метки
-- уже лежат в данных, и плановое перечитывание дописывало их КАЖДЫЕ
-- СУТКИ, поэтому у снятой вакансии со слежением их столько, сколько
-- прошло дней. Починка кода их не уберёт — уберёт эта миграция.
--
-- Применять через DIRECT_URL (SQL Editor Supabase), как остальные
-- ручные миграции проекта. Шаги 2 и 3 идемпотентны: повторный запуск
-- ничего не испортит — меток к тому моменту уже не будет.

-- 1. Колонка состояния. Аддитивно, NULL = «при последней проверке
--    источник отвечал».
ALTER TABLE "job_vacancies"
  ADD COLUMN IF NOT EXISTS "removedFromSourceAt" TIMESTAMP(3);

-- 2. Перенос факта из текста в колонку. Берётся САМАЯ РАННЯЯ дата из
--    найденных меток: она и есть день, когда снятие заметили впервые,
--    а позднейшие метки дописаны повторными тиками и датой снятия не
--    являются.
UPDATE "job_vacancies"
SET "removedFromSourceAt" = (
  SELECT MIN(TO_TIMESTAMP(m[1], 'YYYY-MM-DD'))
  FROM regexp_matches(
    "rawText",
    '\[Снята с публикации: источник ответил 404 — (\d{4}-\d{2}-\d{2})\]',
    'g'
  ) AS m
)
WHERE "rawText" LIKE '%[Снята с публикации%'
  AND "removedFromSourceAt" IS NULL;

-- 3. Вычистка меток из текста источника — и из `previousRawText` тоже:
--    там лежит тот же текст с метками на одну меньше, и diff «Изменения»
--    строится по нему. Оставить его значило бы показывать человеку
--    разницу между двумя нашими же дописками.
UPDATE "job_vacancies"
SET "rawText" = RTRIM(regexp_replace(
      "rawText",
      '\n*\[Снята с публикации: источник ответил 404 — \d{4}-\d{2}-\d{2}\]',
      '',
      'g'
    ))
WHERE "rawText" LIKE '%[Снята с публикации%';

UPDATE "job_vacancies"
SET "previousRawText" = RTRIM(regexp_replace(
      "previousRawText",
      '\n*\[Снята с публикации: источник ответил 404 — \d{4}-\d{2}-\d{2}\]',
      '',
      'g'
    ))
WHERE "previousRawText" LIKE '%[Снята с публикации%';

-- 4. `previousRawText`, ставший равным `rawText` после вычистки, больше
--    не описывает никакого изменения: это была разница только в метках.
--    «Изменения» по нему показали бы пустой diff, поэтому он снимается —
--    честнее сказать «изменений не записано», чем показать пустое
--    сравнение как сравнение.
UPDATE "job_vacancies"
SET "previousRawText" = NULL
WHERE "previousRawText" IS NOT NULL
  AND BTRIM("previousRawText") = BTRIM("rawText");

-- 5. Хеш содержимого в ветке снятия НЕ пересчитывался, хотя текст
--    менялся, — а dedupe() пересчитывает хеш тем, у кого его нет. Чтобы
--    снятые вакансии снова группировались со своими дублями, хеш
--    сбрасывается: пересчитает его сам продукт, уже по чистому тексту.
UPDATE "job_vacancies"
SET "contentHash" = NULL
WHERE "removedFromSourceAt" IS NOT NULL;
