-- Сверка вебхуков и токенов 2026-09-04 — атомарный забор обработки
-- вебхука расшифровки (Conversation.transcriptionClaimedAt).
--
-- Зачем: проверка «разговор ещё в TRANSCRIBING» была read-then-act. Два
-- ретрая провайдера — а ретрай приходит именно тогда, когда наш ответ
-- медленный, то есть первый вызов ещё идёт, — оба читали статус и оба
-- шли дальше: вторая паралингвистическая джоба и второй декремент
-- счётчика потребителей аудио, из-за которого файл удалялся, пока первая
-- джоба его ещё читала.
--
-- Код терпит отставание этой миграции: пока колонки нет, обработчик
-- работает как раньше (с прежней неатомарной проверкой) и один раз
-- пишет предупреждение в лог. То есть выкатывать можно в любом порядке,
-- но до применения гонка остаётся.
--
-- Применять по DIRECT_URL (не через пулер).

ALTER TABLE "conversations"
  ADD COLUMN IF NOT EXISTS "transcriptionClaimedAt" TIMESTAMP(3);

-- Частичный индекс: забор ищет строки с непустой отметкой только для
-- проверки протухания, полный индекс тут не нужен.
CREATE INDEX IF NOT EXISTS "conversations_transcriptionClaimedAt_idx"
  ON "conversations" ("transcriptionClaimedAt")
  WHERE "transcriptionClaimedAt" IS NOT NULL;
