-- Пункт [stored-text-cut] 2026-09-06 — длина текста вакансии ДО обрезки.
--
-- ЗАЧЕМ. Валидатор запроса пропускает 20 000 знаков, а запись режет до
-- 12 000 — и делала это молча. Человек вставлял объявление на 15 000
-- знаков, получал созданную вакансию и нигде не узнавал, что три тысячи
-- знаков в продукт не попали. По этому обрезку дальше считается
-- `contentHash` (склейка дублей), идёт сверка с CV, ищутся признаки
-- мошенничества и собираются основания для листа условий.
--
-- И отдельно: механизм честного отчёта в продукте есть с пункта
-- [input-truncated] — он говорит «в разбор вошли первые N знаков из M».
-- Но M брался из того, что уже лежит в базе, то есть после молчаливой
-- обрезки записка сообщала «вошли 12 000 из 12 000» и была неправдой,
-- не зная об этом. Колонка ниже возвращает записке правду.
--
-- Миграция АДДИТИВНА: одна nullable-колонка. Применять через DIRECT_URL.

ALTER TABLE "job_vacancies"
  ADD COLUMN IF NOT EXISTS "rawTextTotalChars" INTEGER;

-- Для уже существующих строк длина до обрезки неизвестна: текста,
-- который не сохранили, нет нигде. NULL здесь честнее любой подстановки
-- — он значит «не знаем», а не «обрезки не было». Единственное, что
-- можно утверждать без догадки: если сохранённый текст КОРОЧЕ потолка,
-- значит он не обрезался, и его длина и есть полная.
UPDATE "job_vacancies"
SET "rawTextTotalChars" = LENGTH("rawText")
WHERE "rawTextTotalChars" IS NULL
  AND LENGTH("rawText") < 12000;
