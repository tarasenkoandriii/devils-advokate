-- Пункт [ai-locale] 2026-09-02 — эквивалент миграции для schema.prisma.
--
-- ЗАЧЕМ. Telegram присылает language_code в initData с КАЖДЫМ запросом,
-- а guard его выбрасывал: в User колонки под него не было. В итоге язык
-- ответа AI не задавался нигде, и модель следовала языку ВХОДНЫХ ДАННЫХ
-- — разбор украинского видео возвращался русскоязычному пользователю
-- по-английски. Теперь это единственный источник языка ответа для всех
-- AI-фич (инструкцию добавляет AIRouter в общей воронке).
--
-- Аддитивно и безопасно: колонка nullable, NULL = язык неизвестен,
-- берётся дефолт (русский). Заполняется сама при следующем запросе
-- каждого пользователя из Mini App.
--
-- Применять по DIRECT_URL (порт 5432): DDL не проходит через pgbouncer.
--
-- ЕСЛИ НЕ ПРИМЕНЕНО. Первый выкат этого кода прошёл раньше миграции, и
-- каждый AI-вызов падал на «The column users.languageCode does not
-- exist» — отставание базы выглядело как сбой AI. Теперь роутер это
-- переживает: не смог прочитать язык — отвечает на языке по умолчанию и
-- пишет предупреждение в лог. То есть без миграции сервис работает, но
-- язык пользователя не сохраняется и ответы всегда будут русскими.

ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "languageCode" TEXT;

