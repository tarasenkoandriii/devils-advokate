-- Пункт [forecast-without-source] 2026-09-06 — у прогноза появляется
-- автор, а «нет данных» перестаёт быть описанием погоды.
--
-- ЗАЧЕМ. Прогноз приходит от одного из двух сервисов (Windy с ключом,
-- Open-Meteo без), переключение между ними было молчаливым: колонки под
-- автора не существовало, и человек читал «ясно, 18 °C», не зная, чей
-- это прогноз. Отдельно: когда сервис отвечал, но данных на дату не
-- давал, в `condition` писалась СТРОКА «нет данных» — и она уходила в
-- промпт как описание погоды, после чего модель выдавала рекомендацию
-- «проводить / перенести». Теперь пусто это NULL, а рекомендации в
-- таком случае нет вовсе.
--
-- МИГРАЦИЯ НЕ АДДИТИВНА: два DROP NOT NULL. Применять через DIRECT_URL
-- (SQL Editor Supabase), как остальные ручные миграции проекта.

-- 1. Автор прогноза. NULL у строк, созданных до этой правки — мы честно
--    не знаем, какой сервис их дал.
ALTER TABLE "weather_forecasts"
  ADD COLUMN IF NOT EXISTS "source" TEXT;

-- 2. «Нет данных» перестаёт быть значением описания.
ALTER TABLE "weather_forecasts"
  ALTER COLUMN "condition" DROP NOT NULL;

UPDATE "weather_forecasts"
SET "condition" = NULL
WHERE "condition" = 'нет данных';

-- 3. Рекомендация становится необязательной: без данных о погоде
--    советовать нечего.
ALTER TABLE "weather_forecasts"
  ALTER COLUMN "recommendation" DROP NOT NULL;

-- 4. Уже записанные советы, построенные на строке «нет данных»,
--    снимаются: это были выводы о встрече человека, сделанные из
--    отсутствия данных. Причина переписывается прямым текстом — строка
--    остаётся, чтобы человек видел, что запрос был, и понимал, почему
--    совета нет.
UPDATE "weather_forecasts"
SET "recommendation" = NULL,
    "recommendationReason" = 'Данных о погоде на это время сервис не дал — советовать по ним нечего. Прежний совет здесь был построен на пустом ответе и снят.'
WHERE "condition" IS NULL;
