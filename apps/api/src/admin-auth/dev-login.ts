// Docker dev-запуск (DOCKER.md): один-единственный модуль, отвечающий на
// вопрос «разрешён ли сейчас dev-вход вообще». Вынесен отдельно от
// AdminAuthService намеренно — та же проверка нужна и сервису (чтобы не
// создать сессию), и контроллеру (чтобы не отдать 500 вместо честного
// 404), и тесту; три копии условия `ALLOW_DEV_AUTH === 'true'` — ровно
// тот способ, которым такие флаги и разъезжаются.
//
// ДВА условия, а не одно (в отличие от TelegramAuthGuard, где исторически
// проверяется только ALLOW_DEV_AUTH): admin dev-вход выдаёт сессию с
// ПОЛНЫМИ правами оператора и модератора, то есть по последствиям он
// строго опаснее, чем dev-bypass TMA-пользователя. Поэтому здесь
// добавлен второй, независимый предохранитель — NODE_ENV !== 'production'.
// Даже если ALLOW_DEV_AUTH="true" случайно утечёт в продовое окружение
// (скопировали .env, забыли переменную в Vercel-проекте), на проде
// NODE_ENV=production выставляется платформой автоматически, и вход
// останется закрытым. Одна ошибка конфигурации не должна открывать
// админку — нужны обе сразу.

export interface DevAuthEnv {
  ALLOW_DEV_AUTH?: string;
  NODE_ENV?: string;
}

export function isDevAuthAllowed(env: DevAuthEnv = process.env): boolean {
  return env.ALLOW_DEV_AUTH === 'true' && env.NODE_ENV !== 'production';
}

/** Единый неймспейс telegramId для «ненастоящих» пользователей — тот же
 * префикс "dev-", что уже использует TelegramAuthGuard.tryDevBypass().
 * Благодаря этому dev-вход в админку и dev-вход в TMA с одинаковым id
 * дают ОДНОГО пользователя, а не двух разных: оператор, зашедший в
 * админку как dev-123, видит в модерации ровно те данные, которые сам
 * же создал в TMA под X-Dev-User-Id: 123. Разъехавшиеся неймспейсы
 * сделали бы локальную проверку сквозных сценариев бессмысленной. */
export function devTelegramId(rawId: string): string {
  return `dev-${rawId}`;
}
