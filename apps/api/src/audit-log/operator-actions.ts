// и отказ, а НЕ аудировались ровно два — СУММА реферальной платы и
// ПОДЪЁМ НАД ОРГАНИЧЕСКОЙ ВЫДАЧЕЙ. То есть именно те, что про деньги с
// внешней стороной и про то, что человек увидит первым.
//
// Второе стои́т назвать отдельно. Флаг приоритетного партнёра поднимает
// заведение над обычной выдачей, и экран честно рисует такие карточки
// отдельным списком с пометкой «Реклама». Пометка честна ПЕРЕД
// ЧИТАТЕЛЕМ, но она не отвечает на вопрос «кто и когда это решил», —
// а платное продвижение ровно этот вопрос и порождает. Журнал для того
// и существует.
//
// ПОЧЕМУ ОСТАЛЬНЫЕ НУЛИ — НЕ ТО ЖЕ САМОЕ, и почему они здесь названы,
// а не исправлены заодно: у каждого своя причина, и причины разные.
// Список ниже — реестр: каждое операторское действие либо пишет в
// журнал, либо стои́т тут с объяснением. Сверка держит совпадение.

/** Почему операторское действие не пишет в журнал. */
export type UnauditedReason =
  /** Действует над СОБСТВЕННЫМИ данными оператора, без имперсонации:
   * песочница выполняет всё от его имени и его согласиями. Журнал
   * операторских решений — про действия НАД ДРУГИМИ. */
  | 'operator-own-data'
  /** Черновик или внутренний объект, который ещё ничего не меняет для
   * пользователей: становится значимым только при повышении статуса —
   * и ВОТ ОНО уже пишется. */
  | 'draft-not-yet-effective'
  /** Пересчёт из уже имеющихся данных, без решения человека: результат
   * воспроизводим, входные данные те же. Запись сказала бы «оператор
   * решил», чего не было.
   *
   * Сюда же не попал пересчёт калибровки: он не требует роли вообще
   * (запускается расписанием), то есть операторской мутацией не
   * является и в реестре ему делать нечего. Проверено, а не
   * предположено — первая редакция реестра внесла его по памяти. */
  | 'recomputation-not-a-decision';

export interface UnauditedOperatorAction {
  service: string;
  method: string;
  reason: UnauditedReason;
}

