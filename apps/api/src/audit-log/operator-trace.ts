// Пункт [operator-left-a-trace-unsaid] 2026-09-25 — оператор не знал, что
// его решение человек прочитает.
//
// НАЙДЕНО. Предыдущие две сверки открыли человеку журнал решений о нём:
// сначала экран, потом всю область журнала. Другая сторона того же
// разговора — оператор. Он ограничивает доступ, модерирует заявку,
// отклоняет заявку заведения; каждое такое действие пишется в журнал, и
// теперь человек читает его словами у себя в Центре приватности. На
// экране оператора об этом не сказано.
//
// МЕРА. Экранов админки, выполняющих действия из
// `AUDITED_OPERATOR_ACTIONS`, — пять. Говорят о записи в журнал ДВА
// (модерация пользователей, домены). Молчат ТРИ: модерация библиотеки,
// модерация заведений, промпты.
//
// ПОЧЕМУ НЕ ТРИ ПОДПИСИ РУКАМИ. Ровно так родился дефект пункта
// [screen-said-what-server-unsaid]: две копии одного текста, из которых
// исправили одну. Здесь копий было бы пять, и первое же изменение
// области журнала развело бы их. Поэтому след считается на сервере — из
// тех же реестров, что питают экран человека, — и приезжает на экран
// оператора данными.
//
// И СЛЕД РАЗНЫЙ У РАЗНЫХ ДЕЙСТВИЙ, что подписью «пишется в журнал» не
// передать. На одном экране заведений четыре действия: одобрение и
// отклонение заявки человек УВИДИТ (заявка — его запись), а признак
// приоритетного партнёра и вознаграждение за переход — нет (запись
// принадлежит заведению, связи с человеком у неё в схеме нет). Промпты
// не видны никому из людей: это внутреннее изменение продукта. Сказать
// «человек это увидит» там, где не увидит, — такая же неправда, как
// промолчать там, где увидит.
//
// ЧЕСТНАЯ ГРАНИЦА. «Увидит» здесь означает: запись доходит до его
// экрана. Не означает, что он туда зайдёт, и не означает, что он поймёт
// причину: свободная заметка оператора человеку не отдаётся (пункт
// [audit-trail]), и об этом на экране оператора сказано прямо — иначе
// оператор решит, что его формулировку прочитают, и напишет её не тому
// адресату.

import {
  DECISION_RESOURCE,
  visibleToPerson,
  whyNotVisible,
} from '../privacy-center/decision-scope';
import { DECISION_LABELS } from '../privacy-center/decision-labels';
import { AUDITED_OPERATOR_ACTIONS } from './operator-actions';

export interface OperatorTrace {
  /** Имя действия в журнале — то же, что увидит человек рядом с подписью. */
  action: string;
  /** Что произошло, словами — той же фразой, что прочитает человек. */
  what: string;
  /** Вид записи журнала. */
  resource: string;
  /** Дойдёт ли запись до экрана человека. */
  visibleToPerson: boolean;
  /** Почему не дойдёт — словами, или null когда дойдёт. */
  whyNotVisible: string | null;
}

/** След одного действия оператора. */
export function operatorTrace(action: string): OperatorTrace {
  const label = DECISION_LABELS[action];
  return {
    action,
    // Та же честная оговорка, что у человека: выдуманной подписи здесь не
    // появляется, иначе оператор поверит формулировке, которой никто не
    // проверял.
    what: label ? label.what : `${action} — название действия не расшифровано`,
    resource: DECISION_RESOURCE[action] ?? 'не описан',
    visibleToPerson: visibleToPerson(action),
    whyNotVisible: whyNotVisible(action),
  };
}

/** След каждого действия, которое ОБЯЗАНО оставлять запись.
 *
 * Список ведётся не здесь: он взят из `AUDITED_OPERATOR_ACTIONS`, где
 * живёт правило «решение оператора о чужом обязано оставить след».
 * Экран оператора и это правило не могут разойтись по построению. */
export const OPERATOR_TRACES: readonly OperatorTrace[] = AUDITED_OPERATOR_ACTIONS.map(operatorTrace);

/** Что оператору сказано в любом случае, независимо от действия.
 *
 * Отдельной строкой, а не в тексте компонента: это утверждение о
 * продукте, и место ему там же, где остальные утверждения о журнале. */
export const OPERATOR_TRACE_ALWAYS =
  'Запись о решении не редактируется и не удаляется. Ваша свободная заметка человеку не показывается — она остаётся в журнале для разбора жалобы, а человек видит действие, дату и то, кем оно сделано.';
