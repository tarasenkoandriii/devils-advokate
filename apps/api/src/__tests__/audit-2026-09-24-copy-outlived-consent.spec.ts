// Сверка 2026-09-24 — копия пережила отзыв согласия.
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [same-line-not-drawn] сравнил два
// соседних разбора и нашёл границу у одного из двух. Тот же приём
// применён к двум дорогам отзыва согласия кандидата — и снова одна из
// двух делала то, что обещали обе.
//
// ИЗМЕРЕНИЕ. Отозвать согласие можно двумя маршрутами:
//
//  • САМОШЕРИНГ (соискатель отзывает свою ссылку) — гасил ссылку И
//    ставил `consentRevokedAt` копии, созданной у принимающей стороны;
//  • РЕКРУТЕРСКИЙ ОТЗЫВ (рекрутер записывает просьбу кандидата) — ставил
//    отметку исходному профилю и гасил строки шеринга, а КОПИИ НЕ ТРОГАЛ.
//
// ЧТО ЭТО ЗНАЧИЛО НА ДЕЛЕ. Кандидат просит рекрутера убрать его данные.
// Рекрутер нажимает кнопку, продукт отвечает сообщением, которое
// начинается словами «Кандидат отозвал согласие на обработку — по нему
// не формируются отчёты и разборы». Исходный профиль помечен, ссылки
// погашены — а копия, уже принятая другим агентством или работодателем
// в СВОЙ проект, остаётся с `consentRevokedAt: null`. Там
// `assertConsentActive` проходит, и по человеку продолжают формироваться
// отчёты, сводки и доставки.
//
// То есть ровно то, ради чего поле `consentRevokedAt` и заводилось —
// см. шапку `consent-revocation.ts`, где сказано: «человек отзывал
// согласие, а его разбор продолжал уходить наружу: это не косметика, а
// ровно тот случай, ради которого поле и заводилось». Случай тот же,
// только на шаг дальше: не в отчётах своего проекта, а в копии у чужого.
//
// И ОБЕЩАНИЕ БЫЛО ДАНО ПРЯМО. Над `revokeConsent` стои́т комментарий:
// «Вместе с профилем гасятся все живые ссылки на него». Ссылки — да.
// Принятые копии — нет, и о них не было сказано ничего.
//
// ПОЧЕМУ ТРАНЗИТИВНО. Принявший копию владеет ею и может поделиться
// дальше. Гасить один уровень значило бы починить ближний случай и
// оставить дальний — повторить тот же изъян на шаг глубже. Обход идёт
// по родословной шерингов, у него есть потолок глубины (в данных ничто
// не запрещает цикл `A → B → A`), и упёртый потолок ВОЗВРАЩАЕТСЯ НАРУЖУ
// числом: сказать «отозвано везде», не дойдя до конца, — ровно та
// неправда, которую пункт убирает.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Оба маршрута проверены там, где работают:
// audit-2026-09-03-gaps.service.spec.ts (рекрутерский отзыв догоняет
// копию и копию копии; цикл не зацикливает обход) и
// audit-2026-09-04-freeze.service.spec.ts (то же для самошеринга).
// Здесь — то, что иначе не выразить.

import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';
import { MAX_COPY_CHAIN_DEPTH } from '../interview-pool/consent-revocation';

const SRC = join(__dirname, '..');

function tsFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : tsFiles(full);
    return name.endsWith('.ts') ? [full] : [];
  });
}

function code(path: string): string {
  return readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

describe('Сверка [copy-outlived-consent]: отзыв — одна дорога на оба маршрута', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: никто не ставит `consentRevokedAt` в обход общего обхода', () => {
    // Форма дефекта была именно такая: у каждого маршрута своя запись
    // отметки, и одна из двух знала про копии. Теперь запись живёт в
    // одном месте; любая новая по месту — это тот же изъян заново.
    // Правило смотрит на ЗАПИСЬ (`data: { … consentRevokedAt … }`), а не
    // на всякое появление имени поля. Первая редакция искала имя — и
    // пожаловалась на строку ОТВЕТА сервиса, где то же поле лежит в
    // возвращаемом объекте. Текстуально одно и то же, по смыслу —
    // противоположное: одно меняет данные, другое рассказывает о них.
    // Тот же урок, что сторож проверок охраняет с самого начала.
    const WRITE = /data:\s*\{[^}]*consentRevokedAt\s*:/;
    const offenders: string[] = [];
    for (const file of tsFiles(SRC)) {
      if (file.endsWith('consent-revocation.ts')) continue;
      if (WRITE.test(code(file))) offenders.push(file.replace(SRC, ''));
    }
    expect(offenders).toEqual([]);

    // Обратная проба: правило обязано ловить запись и НЕ ловить ответ.
    expect(WRITE.test("data: { consentRevokedAt: now }")).toBe(true);
    expect(WRITE.test("return { candidateProfileId, consentRevokedAt: now };")).toBe(false);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: все ТРИ маршрута отзыва идут через общий обход', () => {
    // Третий — отзыв самим кандидатом по публичной ссылке преданкеты —
    // нашла не пара глаз, а правило выше: ручной разбор видел два.
    // Из трёх он же и самый весомый: действует сам человек, без
    // посредника, и обещание здесь весит больше всего.
    const routes = [
      'interview-pool/interview-pool-candidate.service.ts',
      'candidate-self-share/candidate-self-share.service.ts',
      'hiring-extras/hiring-extras.service.ts',
    ];
    for (const rel of routes) {
      const src = code(join(SRC, rel));
      expect([rel, src.includes('revokeConsentCascade')]).toEqual([rel, true]);
    }
  });

  it('КЛЮЧЕВОЙ ТЕСТ: потолок глубины конечен и не равен единице', () => {
    // Единица означала бы «один уровень копий», то есть прежнее
    // поведение самошеринга под новым именем.
    expect(MAX_COPY_CHAIN_DEPTH).toBeGreaterThan(1);
    expect(Number.isFinite(MAX_COPY_CHAIN_DEPTH)).toBe(true);
  });

  it('оба маршрута возвращают наружу, сколько копий остановлено', () => {
    // Число — единственное, по чему человек отличит «копий не было» от
    // «до копий не дошли». Молчание тут читается как первое.
    for (const rel of [
      'interview-pool/interview-pool-candidate.service.ts',
      'candidate-self-share/candidate-self-share.service.ts',
      'hiring-extras/hiring-extras.service.ts',
    ]) {
      const src = code(join(SRC, rel));
      expect([rel, /copiesRevoked/.test(src)]).toEqual([rel, true]);
      expect([rel, /depthExhausted/.test(src)]).toEqual([rel, true]);
    }
  });
});
