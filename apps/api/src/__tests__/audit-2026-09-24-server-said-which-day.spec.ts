// Пункт [server-said-which-day] 2026-09-24 — сервер называл человеку
// день, которого не знает.
//
// ПОВОД. Часового пояса человека в продукте нет. Момент времени сервер
// знает точно, календарный день, выведенный из момента, — нет: разговор
// в 01:00 по Киеву это 22:00 предыдущего дня по UTC. Это разбиралось
// дважды («Аудит времени 2026-09-03» — календарь заменён окном; Пункт
// [date-only] 2026-09-04 — «вместо неверной точности даты нет вовсе») и
// оба раза закрывалось ПО МЕСТУ. Календарный день, выведенный из
// момента, оставался ещё в десяти местах, включая соседний метод того
// же файла, где урок записан словами.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ. (1) Правило по вызову, а не по написанию: три
// разных способа получить день из момента считаются одним нарушением.
// (2) Список исключений закреплён поимённо с причиной — машинные
// адресаты под правило не попадают, но и не попадают «молча».
// (3) Поведение помощников: расстояние во времени, порядок и момент с
// названной зоной — на настоящих датах, а не на упоминании функций.

import * as fs from 'fs';
import * as path from 'path';
import { daysAgo, deadlineRelative, instantUtc, orderLabel, plural } from '../common/server-time';

const SRC = path.join(__dirname, '..');

/** Где выводить день из момента ЗАКОННО — и почему. Адресат каждого из
 * этих мест машина или операторская служебная строка, а не утверждение о
 * человеке. */
const ALLOWED: Array<{ file: string; why: string }> = [
  { file: 'weather-forecast/open-meteo-client.ts', why: 'параметры запроса к Open-Meteo: API принимает именно YYYY-MM-DD' },
  { file: 'admin-sandbox/admin-sandbox.service.ts', why: 'имя песочной сущности, которое оператор создаёт сам себе, — не утверждение о человеке' },
  { file: 'common/server-time.ts', why: 'сам помощник: здесь день по UTC получается и НАЗЫВАЕТСЯ зоной вслух' },
];

/** Три написания одного и того же. Правило смотрит на вызов, а не на
 * одну форму записи: `split('T')[0]` однажды уже прошёл мимо. */
const DERIVATIONS = [
  /toISOString\(\)\s*\.\s*(?:slice|substring|substr)\(\s*0\s*,\s*10\s*\)/,
  /toISOString\(\)\s*\.\s*split\('T'\)\s*\[\s*0\s*\]/,
  /toLocaleDateString\(/,
  /toLocaleString\(/,
];

function sourceFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name !== '__tests__') walk(p);
      } else if (e.name.endsWith('.ts')) out.push(p);
    }
  };
  walk(SRC);
  return out;
}

/** Строки кода без комментариев: комментарий, называющий дефект, сам
 * дефектом не является — иначе правило запретило бы объяснять себя. */
function codeLines(file: string): Array<{ n: number; text: string }> {
  return fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .map((text, i) => ({ n: i + 1, text }))
    .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l.text));
}

describe('[server-said-which-day] сервер не называет день, которого не знает', () => {
  /** Один и тот же проход, разный список прощённых: так обратная проба
   * проверяет ТО ЖЕ измерение, а не соседнее. Первая редакция проверяла
   * совпадения внутри разрешённых файлов отдельным кодом — и мутация
   * «прощать всё» проходила насквозь: пустой список нарушителей
   * означал не чистоту, а то, что никто не смотрел. */
  function scan(allowed: Set<string>): string[] {
    const offenders: string[] = [];
    for (const file of sourceFiles()) {
      const rel = path.relative(SRC, file).split(path.sep).join('/');
      if (allowed.has(rel)) continue;
      for (const l of codeLines(file)) {
        if (DERIVATIONS.some((re) => re.test(l.text))) offenders.push(`${rel}:${l.n}`);
      }
    }
    return offenders;
  }

  it('КЛЮЧЕВОЙ ТЕСТ: календарный день из момента выводится только в разрешённых местах', () => {
    expect(scan(new Set(ALLOWED.map((a) => a.file)))).toEqual([]);
  });

  it('ОБРАТНАЯ ПРОБА: без списка прощённых тот же проход находит ровно их', () => {
    const found = new Set(scan(new Set()).map((o) => o.split(':')[0]));
    expect([...found].sort()).toEqual(ALLOWED.map((a) => a.file).sort());
  });

  it('у каждого исключения названа причина, а не «так исторически»', () => {
    for (const a of ALLOWED) {
      expect(fs.existsSync(path.join(SRC, a.file))).toBe(true);
      expect(a.why.length).toBeGreaterThan(30);
    }
  });

  // ЗДЕСЬ НЕТ проверок на независимость от часового пояса, и это не
  // упущение: внутри jest `process.env.TZ`, изменённый после старта, на
  // поведение дат НЕ ВЛИЯЕТ, и такая проверка проходила бы при любом
  // коде — сравнивались бы два одинаковых прогона. Она написана и живёт
  // в автономном раннере: `server-time-timezone.spec.ts`, где смена
  // пояса действительно работает и где это подтверждено обратной
  // пробой механизма. Первая редакция этого файла содержала её здесь и
  // была театром — поймано обратной пробой, а не рассуждением.

  it('КЛЮЧЕВОЙ ТЕСТ: считается прошедшее ВРЕМЯ, а не разница календарных дней', () => {
    // Мутация «взять день из момента и вычесть дни» прошла первую
    // редакцию этого файла насквозь: в её сценариях календарная разница
    // совпадала с прошедшим временем. Здесь нарочно не совпадает —
    // между моментами два часа, а календарных дней между ними один.
    expect(daysAgo(new Date('2026-09-09T23:00:00.000Z'), new Date('2026-09-10T01:00:00.000Z'))).toBe('меньше суток назад');
    // И в другую сторону: почти двое суток внутри «одного календарного
    // дня разницы» остаются одними сутками, а не двумя.
    expect(daysAgo(new Date('2026-09-08T23:00:00.000Z'), new Date('2026-09-10T22:00:00.000Z'))).toBe('1 день назад');
    expect(deadlineRelative(new Date('2026-09-10T23:00:00.000Z'), new Date('2026-09-09T22:00:00.000Z'))).toBe('через 1 день');
  });

  it('истёкший срок называется истёкшим, а не отрицательным числом', () => {
    const now = new Date('2026-09-10T12:00:00.000Z');
    expect(deadlineRelative(new Date('2026-09-08T12:00:00.000Z'), now)).toBe('срок истёк 2 дня назад');
    expect(deadlineRelative(new Date('2026-09-10T06:00:00.000Z'), now)).toBe('срок истёк менее суток назад');
    expect(deadlineRelative(new Date('2026-09-10T23:00:00.000Z'), now)).toBe('срок истекает в течение суток');
  });

  it('русские формы числа не разъезжаются', () => {
    expect(plural(1, 'день', 'дня', 'дней')).toBe('день');
    expect(plural(2, 'день', 'дня', 'дней')).toBe('дня');
    expect(plural(5, 'день', 'дня', 'дней')).toBe('дней');
    expect(plural(11, 'день', 'дня', 'дней')).toBe('дней');
    // Весь второй десяток, а не только его начало: мутация «до 15»
    // прошла первую редакцию — проверены были 11 и 21, между ними никто
    // не смотрел.
    for (const n of [12, 13, 14, 15, 16, 17, 18, 19, 111, 114]) {
      expect(plural(n, 'день', 'дня', 'дней')).toBe('дней');
    }
    for (const n of [2, 3, 4, 22, 24, 104]) {
      expect(plural(n, 'день', 'дня', 'дней')).toBe('дня');
    }
    expect(plural(105, 'день', 'дня', 'дней')).toBe('дней');
    expect(plural(21, 'день', 'дня', 'дней')).toBe('день');
  });

  it('КЛЮЧЕВОЙ ТЕСТ: направление списка названо вслух, а не оставлено на догадку', () => {
    expect(orderLabel(0, 5, true)).toBe('1 из 5, 1 — самый недавний');
    expect(orderLabel(0, 5, false)).toBe('1 из 5, 1 — самый ранний');
    expect(orderLabel(4, 5, true)).not.toBe(orderLabel(4, 5, false));
  });

  it('момент с зоной называет и зону, и день по этой зоне', () => {
    // Независимость от зоны ПРОЦЕССА проверяется в автономном раннере —
    // здесь она была бы театром (см. заметку выше). Тут — что текст
    // вообще называет зону: без «UTC» рядом число снова становится
    // утверждением о календаре человека.
    const d = new Date('2026-09-09T22:14:00.000Z'); // 10-е по Киеву, 9-е по UTC
    expect(instantUtc(d)).toContain('UTC');
    expect(instantUtc(d)).toContain('9 сентября 2026');
    expect(instantUtc(d)).toContain('22:14');
  });
});
