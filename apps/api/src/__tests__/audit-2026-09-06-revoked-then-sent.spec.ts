// Сверка 2026-09-06 — отзыв согласия не догонял уже поставленную задачу.
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [not-checked-looks-clean] разбирал
// обещания о РЕЗУЛЬТАТЕ («не нашли» против «не смотрели»). Здесь —
// обещание о ДЕЙСТВИИ: «новых запросов от вашего имени больше не будет».
//
// ИЗМЕРЕНИЕ. Согласие на внешний AI проверяется в `prepareJob()` — при
// постановке задачи в очередь. Отправка провайдеру происходит в
// `submitQueued()`, и между ними:
//
//   • lease очереди — пятнадцать минут (QUEUED_LEASE_MS);
//   • `failOrRequeue()` возвращает задачу в QUEUED при транзиентной
//     ошибке, то есть окно продлевается КАЖДОЙ попыткой (до maxRetries);
//   • воркер разбирает очередь пачками по три.
//
// Всё это время `ConsentService.revoke()` не делал с задачами ничего:
// разбор его последствий ([consent-revocation] 2026-09-04) перечислил
// тринадцать типов согласия и для EXTERNAL_AI записал `alsoDoes: null` —
// «сверх пометки ничего». А текст, который читает человек, обещал
// БЕЗУСЛОВНО: «новых запросов от вашего имени больше не будет».
//
// ПОЧЕМУ ЭТО ХУЖЕ ОБЫЧНОГО НЕСООТВЕТСТВИЯ. Запрос, ушедший после отзыва,
// — это не задержавшийся результат старого разбора, а НОВАЯ передача
// данных человека наружу, сделанная после того, как он сказал «нет». И
// при рекью она буквально новая: тот же payload отправляется заново.
// Для задач с аудио — это ещё и файл голоса, у которого своя, отдельная
// тройка проверок.
//
// СДЕЛАНО ДВА ДЕЙСТВИЯ, И ОНИ НЕ ВЗАИМОЗАМЕНЯЕМЫ:
//
//   1. отзыв снимает QUEUED-задачи (их `pendingRequest` ещё никуда не
//      уходил) — это закрывает основную массу и даёт человеку честное
//      «сняты, к провайдеру не уйдут»;
//   2. воркер перепроверяет согласие у самого вызова — это закрывает
//      окно между выборкой задачи воркером и отправкой, которое отменой
//      не закрыть: задача уже забрана.
//
// RUNNING НЕ ТРОГАЕМ НАМЕРЕННО. Их содержимое провайдер уже видел.
// Отменять их значило бы делать вид, что отмена что-то там отменяет, —
// та же неправда, что и прежнее молчание, только зеркальная. Вместо
// этого о них сказано прямо в тексте отзыва.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Оба действия проверены там, где происходят:
// ai-router-async.spec.ts (провайдеру не ушло НИ ОДНОГО запроса; падение
// окончательное, не рекью; аудио отдельно от общего согласия) и
// audit-2026-09-04-consent-revocation.spec.ts (снимается QUEUED, не
// RUNNING и не чужое). Здесь — то, что иначе не выразить.

import { REVOCATION_EFFECTS } from '../consent/consent-revocation-effects';
import { ConsentType } from '@prisma/client';

describe('Сверка [revoked-then-sent]: отзыв догоняет очередь', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: обещание про внешний AI перестало быть безусловным', () => {
    const effect = REVOCATION_EFFECTS[ConsentType.EXTERNAL_AI];
    // Прежний текст кончался словами «новых запросов от вашего имени
    // больше не будет» — и это было неправдой для задачи, которую в тот
    // же миг уже отправляли.
    expect(effect.doesNotUndo).not.toMatch(/новых запросов от вашего имени больше не будет\.?$/);
    expect(effect.doesNotUndo).toContain('дойдёт до него');
    // И сверх пометки отзыв теперь действительно что-то делает.
    expect(effect.alsoDoes).not.toBeNull();
  });

  it('КЛЮЧЕВОЙ ТЕСТ: у каждого типа согласия обещание и последствие согласованы', () => {
    // Общее правило, а не заплата под один тип: если отзыв что-то
    // ДЕЛАЕТ, он обязан это назвать; и в любом случае обязан назвать,
    // чего он НЕ отменяет. Пустая строка здесь — молчание, а молчание
    // читается как «всё стёрли».
    for (const type of Object.values(ConsentType)) {
      const effect = REVOCATION_EFFECTS[type];
      expect([type, effect.doesNotUndo.length > 40]).toEqual([type, true]);
      if (effect.alsoDoes !== null) {
        expect([type, effect.alsoDoes.length > 20]).toEqual([type, true]);
      }
    }
  });
});
