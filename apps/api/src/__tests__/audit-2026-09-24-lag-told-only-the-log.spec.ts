// Сверка 2026-09-24 — отставание миграции знал только лог сервера.
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [operator-money-untraced] искал
// действия без следа. Здесь — СОСТОЯНИЕ без следа: продукт работает в
// урезанном режиме и знает об этом, а человек нет.
//
// ИЗМЕРЕНИЕ. В продукте есть механизм терпимости к неприменённой ручной
// миграции — семь мест. Написан он по верному правилу, и правило
// записано в его шапке: «пробел конфигурации не должен выглядеть как
// отказ функции». Код деградирует предсказуемо и пишет предупреждение.
//
// В ЛОГ СЕРВЕРА. И на этом всё.
//
// ДЛЯ ШЕСТИ МЕСТ ЭТО ЗАКОННО: отставание касается внутренней механики —
// атомарный забор вебхука, сторожевая по статусу задачи, выборка для
// чистки. Человек о ней не знает и знать не должен, а поведение с его
// стороны не меняется.
//
// СЕДЬМОЕ — ИСКЛЮЧЕНИЕ, и названо оно в собственном тексте
// предупреждения: снимок релевантности без колонки `notAssessed`
// теряет СПИСОК НЕПРОВЕРЕННЫХ КАНДИДАТОВ — «пропуски снова невидимы».
// Экран рисует блок «Не вошли в этот снимок» только при непустом
// списке, значит при отставании не рисует ничего, и снимок выглядит
// ПОЛНЫМ. Рекрутер по нему решает, с кем продолжать разговор.
//
// ПОЧЕМУ ЭТО ЗЕРКАЛО ТОГО ЖЕ ПРАВИЛА. Механизм писался против «пробел
// выглядит как ОТКАЗ». Здесь он сам породил «пробел выглядит как
// ПОЛНОТА» — форму, которой заняты полтора десятка сверок подряд. Для
// этого продукта вторая дороже первой: отказ человек видит, полноту —
// нет.
//
// И ЭТО НЕ УМОЗРИТЕЛЬНО. Миграция `pool_snapshot_not_assessed_2026_09_04`
// к этому дню всё ещё в списке неприменённых у владельца. То есть
// разобранное поведение — не «что было бы, если», а то, что происходит
// сейчас.
//
// ЧТО ОТСЮДА СНЯТО. Первая редакция проверяла, что в сервисе снимка
// ВСТРЕЧАЮТСЯ слова `migrationLagAt` и `pendingMigration`. Это чтение
// текста там, где рядом стои́т поведение: спек сервиса подсовывает базу
// без колонки и смотрит на возвращённую пометку. Сторож проверок
// сработал на превышении — и снялось именно это, а не потолок.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Исход проверен в
// interview-pool-relevance.service.spec.ts на настоящем сервисе: база
// отвечает P2022, список не сохраняется, и снимок возвращает пометку —
// а когда миграция применена, пометки нет.

import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';
import { migrationLagAt, markMigrationLag, resetMigrationLagForTests, warnMigrationLagOnce } from '../common/enum-migration-lag';

const SRC = join(__dirname, '..');

function tsFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : tsFiles(full);
    return name.endsWith('.ts') ? [full] : [];
  });
}

function code(path: string): string {
  return readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

describe('Сверка [lag-told-only-the-log]: урезанный режим виден не только в логе', () => {
  beforeEach(() => resetMigrationLagForTests());

  it('КЛЮЧЕВОЙ ТЕСТ: отметка ставится и читается, и до неё отметки нет', () => {
    // Обе стороны: правило, которое всегда говорит «деградировано», не
    // сторожит ничего — как и то, что всегда говорит «нет».
    expect(migrationLagAt('site.a')).toBeNull();
    markMigrationLag('site.a', 'x_2026.sql', 'последствие словами');
    expect(migrationLagAt('site.a')).toEqual({ migration: 'x_2026.sql', consequence: 'последствие словами' });
    // Соседнее место не задето: отметка адресная, а не глобальная.
    expect(migrationLagAt('site.b')).toBeNull();
  });

  it('КЛЮЧЕВОЙ ТЕСТ: предупреждение в лог одноразовое, а отметка живёт независимо', () => {
    // Мутация показала, что порядок двух строк внутри
    // `warnMigrationLagOnce` сам по себе ничего не держит — и это
    // честно записано там же, в комментарии. Держит другое: сброс
    // чистит ОБЕ памяти. Разойдись они, спек получил бы место, которое
    // деградировало и об этом молчит, — ровно ту пару, которую пункт и
    // разбирает, только в собственном инструменте.
    const logged: string[] = [];
    const logger = { warn: (m: string) => logged.push(m) };
    warnMigrationLagOnce(logger, 'site.c', 'm.sql', 'последствие');
    warnMigrationLagOnce(logger, 'site.c', 'm.sql', 'последствие');
    expect(logged).toHaveLength(1);
    expect(migrationLagAt('site.c')).not.toBeNull();

    resetMigrationLagForTests();
    expect(migrationLagAt('site.c')).toBeNull();
    // И предупреждение выдаётся заново — памяти сброшены вместе.
    warnMigrationLagOnce(logger, 'site.c', 'm.sql', 'последствие');
    expect(logged).toHaveLength(2);
    expect(migrationLagAt('site.c')).not.toBeNull();
  });

  it('остальные места терпимости не обязаны сообщать — и это названо, а не забыто', () => {
    // Шесть мест про внутреннюю механику. Проверяется не то, что они
    // молчат, а то, что их ровно столько, сколько разобрано: новое
    // место уронит сверку, и его придётся отнести к одному из двух
    // родов сознательно.
    const users = tsFiles(SRC).filter(
      (f) => !f.endsWith('enum-migration-lag.ts') && /warnEnumMigrationLagOnce\(|warnMigrationLagOnce\(/.test(code(f)),
    );
    expect(users.length).toBe(6);
  });
});
