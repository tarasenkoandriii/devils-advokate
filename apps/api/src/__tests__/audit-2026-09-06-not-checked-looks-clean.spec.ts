// Сверка 2026-09-06 — «не проверено» выглядело как «проверено, чисто».
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [delete-says-done] закрыл вопрос
// «сказали, что удалили» против «удалили». Тот же вопрос на шаг раньше:
// «сказали, что не нашли» против «искали».
//
// ИЗМЕРЕНИЕ. По дереву API 7 обработчиков ошибок не оставляют наружу
// никакого признака неудачи. Пятеро из них безобидны (комментарий,
// запись шага в отчёт, NotFound → null). Двое — нет, и один из двух
// стоит под самой дорогой проверкой продукта.
//
// НАЙДЕННОЕ — И ПОЧЕМУ ЭТО РАСХОЖДЕНИЕ, А НЕ ПРОСТО ПРОБЕЛ. Продукт
// проверяет на защищённые признаки ТРИ текста, одним и тем же разбором:
//
//   • бриф заказчика       — при сбое AI бросает BadGateway → человек знает;
//   • текст вакансии       — при сбое AI бросает из `this.ai`  → человек знает;
//   • дебриф интервьюера   — при сбое AI ГЛОТАЛ и отдавал `complianceFlags: 0`.
//
// То есть правило в продукте БЫЛО — просто не везде, и отсутствовало
// ровно там, где цена выше: дебриф пишет живой человек о живом человеке,
// и речь о признаках, по которым отбирать нельзя. Сверх того ветка
// `if (config)` молча пропускалась целиком: без конфигурации проверки
// ответ был тот же ноль. Это буквально «конфигурационный пробел выглядит
// как отсутствие находок» — принцип, записанный в основании продукта.
//
// ПОЧЕМУ ЭТО НЕ ПОЙМАЛА СВЕРКА [failure-looks-empty] 2026-09-05. Та
// закрывала ЭКРАННУЮ половину: `catch` на клиенте ставил пустой список и
// молчал. Здесь клиентский `catch` не срабатывает вовсе — сервер отвечает
// 200 и честным с виду нулём. Половины две, и вторая была не осмотрена.
//
// ПОЧЕМУ НЕ БРОСАЕМ, КАК У СОСЕДЕЙ. В дебрифе к моменту проверки уже
// созданы черновики позиций. Уронить ответ из-за не удавшейся побочной
// проверки — значит потерять сделанную человеком работу. Решение то же,
// что в [delete-says-done]: не бросать, но сказать.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Сами исходы проверяются там, где они происходят:
// hiring-extras.service.spec.ts (сбой провайдера / нет конфига / удачная
// проверка не помечается), vacancy-intake.service.spec.ts (синонимы),
// tma/skipped-note.spec.ts (формулировка и разметка). Здесь — то, что
// иначе не выразить: что правило теперь ОДНО на все три текста.

import { readFileSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function code(rel: string): string {
  return readFileSync(join(SRC, rel), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

describe('Сверка [not-checked-looks-clean]: ноль без проверки ничего не утверждает', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: ни один compliance-разбор не отвечает молчаливым нулём', () => {
    // Три текста, один разбор, три файла. Каждый обязан ЛИБО бросить,
    // либо назвать причину — третьего («тихо ноль») быть не должно.
    const paths = [
      'client-brief/client-brief.service.ts',
      'vacancy-posting/vacancy-posting.service.ts',
      'hiring-extras/hiring-extras.service.ts',
    ];
    for (const rel of paths) {
      const src = code(rel);
      const говорит = /NotChecked|BadGatewayException/.test(src);
      expect([rel, говорит]).toEqual([rel, true]);
    }
  });

  it('КЛЮЧЕВОЙ ТЕСТ: обработчик, гасивший сбой дебрифа, больше не пуст', () => {
    const src = code('hiring-extras/hiring-extras.service.ts');
    // Прежний вид: `catch` с одной строкой-охранником и ничем больше —
    // ошибка проваливалась в ноль. Проверяется форма ПОСЛЕДСТВИЯ, а не
    // слово: любой обработчик рядом с compliance-разбором обязан что-то
    // записать наружу.
    const catches = [...src.matchAll(/catch\s*\([^)]*\)\s*\{([^{}]*)\}/g)].map((m) => m[1].trim());
    // Пункт [the-empty-scan-was-green] 2026-10-02: без этой строки
    // правило зеленело бы от переписанного `catch` в другом стиле —
    // разбор не нашёл бы НИ ОДНОГО блока, список немых оказался бы пуст,
    // и «немых нет» означало бы «я ничего не разобрал».
    expect(catches.length).toBeGreaterThanOrEqual(2);
    const НЕМОЙ = /instanceof ForbiddenException\) throw err;$/;
    const немые = catches.filter((body) => НЕМОЙ.test(body));
    expect(немые).toEqual([]);
  });

  it('ОБРАТНАЯ ПРОБА: тот же признак немоты ловится на образце', () => {
    // Иначе пустой список выше означал бы не порядок, а признак,
    // который не срабатывает ни на чём.
    const НЕМОЙ = /instanceof ForbiddenException\) throw err;$/;
    expect(НЕМОЙ.test('if (err instanceof ForbiddenException) throw err;')).toBe(true);
    // А обработчик, который что-то записывает наружу, немым не считается.
    expect(НЕМОЙ.test('if (err instanceof ForbiddenException) throw err;\n      this.logger.warn(err);')).toBe(false);
    expect(code('hiring-extras/hiring-extras.service.ts').length).toBeGreaterThan(0);
  });

  it('признак не выдумывается на месте: словарь причин один на весь API', () => {
    const vocab = code('common/not-checked.ts');
    expect(vocab).toContain('not-configured');
    expect(vocab).toContain('provider-failed');
  });
});
