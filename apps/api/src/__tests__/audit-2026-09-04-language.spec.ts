// Сверка языка 2026-09-04 — на каком языке продукт говорит с человеком.
//
// Что нашлось при измерении:
//   • лендинг переведён по-настоящему: три локали (en/uk/ru), словари,
//     переключатель, определение по стране в middleware, дефолт — `en`;
//   • само приложение (TMA) не знает ни одной локали: 531 строка зашита
//     по-русски, механизма выбора языка нет вообще;
//   • сервер отвечал на двух языках сразу — 28 текстов исключений были
//     украинскими внутри полностью русского интерфейса.
//
// То есть человек, пришедший с лендинга (по умолчанию английского),
// открывает приложение и видит русский; а в некоторых доменах сервер
// отвечал ему по-украински. При этом язык человека приложению ИЗВЕСТЕН —
// `User.languageCode` приходит из Telegram, сохраняется при каждом входе и
// используется ровно в двух местах: язык ответа модели и выбор
// STT-провайдера. На то, что продукт ГОВОРИТ человеку, он не влияет никак.
//
// Что 28 сообщений были случайностью, а не решением, видно по ним самим:
// «Транскрипт цієї консультації ще порожній — НЕЧЕГО аналізувати», «Це
// посилання СОИСКАТЕЛЯ» — русские слова внутри украинских фраз. Никто не
// решал, что эти экраны говорят по-украински; так осталось от прохода, в
// котором домены писались.
//
// Этот тест держит ОДНО правило: то, что сервер говорит человеку, звучит
// на одном языке — на языке интерфейса. Он не решает, какой язык у
// продукта правильный (это решение владельца, и полноценная многоязычность
// — отдельная работа, см. TODO.md), он лишь не даёт смеси вернуться
// незаметно.

import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';

const API_SRC = join(__dirname, '..');
const TMA_SRC = join(__dirname, '..', '..', '..', 'tma', 'src');

/** Буквы, которых нет в русском алфавите. Обратное направление (русские
 * ъ/ы/э в украинском тексте) здесь не проверяется: интерфейс русский, и
 * появление русской буквы — это норма, а не смесь. */
const UKRAINIAN_ONLY = /[іїєґІЇЄҐ]/;

/** Собственные имена украинских реестров и норм: они остаются на языке
 * оригинала в любом интерфейсе — как «Bundesbank» не переводят. */
const PROPER_NOUNS = /ЄДРПОУ|РНОКПП|Дія|Прозорро/;

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === '__tests__' || name === 'node_modules' || name === '.next') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith('.ts') || p.endsWith('.tsx')) out.push(p);
  }
  return out;
}

/** Строки, которые уходят человеку: тексты исключений. Остальное
 * (промпты модели, комментарии, названия задач) сюда не входит — промпт
 * читает модель, а язык ЕЁ ответа задаётся отдельно, из `languageCode`. */
function userFacingMessages(file: string): string[] {
  const src = readFileSync(file, 'utf8');
  const out: string[] = [];
  for (const line of src.split('\n')) {
    const trimmed = line.trim();
    if (trimmed.startsWith('//') || trimmed.startsWith('*')) continue;
    if (!/Exception\(/.test(line)) continue;
    for (const m of line.matchAll(/'([^'\n]{6,})'|"([^"\n]{6,})"/g)) {
      out.push(m[1] ?? m[2]);
    }
  }
  return out;
}

describe('Язык: сервер говорит с человеком на одном языке', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: ни одно сообщение об ошибке не написано на языке, отличном от языка интерфейса', () => {
    const offenders: string[] = [];
    for (const file of walk(API_SRC)) {
      for (const message of userFacingMessages(file)) {
        if (!UKRAINIAN_ONLY.test(message)) continue;
        if (PROPER_NOUNS.test(message)) continue; // название реестра — не перевод
        offenders.push(`${file.slice(API_SRC.length + 1)}: ${message.slice(0, 70)}`);
      }
    }
    expect(offenders).toEqual([]);
  });

  it('проверке есть что проверять: сообщений об ошибках в проекте много', () => {
    // Иначе тест выше проходил бы просто потому, что regexp ничего не
    // находит — ровно тот способ самообмана, который ловила мутационная
    // сверка.
    const total = walk(API_SRC).reduce((n, f) => n + userFacingMessages(f).length, 0);
    expect(total).toBeGreaterThan(300);
  });

  it('ИЗМЕРЕНИЕ (не требование): приложение по-прежнему одноязычное, и это записано в TODO.md', () => {
    // Тест намеренно фиксирует ФАКТ, а не запрещает его: полноценная
    // многоязычность — работа со словарём и дисциплиной перевода, не
    // сверка. Если однажды в TMA появится механизм локалей, этот тест
    // упадёт и заставит переписать запись в TODO.md — то есть документация
    // не разойдётся с кодом молча.
    const hasLocaleLayer = walk(TMA_SRC).some((f) => /i18n|useLocale|dictionaries/.test(f));
    expect(hasLocaleLayer).toBe(false);
  });
});
