// Сверка разрушающих действий 2026-09-04 — до чего человек может
// дотянуться, а до чего только сервер.
//
// НАЙДЕНО.
//
// 1. ГЛАВНОЕ: `DELETE /projects/:id` существовал, был закрыт проверкой
//    владения и с Пункта [project-deletion] возвращал честный список
//    того, что переживает удаление, — и его НЕ ЗВАЛ НИ ОДИН ЭКРАН.
//    Человек, желавший убрать один проект, мог только удалить весь
//    аккаунт. Экран приватности при этом прямо сообщал: «Удаление
//    отдельного проекта — на его странице». Указание на кнопку, которой
//    нет, хуже её отсутствия: оно закрывает вопрос — человек не ищет
//    дальше, он считает, что просто не туда посмотрел.
//
//    Это не «мёртвый код»: маршрут работает, права проверяет, отвечает
//    осмысленно. Мёртвой была ДОРОГА к нему.
//
// 2. ПОПУТНО, И ЭТО ПРО САМИ СВЕРКИ. В списке «что переживает удаление
//    проекта» нашлась ЧЕТВЁРТАЯ копия фразы «Журнал аудита — хранится
//    без персональных данных» — того самого утверждения, которое Пункт
//    [audit-trail] в тот же день нашёл неверным и исправил. Исправил в
//    трёх местах: тест, который должен был это держать, читал ОДИН файл
//    (privacy-center.service.ts), и копия в projects.service.ts правку
//    пережила. Сторож, суженный до одного файла, отчитывается за весь
//    дом. Проверка расширена на весь исходник API.
//
// ЧЕСТНАЯ ГРАНИЦА ЭТОГО ЗАХОДА. Сплошную сверку «маршрут есть — клиента
// нет» по всем 691 маршруту сделать не удалось: доменные экраны строят
// пути динамически (`/${domain}/projects`), и наивный разбор дал 289
// «неиспользуемых» маршрутов, из которых подавляющее большинство —
// ложные срабатывания. Числу, которое нельзя защитить, здесь не место.
// Поэтому проверка сужена до РАЗРУШАЮЩИХ маршрутов (@Delete): их восемь,
// каждый разобран поимённо, и именно там цена молчания наибольшая.

import { readdirSync, readFileSync, statSync } from 'fs';
import { join, relative } from 'path';

const API_SRC = join(__dirname, '..');
const TMA_SRC = join(__dirname, '..', '..', '..', 'tma', 'src');
const ADMIN_SRC = join(__dirname, '..', '..', '..', 'admin', 'src');

function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

function walk(dir: string, ext: string[]): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : walk(full, ext);
    return ext.some((e) => name.endsWith(e)) ? [full] : [];
  });
}

/** Разрушающие маршруты API: контроллер + путь. */
function deleteRoutes(): Array<{ route: string; file: string }> {
  const found: Array<{ route: string; file: string }> = [];
  for (const file of walk(API_SRC, ['controller.ts'])) {
    const src = stripComments(readFileSync(file, 'utf8'));
    for (const block of src.matchAll(/@Controller\(\s*(?:'([^']*)')?\s*\)([\s\S]*?)(?=@Controller\(|$)/g)) {
      const prefix = (block[1] ?? '').replace(/^\/|\/$/g, '');
      for (const m of block[2].matchAll(/@Delete\(\s*(?:'([^']*)')?\s*\)/g)) {
        const path = (m[1] ?? '').replace(/^\/|\/$/g, '');
        found.push({ route: '/' + [prefix, path].filter(Boolean).join('/'), file: relative(API_SRC, file) });
      }
    }
  }
  return found;
}

/** Разрушающие маршруты, которые человек вызвать не может и не должен —
 * с причиной. Пустой список означал бы «все восемь доступны из
 * интерфейса»; сейчас это так и есть, и запись здесь появится только
 * вместе с осознанным решением. */
const SERVER_ONLY_DELETES: Record<string, string> = {};

describe('Разрушающие действия: до чего человек может дотянуться', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: каждый маршрут удаления вызывается из клиента или назван серверным', () => {
    // «Маршрут есть, кнопки нет» — не мёртвый код (маршрут работает и
    // права проверяет), а мёртвая ДОРОГА к нему. Снаружи это выглядит
    // как отсутствующая возможность, и человек об этом не узнаёт.
    const client = [...walk(TMA_SRC, ['.ts', '.tsx']), ...walk(ADMIN_SRC, ['.ts', '.tsx'])]
      .map((f) => readFileSync(f, 'utf8'))
      .join('\n');

    const unreachable: string[] = [];
    for (const { route, file } of deleteRoutes()) {
      if (SERVER_ONLY_DELETES[route]) continue;
      // Путь клиента — шаблонная строка: параметр маршрута (`:personId`)
      // соответствует подстановке (`${personId}`), литеральные сегменты
      // обязаны совпасть буквально. Первая версия склеивала только
      // литералы подряд и потому не узнавала
      // `/projects/:projectId/people/:personId` в клиентском
      // `/projects/${projectId}/people/${personId}` — проверка объявляла
      // недостижимым маршрут, который вызывается с двух экранов.
      const pattern = route
        .split('/')
        .filter(Boolean)
        .map((s) => (s.startsWith(':') ? '[^/`\'"]+' : s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
        .join('/');
      // Конец пути обязан совпасть тоже: без этого `/projects/:id`
      // «находился» в вызове `/projects/${projectId}/people/${personId}`
      // — совсем другого маршрута. Проверено мутацией: снятие вызова
      // удаления проекта проходило незамеченным.
      // 2026-09-05 (пункт [public-name]): у публичного клиента другая
      // форма вызова — `publicReq('/path', 'DELETE', …)`, без обёртки
      // `apiDelete`. Проверка её не знала и не увидела бы НИ ОДНОГО
      // удаления на публичной поверхности — то есть была слепа ровно
      // там, где права человека тоньше всего. Слепое пятно закрыто.
      const called =
        new RegExp(`(api|admin)Delete[^(]*\\(\\s*[\`'"]/${pattern}[\`'"]`).test(client) ||
        new RegExp(`publicReq[^(]*\\(\\s*[\`'"]/${pattern}[\`'"]\\s*,\\s*'DELETE'`).test(client);
      if (!called) unreachable.push(`${route} (${file})`);
    }
    expect(unreachable).toEqual([]);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: удаление проекта доступно с его страницы и показывает, что переживает удаление', () => {
    const section = readFileSync(join(TMA_SRC, 'components', 'ProjectDeletionSection.tsx'), 'utf8');
    // Подтверждение в два шага — разрушающее действие не должно
    // срабатывать с первого касания.
    expect(section).toMatch(/confirming/);
    expect(section).toMatch(/Отменить это нельзя/);
    // Список того, что остаётся, приходит с сервера с Пункта
    // [project-deletion]. Если клиент его выбросит, вся та работа станет
    // невидимой — честность, которую никто не читает, равна её отсутствию.
    // Проверяется РЕНДЕР, а не упоминание: первая версия искала слово
    // `notRemovedHere` в файле, и мутация «показывать пустой список»
    // проходила мимо неё.
    expect(section).toMatch(/notRemovedHere\.map\(/);

    const page = readFileSync(join(TMA_SRC, 'app', 'projects', '[id]', 'page.tsx'), 'utf8');
    // Опять же — использование, а не импорт: снятие раздела со страницы
    // оставляло импорт на месте и проверку не роняло.
    expect(page).toMatch(/<ProjectDeletionSection\b/);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: экран приватности больше не указывает на кнопку, которой нет', () => {
    const privacy = stripComments(readFileSync(join(TMA_SRC, 'app', 'privacy', 'page.tsx'), 'utf8'));
    expect(privacy).toContain('Удаление отдельного проекта');
    // Фраза осталась — она стала правдой; проверяется, что рядом есть
    // путь к действию, а не только упоминание о нём.
    expect(privacy).toMatch(/Удалить проект/);
  });

  it('удаление проекта по-прежнему перечисляет, что переживает удаление — и без неверного утверждения', () => {
    const src = stripComments(readFileSync(join(API_SRC, 'projects', 'projects.service.ts'), 'utf8'));
    expect(src).toContain('notRemovedHere');
    // Четвёртая копия неверной фразы жила именно здесь.
    expect(src).not.toContain('Журнал аудита — хранится без персональных данных');
  });

  it('ИЗМЕРЕНИЕ: сколько разрушающих маршрутов у API', () => {
    // Число живёт здесь, чтобы следующая сверка начинала с факта.
    // Появление нового @Delete без дороги к нему поймает первый тест;
    // это — про сам масштаб.
    // 2026-09-05: стало девять. Прибавился DELETE записи о человеке
    // (пункт [no-correction]): до него запись можно было только создать и
    // прочитать, при том что три сервиса ветвились на состояния, которые
    // никто не мог выставить. Число обновлено осознанно — эта проверка
    // ровно для того и стоит, чтобы новый разрушающий маршрут был замечен
    // человеком, а не проехал молча.
    // 2026-09-05: стало одиннадцать. Пункт [public-name] добавил
    // участнику публичного обсуждения право забрать своё — комментарий и
    // нерассмотренную заявку. До него у пришедшего по ссылке не было НИ
    // ОДНОГО способа убрать написанное. Число обновлено осознанно.
    const routes = deleteRoutes();
    expect(routes.length).toBe(11);
    expect(Object.keys(SERVER_ONLY_DELETES)).toHaveLength(0);
  });
});
