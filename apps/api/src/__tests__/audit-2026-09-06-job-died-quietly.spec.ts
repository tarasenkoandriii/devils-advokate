// Сверка 2026-09-06 — фоновая задача умирала тихо.
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [revoked-then-sent] закрыл окно
// между постановкой задачи в очередь и её отправкой. Здесь — другой
// конец той же очереди: что остаётся человеку, когда задача НЕ дошла.
//
// ИЗМЕРЕНИЕ. Обработчиков завершения у роутера три, и они расходились:
//
//   медиа-разбор      — failed → `autoAnalysisError` + откат статуса
//                       разговора. Человек узнаёт, и даже с подсказкой,
//                       почему так бывает;
//   пакетная сверка   — failed → `matchNotes` + снятие `batchMatchJobId`.
//                       Человек узнаёт;
//   паралингвистика   — failed → `logger.warn`. И БОЛЬШЕ НИЧЕГО.
//
// Правило сформулировано в самом продукте — `turning-points.service.ts`
// пишет прямым текстом: «Статус откатывается на TRANSCRIBED (не остаётся
// в ANALYZING навсегда) — тот же принцип, что AIRouterService откатывает
// AIJob в FAILED при исключении». То есть правило было; не было его у
// одного обработчика из трёх.
//
// НАЙДЕНО ТРИ МЕСТА.
//
// 1. ПАРАЛИНГВИСТИКА, ПРОВАЛ. Экран рисует блок «Подача» только при
//    непустом списке отметок — значит при провале не появлялось НИЧЕГО.
//    Человек, включивший галочку «паузы, темп, несовпадение слов и
//    интонации», не видел отметок и заключал, что их нет.
//
// 2. ПАРАЛИНГВИСТИКА, ОТБРОШЕННОЕ. Модель сослалась на несуществующие
//    реплики — сигналы пропускаются (верно: полный отказ выбросил бы и
//    валидные), но число уходило в лог и никуда больше. При том что ВЕСЬ
//    механизм `skippedWithoutQuote` в проекте существует ровно затем,
//    чтобы такое число доходило до человека.
//
// 3. ПАКЕТНАЯ СВЕРКА, ТРЕТИЙ ВЫХОД. У обработчика три выхода. Ветка
//    `failed` снимала `batchMatchJobId` — правильно. Ветка разбора при
//    ошибке JSON писала только в лог, и поле оставалось заполненным. А
//    матрица считает `queued: !!batchMatchJobId` и печатает «· в
//    очереди». Джоба у роутера уже COMPLETED, обработчик больше никто не
//    позовёт — строка говорила «в очереди» НАВСЕГДА. Ожидание без
//    выхода: худшая форма молчания, потому что человек не просто не
//    знает — он знает НЕВЕРНОЕ и ждёт.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Исходы проверены там, где происходят:
// paralinguistics.spec.ts (провал оставляет след; удачный проход
// СНИМАЕТ прошлую ошибку и число; причина обрезается, но не теряется),
// vacancy-intake.service.spec.ts (ожидание кончается, заметка не выдаёт
// пустоту за результат), tma/skipped-note.spec.ts (формулировки и
// разметка). Здесь — то, что иначе не выразить: правило стало общим.

import { readFileSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function code(rel: string): string {
  return readFileSync(join(SRC, rel), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Все обработчики завершения асинхронных задач роутера. Список, а не
 * обход дерева: их регистрация — одна строка `registerCompletionHandler`,
 * и она проверяется отдельным утверждением ниже, чтобы новый обработчик
 * нельзя было завести мимо этой сверки. */
const HANDLERS = [
  'conversations/paralinguistics.service.ts',
  'media-review/media-review-auto.service.ts',
  'vacancy-intake/job-search-tools.service.ts',
];

describe('Сверка [job-died-quietly]: провал фоновой задачи оставляет след', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: ни один обработчик не отвечает на провал одним логом', () => {
    for (const rel of HANDLERS) {
      const src = code(rel);
      // Признак по последствию: рядом с разбором исхода должна стоять
      // ЗАПИСЬ в базу, а не только строка в журнал сервера. Журнал
      // читаем мы, а утверждение на экране читает человек.
      const пишетВБазу = /kind === 'failed'[\s\S]{0,900}?prisma\.\w+\.update/.test(src) ||
        /else \{[\s\S]{0,600}?prisma\.\w+\.update/.test(src);
      expect([rel, пишетВБазу]).toEqual([rel, true]);
    }
  });

  it('КЛЮЧЕВОЙ ТЕСТ: список обработчиков в этой сверке полон', () => {
    // Иначе правило сторожит ровно те файлы, которые уже исправлены, —
    // ошибка, которую эта сессия ловила у себя четырежды.
    const registrations: string[] = [];
    for (const rel of [...HANDLERS, 'ai-router/ai-router.service.ts']) {
      if (/registerCompletionHandler\(\s*[A-Z_]/.test(code(rel))) registrations.push(rel);
    }
    expect(registrations.sort()).toEqual([...HANDLERS].sort());
  });

  it('КЛЮЧЕВОЙ ТЕСТ: маркер ожидания снимается на КАЖДОМ выходе обработчика сверки', () => {
    const src = code('vacancy-intake/job-search-tools.service.ts');
    const handler = src.slice(src.indexOf('onBatchOutcome'), src.indexOf('async matrix'));
    // Выходов три (failed, разобрано, не разобрано) — снятий поля
    // должно быть столько же. Раньше их было два.
    const снятий = (handler.match(/batchMatchJobId: null/g) ?? []).length;
    expect(снятий).toBe(3);
  });
});
