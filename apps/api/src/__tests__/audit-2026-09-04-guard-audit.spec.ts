// Сверка самих проверок 2026-09-04 — насколько сторожа сторожат.
//
// ПОЧЕМУ ЭТОТ ЗАХОД ВООБЩЕ СОСТОЯЛСЯ. За день до него две сверки подряд
// закончились одинаково: мутационная проверка ловила меньше половины
// правок, и оба раза по одной причине — проверка была написана НА
// УПОМИНАНИЕ, а не на поведение. «В файле есть слово `take`». «В файле
// есть `notRemovedHere`». Такие проверки зелены и тогда, когда защищаемое
// ими свойство исчезло. Два совпадения — уже повод проверить весь класс,
// а не ждать третьего.
//
// ЧТО ИЗМЕРЕНО. Исходники как текст читают 14 спеков; текстовые
// утверждения (`toContain` / `toMatch` по прочитанному файлу) есть в
// девяти из них, всего 53 на момент начала захода (60 после правок —
// закрытие дыр добавило проверок). По ним прогнан один и тот же вид
// мутации: СОХРАНИТЬ СЛОВО, УБИТЬ ПОВЕДЕНИЕ. Одиннадцать мутаций, семь
// не пойманы:
//
//  1. `take: DISPATCH_BATCH` на месте, константа поднята до 1 000 000 —
//     потолок остался словом. НЕ ПОЙМАН.
//  2. `invented++` в файле есть, но обёрнут в `if (false)` — счётчик
//     потерянных находок не считает. НЕ ПОЙМАН.
//  3. `data: input` переписано в `data: { ...input }` — дыра та же,
//     форма другая. НЕ ПОЙМАН.
//  4. У публичной поверхности стёрта причина, запись осталась — реестр
//     превратился в список имён. НЕ ПОЙМАН.
//  5. «Что сломается без этой крон-задачи» заменено отпиской «Задача не
//     выполняется, требуется применить файл» — длиннее тридцати символов
//     и бесполезно. НЕ ПОЙМАН.
//  6. Причина исключения из выгрузки заменена на «Не выгружается».
//     ПОЙМАН (проверка требовала конкретных слов).
//  7. Сбой строки в сторожевой логируется, но не считается. ПОЙМАН.
//  8. Связь осталась в реестре выгрузки, но выпала из `include`. ПОЙМАН.
//  9. `humanizeApiError` возвращает исходную строку. Спеками API НЕ
//     ПОЙМАН, набором TMA — ПОЙМАН (поведенческий тест там есть).
// 10. Маркер «стёрто» превращён в пустую строку — тесты сравнивали
//     результат С САМОЙ КОНСТАНТОЙ и потому прошли все. НЕ ПОЙМАН.
// 11. «Чего отзыв не отменяет» заменено на «Ничего дополнительно не
//     отменяется этим действием». НЕ ПОЙМАН.
//
// ЧТО СДЕЛАНО. Семь непойманных закрыты там, где живут: потолки
// проверяются как ЧИСЛА у своих объявлений; счётчик потерянных находок
// — поведенческим тестом с перехватом логгера; `data: { ...input }`
// добавлен в проверку; реестры требуют объяснения, а не только записи;
// пустые формулы («Задача не выполняется…», «Ничего…») запрещены прямо;
// маркер «стёрто» проверяется отдельно от кода, который им пользуется.
// После правок все одиннадцать мутаций пойманы.
//
// ЧЕГО ЭТОТ ЗАХОД НЕ УМЕЕТ И НЕ БУДЕТ. Качество текста тестом не
// проверяется — можно запретить конкретные пустые формулы, но нельзя
// потребовать, чтобы объяснение было хорошим. Это записано в самих
// проверках рядом с запретами, чтобы следующий читатель не принял
// «формула не в списке» за «объяснение осмысленно».
//
// И ГЛАВНОЕ, РАДИ ЧЕГО ЗАПИСЬ ОСТАЁТСЯ. Конвенционная проверка по тексту
// исходника — законный и дешёвый инструмент, отказываться от него не
// нужно. Но у него есть свойство, которое легко забыть: он подтверждает
// НАЛИЧИЕ СЛОВА. Если инвариант можно выразить числом, поведением или
// перехватом — так и надо; текстовая проверка остаётся для того, что
// иначе не выразить, и тогда её саму обязана проверить мутация.

import { readdirSync, readFileSync } from 'fs';
import { join } from 'path';

const TESTS_DIR = __dirname;

function textAssertionStats(): { specs: number; assertions: number } {
  let specs = 0;
  let assertions = 0;
  for (const name of readdirSync(TESTS_DIR)) {
    if (!name.endsWith('.spec.ts')) continue;
    const src = readFileSync(join(TESTS_DIR, name), 'utf8');
    if (!src.includes('readFileSync')) continue;
    const found = src.match(/expect\([^)]*\)\.(?:not\.)?(?:toContain|toMatch)\(/g);
    if (!found) continue;
    specs++;
    assertions += found.length;
  }
  return { specs, assertions };
}

describe('Сверка самих проверок: сторож, который сторожит слово', () => {
  it('ИЗМЕРЕНИЕ: сколько проверок опираются на текст исходника', () => {
    // Число живёт здесь, чтобы следующая сверка начинала с факта.
    // Рост сам по себе не дефект: текстовая проверка законна там, где
    // инвариант иначе не выразить. Дефект — когда она стоит там, где
    // можно было проверить число или поведение.
    const { specs, assertions } = textAssertionStats();
    expect(specs).toBeGreaterThanOrEqual(8);
    expect(assertions).toBeGreaterThan(40);
    /** ПОТОЛОК ПОДНЯТ 2026-09-06, Пункт [export-user-scope] — и вот что
     * было сделано ПРЕЖДЕ, чем его поднимать.
     *
     * Потолок 200 сработал: три сверки подряд довели счёт до 211. Это
     * и есть работа этой проверки — заставить посмотреть. Посмотрели:
     * из трёх новых сверок убраны ДЕСЯТЬ текстовых утверждений, у
     * которых уже был поведенческий двойник (вектор отпечатка и ключи
     * самошеринга проверяются на реальном ответе `exportData()`;
     * повторный отзыв оффера и случай нуля копий — через сервис). Счёт
     * стал 201, и остаток — законный: сверка двух ИСХОДНИКОВ между
     * собой (серверный `select` против интерфейса экрана), проверки
     * текста на экранах, где рантайма в этих тестах нет, и правила «в
     * коде не осталось такой-то дописи».
     *
     * ИЗВЕСТНАЯ ПОГРЕШНОСТЬ ИЗМЕРЕНИЯ, названная, а не исправленная
     * подгонкой: счётчик берёт любой `toContain`/`toMatch` в файле, где
     * есть `readFileSync`, — включая `expect(массив).toContain(поле)`,
     * который к тексту исходника отношения не имеет. То есть настоящая
     * опора на текст МЕНЬШЕ 201. Точнее отличить регуляркой нельзя, а
     * ослаблять сам инструмент, чтобы пройти его же потолок, — ровно
     * то, против чего он стоит. Поэтому инструмент оставлен как есть, а
     * погрешность записана здесь. */
    /** ПОТОЛОК ПОДНЯТ ВТОРОЙ РАЗ, 2026-09-06, Пункт
     * [forecast-without-source] — и снова ПОСЛЕ работы, а не вместо
     * неё. Счёт дошёл до 231; убраны четыре текстовых утверждения, у
     * которых появился поведенческий двойник (подпись автора прогноза
     * сверяется на сохранённой строке, половинчатый ответ — на
     * настоящем промпте). Счёт 227.
     *
     * ЧТО ЭТО ЗНАЧИТ НА ДАЛЬШЕ, чтобы следующая сверка не начинала с
     * нуля: у счёта есть ПОСТОЯННЫЙ ПОЛ, и он растёт с каждым экраном.
     * Проверки текста экранов TMA (.tsx) иначе не выразить — в этом
     * процессе их нечем выполнить, рантайма у них здесь нет; то же с
     * содержимым ручных миграций (.sql). Такие утверждения не дефект и
     * убыть не могут. Дефект — текстовая проверка там, где есть
     * поведение; ровно её и надо искать при каждом срабатывании
     * потолка, а не сокращать число ради числа. */
    /** ПОТОЛОК ПОДНЯТ ТРЕТИЙ РАЗ, 2026-09-06, Пункт [scope-not-applied]
     * — и снова только после работы.
     *
     * Сделано ДВАЖДЫ за одну сверку. Первое: проверка «образец зовёт
     * общий помощник» переведена на поведение — steelman.service.spec.ts
     * прогоняет реальный сервис с фактом чужого проекта и с фактом
     * PRIVATE_TO_USER и смотрит, что ни один не дошёл до промпта.
     * Второе: файл сверки РАЗДЕЛЁН НА ДВА — правила на данных
     * (`toContain` по массиву разрешённых значений) отделены от правил
     * на тексте исходника. Это не обход инструмента, а исправление его
     * измерения: он считает по файлу, и проверки на данных, лежащие
     * рядом с `readFileSync`, завышали счёт, не опираясь ни на какой
     * текст. Погрешность была названа в этом же комментарии двумя
     * сверками раньше — теперь она ещё и уменьшена там, где это честно.
     *
     * Остаток — тот самый ПОСТОЯННЫЙ ПОЛ: проверки текста экранов TMA
     * и содержимого ручных миграций, у которых в этом процессе нет
     * рантайма. Их не убудет, и сокращать число ради числа не нужно. */
    /** ПОТОЛОК ПОДНЯТ ЧЕТВЁРТЫЙ РАЗ, 2026-09-24, Пункт
     * [log-says-we-saw-it] — и снова ТОЛЬКО ПОСЛЕ РАБОТЫ.
     *
     * Счёт дошёл до 258. Сделано, в этом порядке:
     *
     * 1. Файл сверки разделён на два — правила о СЛОВАРЕ (утверждения по
     *    массиву имён действий) отделены от правил по тексту дерева. Та
     *    же мера, что в [scope-not-applied], и по той же причине: она
     *    исправляет ИЗМЕРЕНИЕ, а не обходит инструмент.
     *
     * 2. И тут же обнаружилось третье проявление той самой погрешности,
     *    которую этот сторож охраняет. Разделение счёт не уменьшило, а
     *    УВЕЛИЧИЛО — 258 стало 260. Причина: новый файл, не читающий ни
     *    одного исходника, назвал имя функции чтения ДОСЛОВНО в своём
     *    объяснительном комментарии. Сторож ищет это имя по тексту файла
     *    и не отличает вызов от упоминания. Имя из комментария убрано —
     *    счёт 256.
     *
     *    Записано здесь, а не только там: это не курьёз, а ровно тот
     *    урок, который сторож и стои́т охранять — проверка по тексту
     *    подтверждает НАЛИЧИЕ СЛОВА, включая слово о себе самой.
     *
     * 3. Остаток +2 переносить некуда, и это честно. Оба утверждения
     *    говорят о ВСЁМ ДЕРЕВЕ сразу: «ни один сервис больше не пишет
     *    прежнее имя действия». Поведенческие двойники у них есть, но
     *    только для двух известных мест записи
     *    (hiring-extras.service.spec.ts проверяет оба), а ценность
     *    правила — в ТРЕТЬЕМ, которого ещё нет. Рантайма, который
     *    перечислил бы вызовы журнала во всех сервисах, в этом процессе
     *    нет. Это тот самый ПОСТОЯННЫЙ ПОЛ, о котором сказано выше.
     *
     * 4. ПОДЪЁМ 258 → 260, Пункт [coverage-report-outlived-the-product]
     *    2026-09-24, и причина у него новая.
     *
     *    Предмет той сверки — ДОКУМЕНТ: `SANDBOX-COVERAGE.md`, по
     *    которому владелец решает, что прогонять после деплоя. Он
     *    говорил «все 6 доменов», а их восемь.
     *
     *    У утверждения о тексте документа поведенческого двойника нет
     *    ПО УСТРОЙСТВУ: у markdown-файла нет поведения, и единственный
     *    способ проверить написанное в нём — прочитать написанное. Это
     *    не та слабость, ради которой сторож заведён (проверка, которая
     *    подтверждает наличие слова вместо поведения кода), а
     *    единственно возможная форма для этого предмета.
     *
     *    Перенести было некуда, ослаблять сторож нельзя, заменить
     *    матчер на `includes(...).toBe(true)` — значит обойти меру, не
     *    изменив сути. Поэтому +2 и запись здесь. */
    expect(assertions).toBeLessThan(260);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: инварианты, выразимые числом, проверяются как числа', () => {
    // Прямая проверка того, что правки этого захода на месте: если
    // потолок снова начнёт проверяться только наличием слова `take`,
    // мутация «поднять константу» опять пройдёт незамеченной.
    const bg = readFileSync(join(TESTS_DIR, 'audit-2026-09-04-background-jobs.spec.ts'), 'utf8');
    expect(bg).toMatch(/toBeLessThanOrEqual\(1000\)/);

    // Счётчик потерянных находок держится поведением, а не словом.
    const tp = readFileSync(join(TESTS_DIR, 'turning-points.service.spec.ts'), 'utf8');
    expect(tp).toMatch(/warnings\.length/);

    // Реестры требуют объяснения, а не только записи.
    const oi = readFileSync(join(TESTS_DIR, 'audit-2026-09-04-outside-input.spec.ts'), 'utf8');
    expect(oi).toMatch(/unexplained/);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: запрет пустых формул стоит там, где текст обязан что-то сообщать', () => {
    // Три реестра объясняют человеку последствия: что сломается без
    // крон-задачи, чего не отменяет отзыв согласия, что не входит в
    // выгрузку. Во всех трёх «объяснение» можно было подменить фразой
    // нужной длины, ничего не сообщающей.
    const withFormulaBan = [
      'audit-2026-09-04-background-jobs.spec.ts',
      'audit-2026-09-04-consent-revocation.spec.ts',
    ];
    for (const name of withFormulaBan) {
      const src = readFileSync(join(TESTS_DIR, name), 'utf8');
      expect(src).toMatch(/EMPTY_FORMULAS/);
      // И рядом — прямо сказано, чего проверка не умеет.
      expect(src).toMatch(/качество текста тестом не про/i);
    }
  });
});
