// Сверка 2026-09-06 — отзыв не оставил следа у того, кто его сделал.
//
// ИЗМЕРЕНО ПЕРВЫМ. Счётчики, которые игнорируют отметку отзыва: шесть
// мест. Проверены все — ПЯТЬ ОКАЗАЛИСЬ ВЕРНЫМИ, и это записано, а не
// переделано в находку:
//
//  • `privacy-center.countUserData()` считает ВСЕ ConsentRecord,
//    включая отозванные, — и правильно: это счётчик «что о вас
//    хранится», а отозванная запись согласия хранится. Активный
//    список рядом, в `getOverview()`, фильтрует `revokedAt: null`;
//  • четыре счётчика вакансий не смотрят на `removedFromSourceAt` —
//    потолок загрузки и статистика по своей базе считают вакансии как
//    хранимые объекты, а снятая с публикации никуда не девается.
//
// НАЙДЕННОЕ. Шестое место привело к другому: `OfferExchangeService.withdraw()`
// помечал `withdrawnAt` ТОЛЬКО НА КОПИЯХ — строках в проекте
// кандидата. Оригинал оффера в проекте работодателя оставался
// нетронутым навсегда, а экран работодателя читает именно его
// (`sheetsApi.get` по листам своего проекта).
//
// Что видел работодатель после нажатия «Отозвать»:
//  • бейдж по-прежнему «передан кандидату» — у кандидата при этом
//    честно стояло «отозван». Две стороны читали одно действие
//    по-разному, и неверной была сторона того, кто действие совершил;
//  • кнопка «Отозвать» на месте; второе нажатие выглядит как первое:
//    `updateMany` с фильтром `withdrawnAt: null` помечал ноль копий и
//    молчал об этом (число возвращалось, но экран его не показывал);
//  • кнопка «Передать кандидату» тоже на месте — отозванный оффер
//    отправлялся снова тем же нажатием.
//
// ИНВЕНТАРЬ, А НЕ ДОГАДКА. Отзывов в продукте пять: согласие кандидата
// на передачу (CandidateSelfShare), согласие пользователя
// (ConsentRecord), инвайт команды, инвайт группы, оффер. Четыре ставят
// отметку на строку, которую видит сам отзывающий, — и экраны её
// читают (например, `CandidateSheetTools` печатает «отозвано» и
// прячет кнопку). Оффер был единственным исключением.
//
// ПОЧЕМУ ПРОВЕРКА НИЖЕ — СПИСОК, А НЕ ОБХОД ДЕРЕВА. Соответствие
// «действие → строка, которую видит его автор» механически не
// выводится: оно про то, какой экран что читает. Список из пяти —
// честный инструмент там, где места перечислимы (то же обоснование,
// что у остальных списочных проверок проекта, см. [guard-scope]).
// Поведение же проверяется поведением: ключевые тесты отзыва живут в
// employer-hiring.service.spec.ts и работают через сервис, а не через
// текст файла.

import * as fs from 'fs';
import * as path from 'path';

const SRC = path.join(__dirname, '..');
const read = (...p: string[]) => fs.readFileSync(path.join(SRC, ...p), 'utf8').replace(/\/\/[^\n]*/g, '');

describe('Сверка [withdraw-no-trace]: отзыв обязан быть виден его автору', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: отзыв оффера пишет отметку на сам оффер, а не только на копии', () => {
    const code = read('employer-hiring', 'offer-exchange.service.ts');
    expect(code).toContain('tx.offerDocument.update({ where: { id: offer.id }, data: { withdrawnAt: now } })');
    // Копии по-прежнему помечаются — отзыв обязан дойти до адресата.
    expect(code).toContain('tx.offerDocument.updateMany(');
    // Обе записи в одной транзакции: половина отзыва хуже, чем его
    // отсутствие — одна из сторон читала бы неверное.
    expect(code).toContain('this.prisma.$transaction(');
  });

  /** ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: «отозванный нельзя отправить снова»,
   * «отозвать дважды нельзя» и «ноль копий объяснён словами»
   * проверяются ПОВЕДЕНИЕМ, через сервис, в
   * employer-hiring.service.spec.ts. Текстовые двойники этих проверок
   * были здесь и убраны: метапроверка проверок
   * (audit-2026-09-04-guard-audit) считает опору на текст исходника, и
   * дублировать поведенческий тест текстовым — ровно тот случай,
   * против которого она стоит. */

  describe('инвентарь отзывов: каждый ставит отметку на строку своего автора', () => {
    const cases: Array<{ what: string; file: string[]; expect: string }> = [
      {
        what: 'согласие кандидата на передачу',
        file: ['candidate-self-share', 'candidate-self-share.service.ts'],
        expect: 'candidateShare.update({ where: { id: share.id }, data: { revokedAt: now } })',
      },
      {
        what: 'согласие пользователя',
        file: ['consent', 'consent.service.ts'],
        expect: 'data: { revokedAt: new Date(), granted: false }',
      },
      {
        what: 'инвайт команды найма',
        file: ['interview-pool', 'interview-pool-team.service.ts'],
        expect: 'data: { revokedAt: invite.revokedAt ?? new Date() }',
      },
      {
        what: 'инвайт инвест-группы',
        file: ['investment', 'investment-group.service.ts'],
        expect: 'data: { revokedAt: invite.revokedAt ?? new Date() }',
      },
      {
        what: 'оффер работодателя',
        file: ['employer-hiring', 'offer-exchange.service.ts'],
        expect: 'where: { id: offer.id }, data: { withdrawnAt: now }',
      },
    ];

    for (const c of cases) {
      it(`${c.what} — отметка на строке, которую видит автор отзыва`, () => {
        expect(read(...c.file)).toContain(c.expect);
      });
    }

    it('инвентарь не усох: пять отзывов, все перечислены', () => {
      expect(cases).toHaveLength(5);
    });
  });

  describe('экран работодателя', () => {
    const ws = fs.readFileSync(
      path.join(SRC, '..', '..', 'tma', 'src', 'components', 'domains', 'employer-hiring', 'EmployerHiringWorkspace.tsx'),
      'utf8',
    );

    it('КЛЮЧЕВОЙ ТЕСТ: результат отзыва показывается, а не пропадает', () => {
      // Раньше вызов шёл без заголовка — значит `setOut` не звался и
      // ответ сервера никуда не доходил.
      expect(ws).toContain("employerApi.offerWithdraw(o.id), 'Оффер отозван'");
    });

    it('подпись панели больше не обещает, что помечается только копия', () => {
      expect(ws).not.toContain('Отзыв оффера помечает копию у кандидата.');
      expect(ws).toContain('и копию у кандидата, и сам оффер у вас');
    });
  });
});
