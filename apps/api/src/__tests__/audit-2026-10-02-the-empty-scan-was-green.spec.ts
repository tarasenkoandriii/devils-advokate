// Пункт [the-empty-scan-was-green] 2026-10-02 — правило по дереву,
// которое перестало читать дерево, остаётся ЗЕЛЁНЫМ.
//
// ПОВОД — прогон 19, и там это случилось дважды.
//
//  • `intake-scenarios-have-ui.spec.ts` разбирал чужой файл регуляркой.
//    Литерал реестра стал вызовом функции, разбор перестал находить
//    что-либо. Спасло ровно одно: функция БРОСАЕТ при пустом разборе.
//    Вернула бы она пустой список — `expect(missing).toEqual([])` стало
//    бы зелёным, и инвариант «у каждого сценария интейка есть экран»
//    умер бы молча.
//  • Сверщик чисел считал комментарии, и его зелёный держался только до
//    первого, кто процитировал оператор в прозе.
//
// Класс один: проверка, которая утверждает ОТСУТСТВИЕ находок, не
// отличает «ничего нет» от «я ничего не читал». Это та же порода, что
// обрезанные списки и «пробел выглядит как полнота», только предмет —
// сама страховочная сетка.
//
// ПОЧЕМУ ПРАВИЛО, А НЕ ТРИ ПРАВКИ. В шапке
// `audit-2026-09-25-probe-checked-the-neighbour.spec.ts` записано:
// «сорок четыре сканирующие спеки, утверждающие "список пуст",
// проверены отдельно: у каждой есть доказательство, что разбор вообще
// что-то находит». Проверено РУКАМИ, один раз, 2026-09-25. С тех дня
// спек стало больше, и две из них сломались именно так. Ручная сверка,
// которую ничто не держит, — это запись о прошлом, а не проверка.
//
// ИЗМЕРЕНО ПЕРЕД ПРАВИЛОМ, и измерение сузилось дважды. Спек, которые
// читают файлы И утверждают пустоту, — 68. Доказательство, что разбор
// что-то находит, есть у 65. Без него — ТРИ:
// `audit-2026-09-05-input-truncated` (обход 487 файлов api),
// `audit-2026-09-06-not-checked-looks-clean` (разбор catch-блоков) и
// `audit-2026-09-30-green-deploy-pointed-at-localhost` (обход tma и
// admin). Все три закрыты порогом и обратной пробой в том же файле.
//
// Первые два замера были неверны и это стоит записать: первый дал «0
// нарушителей», потому что признаком доказательства считалось любое
// `toBe(true)` в файле; второй дал «88», потому что он требовал
// доказательства у КАЖДОГО подлежащего и не видел доказательств,
// лежащих в соседнем тесте. Ни одно из этих чисел не годилось, и
// правило заведено на третьем — том, где единица измерения совпала с
// тем, как доказательство в этом проекте и пишется: соседним тестом в
// том же файле.
//
// ЧЕСТНАЯ ГРАНИЦА, И ОНА ВАЖНА. Правило проверяет, что в файле есть
// ХОТЯ БЫ ОДНО доказательство непустоты разбора, а не что оно
// покрывает именно тот разбор, чей результат объявлен пустым. Точнее
// различить разбором текста нельзя: подлежащее собирается из фильтров,
// обходов и регулярок, и «какой именно обход доказан» — вопрос к
// смыслу, а не к тексту. Поэтому правило ловит ОДИН признак — что файл
// вообще не доказывает ничего. Именно в таком виде оно и нашло три
// настоящих места.

import * as fs from 'fs';
import * as path from 'path';

const APPS = ['api', 'tma', 'admin', 'landing'];
const REPO = path.join(__dirname, '..', '..', '..', '..');

/** Код спеки без комментариев: иначе доказательством считалось бы
 *  ОБЪЯСНЕНИЕ доказательства. Одиннадцать раз в этом проекте разбор
 *  принимал комментарий за код — в том числе вчера, в сверщике чисел.
 *  Ниже стои́т обратная проба именно на это. */
function withoutComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|\s)\/\/[^\n]*/g, ' ');
}

/** Спека читает файлы — то есть её вывод зависит от разбора, а не
 *  только от своих же образцов. */
const READS_FILES = /readFileSync|readdirSync/;

/** Спека утверждает, что находок НЕТ. Ровно это утверждение и
 *  становится неправдой, когда разбор перестаёт читать. */
const CLAIMS_EMPTY =
  /toEqual\(\s*\[\s*\]\s*\)|toStrictEqual\(\s*\[\s*\]\s*\)|toHaveLength\(\s*0\s*\)|\.\s*(?:length|size)\s*\)\s*\.\s*toBe\(\s*0\s*\)/;

/** Чем спека может доказать, что её разбор что-то НАХОДИТ.
 *
 *  Список взят из того, как это написано в уже существующих 65 спеках, а
 *  не придуман про запас: широкий список признал бы доказательством
 *  любое утверждение и правило стало бы шумом, который отключают. */
export const PROOF_FORMS: Array<{ name: string; why: string; re: RegExp }> = [
  {
    name: 'порог снизу',
    why: '`toBeGreaterThan(N)` по числу прочитанного — пустой разбор его не пройдёт',
    re: /toBeGreaterThan(?:OrEqual)?\(/,
  },
  {
    name: 'точное положительное число',
    why: 'измерение вида «мест ровно пять»: ноль прочитанных файлов даёт ноль мест',
    re: /\.\s*(?:length|size)\s*\)\s*\.\s*toBe\(\s*[1-9]|toHaveLength\(\s*[1-9]|\.\s*(?:length|size)\s*>=?\s*[1-9]\s*\)\s*\.\s*toBe\(\s*true|expect\(\s*\w+\s*\)\s*\.\s*toBe\(\s*[1-9]\d*\s*\)/,
  },
  {
    name: 'проба в названии теста',
    why: 'отдельный тест прогоняет то же правило на образце, где находка ОБЯЗАНА быть',
    re: /(?:it|test)\(\s*[`']\s*(?:ОБРАТНАЯ ПРОБА|обратная проба|проба)/i,
  },
  {
    name: 'бросок при пустом разборе',
    why: 'разбор не возвращает пустоту молча — он отказывается',
    re: /throw new Error\(/,
  },
];

export interface ScanningSpec {
  file: string;
  proofs: string[];
}

function specFiles(): string[] {
  const out: string[] = [];
  for (const app of APPS) {
    const dir = path.join(REPO, 'apps', app, 'src', '__tests__');
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) if (f.endsWith('.spec.ts')) out.push(path.join(dir, f));
  }
  return out;
}

/** Решение по ТЕКСТУ спеки — единственное место, где оно принимается.
 *
 *  `null` значит «это не сканирующая спека»: она либо не читает файлов,
 *  либо не утверждает пустоту, и правило к ней не относится. */
function proofsIn(src: string): string[] | null {
  const clean = withoutComments(src);
  if (!READS_FILES.test(clean) || !CLAIMS_EMPTY.test(clean)) return null;
  return PROOF_FORMS.filter((p) => p.re.test(clean)).map((p) => p.name);
}

/** Спеки, которые читают файлы и утверждают пустоту, с перечнем
 *  доказательств у каждой.
 *
 *  Решение берётся у `proofsIn`, а не повторяется здесь. Первая редакция
 *  повторяла — и обратные пробы проверяли ОДНУ копию решения, пока
 *  ключевой тест пользовался ДРУГОЙ. Поймал это сторож
 *  [probe-checked-the-neighbour]: ровно его предмет, «проба проверяет
 *  соседнее выражение», и он сработал на первом же прогоне. */
export function scanningSpecs(files: string[]): ScanningSpec[] {
  const out: ScanningSpec[] = [];
  for (const file of files) {
    const proofs = proofsIn(fs.readFileSync(file, 'utf8'));
    if (proofs === null) continue;
    out.push({ file: path.basename(file), proofs });
  }
  return out;
}

describe('[the-empty-scan-was-green] правило по дереву доказывает, что дерево прочитано', () => {
  it('ИЗМЕРЕНИЕ: сканирующих спек столько, и разбор их находит', () => {
    // Порог снизу — чтобы правило нельзя было выполнить, перестав
    // находить сами спеки: пустой список «нарушителей» получился бы
    // тогда ровно той ошибкой, против которой правило стои́т.
    expect(scanningSpecs(specFiles()).length).toBeGreaterThan(60);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: ни одна сканирующая спека не утверждает пустоту без доказательства, что разбор что-то находит', () => {
    const naked = scanningSpecs(specFiles())
      .filter((s) => s.proofs.length === 0)
      .map((s) => s.file);
    // Пустой массив, а не длина: сообщение назовёт файл.
    expect(naked).toEqual([]);
  });

  it('ИЗМЕРЕНИЕ: какими формами доказательства пользуются — чтобы следующий заход начинал с факта', () => {
    const used = new Map<string, number>();
    for (const s of scanningSpecs(specFiles())) for (const p of s.proofs) used.set(p, (used.get(p) ?? 0) + 1);
    // Каждая объявленная форма ДЕЙСТВИТЕЛЬНО встречается. Форма, которой
    // не пользуется никто, — это разрешение, выданное на будущее, и
    // проверить её нечем.
    for (const form of PROOF_FORMS) {
      expect([form.name, (used.get(form.name) ?? 0) > 0]).toEqual([form.name, true]);
    }
  });

  it('ОБРАТНАЯ ПРОБА: тот же проход объявляет образец БЕЗ доказательства недоказанным, а с порогом — доказанным', () => {
    // Иначе пустой список выше означал бы не порядок, а решение,
    // которое не срабатывает ни на чём. Проход — ТОТ ЖЕ, на временных
    // файлах: проверять параллельную копию решения значило бы проверять
    // соседнее выражение, и на этом сторож [probe-checked-the-neighbour]
    // уже поймал первую редакцию этой спеки.
    const dir = fs.mkdtempSync(path.join(require('os').tmpdir(), 'empty-scan-'));
    // Образцы собираются из кусков: литералом они нашлись бы в тексте
    // самой этой спеки, и правило поймало бы собственную декорацию.
    const IT = ['i', 't'].join('');
    const READ = ['readFile', 'Sync'].join('');
    const naked = [
      `const scan = () => ${READ}('x', 'utf8').match(/rule/g) ?? [];`,
      `${IT}('КЛЮЧЕВОЙ ТЕСТ: нарушителей нет', () => { expect(scan()).toEqual([]); });`,
    ].join('\n');
    const nakedFile = path.join(dir, 'sample-naked.spec.ts');
    const flooredFile = path.join(dir, 'sample-floored.spec.ts');
    fs.writeFileSync(nakedFile, naked);
    fs.writeFileSync(flooredFile, `${naked}\n${IT}('измерение', () => { expect(scan().length).toBeGreaterThan(3); });`);

    expect(scanningSpecs([nakedFile])[0].proofs).toEqual([]);
    expect(scanningSpecs([flooredFile])[0].proofs).toContain('порог снизу');

    // Доказательство, лежащее В КОММЕНТАРИИ, доказательством не
    // считается: одиннадцать раз в этом проекте разбор принимал
    // комментарий за код, последний — вчера, в сверщике чисел.
    const commentedFile = path.join(dir, 'sample-commented.spec.ts');
    fs.writeFileSync(commentedFile, `${naked}\n// порог был бы expect(scan().length).toBeGreaterThan(3)\n`);
    expect(scanningSpecs([commentedFile])[0].proofs).toEqual([]);

    // А спека, которая файлов не читает, правилу не подчиняется вовсе:
    // утверждение «список пуст» о собственных образцах — другой предмет,
    // там нечему перестать читаться.
    const noFilesFile = path.join(dir, 'sample-no-files.spec.ts');
    fs.writeFileSync(noFilesFile, `${IT}('свои образцы', () => { expect([].filter(Boolean)).toEqual([]); });`);
    expect(scanningSpecs([noFilesFile])).toEqual([]);

    fs.rmSync(dir, { recursive: true, force: true });
  });
});
