// Сверка 2026-09-06 — удаление говорило «готово» всегда.
//
// КОНТЕКСТ. Продукт кладёт файлы во внешнее хранилище (Vercel Blob) и
// удаляет их оттуда. Две дороги:
//
//  • ПРОВЕРКА ФОТО. Провайдер реверс-поиска принимает только публичный
//    URL, поэтому фото ВРЕМЕННО РАЗМЕЩАЕТСЯ ПУБЛИЧНО В ИНТЕРНЕТЕ. Это
//    осознанный риск, под отдельным согласием PUBLIC_IMAGE_SEARCH, и
//    экран говорит человеку прямым текстом: «Ссылка удаляется сразу
//    после завершения поиска» — БЕЗУСЛОВНО;
//  • УДАЛЕНИЕ АККАУНТА. Чистка внешних артефактов удаляет доказательства
//    ДТП и пишет в запись аудита, сколько удалено и сколько не вышло.
//
// НАЙДЕННОЕ. `deleteBlob()` возвращала `void` и глотала всё:
//
//  1. брошенную ошибку сети — намеренно, и это решение верное: удаление
//     не должно ронять уже полученный результат поиска;
//  2. но ТАКЖЕ любой не-2xx ответ, потому что `response.ok` не
//     проверялся ВООБЩЕ. 403 от хранилища был неотличим от успеха — а
//     контракт DELETE-эндпоинта, по признанию самого файла, подтверждён
//     источниками слабее, чем PUT, то есть именно этот случай был
//     вероятнее прочих.
//
// Отсюда два следствия, и оба про утверждения, которые читает человек:
//
//  • фото могло остаться публично доступным, а человек читал
//    безусловное обещание, что ссылка удалена;
//  • `evidenceDeleted++` стоял в `try`, а `evidenceFailed++` — в
//    `catch`, которому ловить было НЕЧЕГО. Счётчик «удалено» был завышен
//    по построению, и именно он уходит в запись аудита при удалении
//    аккаунта: человек читал, что его доказательства ДТП убраны из
//    внешнего хранилища, при том что они могли остаться.
//
// И СНЯТО НЕВЕРНОЕ УТЕШЕНИЕ. В комментарии стояло: «если удаление не
// сработало — blob истечёт по TTL кэша Vercel, не остаётся навсегда».
// Это рассуждение написано про blob КЭША результата; у Vercel Blob
// самого по себе срока жизни нет — загруженный файл лежит, пока его не
// удалят. Для фотографии человека, лежащей публично, разница
// принципиальная.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Сам исход удаления проверяется в
// vercel-blob.spec.ts (сеть упала / 403 / успех), счётчики чистки — в
// external-artifacts-cleanup.spec.ts, ответ проверки фото — в
// photo-verification.service.spec.ts. Здесь — то, что иначе не
// выразить: обещание на экране и отсутствие второй копии правила.
//
// СНЯТО ОТСЮДА ОСОЗНАННО. Первая редакция этой сверки держала ещё две
// проверки — «в vercel-blob.ts есть `if (!response.ok)`» и «в чистке
// стоит `if (outcome.deleted)`». Обе читали ТЕКСТ того, что рядом уже
// проверено ПОВЕДЕНИЕМ: 403 как неудача — vercel-blob.spec.ts, счётчик
// 1/1 вместо 2/0 — external-artifacts-cleanup.spec.ts. Проверка формы
// строки при живой проверке смысла не добавляет защиты, зато ломается
// от переименования и приучает чинить тест вместо кода. Сторож
// audit-2026-09-04-guard-audit.spec.ts на этом и сработал: сначала
// переносим в поведение, и только если перенести некуда — поднимаем
// потолок. Здесь переносить не пришлось: поведение уже было.

import { readFileSync } from 'fs';
import { join } from 'path';

const API_SRC = join(__dirname, '..');
const TMA = join(API_SRC, '..', '..', 'tma', 'src');

describe('Сверка [delete-says-done]: «удалено» должно значить удалено', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: обещание на экране перестало быть безусловным', () => {
    const section = readFileSync(join(TMA, 'components', 'PhotoVerificationSection.tsx'), 'utf8');
    expect(section).toContain('Ссылка удаляется сразу после завершения поиска');
    // И сразу за обещанием — что будет, если не выйдет.
    expect(section).toContain('а если удалить не');
    expect(section).toContain('{publicCopyNote && ');
  });

  it('неверное утешение про «истечёт по TTL» убрано из кода', () => {
    const blob = readFileSync(join(API_SRC, 'common', 'vercel-blob.ts'), 'utf8');
    // Прежнее утешение стояло в теле функции, отступом кода.
    expect(blob).not.toContain('    // (см. документацию), не остаётся навсегда');
    expect(blob).toContain('самого по себе срока жизни нет');
  });
});
