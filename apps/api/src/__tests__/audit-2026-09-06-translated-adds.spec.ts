// Сверка 2026-09-06 — перевод дописал то, чего человек не писал.
//
// НАЙДЕННОЕ. Обещание продукта здесь одно из самых сильных: «CV
// собирается только из ваших слов». На ПЕРЕФОРМУЛИРОВКЕ его держит
// детерминированный барьер — `rephraseAddsNothing()`: добавленное число
// или навык не попадает в базу, ответ уходит на повтор, и в коде это
// объяснено прямо («достаточно одной добавленной цифры, чтобы человек
// отправил работодателю чужое достижение под своим именем»).
//
// На ПЕРЕВОДЕ того же CV барьера не было вовсе. Вместо него — обратная
// сверка: вторая модель сообщает о первой, что та потеряла и что
// дописала. Это самоотчёт, а не проверка, и:
//
//  1. вариант сохранялся НЕЗАВИСИМО от того, что самоотчёт сказал;
//  2. сам самоотчёт ничем не проверялся — «добавлено: …» могло
//     называть текст, которого в переводе нет (у проекта для этого
//     давно есть `quoteOccursIn`, применявшийся к цитате расхождения
//     между вариантами, — здесь он не применялся);
//  3. экран печатал одну строку «Потеряно: … · Добавлено: …», где обе
//     половины из самоотчёта и обе без различения, а «ничего» рядом с
//     «ничего» читается как «перевод чистый».
//
// ЦЕНА ВЫШЕ, ЧЕМ У ПЕРЕФОРМУЛИРОВКИ: человек отправляет резюме на
// языке, которым чаще всего владеет хуже, чем адресат. Заметить в нём
// дописанную цифру ему труднее, чем в родном тексте.
//
// ЧИСЛА ПЕРЕЖИВАЮТ ПЕРЕВОД — на этом и стоит новый барьер. Слова между
// языками сравнивать нечем, цифры остаются цифрами.

import {
  translationAddsNoNumbers,
  verifiedBackCheck,
  numbersInAcrossLocales,
  rephraseAddsNothing,
} from '../terms-sheet/cv-variant-barriers';

describe('[translated-adds] в переводе не появляется того, чего человек не писал', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: дописанное в переводе число найдено', () => {
    // Это и есть весь пункт: «участвовал в росте» → «grew revenue by 30%».
    const check = translationAddsNoNumbers(
      'Участвовал в проекте роста выручки. Опыт 5 лет.',
      'Grew revenue by 30%. 5 years of experience.',
    );
    expect(check.ok).toBe(false);
    expect(check.addedNumbers).toEqual(['30']);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: честный перевод НЕ помечается дописавшим', () => {
    // Барьер, который срабатывает всегда, не барьер: им перестают
    // пользоваться, и вместе с ним пропадает настоящая находка.
    expect(translationAddsNoNumbers('Опыт 5 лет, команда из 12 человек.', '5 years of experience, a team of 12.').ok).toBe(true);
    expect(translationAddsNoNumbers('Без цифр вовсе.', 'No numbers at all.').ok).toBe(true);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: разрядные разделители разных языков — одно число', () => {
    // «1 000» по-русски, «1,000» по-английски, «1.000» по-немецки.
    // Не учесть это значило бы валить проверку на каждом переводе с
    // числом больше тысячи — и её бы отключили.
    expect(numbersInAcrossLocales('оборот 1 000 000')).toEqual(numbersInAcrossLocales('turnover 1,000,000'));
    expect(translationAddsNoNumbers('Бюджет 1 500 тыс.', 'Budget of 1,500 thousand.').ok).toBe(true);
    // А дробная часть разрядом не становится: 2,5 — это 2.5, не 25.
    expect(numbersInAcrossLocales('2,5')).toEqual(['2.5']);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: потерянное число — НЕ «добавленное»', () => {
    // Барьер односторонний намеренно. Число, записанное словом («five
    // years»), для него потеря, а не добавление; смешать их значило бы
    // получить одно невнятное «что-то не так».
    const check = translationAddsNoNumbers('Опыт 5 лет.', 'Five years of experience.');
    expect(check.ok).toBe(true);
    expect(check.addedNumbers).toEqual([]);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: самоотчёт обратной сверки проверяется на дословность', () => {
    // «Добавлено» обязано встречаться в ПЕРЕВОДЕ, «потеряно» — в
    // ОРИГИНАЛЕ. Иначе человеку предлагается обсуждать выдумку — тот же
    // уговор, что у цитаты расхождения между вариантами CV.
    const original = 'Руководил командой. Опыт 5 лет.';
    const translated = 'Led the team. 5 years of experience. Certified architect.';
    const verified = verifiedBackCheck(
      { lost: ['Руководил командой', 'чего в оригинале не было'], added: ['Certified architect', 'выдуманная строка'] },
      original,
      translated,
    );
    expect(verified.lost).toEqual(['Руководил командой']);
    expect(verified.added).toEqual(['Certified architect']);
    // Отброшенное не исчезает молча — правило всей этой сессии.
    expect(verified.unverifiable).toBe(2);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: мусор вместо самоотчёта не превращается в находку', () => {
    // Модель может вернуть не тот тип вовсе. Молчание честнее выдумки.
    for (const bad of [{}, { lost: null, added: 'строка' }, { lost: [1, 2], added: [{}] }]) {
      const v = verifiedBackCheck(bad as never, 'оригинал', 'перевод');
      expect(v.lost).toEqual([]);
      expect(v.added).toEqual([]);
    }
  });

  it('ИЗМЕРЕНИЕ: барьер перевода и барьер переформулировки — разные, и оба на месте', () => {
    // Барьер переформулировки ловит и числа, и технологии: там сравнение
    // идёт внутри ОДНОГО языка. На переводе сравнивать слова нечем, и
    // делать вид, что барьер закрывает и это, было бы той же подменой,
    // которую он призван ловить.
    const rephrase = rephraseAddsNothing('Писал сервисы.', 'Писал сервисы на Kubernetes.');
    expect(rephrase.ok).toBe(false);
    expect(rephrase.addedTerms.length).toBeGreaterThan(0);
    // У перевода тот же ввод проходит: слово в другом языке ничего не
    // доказывает, и барьер об этом честно молчит.
    expect(translationAddsNoNumbers('Писал сервисы.', 'Built services on Kubernetes.').ok).toBe(true);
  });
});
