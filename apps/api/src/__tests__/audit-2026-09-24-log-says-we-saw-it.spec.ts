// Сверка 2026-09-24 — журнал писал утверждение оператора как наблюдение.
//
// КАК СВЕРКА ВЫРОСЛА ИЗ ПРЕДЫДУЩЕЙ. [same-answer-either-way] закончился
// тем, что правило нашлось не глазами, а обходом дерева. Здесь тот же
// приём применён к журналу — единственному месту продукта, чья работа
// целиком состоит в утверждениях о прошлом.
//
// ИЗМЕРЕНИЕ. Записей в журнале шестнадцать, и они двух родов:
//
//  • НАБЛЮДЕНИЯ — продукт сам совершил действие и потому ЗНАЕТ, что оно
//    произошло: кандидат добавлен, оффер отозван, заказ принят, досье
//    создано, экспорт сформирован. Четырнадцать записей;
//  • УТВЕРЖДЕНИЯ — продукт действия не совершал и наблюдать не мог. Он
//    записал то, что сказал оператор, нажав кнопку. Две записи.
//
// ДВЕ ЭТИ. «Письмо-статус отправлено» — письмо отправляет человек своей
// почтой, и рамка самого письма это говорит прямым текстом: «отправляет
// человек». «Уведомление об AI показано кандидату» — показывает человек,
// на своём экране, вне продукта.
//
// ПОЧЕМУ ЭТО НЕ ПРИДИРКА К СЛОВАМ. Во-первых, вторая из двух — ровно та
// запись, которой доказывают, что кандидата предупредили об AI. В
// журнале нет ничего, что весило бы больше, и получена она из нажатия.
//
// Во-вторых, первая ЧИТАЕТСЯ ОБРАТНО КАК ФАКТ: чеклист закрытия вакансии
// собирал из этих записей множество «кому ответили», возвращал остальных
// полем `candidatesWithoutAnswer`, а экран под пустым списком писал
// утвердительно: «Всем ответили.» Нажатие кнопки превращалось в
// утверждение продукта о том, что живой человек получил ответ.
//
// ПОЧЕМУ ЭТО «ПРАВИЛО БЫЛО, ПРОСТО НЕ ВЕЗДЕ» — и это главное. Различие
// уже проведено, В ТОМ ЖЕ ЖУРНАЛЕ, у соседней пары записей, и проведено
// в точности как надо: `candidate_consent.revoked_by_recruiter` против
// `candidate_consent.revoked_by_candidate`, с комментарием прямым
// текстом — «„кандидат попросил, и я записал" и „кандидат отозвал сам" —
// разные события, и складывать их нельзя», — и с обязательным
// подтверждением `candidateAskedToRevoke`, без которого записи нет
// вовсе. У двух других утверждений о кандидате не было ни имени, ни
// подтверждения.
//
// И СВЕРХ ТОГО: у продукта есть целый словарь на эту тему —
// `common/fact-provenance.ts`, где «со слов пользователя» и «догадка, не
// проверено» не дают выглядеть проверенным. Журнал жил мимо него.
//
// ЧЕГО НЕ СДЕЛАНО И ПОЧЕМУ. Поля «род записи» в `AuditLogEntry` не
// появилось: род читается из имени действия, а имя обязано быть
// стабильным (по нему ищут), тогда как новое поле у существующих строк
// было бы NULL — «род неизвестен» у всей истории. Имя честнее.
//
// ПОВЕДЕНИЕ, НЕ ТЕКСТ. Исходы проверены в hiring-extras.service.spec.ts:
// без подтверждения записи нет; имя действия говорит, с чьих слов;
// прежнее имя читается (строки за него уже есть); ответ называет себя
// отметкой со слов. Здесь — то, что иначе не выразить.

import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';
import { isSelfReportedAction, AUDIT_STATUS_LETTER_LEGACY, AUDIT_AI_NOTICE_LEGACY } from '../common/audit-claim';

const SRC = join(__dirname, '..');

function tsFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : tsFiles(full);
    return name.endsWith('.ts') ? [full] : [];
  });
}

function code(path: string): string {
  return readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Все имена действий, которые сервисы РЕАЛЬНО пишут в журнал — из
 * кода, а не из списка в этом файле: список устарел бы молча. */
function writtenActions(): string[] {
  const out: string[] = [];
  for (const file of tsFiles(SRC)) {
    const src = code(file);
    for (const m of src.matchAll(/action:\s*'([^']+)'/g)) out.push(m[1]);
  }
  return [...new Set(out)];
}

describe('Сверка [log-says-we-saw-it]: журнал не путает утверждение с наблюдением', () => {
  it('КЛЮЧЕВОЙ ТЕСТ: ни одно прежнее имя-утверждение больше не ПИШЕТСЯ', () => {
    // Читать их обязаны — строки за них в журнале есть. Писать нельзя:
    // имя `status_letter.sent` утверждает отправку, которой продукт не
    // видел.
    const written = writtenActions();
    expect(written).not.toContain(AUDIT_STATUS_LETTER_LEGACY);
    expect(written).not.toContain(AUDIT_AI_NOTICE_LEGACY);
    // Разбор жив — имена действий вообще находятся.
    expect(written.length).toBeGreaterThan(8);
  });

  it('КЛЮЧЕВОЙ ТЕСТ: каждое записываемое утверждение названо так, что видно, чьё оно', () => {
    // Правило по ФОРМЕ имени, а не по списку: любое действие, которое
    // продукт не наблюдал, обязано называть источник — `_by_recruiter`
    // или `_by_candidate`. Иначе через месяц заведётся третье
    // безымянное, ровно как завелись эти два.
    const claims = writtenActions().filter(isSelfReportedAction);
    expect(claims.length).toBeGreaterThan(0);
    for (const action of claims) {
      expect([action, /_by_(recruiter|candidate)$/.test(action)]).toEqual([action, true]);
    }
  });

  it('КЛЮЧЕВОЙ ТЕСТ: запись-утверждение не делается без подтверждения оператора', () => {
    // Приём взят у уже работающего `candidateAskedToRevoke`: без
    // подтверждения записи нет вовсе. Проверяется, что рядом с каждой
    // такой записью подтверждение действительно требуется.
    // Имя действия ищется по КОНСТАНТЕ, а не по строке: в сервисах
    // литерала нет и быть не должно — имя живёт в одном месте
    // (`common/audit-claim.ts`), иначе читатель и писатель разъедутся,
    // как уже разъезжались в [label-is-the-choice]. Поэтому файл
    // находится по имени подтверждения, а запись — по имени константы.
    const CONFIRMATIONS: Array<[flag: string, marker: string]> = [
      ['recruiterSentIt', 'AUDIT_STATUS_LETTER_MARKED_SENT'],
      ['noticeShownToCandidate', 'AUDIT_AI_NOTICE_MARKED_SHOWN'],
      // Уже работавший случай — он и был образцом.
      ['candidateAskedToRevoke', "'candidate_consent.revoked_by_recruiter'"],
    ];
    for (const [flag, marker] of CONFIRMATIONS) {
      const file = tsFiles(SRC).find((f) => code(f).includes(flag) && code(f).includes(marker));
      expect([flag, !!file]).toEqual([flag, true]);
      const src = code(file!);
      // Отказ стоит ДО записи: подтверждения нет — записи нет вовсе.
      const отказ = src.indexOf(`dto?.${flag}`) >= 0 ? src.indexOf(`dto?.${flag}`) : src.indexOf(`dto.${flag}`);
      expect([flag, отказ]).not.toEqual([flag, -1]);
      // Место ЗАПИСИ, а не строка импорта: имя константы стоит и в
      // импорте, вверху файла, то есть раньше любого отказа. Первая
      // версия этой проверки поймалась именно на этом — и поймалась
      // случайно, чем и подтвердила, зачем нужны обратные пробы.
      const запись = new RegExp(`action:\\s*${marker.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`).exec(src);
      expect([flag, !!запись]).toEqual([flag, true]);
      expect([flag, отказ < запись!.index]).toEqual([flag, true]);
    }
  });
});
