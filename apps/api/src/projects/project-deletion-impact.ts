// Пункт [project-deletion-took-a-stranger] 2026-09-30 — удаление ПРОЕКТА
// уносит чужое, и человеку об этом не сказано.
//
// ПОВОД. Пункт [cascade-took-a-stranger] 2026-09-26 закрыл это для
// удаления АККАУНТА: человек до решения видит, что его удаление заберёт
// у других, и после — что забрало. Удаление проекта осталось как было.
//
// ЧЕМ ЭТО ОСОБЕННО НЕХОРОШО. Экран удаления проекта САМ СЕБЕ ставит это
// правило — в его шапке записано: «Что именно исчезнет — сказано ДО
// нажатия, а не после. Человек решает по этому тексту». А перечисляет
// текст только СВОЁ: разговоры, расшифровки, аргументы, находки,
// договорённости, напоминания. Ни слова о том, что вместе с проектом
// исчезнут слова приглашённых в обсуждение и записи, на которые
// опирается контрагент. Правило объявлено и исполнено наполовину — это
// хуже, чем не объявлять: объявленное закрывает вопрос.
//
// ИЗМЕРЕНО ПО СХЕМЕ. С проектом каскадно уходят 50 моделей. Из них
// поле, называющее ДРУГОГО человека или ДРУГОЙ проект, есть у шести —
// и шестая, `PublicParticipant`, механическим правилом НЕ НАХОДИТСЯ
// вовсе: у приглашённого по ссылке нет аккаунта, и колонки с чужим
// идентификатором у него нет — только имя, которое он сам написал.
// Именно поэтому реестр ниже ведётся руками, а разбор схемы держит его
// ЗАМКНУТОСТЬ, а не заменяет его.
//
// ЧЕСТНАЯ ГРАНИЦА ЧИСЕЛ — та же, что у удаления аккаунта. Считается ДО
// каскада, после него считать нечего. Если между подсчётом и удалением
// кто-то напишет комментарий, число окажется меньше факта; врать в эту
// сторону лучше, чем в обратную, и это единственная сторона, в которую
// оно может ошибиться.

import type { PrismaService } from '../prisma/prisma.service';

export interface ProjectLoss {
  readonly key: string;
  /** Текст с числом — человеку, а не оператору. */
  readonly text: (count: number) => string;
  /** Чья это потеря и по какой цепочке она происходит. */
  readonly why: string;
  readonly count: (prisma: PrismaService, projectId: string) => Promise<number>;
}

