/** Как разбор схемы классифицирует каждую каскадную модель, у которой
 *  есть поле с чужим идентификатором.
 *
 *  Нужен затем, чтобы «поле есть, но потери нет» было РЕШЕНИЕМ С
 *  ПРИЧИНОЙ, а не молчанием. Новая такая модель уронит сверку. */
export type CascadeVerdict = 'чужое' | 'своё';

export interface CascadeClassification {
  readonly model: string;
  readonly fields: readonly string[];
  readonly verdict: CascadeVerdict;
  readonly why: string;
  /** Ключ записи в `PROJECT_TAKES_FROM_OTHERS`, которая эту потерю
   *  СЧИТАЕТ. Обязателен у «чужого» и запрещён у «своего» — иначе
   *  вердикт был бы словом без последствий: мутация «объявить чужое
   *  своим» проходила насквозь, пока этой связи не было. */
  readonly loss?: string;
}

