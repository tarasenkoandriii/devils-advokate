export interface CountedProjectLoss {
  key: string;
  count: number;
  text: string;
  why: string;
}

/** Что именно заберёт удаление проекта — только то, чего не ноль.
 *
 * Ноль не показывается: «0 комментариев исчезнет» не сообщает ничего о
 * последствиях и разбавляет то, что сообщает. То же правило, что у
 * удаления аккаунта. */
export async function projectTakesFromOthers(
  prisma: PrismaService,
  projectId: string,
): Promise<CountedProjectLoss[]> {
  const counts = await Promise.all(PROJECT_TAKES_FROM_OTHERS.map((l) => l.count(prisma, projectId)));
  return PROJECT_TAKES_FROM_OTHERS.map((l, i) => ({
    key: l.key,
    count: counts[i],
    text: l.text(counts[i]),
    why: l.why,
  })).filter((l) => l.count > 0);
}

