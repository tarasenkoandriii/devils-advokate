// Пункт [state-not-sent] 2026-09-06 — состояние источника отдельно от
// текста источника.
//
// ЧТО БЫЛО. Перечитывание вакансии, получив 404, дописывало в конец
// `rawText` строку «[Снята с публикации: источник ответил 404 —
// ДАТА]». Это единственное место, где факт снятия вообще хранился:
// колонки под него не было.
//
// Четыре следствия, и ни одно не гипотетическое:
//
//  1. ПОЛЕ ОБЕЩАЛО ДРУГОЕ. В schema.prisma над `rawText` написано
//     «текст страницы вакансии (safe-url-fetch), НЕ пересказ».
//     Продукт дописывал туда собственные слова — и дальше отдавал
//     этот текст и модели (сверка с CV, признаки мошенничества,
//     позиции по пунктам листа), и человеку, как текст источника.
//  2. МЕТКА ДОПИСЫВАЛАСЬ КАЖДЫЕ СУТКИ. Плановое перечитывание берёт
//     вакансии со слежением, у которых прошли сутки; снятая вакансия
//     под это условие подходит всегда. Каждый тик: снова 404, снова
//     `previousRawText = rawText`, снова плюс строка. Текст рос на
//     строку в день без потолка (ограничение MAX_VACANCY_TEXT_CHARS
//     стоит на ЗАГРУЗКЕ, а не на этой дописи), а «Изменения»
//     показывали свежий diff каждый день — вакансия не менялась с
//     момента снятия, менял её мы сами.
//  3. ХЕШ РАСХОДИЛСЯ С ТЕКСТОМ. В ветке снятия `contentHash` не
//     пересчитывался, хотя `rawText` менялся. А `dedupe()`
//     пересчитывает хеш тем, у кого его нет, — то есть по тексту с
//     метками: снятая вакансия переставала группироваться со своими
//     дублями.
//  4. ЭКРАН НЕ МОГ ПОКАЗАТЬ СНЯТИЕ. Списку нечего было отдать, кроме
//     подстроки в тексте, которого в списке нет вовсе. Человек видел
//     снятую вакансию как обычную: открывал лист условий, запускал
//     сверку, ждал ответа.
//
// ЧТО СТАЛО. Колонка `removedFromSourceAt`. Текст источника не
// трогается вообще — ни при снятии, ни при повторных проверках.
//
// ПРОВЕРЯТЬ СНЯТУЮ ВАКАНСИЮ ПРОДОЛЖАЕМ — сознательно. Проще было бы
// исключить её из планового перечитывания (404 нового не сообщает), но
// вакансию возвращают на площадку, и человеку, который просил следить,
// это важнее экономии одного запроса в сутки. Повторное 404 ничего не
// перезаписывает и не считается изменением; ответ 200 снимает отметку
// и сообщает об этом отдельно.
//
// ИСТОРИИ ЭПИЗОДОВ СНЯТИЯ НЕТ, И ОНА НЕ ЗАВОДИТСЯ. Колонка одна:
// «снята сейчас» или «нет». Заводить таблицу эпизодов ради случая,
// которого мы ни разу не наблюдали, значило бы гадать, а не переносить
// принятое решение — тот же принцип, по которому в проекте не заведено
// «скользящее окно» без зафиксированного размера.

/** Старая метка, которую дописывали в текст. Нужна, чтобы вычистить её
 * из уже накопленных строк и чтобы правило поймало её возвращение. */
import { daysAgo } from '../common/server-time';

export const REMOVAL_MARKER_RE = /\n*\[Снята с публикации: источник ответил 404 — (\d{4}-\d{2}-\d{2})\]/g;

export interface StrippedText {
  text: string;
  /** Самая ранняя дата из найденных меток — именно она и есть день,
   * когда снятие заметили впервые. Позднейшие метки дописаны
   * повторными тиками и датой снятия не являются. */
  removedFromSourceAt: Date | null;
  /** Сколько меток было — прямая мера того, сколько суток тик
   * дописывал в текст. */
  markers: number;
}

/** Убирает старые метки из накопленного текста и достаёт из них дату.
 * Применяется к данным, которые УЖЕ есть: починка обязана доходить до
 * них, иначе текст с метками доживёт до конца жизни вакансии. */
export function stripRemovalMarkers(text: string): StrippedText {
  const dates: string[] = [];
  const cleaned = text.replace(REMOVAL_MARKER_RE, (_m, d: string) => {
    dates.push(d);
    return '';
  });
  dates.sort();
  return {
    text: cleaned.trimEnd(),
    removedFromSourceAt: dates.length > 0 ? new Date(`${dates[0]}T00:00:00.000Z`) : null,
    markers: dates.length,
  };
}

export function isRemovedFromSource(v: { removedFromSourceAt?: Date | null }): boolean {
  return !!v.removedFromSourceAt;
}

/** Текст для человека. Пусто здесь не значит «вакансия в порядке» —
 * значит «при последней проверке источник отвечал», и когда была
 * последняя проверка, сказано рядом. */
export function availabilityNote(v: {
  removedFromSourceAt?: Date | null;
  lastRefetchedAt?: Date | null;
  sourceUrl?: string | null;
}): string | null {
  if (v.removedFromSourceAt) {
    // Пункт [server-said-which-day] 2026-09-24: было число по UTC в
    // тексте, который читает соискатель. Для «когда перестал отвечать»
    // расстояние во времени и точнее по смыслу, и не зависит от того,
    // где человек живёт.
    const d = daysAgo(v.removedFromSourceAt);
    return `Источник перестал отвечать ${d} (404/410). Текст вакансии сохранён таким, каким был — он не менялся с тех пор. Снятие с публикации не всегда значит, что место занято: объявление снимают и переписывают, и его возвращают.`;
  }
  if (!v.sourceUrl) return null;
  if (!v.lastRefetchedAt) return 'Источник не перечитывался ни разу — сказать, на месте ли вакансия сейчас, нельзя.';
  return null;
}
