// Аудит 2026-09-03 («правило, которое держится только промптом») —
// детерминированные барьеры для варианта CV.
//
// Промпт переформулировки говорит: «ЗАПРЕЩЕНО добавлять опыт, навыки,
// цифры, обязанности, которых нет во фрагменте». Проверялось при этом
// только то, что модель вернула строку. А обещание продукта здесь одно из
// самых сильных — «CV собирается только из ваших слов»: достаточно одной
// добавленной цифры («увеличил конверсию на 30%»), чтобы человек отправил
// работодателю чужое достижение под своим именем и не заметил этого.
//
// Барьер намеренно узкий и односторонний: он ловит ДОБАВЛЕННОЕ, а не
// «неточный пересказ». Что проверяется:
//   • числа — каждое число в переформулировке должно быть в оригинале
//     (иначе это новая цифра, а цифры в резюме и есть достижения);
//   • технологии — навык, названный в переформулировке, должен быть в
//     оригинале (словарь TECH_TERMS, заведомо неполный — см. его файл).
// Чего он НЕ проверяет и не может: смысловые преувеличения без чисел
// («ключевую роль» вместо «участвовал»). Это остаётся на промпте и на
// глазах человека, и делать вид, что барьер закрывает и это, — было бы
// той же подменой, которую он призван ловить.

import { TECH_TERMS, mentionsTerm } from '../job-search/tech-terms';

/** Числа текста в нормализованном виде: 30, 1000, 2.5. Проценты и знаки
 * отбрасываются — «30%» и «30 %» это одно и то же число. */
export function numbersIn(text: string): string[] {
  return (text.match(/\d+(?:[.,]\d+)?/g) ?? []).map((n) => n.replace(',', '.').replace(/\.0+$/, ''));
}

export interface RephraseCheck {
  ok: boolean;
  addedNumbers: string[];
  addedTerms: string[];
}

export function rephraseAddsNothing(original: string, rephrased: string): RephraseCheck {
  const originalNumbers = new Set(numbersIn(original));
  const addedNumbers = [...new Set(numbersIn(rephrased))].filter((n) => !originalNumbers.has(n));
  const addedTerms = TECH_TERMS.filter((t) => mentionsTerm(rephrased, t) && !mentionsTerm(original, t));
  return { ok: addedNumbers.length === 0 && addedTerms.length === 0, addedNumbers, addedTerms };
}

/** Цитата расхождения между вариантами CV (К-23) обязана дословно
 * встречаться в том варианте, на который ссылается. Иначе «расхождение»
 * построено на фразе, которой человек не писал, — и обсуждать с
 * работодателем ему предлагается выдумку.
 *
 * Сравнение по нормализованному тексту: регистр, пробелы и типографские
 * кавычки/тире не должны решать, показать находку или нет. */
/** Пункт [one-quote-rule] 2026-09-06: эта реализация была самой
 * осторожной из пяти (типографика + минимальная длина), и именно она
 * стала единственной — переехала в `common/quote-match.ts`. Здесь
 * переэкспорт под прежним именем: домен вариантов CV говорит
 * «встречается ли», а не «из источника ли». */
import { quoteIsFromSource as quoteOccursIn, normalizeForQuoteMatch } from '../common/quote-match';
export { quoteOccursIn, normalizeForQuoteMatch };

// ── Пункт [translated-adds] 2026-09-06 ──
//
// НАЙДЕНО. Барьер выше стоит на ПЕРЕФОРМУЛИРОВКЕ: добавленное число не
// попадает в базу, ответ уходит на повтор. На ПЕРЕВОДЕ того же CV
// барьера не было вовсе — только «обратная сверка», где вторая модель
// сообщает о первой, что та потеряла и что дописала. Разница
// принципиальная: там проверка, здесь самоотчёт. И вариант сохранялся
// независимо от того, что самоотчёт сказал.
//
// Цена та же, что у переформулировки, и выше: человек отправляет
// работодателю резюме на языке, которым чаще всего владеет хуже, чем
// адресат. Дописанная цифра в нём — чужое достижение под его именем, и
// заметить её ему труднее, чем в родном тексте.
//
// ЧИСЛА ПЕРЕЖИВАЮТ ПЕРЕВОД. Слова меняются целиком — сравнивать их
// между языками нечем. Цифры остаются цифрами: «5 лет» → «5 years».
// Поэтому барьер здесь ровно один и намеренно узкий — число, которого
// не было в оригинале.
//
// ЧЕГО ОН НЕ ЛОВИТ — и делать вид, что ловит, нельзя:
//   • число, записанное словом («five years») — это для проверки
//     ПОТЕРЯ числа, а не добавление; ловится обратной сверкой, не здесь;
//   • смысловое преувеличение без цифр — то же ограничение, что у
//     барьера переформулировки, и по той же причине.
//
// РАЗДЕЛИТЕЛИ РАЗРЯДОВ. «1 000» в русском, «1,000» в английском,
// «1.000» в немецком — одно число. Не убрать их значило бы завалить
// проверку ложными срабатываниями на каждом переводе с числом больше
// тысячи, а проверка, которая кричит всегда, не проверка.

/** Число без разрядных разделителей: 1 000 / 1,000 / 1.000 → 1000. */
function normalizeNumber(raw: string): string {
  const compact = raw.replace(/[\s\u00a0]/g, '');
  // Три цифры после разделителя — это разряд, а не дробная часть.
  const degrouped = compact.replace(/[.,](?=\d{3}\b)/g, '');
  return degrouped.replace(',', '.').replace(/\.0+$/, '');
}

export function numbersInAcrossLocales(text: string): string[] {
  return (text.match(/\d[\d\s\u00a0.,]*\d|\d/g) ?? []).map(normalizeNumber).filter((n) => n.length > 0);
}

export interface TranslationCheck {
  ok: boolean;
  /** Числа, которых в оригинале не было. */
  addedNumbers: string[];
}

/** Барьер перевода: в переводе не должно появиться числа, которого нет в
 * оригинале. Односторонний намеренно — потерянное число это тоже беда,
 * но другая (о ней говорит обратная сверка), и смешивать их значило бы
 * получить одно невнятное «что-то не так». */
export function translationAddsNoNumbers(original: string, translated: string): TranslationCheck {
  const source = new Set(numbersInAcrossLocales(original));
  const addedNumbers = [...new Set(numbersInAcrossLocales(translated))].filter((n) => !source.has(n));
  return { ok: addedNumbers.length === 0, addedNumbers };
}

/** Проверка САМООТЧЁТА обратной сверки. Модель называет, что потеряно и
 * что дописано; названное обязано дословно встречаться там, где ему
 * место, — иначе человеку предлагается обсуждать выдумку. Тот же уговор,
 * что у цитаты расхождения между вариантами (`quoteOccursIn` выше), и
 * здесь он не применялся вовсе.
 *
 * Отброшенное не исчезает молча: число возвращается наружу — правило
 * всей этой сессии. */
export function verifiedBackCheck(
  backCheck: { lost?: unknown; added?: unknown },
  original: string,
  translated: string,
): { lost: string[]; added: string[]; unverifiable: number } {
  const asList = (v: unknown): string[] => (Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string') : []);
  const rawLost = asList(backCheck.lost);
  const rawAdded = asList(backCheck.added);
  // Потерянное должно быть в ОРИГИНАЛЕ, дописанное — в ПЕРЕВОДЕ.
  const lost = rawLost.filter((q) => quoteOccursIn(q, original));
  const added = rawAdded.filter((q) => quoteOccursIn(q, translated));
  return { lost, added, unverifiable: rawLost.length - lost.length + (rawAdded.length - added.length) };
}
