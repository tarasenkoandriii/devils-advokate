// pg_cron — про заморозку не знала ничего. Ни один фоновый запрос не
// фильтровал `frozenAt`.
//
// Что это значило на деле: задача к модели, поставленная в очередь до
// заморозки, уходила провайдеру ПОСЛЕ неё — деньги тратились на проект,
// который оператор уже остановил, а результат записывался внутрь. И
// вакансии, за которыми человек просил следить, перечитывались дальше,
// принося в замороженный проект новые данные. То есть «изменения
// недоступны» было неправдой: они продолжались, просто не человеческой
// рукой.
//
// ГРАНИЦА, И ПОЧЕМУ ОНА ЗДЕСЬ. Заморозка останавливает НОВУЮ работу над
// проектом и не мешает закончить уже начатую. Это не новое правило: тем
// же различением уже пользуется отзыв согласия — Пункт [revoked-then-sent]
// снимает только QUEUED, а RUNNING не трогает, потому что «делать вид,
// что отмена что-то там отменяет», когда содержимое уже у провайдера, —
// неправда. Здесь то же самое.
//
// И заморозка не запирает человека: она «запрещает менять проект, а не
// наказывает» — формулировка из самого guard'а, где по этой причине
// оставлен работающим отзыв собственного шеринга. Поэтому напоминания
// человеку продолжают приходить: напоминание — не изменение проекта, а
// сообщение о СОБСТВЕННОМ плане человека, и молча его глушить значило бы
// сделать заморозку наказанием, о котором никому не сказали.
//
// Обе стороны границы перечислены ниже поимённо и проверяются тестом:
// список «продолжается» — такая же часть решения, как список
// «останавливается».

