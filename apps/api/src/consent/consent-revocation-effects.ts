// Пункт [consent-revocation] 2026-09-04 — что именно делает отзыв
// согласия, по каждому типу.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ. `ConsentService.revoke()` только помечал запись
// `revokedAt` и возвращал `{ revoked: true }`. Для большинства типов это
// правильно и достаточно: согласие — разрешение на БУДУЩЕЕ действие, и
// отзыв его прекращает. Но не для всех, и разница нигде не была ни
// зафиксирована, ни сказана человеку.
//
// НАЙДЕНО ДВА МЕСТА, ГДЕ ОТЗЫВ НИЧЕГО НЕ ОТЗЫВАЛ.
//
// 1. PUBLIC_SHARING. `enableSharing()` требует согласия перед тем, как
//    выдать `publicShareToken`, — а `publicView(token)` его больше
//    никогда не перепроверяет. Человек, нажавший «отозвать согласие на
//    публичный доступ», видел «готово», и страница обсуждения
//    продолжала открываться у всех, кому он раньше дал ссылку. Причём
//    сам продукт уже описывал такое состояние в тексте ошибки
//    («обсуждение больше не публично доступно») — состояние, которого
//    отзыв согласия создать не мог.
//
// 2. VOICE_BIOMETRIC. Здесь правильный путь В ПРОЕКТЕ БЫЛ:
//    `VoiceEmbeddingService.forget()` удаляет вектор и только потом
//    отзывает согласие. Но общий эндпоинт `DELETE /consent/:type` —
//    именно тот, которым человек пользуется в Центре приватности, —
//    звал `revoke()` напрямую, мимо удаления. Две двери, из которых
//    правильная только одна; та же форма «правило было, просто не
//    везде», что уже находилась в этих сверках несколько раз. И тип
//    согласия здесь особый: его формулировка — не «можно обрабатывать»,
//    а «можно ХРАНИТЬ постоянный биометрический идентификатор». Отзыв
//    разрешения на хранение, оставляющий хранимое, — противоречие в
//    определении.
//
// ЧТО ЗДЕСЬ ЕЩЁ ВАЖНО. Для остальных одиннадцати типов «только на
// будущее» — законный ответ, и менять его не нужно. Но его НАДО
// ПРОИЗНЕСТИ: человек, отзывающий согласие на внешний AI, вправе знать,
// что уже сделанные разборы остаются у него, а провайдер данные уже
// видел, и это неотзываемо. Молчание здесь читается как «всё стёрли» —
// та же форма, которую эти сверки разбирают с самого начала, только
// зеркальная: не пробел выглядит как полнота, а бездействие выглядит
// как действие.

import { ConsentType } from '@prisma/client';

export interface RevocationEffect {
  /** Что отзыв делает СВЕРХ пометки записи. `null` — ничего, и это
   * законно: согласие разрешало будущее действие, отзыв его прекращает. */
  alsoDoes: string | null;
  /** Что отзыв НЕ отменяет — человеческим текстом, без юридических
   * формулировок. Пустая строка недопустима: у каждого типа есть что-то,
   * что остаётся, и назвать это обязательно. */
  doesNotUndo: string;
}

