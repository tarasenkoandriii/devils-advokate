/** Отчёт, который возвращается человеку. `revoked: false` означает, что
 * активного согласия этого типа и не было, — отдельное утверждение, а не
 * «сделано». */
export interface RevocationReport {
  consentType: ConsentType;
  revoked: boolean;
  recordsRevoked: number;
  /** Что реально сделано сверх пометки: заполняется только если сделано. */
  alsoDone: string[];
  /** Что отзыв не отменяет — всегда, даже когда отзывать было нечего. */
  doesNotUndo: string;
}
