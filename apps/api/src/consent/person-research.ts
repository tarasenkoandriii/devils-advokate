// НАЙДЕННОЕ. В ТЗ записано решение владельца (§16.0): «исследование
// человека — только через существующий контур `PERSON_RESEARCH`,
// отдельно». Контура не было. `ConsentType.PERSON_RESEARCH` есть в
// схеме, есть в типах клиента и есть в реестре последствий отзыва (там
// для него написано, что именно отзыв НЕ отменяет) — но за весь
// `apps/api/src` его не требует ни одна строка и не выдаёт ни один
// экран. Согласие, которое нельзя дать и которое ничего не открывает:
// слово «существующий» в ТЗ было неправдой с того дня, как его
// написали.
//
// ПОЧЕМУ ЭТО НЕ ФОРМАЛЬНОСТЬ. Предмет здесь — данные ЧЕЛОВЕКА, которого
// в продукте нет: он не наш пользователь, согласия он не давал и
// возразить не может. Единственное, чем продукт мог защитить его, —
// отдельное осознанное решение пользователя. Вместо него всё
// исследование людей шло под общим `EXTERNAL_AI`, выданным один раз в
// самом начале ради ответа на первый вопрос.
//
// ГДЕ ПРОВЕДЕНА ГРАНИЦА. Требование стои́т там, где ПРЕДМЕТ разбора —
// названный человек, то есть где на выходе появляется новое знание О
// НЁМ. Там, где человек лишь ограничивает выборку (позиция, реплика,
// факт, скрипт для самого пользователя), требования нет: гасить их
// значило бы спрашивать согласие на разбор собственного разговора
// пользователя. Обе стороны границы перечислены здесь поимённо, и обе
// проверяются тестом: список «не требует» — такая же часть решения, как
// список «требует», и он не должен молча зарасти.

