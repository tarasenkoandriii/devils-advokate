// в коді, але структурний паттерн "фіксований чек-лист, не AI-agenda
// з історії" переюзаний тут свідомо).

import { PurchaseCategory } from '@prisma/client';

const COMMON_ITEMS = ['Бюджет (вилка мін-макс, валюта)', 'Спосіб фінансування (готівка/іпотека/кредит/trade-in)', 'Терміновість (наскільки швидко потрібно закрити покупку)'];

const REAL_ESTATE_ITEMS = [
  ...COMMON_ITEMS,
  'Тип нерухомості (квартира/будинок/комерція)',
  'Кількість кімнат/спалень',
  'Район/райони, які розглядаються',
  'Поверх (мінімальний/максимальний прийнятний)',
  'Стан (новобудова/вторинка/потребує ремонту)',
  'Критичні "стоп-фактори" (наприклад перший/останній поверх, відсутність ліфта)',
];

const VEHICLE_ITEMS = [
  ...COMMON_ITEMS,
  'Марка/модель (або клас авто, якщо марка не принципова)',
  'Рік випуску (мінімальний прийнятний)',
  'Пробіг (максимальний прийнятний)',
  'Трансмісія (автомат/механіка)',
  'Тип пального (бензин/дизель/гібрид/електро)',
  'Критичні "стоп-фактори" (наприклад участь в ДТП, більше N власників)',
];

export function getOnboardingChecklist(category: PurchaseCategory): string[] {
  return category === PurchaseCategory.REAL_ESTATE ? REAL_ESTATE_ITEMS : VEHICLE_ITEMS;
}
