// рядом спросили «не пусто?», а у этого не спросили.
//
// НАЙДЕНО. Пункт [validation] разметил DTO валидаторами, и разметка
// дошла до всех публичных поверхностей. Но вопрос «может ли это быть
// пустой строкой?» задавался НЕ ВЕЗДЕ — и форма пропуска узнаётся
// сразу: в одном классе у главного поля непустота запрещена, а у
// соседнего проверен только ТИП. То есть вопрос задавали, подумали — и
// про соседа забыли. Таких классов двадцать пять.
//
// И ОТДЕЛЬНО — СПИСКИ. Полей-списков строк пятнадцать, и запрета пустого
// ЭЛЕМЕНТА не было НИ У ОДНОГО. Среди них `constraints`,
// `nonNegotiables`, `negotiables` и `doNotSay` — то, что человек сказал
// о своих границах и что продукт показывает ему обратно его же словами.
// Пустая строка в таком списке рисуется пунктом: человек видит пустую
// строчку среди своих ограничений и не может понять, что он имел в виду.
// В `doNotSay` — списке того, чего продукт говорить НЕ должен, — пустой
// пункт хуже шума.
//
// ЧЕМ ПУСТАЯ СТРОКА ХУЖЕ ОТСУТСТВИЯ. Отсутствие поле не заполняет:
// продукт знает, что не знает, и так и говорит. Пустая строка
// СОХРАНЯЕТСЯ КАК ЗНАЧЕНИЕ, и дальше неотличима от ответа — ровно
// «пробел выглядит как полнота», только на входе, а не на выходе.
//
// ЧТО СДЕЛАНО. Свободнотекстовым полям и всем спискам строк непустота
// запрещена. Осталось двадцать одно поле, у которых её нет намеренно, —
// они перечислены ниже с причиной. Сверка держит замкнутость: новое
// поле со строкой и без ответа на этот вопрос уронит сборку.
//
// ЦЕНА, КОТОРУЮ НАДО НАЗВАТЬ. Клиент, до сих пор присылавший `""` в
// необязательном поле, получит 400 вместо молчаливой записи пустоты.
// Это и есть смысл правки, но это ИЗМЕНЕНИЕ ПОВЕДЕНИЯ, а не только
// ужесточение проверки, и прятать его в списке «улучшений» нечестно.

