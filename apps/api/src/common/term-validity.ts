// Пункт [term-never-ends] 2026-09-06 — срок объявлен, но не наступает.
//
// ЧТО ИЗМЕРЕНО. Восемь моделей несут `expiresAt`. Семь из них
// проверяются на каждом входе, и проверка написана по месту — одной
// строкой, скопированной столько раз, сколько входов. Так работает,
// пока копий не станет на одну больше, чем помнит автор. Их стало.
//
// ЧТО НАЙДЕНО.
//
// 1. `EngagementService.assertActive()` принимает
//    `{ status, expiresAt }` — и `expiresAt` НЕ ЧИТАЕТ. Поле объявлено
//    в сигнатуре самой функции: то есть намерение проверить срок
//    записано, а проверки нет. Три места зовут эту функцию, и все три —
//    передачи данных между работодателем и агентством: доставка отчёта,
//    запрос по кандидату, ревью текста вакансии. Заказ с истёкшим
//    сроком продолжал считаться действующим.
//
// 2. `OfferExchangeService.shareToCandidate()` — единственный из пяти
//    входов по `CandidateShare`, где нет проверки срока. Остальные
//    четыре проверяют. То есть соискатель поставил ссылке срок, а по
//    этому пути после срока в его лист всё равно ложилась копия оффера.
//
// 3. Чеклист закрытия вакансии (Р-14) называет «активными» и заказы, и
//    шеринги, применяя ДВА РАЗНЫХ ослабленных определения: заказы — по
//    `status`, шеринги — по `revokedAt`. Ни одно не включает срок, и
//    оба расходятся с тем, что об «активности» думает сам сервис.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЕЩЁ ОДНА СТРОКА ПО МЕСТУ. Потому что
// именно «ещё одна строка по месту» и есть найденный изъян. Эта сессия
// встречала форму «правило было, просто не везде» шесть раз; каждый раз
// лечение было одно — сделать правило ОДНИМ предметом, который нельзя
// забыть позвать, потому что звать нечего кроме него.
//
// ГРАНИЦА, КОТОРУЮ ЭТОТ МОДУЛЬ НЕ ПЕРЕХОДИТ. Он отвечает на вопрос
// «можно ли ПО ЭТОЙ ЗАПИСИ действовать сейчас», и только. Он не решает,
// что делать с уже полученным: истёкший заказ не отменяет доставленные
// отчёты, истёкшая ссылка не забирает принятую копию. Это ровно то
// разделение, которое `consent-revocation-effects.ts` проводит для
// отзыва согласия, и оно здесь то же самое.

/** Запись со сроком действия. Намеренно структурная, а не по модели:
 * условие одно для всех восьми, и заводить восемь одинаковых проверок
 * значило бы повторить изъян в другом виде. */
export interface HasTerm {
  expiresAt: Date;
}

/** Срок ещё не вышел. `now` параметром — чтобы проверка была проверяема
 * без подмены системных часов. */
export function termIsCurrent(record: HasTerm, now: Date = new Date()): boolean {
  return record.expiresAt > now;
}

/** Отозвано ли — отдельным предикатом, потому что «истекло» и
 * «отозвали» человеку значат разное: первое проходит само, второе
 * сделал кто-то. Тексту отказа эта разница НЕ передаётся (см. ниже),
 * но коду она нужна. */
export function isRevoked(record: { revokedAt?: Date | null }): boolean {
  return !!record.revokedAt;
}

/** Ссылка годна к использованию: срок не вышел и её не отзывали. */
export function shareIsUsable(
  record: HasTerm & { revokedAt?: Date | null },
  now: Date = new Date(),
): boolean {
  return termIsCurrent(record, now) && !isRevoked(record);
}

/** Единая формулировка отказа.
 *
 * «Просрочено» и «отозвано» намеренно неразличимы в тексте — решение,
 * уже принятое в `interview-pool-team.service.ts` и записанное там
 * словами: тот, у кого ссылка, не должен по ответу понимать, отозвали
 * её конкретно ему или срок вышел у всех. Формулировка живёт здесь,
 * чтобы не разъехаться по пяти файлам. */
export const TERM_OVER_MESSAGE = 'Ссылка недействительна или просрочена';
