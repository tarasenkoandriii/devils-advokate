// Пункт [the-first-row-was-whichever] 2026-10-05 — «активная версия
// промпта» читалась в 41 месте своей копией запроса, и все 41 копии
// выбирали НЕ ТУ строку, когда активных оказывалось две.
//
// ЧТО БЫЛО. Инвариант «ровно одна ACTIVE на promptId» записан словами в
// шапке `promoteToActive` и не обеспечен ничем: ни уникального
// ограничения в базе, ни транзакции, ни блокировки (измерено — в
// `prompt-registry.service.ts` не было ни одного `$transaction`).
// Вдобавок ACTIVE создаёт не только `promoteToActive`, но и `rollback`,
// а до появления этого сервиса версии активировали ручным SQL — то
// есть данные, которые уже лежат в базе, инварианта не несут.
//
// ПОЧЕМУ ИМЕННО «ПОСЛЕДНЯЯ АКТИВИРОВАННАЯ», А НЕ «САМАЯ НОВАЯ».
// Все 41 копии сортировали по `createdAt: 'desc'` — и это ровно та
// сортировка, которая ломает ОТКАТ. `rollback` возвращает в ACTIVE
// версию, СОЗДАННУЮ РАНЬШЕ; если недобитая новая версия осталась
// активной, сортировка по созданию выбирает её — то есть ту самую,
// от которой оператор только что откатился. Он видит успешный ответ,
// видит запись в журнале аудита, а продукт продолжает отвечать
// откаченным промптом. Поэтому ключ — `updatedAt`: статус меняется
// только `update`-ом, значит «последняя переведённая в ACTIVE».
//
// ВТОРОЙ КЛЮЧ `id` — ПОТОМУ ЧТО `updatedAt` НЕ УНИКАЛЕН. Это тот же
// урок, что Пункт [tie-is-random] 2026-09-06: `@updatedAt` ставит
// время, а не номер, и два `update` в одну миллисекунду дают ту же
// ничью заново. `id` — `@id @default(cuid())`, он её разрывает, и
// cuid монотонен по времени, так что порядок ещё и осмыслен.
//
// ЧЕГО ЭТО НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ. Сортировка делает произвольный
// выбор ВОСПРОИЗВОДИМЫМ, а не правильным — возражение записано в
// проекте раньше, в `employer-dossier/single-dossier.ts`. Правильным
// его делает ограничение базы: частичный уникальный индекс
// `(promptId) WHERE status = 'ACTIVE'` лежит в
// `prisma/manual-migrations/one_active_row_2026_10_05.sql` и ЕЩЁ НЕ
// ПРИМЕНЁН — его применяет владелец, и он может не создаться, если
// две ACTIVE в базе уже есть. Пока индекса нет, одна ACTIVE держится
// замком в `promoteToActive`/`rollback`, а эта функция отвечает на
// вопрос «какую читать», если их всё-таки две.

import { PromptVersionStatus } from '@prisma/client';

import { PrismaService } from '../prisma/prisma.service';

/** Активная версия промпта — ОДНО место чтения на весь продукт.
 * 41 копия этого запроса была сама дефектом: разъехаться они не
 * успели, но исправить ошибку пришлось бы в 41 месте. */
export async function activePromptVersion(prisma: PrismaService, promptId: string) {
  return prisma.promptVersion.findFirst({
    where: { promptId, status: PromptVersionStatus.ACTIVE },
    orderBy: [{ updatedAt: 'desc' }, { id: 'desc' }],
  });
}
