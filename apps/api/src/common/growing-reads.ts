export type GrowingReadState =
  /** Потолок стоит, и ответ говорит, что список неполон. */
  | 'bounded-and-says-so'
  /** Потолка нет намеренно, причина названа в `why`. */
  | 'unbounded-on-purpose';

export interface GrowingRead {
  /** Файл относительно apps/api/src. */
  file: string;
  /** Модель Prisma, которую читают. */
  model: string;
  /** Что растит это множество. */
  grows: string;
  state: GrowingReadState;
  /** Для 'bounded-and-says-so' — где стои́т потолок; для
   *  'unbounded-on-purpose' — почему его нет. */
  why: string;
}

