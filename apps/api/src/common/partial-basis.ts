// Пункт [partial-basis] 2026-09-04 — на чём на самом деле построен
// вывод, который читает человек.
//
// НАЙДЕНО. Разборы о человеке строятся на срезе данных, а подаются как
// разборы на всех данных. В четырёх местах подряд контекст собирался так:
//
//   behaviorPrecedent.findMany({ where: { personId }, take: 5,
//                                orderBy: [{ createdAt: 'desc' }, { id: 'desc' }] })
//   → «Известные прецеденты поведения: …»
//
// Модели говорили «ИЗВЕСТНЫЕ прецеденты», отдавая ей пять последних из
// скольких угодно. Разница не косметическая: на полном списке вывод «он
// так никогда не делал» неверен, а на срезе выглядит обоснованным —
// модель не может знать, что видит часть, если ей об этом не сказать.
// Ровно так же собирались «ключевые аргументы» — пять самых весомых из
// всех, названные без слова «пять».
//
// Сами лимиты законны: промпт не резиновый, и в коде это честно
// объяснено комментариями. Незаконно другое — что усечение было видно
// ТОЛЬКО в комментариях к коду. Это тот же изъян, вокруг которого
// построен весь продукт: пробел не должен выглядеть как полнота.
//
// ЧЕГО ЗДЕСЬ НЕТ. Сохранённые разборы не носят это знание с собой:
// колонки под него нет ни у одной модели результата, и заводить пятую
// ручную миграцию ради подписи под текстом — не та цена. Поэтому
// основание сообщается вместе со СВЕЖИМ ответом и говорится об этом
// прямо, а не выдаётся за свойство сохранённой записи (см. пункт в
// `TODO.md`).

export interface PartialBasis {
  /** Что именно урезано — словами, которые человек уже видит на экране. */
  what: string;
  /** Сколько вошло в разбор. */
  used: number;
  /** Сколько есть всего. */
  total: number;
  /** Чем отбирали: «последние» по дате или «самые весомые». */
  by: 'recent' | 'weight';
}

export function partialBasis(what: string, used: number, total: number, by: 'recent' | 'weight'): PartialBasis {
  return { what, used, total, by };
}

/** Урезано ли на самом деле. У большинства людей прецедентов меньше
 * лимита, и тогда говорить не о чем: сообщение об усечении там, где
 * усечения не было, — такой же обман, только в другую сторону. */
export function isTruncated(basis: PartialBasis): boolean {
  return basis.total > basis.used;
}

export function truncated(bases: readonly PartialBasis[]): PartialBasis[] {
  return bases.filter(isTruncated);
}

/** Приписка для МОДЕЛИ. Ставится вплотную к самому списку, а не в конец
 * промпта: свойство относится к этому списку, и в конце его легко
 * потерять из виду. */
export function promptBasisNote(basis: PartialBasis): string {
  if (!isTruncated(basis)) return '';
  return basis.by === 'recent'
    ? ` (в разбор вошли последние ${basis.used} из ${basis.total}; более ранние не показаны — не делай выводов о том, чего в списке нет)`
    : ` (в разбор вошли ${basis.used} самых весомых из ${basis.total}; остальные не показаны — не делай выводов о том, чего в списке нет)`;
}

/** Приписка для ЧЕЛОВЕКА. Пустая строка, если разбор построен на всём:
 * тогда и говорить не о чем. */
export function humanBasisNote(bases: readonly PartialBasis[]): string | null {
  const cut = truncated(bases);
  if (cut.length === 0) return null;
  const parts = cut.map((b) =>
    b.by === 'recent'
      ? `${b.what} — последние ${b.used} из ${b.total}`
      : `${b.what} — ${b.used} самых весомых из ${b.total}`,
  );
  return `Разбор построен не на всех данных: ${parts.join('; ')}. Это ограничение размера запроса к модели, а не признак того, что остальное неважно.`;
}

/** Приписка для ЭКРАНА, который человек читает как готовую сводку —
 * карточка разговора, повестка. Отличается от `humanBasisNote` не
 * вежливостью, а точностью: там речь о разборе, который только что
 * построили, здесь — о том, что показано на экране прямо сейчас.
 *
 * Пункт [shown-not-all] 2026-09-05: «Ключевые аргументы» на карточке —
 * пять самых весомых из всех, и человек уносил эту пятёрку в разговор,
 * считая её своим набором целиком. То же слово «ключевые», что уже
 * ловилось в промптах пунктом [partial-basis], только здесь его читает
 * не модель, а человек, и сразу идёт с ним говорить. */
export function shownBasisNote(bases: readonly PartialBasis[]): string | null {
  const cut = truncated(bases);
  if (cut.length === 0) return null;
  const parts = cut.map((b) =>
    b.by === 'recent'
      ? `${b.what} — последние ${b.used} из ${b.total}`
      : `${b.what} — ${b.used} самых весомых из ${b.total}`,
  );
  return `Показано не всё: ${parts.join('; ')}. Остальное не исчезло — оно в проекте целиком.`;
}
