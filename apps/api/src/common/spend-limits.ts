/** Откуда взялось действующее значение потолка.
 *
 * Пункт [the-lever-that-silently-did-nothing] 2026-09-30: раньше этого
 * различения не было вовсе, и три совершенно разных состояния выглядели
 * одинаково — «потолок 300». «Владелец выставил 300», «владелец ничего
 * не выставлял» и «владелец выставил, но значение не прочиталось» — это
 * три разные вещи, и последняя хуже первых двух, потому что рычаг
 * кажется нажатым. */
export type LimitSource =
  /** Значение взято из переменной окружения. */
  | 'окружение'
  /** Переменной нет — работает умолчание из кода. */
  | 'умолчание: переменная не задана'
  /** Переменная задана, но значение не прочиталось (не число или
   *  отрицательное). Работает умолчание, и об этом обязаны сказать. */
  | 'умолчание: значение не прочитано'
  /** Потолок зашит в коде и переменной не перекрывается. */
  | 'зашито в коде';

export interface ResolvedLimit {
  readonly value: number;
  readonly source: LimitSource;
  /** Что стои́т в переменной, если она задана. Нужно ровно затем, чтобы
   *  оператор увидел СВОЮ опечатку, а не просто «не прочитано». Значения
   *  потолков — числа, секретов здесь нет; длина обрезана, чтобы в экран
   *  не приехало чужое содержимое, если переменную перепутали. */
  readonly raw: string | null;
}

/** Действующее значение потолка И ПРИЧИНА, по которой оно действующее.
 *
 * Поведение при разборе не изменилось ни в одном случае — это проверяет
 * соседняя сверка, перебирающая все варианты. Добавлена только причина:
 * раньше она существовала в коде и не доезжала ни до кого. */
export function resolveLimit(env: string | null, fallback: number): ResolvedLimit {
  if (!env) return { value: fallback, source: 'зашито в коде', raw: null };
  const raw = process.env[env];
  if (raw === undefined || raw === '') {
    return { value: fallback, source: 'умолчание: переменная не задана', raw: null };
  }
  const shown = raw.slice(0, 40);
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed < 0) {
    return { value: fallback, source: 'умолчание: значение не прочитано', raw: shown };
  }
  return { value: Math.floor(parsed), source: 'окружение', raw: shown };
}

/** Единственное чтение потолка из окружения. Было пять почти одинаковых
 * разборов; отличались они мелочами (где-то `?? '300'`, где-то проверка
 * `> 0`, где-то `>= 0`), и именно такие мелочи разъезжаются. Невалидное
 * значение молча падает на умолчание: неверно настроенный env не должен
 * ронять работу — но и не должен снимать потолок.
 *
 * «Молча» относится к РАБОТЕ продукта, а не к оператору: с 2026-09-30
 * причина видна на вкладке «БД» (см. `resolveLimit`). Раньше она не была
 * видна нигде, и выставленный с опечаткой рычаг не отличался от
 * невыставленного. */
export function limitFrom(env: string | null, fallback: number): number {
  return resolveLimit(env, fallback).value;
}

/** Потолок по ключу реестра — чтобы место применения и документация
 * ссылались на одну запись, а не на две копии числа. */
export function spendLimit(env: string): number {
  const entry = SPEND_LIMITS.find((l) => l.env === env);
  if (!entry) throw new Error(`Потолок ${env} не описан в SPEND_LIMITS`);
  return limitFrom(entry.env, entry.fallback);
}
