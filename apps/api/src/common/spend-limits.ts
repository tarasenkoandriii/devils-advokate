/** Единственное чтение потолка из окружения. Было пять почти одинаковых
 * разборов; отличались они мелочами (где-то `?? '300'`, где-то проверка
 * `> 0`, где-то `>= 0`), и именно такие мелочи разъезжаются. Невалидное
 * значение молча падает на умолчание: неверно настроенный env не должен
 * ронять работу — но и не должен снимать потолок. */
export function limitFrom(env: string | null, fallback: number): number {
  if (!env) return fallback;
  const raw = process.env[env];
  if (raw === undefined || raw === '') return fallback;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed < 0) return fallback;
  return Math.floor(parsed);
}

/** Потолок по ключу реестра — чтобы место применения и документация
 * ссылались на одну запись, а не на две копии числа. */
export function spendLimit(env: string): number {
  const entry = SPEND_LIMITS.find((l) => l.env === env);
  if (!entry) throw new Error(`Потолок ${env} не описан в SPEND_LIMITS`);
  return limitFrom(entry.env, entry.fallback);
}
