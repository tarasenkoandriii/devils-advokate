// мог их выставить, потому что не знал, что они есть: всё работало на
// значениях, выбранных в коде.
//
// ПОЧЕМУ ЭТО НЕ ЗАМЕТИЛИ. В VERCEL.md стоит обещание: «список ниже
// сверен со `apps/api/.env.example` АВТОМАТИЧЕСКИ, не по памяти».
// Сверка была настоящей — и бесполезной для этого случая: она сравнивала
// ДОКУМЕНТ С ДОКУМЕНТОМ. Переменная, прочитанная из `process.env` и не
// записанная в `.env.example`, невидима для обеих сторон такой сверки.
// Это та же ошибка, что разбирает весь ряд: проверка измеряет то, что
// измеряет, а не то, что обещает.
//
// И ВТОРОЙ СЛОЙ. `SANDBOX-COVERAGE.md`, раздел «Где тратятся реальные
// деньги и квоты», называет транскрибацию ПЕРВОЙ («поминутно») и
// заканчивается фразой «Лимиты нигде не обходятся». Фраза верна
// буквально — существующие потолки действительно не обойти — и читается
// как «расходы ограничены». У транскрибации потолка НЕ БЫЛО ВОВСЕ: был
// только предел размера одного файла, 500 МБ. Пробел выглядел как
// полнота ровно там, где деньги тратятся быстрее всего.
//
// ЧТО ЭТОТ РЕЕСТР. Одно место, где перечислены все потолки расходов: и
// перекрываемые окружением, и жёстко зашитые. Зашитые перечислены не для
// симметрии — чтобы было видно, что их НЕЛЬЗЯ подкрутить, не трогая код.
// Документация сверяется с этим реестром и с самим кодом, а не с другим
// документом.

