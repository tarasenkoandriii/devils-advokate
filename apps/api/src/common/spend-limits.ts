// НАЙДЕННОЕ. Расходы продукта ограничены потолками на пользователя в
// сутки. Шесть из них перекрываются переменными окружения — то есть это
// РЫЧАГИ ВЛАДЕЛЬЦА, единственный способ сказать «дороже этого не
// тратить». Ни одна из шести не названа ни в `apps/api/.env.example`, ни
