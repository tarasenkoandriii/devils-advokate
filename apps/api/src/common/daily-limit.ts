// Пункт [the-day-was-the-servers] 2026-10-26 — «попробуйте завтра» у
// потолка, который не сбрасывается завтра.
//
// ИЗМЕРЕНО. Суточных потолков в продукте одиннадцать, и все одиннадцать
// устроены одинаково: считаются записи с `createdAt >= now - 24ч`. Это
// СКОЛЬЗЯЩЕЕ окно. Календарной полуночи в механизме нет ни у одного —
// и правильно, потому что часового пояса человека у сервера нет (это
// разобрано и записано в `server-time.ts`, Пункт [server-said-which-day]).
//
// А текст отказа говорил три разных вещи:
//   • «Попробуйте позже» — честно, но не отвечает на единственный
//     вопрос, который у человека есть;
//   • «попробуйте завтра» (поиск YouTube, анализ мотивов, проверка
//     фото) — НЕПРАВДА. Истративший потолок в 23:00 приходит в 00:05 и
//     получает тот же отказ тем же текстом. Полночь здесь не значит
//     ничего;
//   • ничего про сброс вовсе (распознавание документов).
//
// ЧТО ПРОДУКТ ЗНАЛ И НЕ ГОВОРИЛ. Момент освобождения вычисляется точно:
// это `createdAt` САМОЙ СТАРОЙ записи окна плюс сутки. Когда ей
// исполнится 24 часа, она выпадет из окна и место освободится — ровно
// одно. Ни один экран продукта не показывал ни остатка потолка, ни
// времени сброса (проверено: `outwardCallsLeft` не вызывался вообще
// ниоткуда), то есть человек не мог узнать этого никак.
//
// ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ:
//  • не меняет механизм. Окно осталось скользящим: календарные сутки
//    требовали бы часового пояса человека, которого нет, и подмена
//    одной неточности другой — не правка;
//  • не обещает, что через названное время освободится ВСЁ. Освободится
//    одно место, и это сказано словом «место»: «освободится через 3 ч» о
//    всём потолке было бы новой неправдой;
//  • лишний запрос делается ТОЛЬКО на пути отказа. Счастливый путь
//    остался в один `count`: платить за вежливость отказа теми же
//    миллисекундами у всех — значит платить за то, что почти никому не
//    нужно.

import { timeUntil } from './server-time';

/** Длина окна. Одно число на весь продукт: одиннадцать копий `24 * 60 *
 *  60 * 1000` разъехались бы, и «сутки» у двух потолков стали бы разными
 *  сутками. */
export const DAILY_WINDOW_MS = 24 * 60 * 60 * 1000;

/** Начало окна. Не полночь — «сутки назад от сейчас». */
export function dailyWindowStart(now: Date = new Date()): Date {
  return new Date(now.getTime() - DAILY_WINDOW_MS);
}

/** Когда освободится одно место: самой старой записи окна исполнятся
 *  сутки. `null` — если самую старую не удалось прочитать; тогда отказ
 *  обходится без обещания времени, а не выдумывает его. */
export function releaseAt(oldestInWindow: Date | null | undefined): Date | null {
  if (!oldestInWindow) return null;
  return new Date(oldestInWindow.getTime() + DAILY_WINDOW_MS);
}

/** Текст отказа по суточному потолку — ОДИН на все одиннадцать мест.
 *
 *  `subject` — чего именно потолок, в именительном или родительном, как
 *  уже написано в реестре расходов: «озвучки», «проверок фото».
 *  `unit` — как измеряется потолок: «/сутки», «мин/сутки».
 *
 *  Слово «завтра» здесь не появится по построению: функция знает только
 *  расстояние во времени. */
export function dailyLimitRefusal(args: {
  subject: string;
  limit: number;
  unit?: string;
  oldestInWindow?: Date | null;
  /** Что именно освободится. У потолка по ЧИСЛУ это «одно место»; у
   *  потолка по ДЛИТЕЛЬНОСТИ — длительность самой старой записи, и
   *  называть её «местом» было бы неправдой о размере освобождающегося. */
  releases?: string;
  now?: Date;
}): string {
  const unit = args.unit ?? '/сутки';
  const head = `Достигнут суточный лимит: ${args.subject} (${args.limit}${unit}).`;
  const release = releaseAt(args.oldestInWindow);
  if (!release) {
    // Честное «позже»: когда освободится, мы в этот раз не знаем.
    return `${head} Попробуйте позже.`;
  }
  const what = args.releases ?? 'одно место';
  return `${head} Потолок скользящий: ${what} освободится через ${timeUntil(release, args.now)}.`;
}
