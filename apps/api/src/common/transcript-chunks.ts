// Сверка длинных разговоров 2026-09-04 — почему продукт переставал
// работать ровно на своём главном случае.
//
// Заход [input-limits] (2026-09-03) поставил общий потолок длины запроса
// к модели: 120 000 символов, «заведомо больше любого честного серверного
// промпта». Число выбиралось по САМОМУ ДЛИННОМУ ПРОМПТУ В КОДЕ (сверка
// вариантов CV, 24 000) — то есть по тому, что видно в исходниках. А
// транскрипт в исходниках не виден: его длину задаёт человек, который
// записал разговор.
//
// Посчитано: час живой речи это примерно 54 000 символов текста плюс
// служебные части строк (идентификатор реплики, метка говорящего) —
// около 77 000 символов промпта. Дальше:
//
//     90 минут → 116 100 символов, ещё проходит
//     105 минут → 135 450, ОТКАЗ
//     3 часа   → 232 200, ОТКАЗ
//
// То есть примерно с полутора часов разбор переставал работать вовсе. При
// этом загрузка принимает файл до 500 МБ — часы записи, — расшифровка за
// эти часы платится, а на разборе человек получал «слишком длинный текст,
// сократите». Сократить записанный разговор нельзя: он такой, какой был.
// Двухчасовые переговоры и трёхчасовой семейный разговор — не крайний
// случай этого продукта, а его основной.
//
// Почему нельзя было просто обрезать (и почему потолок вообще появился):
// модель ответила бы про урезанный фрагмент, а человек считал бы, что она
// видела весь разговор. Это ровно та ложь умолчанием, которую продукт
// обещает не допускать. Поэтому здесь — разбор ЧАСТЯМИ: модель видит
// каждую часть целиком, находки складываются, и человеку говорится, что
// разбор шёл частями.
//
// ЧТО ЧАСТИ ТЕРЯЮТ — это должно быть сказано, а не спрятано. Находка,
// которая видна только при сопоставлении начала разговора с концом
// («в начале обещал одно, через два часа другое»), в разбивке по частям
// не найдётся. Поэтому приём применяется только к детекторам, чья находка
// живёт ВНУТРИ одной реплики: переломные моменты, манипулятивные приёмы,
// «это лучше не говорить». Разбор расхождений (`discrepancy-analysis`)
// сюда сознательно не включён: его работа и есть сопоставление слов друг
// с другом через весь разговор и с прошлыми разговорами, и разрезание
// окнами молча ослабило бы ровно то, что он обещает. Там остаётся честный
// отказ с названной причиной.

import { MAX_USER_PROMPT_CHARS } from '../ai-router/prompt-limits';

/** Запас под системный промпт, контекст аргументов и разметку JSON —
 * всё, что уезжает в тот же запрос помимо самих реплик. */
const RESERVED_FOR_CONTEXT = 20_000;

export const CHUNK_BUDGET_CHARS = MAX_USER_PROMPT_CHARS - RESERVED_FOR_CONTEXT;

/** Примерно столько символов даёт минута живой речи — по этому числу
 * считается граница, которую видит человек в тексте отказа. Оценка, и
 * названа оценкой: точную длину знает только сам транскрипт. */
export const CHARS_PER_MINUTE_OF_SPEECH = 900;

export interface ChunkableSegment {
  id: string;
  text: string;
}

/** Режет реплики на части, каждая из которых укладывается в бюджет.
 * Реплику никогда не делит: половина фразы в одной части и половина в
 * другой — это уже искажение того, что человек сказал.
 *
 * Одна реплика длиннее целого бюджета (расшифровка без пауз, испорченная
 * диаризация) остаётся отдельной частью как есть: резать её здесь значило
 * бы принять решение за человека молча. Такая часть уйдёт в роутер и
 * получит честный отказ по длине — видимый, а не тихий. */
export function chunkSegments<T extends ChunkableSegment>(
  segments: T[],
  renderLine: (segment: T) => string,
  budget: number = CHUNK_BUDGET_CHARS,
): T[][] {
  const chunks: T[][] = [];
  let current: T[] = [];
  let size = 0;

  for (const segment of segments) {
    const lineSize = renderLine(segment).length + 1; // +перевод строки
    if (current.length > 0 && size + lineSize > budget) {
      chunks.push(current);
      current = [];
      size = 0;
    }
    current.push(segment);
    size += lineSize;
  }
  if (current.length > 0) chunks.push(current);
  return chunks;
}

/** Текст, который человек увидит рядом с находками, если разбор шёл
 * частями. Говорит три вещи: что частей было больше одной, почему так
 * вышло, и ЧЕГО такой разбор не увидит. Третье — главное: без него
 * «разобрано» читалось бы как «разобрано целиком». */
export function chunkedAnalysisNotice(chunkCount: number, minutes: number | null): string | null {
  if (chunkCount <= 1) return null;
  const length = minutes ? `примерно ${minutes} мин. ` : '';
  return (
    `Разговор ${length}длиннее, чем помещается в один разбор, поэтому он разобран по частям (${chunkCount}). ` +
    'Каждая часть проанализирована целиком, ничего не отброшено. ' +
    'Чего такой разбор не увидит: связь между началом и концом разговора — например, что сказанное в первые ' +
    'минуты расходится со сказанным через два часа. Это ограничение самого способа, а не признак, что таких ' +
    'мест нет.'
  );
}

/** Оценка длительности по объёму текста — для текста отказа и для
 * подписи. Возвращает null, если оценивать не из чего. */
export function estimateMinutes(totalChars: number): number | null {
  if (totalChars <= 0) return null;
  return Math.max(1, Math.round(totalChars / CHARS_PER_MINUTE_OF_SPEECH));
}
