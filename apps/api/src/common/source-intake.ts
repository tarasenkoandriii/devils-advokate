// про всё.
//
// НАЙДЕНО. Пункт [partial-basis] 2026-09-04 закрыл усечение на ВЫХОДЕ:
// разбор строился на пяти последних прецедентах из скольких угодно, а
// подавался как разбор на всех. Ровно та же беда на ВХОДЕ осталась
// незамеченной, и она тяжелее:
//
//   const text = params.text.slice(0, MAX_SOURCE_TEXT_CHARS);   // 16 000
//   userPrompt: userPrompt.slice(0, 24_000)
//
// Человек вставляет оффер на сорок тысяч знаков — разбирается первая
// треть. Ответ приходит обычный: «Черновиков позиций: 7 —
// подтвердите их в списке пунктов». Ни слова о том, что до второй
// половины текста разбор не дошёл. А неприятные условия живут как раз
// в конце документа.
//
// ХУЖЕ ВСЕГО ТАМ, ГДЕ ПУСТО. `skipped-note.ts` уже писал об этом
// прямо: «Под пустым списком экраны пишут утвердительно:
// „Compliance-флагов нет“, „Расхождений не найдено“». Если проверка
// дебрифа прочитала 24 000 знаков из сорока тысяч и ничего не нашла,
// человек читает «нарушений нет» — утверждение обо всём тексте,
// сделанное по его куску.
//
// ПОЧЕМУ НЕ «ПРОСТО ПОДНЯТЬ ПОТОЛОК». Потолок законен: промпт не
// резиновый, и у моделей есть предел. Незаконно молчание о нём. Тот же
// вывод, что в [partial-basis]: усечение было видно ТОЛЬКО в
// комментариях к коду.
//
// МОДЕЛИ ГОВОРИТСЯ ТОЖЕ. Модель не может знать, что видит часть, если
// ей об этом не сказать: на обрезанном тексте вывод «такого условия в
// документе нет» звучит так же уверенно, как на полном.

/** Сколько текста источника вошло в разбор. */
export interface SourceIntake {
  /** Знаков ушло в разбор. */
  used: number;
  /** Знаков было. */
  total: number;
  /** Потолок, из-за которого срезано. */
  limit: number;
}

/** Обрезает текст и сообщает, что именно случилось. Одна функция
 * вместо `slice` на месте вызова — чтобы обрезать и промолчать было
 * не проще, чем обрезать и сказать. */
export function takeSource(text: string, limit: number): { text: string; intake: SourceIntake } {
  return { text: text.slice(0, limit), intake: { used: Math.min(text.length, limit), total: text.length, limit } };
}

export function isTruncatedIntake(intake: SourceIntake): boolean {
  return intake.total > intake.used;
}

/** Приписка для МОДЕЛИ — вплотную к самому тексту, а не в конец
 * промпта: свойство относится к этому тексту, и в конце его легко
 * потерять из виду (тот же довод, что в `partial-basis.ts`). */
export function promptIntakeNote(intake: SourceIntake): string {
  if (!isTruncatedIntake(intake)) return '';
  return (
    `\n\n[В разбор вошли первые ${intake.used} знаков из ${intake.total}; конец текста не показан. ` +
    'Не делай выводов о том, чего в показанной части нет: отсутствие условия здесь не значит, что его нет в документе.]'
  );
}

/** Приписка для ЧЕЛОВЕКА. `null`, если текст вошёл целиком: сообщение
 * об усечении там, где усечения не было, — такой же обман, только в
 * другую сторону. */
export function intakeNote(intake: SourceIntake): string | null {
  if (!isTruncatedIntake(intake)) return null;
  const percent = Math.round((intake.used / intake.total) * 100);
  return (
    `Разобран не весь текст: прочитаны первые ${intake.used} знаков из ${intake.total} (${percent}%). ` +
    'Остальное в разбор не попало — это предел одного запроса к модели. ' +
    'Разбейте текст на части и повторите, иначе о конце документа продукт не сказал ничего — ни что там что-то есть, ни что там пусто.'
  );
}

