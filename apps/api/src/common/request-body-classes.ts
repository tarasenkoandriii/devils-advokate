// Пункт [body-classes] 2026-09-04 — почему тело запроса объявляется
// КЛАССОМ, а не интерфейсом, и где из этого сделаны исключения.
//
// Пункт [outside-input] 2026-09-04 намерил пятнадцать мест, где `@Body()`
// типизирован интерфейсом, и отложил их отдельной работой с прямой
// формулировкой: «для них ValidationPipe бессилен СТРУКТУРНО (у
// интерфейса нет метатипа в рантайме), сколько декораторов ни пиши».
// Это не преувеличение: интерфейс исчезает при компиляции, в рантайме
// Nest получает `Object`, и pipe пропускает тело как есть — даже если
// рядом лежит идеально размеченный DTO. Тринадцать из пятнадцати
// переведены в классы этим заходом.
//
// ПОЧЕМУ ПЕРЕВОД БЕЗОПАСЕН. TypeScript типизирует структурно: класс без
// приватных полей взаимозаменяем с одноимённым интерфейсом везде, где
// тот использовался, — включая объектные литералы в тестах и вызовы
// сервисов. Поэтому интерфейсы заменены классами НА МЕСТЕ, а сигнатуры
// сервисов не тронуты: HTTP-граница получает проверку, внутренний код
// не замечает разницы.
//
// ОТКУДА ВЗЯТЫ ПОТОЛКИ. Не из головы, а из уже сложившихся в проекте:
// комментарий — 2000 (ревью вакансии), развёрнутый ответ человека —
// 4000 (анкета кандидата), короткое обещание/прогноз — 1000, причина —
// 300. Списки — `ArrayMaxSize`, потому что массив без потолка это тот же
// безлимитный текст, только в другой обёртке.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. `whitelist` у ValidationPipe по-прежнему
// выключен (обоснование — в create-app.ts): недекорированных DTO-классов
// в контроллерах всё ещё больше половины, и включение вырезало бы у них
// все поля. Перевод интерфейсов в классы к этому не приближает и не
// отдаляет — он закрывает другую дыру: ту, где проверка была невозможна
// в принципе.

