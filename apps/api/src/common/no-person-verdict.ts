//  • ПАРАЛИНГВИСТИКА (§7.4). В промпте стои́т прямой запрет: «ЗАПРЕЩЕНЫ
//    суждения о правдивости, намерениях, характере, психическом
//    состоянии, любая „детекция лжи"». И сверх того — ВТОРАЯ ЛИНИЯ:
//    `parseParalinguisticsOutput` проверяет ВЫХОД модели по стоп-словам,
//    и попадание означает провал валидации, то есть сигнал не
//    записывается вовсе. Экран под находками пишет: «Только описание
//    наблюдаемого. Это не оценка правдивости и не „детектор лжи"».
//
//  • ДЕТЕКТОР МАНИПУЛЯЦИЙ (полный разбор и живой). Ни запрета в промпте,
//    ни проверки выхода. Валидатор `isValidManipulationPayload` смотрит
//    ФОРМУ ответа — что это массив и что поля нужных типов, — и ни слова
//    о содержании. А содержание здесь прямее, чем у паралингвистики:
//    модель получает реплику с указанием говорящего и возвращает
//    `technique` и `description` СВОБОДНЫМ ТЕКСТОМ плюс число
//    уверенности. Ничто не мешало ответу «собеседник лжёт и
//    манипулирует, типичный нарцисс» — форма верная, запись пройдёт.
//
// ПОЧЕМУ ЭТО ВАЖНЕЕ ОБЫЧНОГО «ПРАВИЛО НЕ ВЕЗДЕ». Запрет выводов о
// личности — не гигиена, а ОДНО ИЗ ТРЁХ ОСНОВАНИЙ ПРОДУКТА: «не детектор
// лжи», «никаких оценок людей», «решения принимает человек». Из двух
// разборов, где этот запрет вообще применим, он стоял у одного.
//
// ЧЕГО ЭТОТ ФИЛЬТР НЕ ДЕЛАЕТ — и это сказано прямо в исходнике, откуда он
// взят: он ГРУБЫЙ. Список слов не ловит вывод о личности, выраженный
// иначе, и не должен притворяться, что ловит. Первая линия — промпт;
// это вторая, на случай, когда первая не сработала.
//
// И ЧЕГО В СПИСКЕ НЕТ НАМЕРЕННО: слов «манипуляция», «манипулирует»,
// «давление». Назвать приём аргументации его именем — это работа
// детектора, а не вывод о человеке. Фильтр отделяет «в этой реплике
// подмена тезиса» от «этот человек лжец»; смешать их значило бы
// выключить сам разбор под видом его починки.

/** Стоп-слова «выводов о личности» в выходе модели: утверждения о
 * правдивости и клинические ярлыки. Попадание — провал валидации и
 * повтор запроса, а не запись находки о человеке. */
export const PERSON_VERDICT_PATTERNS =
  /лжёт|лжет|врёт|врет|обманывает|лживый|лгун|is lying|liar|deceptive person|психопат|нарцисс|социопат|патологическ(ий|ая) лж/i;

/** true — в тексте есть вывод о личности, которого быть не должно. */
export function hasPersonVerdict(text: string): boolean {
  return PERSON_VERDICT_PATTERNS.test(text);
}

