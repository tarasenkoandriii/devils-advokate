// Пункт [computed-for-the-person-never-shown] 2026-09-30 — во что упирался
// сторож языка.
//
// ПОВОД. Сверка языка 2026-09-04 нашла 28 украинских сообщений внутри
// полностью русского интерфейса и завела правило: то, что сервер говорит
// человеку, звучит на одном языке. Правило верное. Но читало оно ТОЛЬКО
// СТРОКИ, В КОТОРЫХ ЕСТЬ `Exception(` — то есть тексты ошибок.
//
// А человеку продукт говорит не только ошибками. `historyDisclaimer`
// предупреждал рекрутёра «Ці дані зі співбесіди на іншу вакансію…» —
// целое предложение по-украински, поле обычного ответа, и сторож его не
// видел двадцать шесть дней. Это «правило было, просто не везде»: ровно
// та порода, которую проект ловит у себя чаще всего.
//
// ЧТО ТЕПЕРЬ ЧИТАЕТСЯ. Кроме сообщений об ошибках — строковые значения
// полей, которыми продукт обращается к человеку: `note`, `frame`,
// `disclaimer`, `reason`, `message`, `hint`, `label` и подобные. Промпты
// модели сюда не входят по-прежнему: промпт читает модель, и язык ЕЁ
// ответа задаётся отдельно, из `languageCode`.
//
// ЧЕСТНАЯ ГРАНИЦА. Сторож смотрит на БУКВЫ, а не на смысл: он ловит
// украинские і/ї/є/ґ в тексте, который уходит человеку. Русский текст с
// украинским порядком слов он не отличит, и не должен — это работа
// человека. И он ничего не говорит о том, ПРАВИЛЬНЫЙ ли язык у
// продукта: полноценная многоязычность — решение владельца, записанное
// в TODO.md.

/** Буквы, которых нет в русском алфавите. */
export const UKRAINIAN_ONLY = /[іїєґІЇЄҐ]/;

export interface ProperNoun {
  readonly pattern: RegExp;
  readonly why: string;
}

/** Собственные имена, остающиеся на языке оригинала в любом интерфейсе —
 *  как «Bundesbank» не переводят.
 *
 *  Список ведётся ЗАПИСЯМИ С ПРИЧИНОЙ, а не одной регуляркой: следующий
 *  читатель должен видеть, почему конкретное имя здесь, и не дописывать
 *  в общий шаблон всё, что покраснело. */
export const PROPER_NOUNS: readonly ProperNoun[] = [
  { pattern: /ЄДРПОУ/, why: 'код в украинском государственном реестре — идентификатор, а не слово' },
  { pattern: /РНОКПП/, why: 'украинский налоговый номер — идентификатор' },
  { pattern: /Дія/, why: 'название государственного сервиса' },
  { pattern: /Прозорро/, why: 'название системы государственных закупок' },
  { pattern: /Єдиний державний реєстр/, why: 'официальное название реестра — по нему его и ищут' },
  { pattern: /ЄДР/, why: 'общепринятое сокращение того же реестра; `\\b` здесь не работает — он считает буквы по ASCII' },
  { pattern: /Державний реєстр санкцій/, why: 'официальное название реестра санкций' },
  { pattern: /Єдиний державний реєстр судових рішень/, why: 'официальное название реестра судебных решений' },
  { pattern: /ДПС/, why: 'название налоговой службы' },
  { pattern: /НАЗК/, why: 'название агентства по предотвращению коррупции' },
  { pattern: /РНБО/, why: 'название совета национальной безопасности' },
  { pattern: /Мін’юст|Мін'юст/, why: 'название министерства — владелец реестра' },
];

export function isProperNoun(text: string): boolean {
  return PROPER_NOUNS.some((n) => n.pattern.test(text));
}

/** Имена полей, значением которых продукт обращается К ЧЕЛОВЕКУ.
 *
 *  Список закрытый и короткий НАРОЧНО. Взять «все строковые поля» значило
 *  бы читать и промпты, и ключи телеметрии, и имена задач — сторож стал
 *  бы шумом, который отключают. */
export const SPOKEN_FIELDS: readonly string[] = [
  'note',
  'frame',
  'disclaimer',
  'historyDisclaimer',
  'caveat',
  'notice',
  'draftReason',
  'reason',
  'message',
  'hint',
  'label',
  'summary',
  'title',
  'text',
  'whyNot',
  'alsoDoes',
  'doesNotUndo',
  'suggestion',
  'companyChoice',
];

/** Строка кода → тексты, которые она говорит человеку.
 *
 *  Две породы: сообщение исключения (так было с 2026-09-04) и значение
 *  поля из `SPOKEN_FIELDS` (добавлено 2026-09-30). */
export function spokenStrings(line: string): string[] {
  const trimmed = line.trim();
  if (trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('/*')) return [];
  const out: string[] = [];
  if (/Exception\(/.test(line)) {
    for (const m of line.matchAll(/'([^'\n]{6,})'|"([^"\n]{6,})"/g)) out.push(m[1] ?? m[2]);
  }
  const names = SPOKEN_FIELDS.join('|');
  const re = new RegExp(`\\b(?:${names})\\s*[:=]\\s*(\`[^\`]{6,}\`|'[^'\\n]{6,}'|"[^"\\n]{6,}")`, 'g');
  for (const m of line.matchAll(re)) out.push(m[1].slice(1, -1));
  return out;
}
