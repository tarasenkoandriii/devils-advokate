// просроченный пункт, который ничем не обнаруживался — и на способ
// написать такой же завтра.
//
// ЧЕСТНАЯ ГРАНИЦА, И ОНА УЗКАЯ. Проверяется ОДНА порода утверждений:
// «у названного места нет теста». Не «не сделано», не «осталось», не «в
// очереди» — эти слова в документе значат слишком разное, и разбор
// русской прозы тут был бы не сторожем, а его изображением. Всё
// остальное, что документ говорит о себе, по-прежнему держит человек.

/** Что сторож делает с утверждением. */
export type AbsenceState =
  /** Пробел есть сегодня. Сторож доказывает, что его не закрыли молча:
   *  как только он закрыт, утверждение обязано быть переписано. */
  | 'держится'
  /** Пробел закрыт, документ это говорит. Сторож доказывает, что
   *  закрытие на месте: если спека, закрывшая пробел, исчезнет,
   *  пометка «закрыто» станет неправдой в другую сторону. */
  | 'закрыто';

export interface ClaimedAbsence {
  readonly doc: 'TODO.md' | 'README.md';
  /** Якорь раздела: `## Пункт [x]` в `TODO.md`, `Дополнение … (Пункт [x]
   *  в TODO.md)` в `README.md`. Якорь, а не номер строки, — номера едут
   *  от каждой вставки, и сторож на них краснел бы впустую. */
  readonly anchor: string;
  /** Сколько совпадений даёт разбор под этим якорем. Число, а не факт
   *  наличия: два утверждения в одном разделе — два разных пробела. */
  readonly phrases: number;
  /** Чего, по документу, нет. */
  readonly about: string;
  readonly state: AbsenceState;
  /** Чем сторож проверяет ИМЕННО ЭТО утверждение — имя пробы в спеке.
   *  Без этого поля реестр был бы списком, а не проверкой. */
  readonly probe: string;
}

export interface AbsenceClaim {
  readonly anchor: string;
  readonly line: number;
  readonly phrases: readonly string[];
}

/** Слова, которыми документ говорит «теста нет».
 *
 * Список короткий НАРОЧНО. Каждая форма взята из текста, который уже
 * написан, а не придумана про запас: широкий список ловил бы «не
 * покрытие, а десять правил» и «продукт этого не проверяет» — оба про
 * другое, и сторож с ними стал бы шумом, который отключают. */
export const ABSENCE_PHRASES: RegExp =
  /без тестов|без единого теста|не покрыт(?:а|о|ы)?(?![а-яё])|тест(?:а|ов)?[^.\n]{0,24}?нет|не протестирован/gi;

const ANCHOR_RE: Record<ClaimedAbsence['doc'], RegExp> = {
  // Раздел `TODO.md` начинается заголовком; ссылки на пункты внутри
  // текста якорем НЕ считаются — иначе раздел менял бы имя посреди себя.
  'TODO.md': /^## Пункт \[([^\]]+)\]/,
  // В `README.md` дополнение занимает одну строку и само называет пункт.
  'README.md': /^\*\*Дополнение [^*]*\(Пункт \[([^\]]+)\]/,
};

/** Все утверждения «теста нет» в тексте документа, с якорем раздела. */
export function absenceClaims(doc: ClaimedAbsence['doc'], text: string): AbsenceClaim[] {
  const anchorRe = ANCHOR_RE[doc];
  const out: AbsenceClaim[] = [];
  let anchor = '(до первого якоря)';
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const a = anchorRe.exec(lines[i]);
    if (a) anchor = a[1];
    const phrases = lines[i].match(ABSENCE_PHRASES);
    if (phrases) out.push({ anchor, line: i + 1, phrases });
  }
  return out;
}

/** Сколько утверждений даёт разбор под каждым якорем. */
export function absenceCounts(doc: ClaimedAbsence['doc'], text: string): Map<string, number> {
  const out = new Map<string, number>();
  for (const c of absenceClaims(doc, text)) {
    out.set(c.anchor, (out.get(c.anchor) ?? 0) + c.phrases.length);
  }
  return out;
}

