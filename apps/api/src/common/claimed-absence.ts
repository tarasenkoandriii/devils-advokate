/** Строка таблицы «чем закрыт каждый пункт»: слева — что названо
 *  пробелом, справа — чем закрыт. */
export interface ClosedRow {
  readonly named: readonly string[];
  readonly closedBy: readonly string[];
}

/** Имена, названные пробелом, и спека, названная закрытием, — ИЗ САМОГО
 *  документа.
 *
 *  Переписать их сюда константой было первым решением, и мутация его
 *  убила: выпавшее из константы имя никто не замечал, потому что
 *  сверялась константа сама с собой. Тот же дефект, что и находка
 *  пункта, только на этаж ниже. Теперь источником служит строка
 *  таблицы: убрать имя из документа — уронить сверку, добавить — тоже. */
export function closedRow(todo: string, rowStartsWith: string): ClosedRow | null {
  for (const line of todo.split('\n')) {
    if (!line.startsWith(`| ${rowStartsWith}`)) continue;
    const cells = line.split('|').map((c) => c.trim());
    // cells[0] пуст (строка начинается с `|`), дальше — левая и правая.
    const ticks = (cell: string): string[] => [...cell.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    return { named: ticks(cells[1] ?? ''), closedBy: ticks(cells[2] ?? '') };
  }
  return null;
}

