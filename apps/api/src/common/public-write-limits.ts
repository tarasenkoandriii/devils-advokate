/** Действующее значение потолка и причина, по которой оно действующее —
 *  тем же механизмом, что у потолков расходов (Пункт
 *  [the-lever-that-silently-did-nothing]): выставленный с опечаткой
 *  рычаг не должен быть неотличим от невыставленного. */
export function publicWriteLimit(key: string): { value: number; source: LimitSource; raw: string | null } {
  const entry = PUBLIC_WRITE_LIMITS.find((l) => l.key === key);
  if (!entry) throw new Error(`Потолок публичной записи ${key} не описан в PUBLIC_WRITE_LIMITS`);
  return resolveLimit(entry.env, entry.fallback);
}

/** Проверка потолка. Ноль отключает потолок совсем — как и у потолков
 *  расходов, и по той же причине: владельцу нужен способ сказать «не
 *  ограничивай», а не только «ограничь иначе». */
export async function assertUnderPublicWriteLimit(key: string, current: () => Promise<number>): Promise<void> {
  const limit = publicWriteLimit(key);
  if (limit.value === 0) return;
  if ((await current()) < limit.value) return;
  const entry = PUBLIC_WRITE_LIMITS.find((l) => l.key === key)!;
  throw new BadRequestException(entry.refusal);
}

