import { BadRequestException } from '@nestjs/common';

import { resolveLimit, type LimitSource } from './spend-limits';

/** По чему считается потолок. */
export type PublicWriteScope =
  /** Всего в одном обсуждении. */
  | 'обсуждение'
  /** От одного участника обсуждения. */
  | 'участник'
  /** Всего под одной записью публичной библиотеки. */
  | 'запись библиотеки';

export interface PublicWriteLimit {
  readonly key: string;
  /** Что ограничивается — словами, как сказал бы владелец. */
  readonly what: string;
  readonly env: string;
  readonly fallback: number;
  readonly scope: PublicWriteScope;
  /** Что читает человек, упёршийся в потолок. Текст ему, а не оператору:
   *  он не сделал ничего плохого, он просто пришёл последним. */
  readonly refusal: string;
  /** Что случилось бы без потолка. */
  readonly why: string;
}

