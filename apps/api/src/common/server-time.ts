// Пункт [server-said-which-day] 2026-09-24.
//
// ЧЕГО СЕРВЕР НЕ ЗНАЕТ. Часового пояса человека в продукте нет — ни в
// схеме, ни в запросах. Это осознанное решение, записанное дважды:
// «Аудит времени 2026-09-03» в religious-reminder.service.ts («часового
// пояса у пользователя в продукте нет, и заводить его ради напоминания
// незачем» — там календарь заменён окном) и Пункт [date-only]
// 2026-09-04 в discrepancy-analysis.service.ts («вместо неверной
// точности даты нет вовсе»).
//
// ЧТО ИЗ ЭТОГО СЛЕДУЕТ. Момент времени (`DateTime` в базе) — знание
// точное. Календарный день, выведенный из момента, — знание, которого у
// сервера НЕТ: один и тот же момент попадает на разные числа у людей с
// разным смещением. Разговор в 01:00 по Киеву — это 22:00 предыдущего
// дня по UTC, и `toISOString().slice(0, 10)` называет ПРЕДЫДУЩЕЕ число.
// А срок, собранный на клиенте как конец местного дня (см.
// `apps/tma/src/lib/date-only.ts`), у человека западнее Гринвича
// приходится на СЛЕДУЮЩЕЕ число по UTC — то есть исправление записи
// сдвинуло чтение в другую сторону.
//
// ПРАВИЛО. Серверный текст, который прочитает человек (в том числе через
// модель — она повторяет то, что ей дали), не называет календарный день,
// выведенный из момента. Вместо него — одно из трёх:
//   1) порядок («разговор 2 из 5»), если день был нужен только для
//      хронологии;
//   2) расстояние во времени («через 3 дня», «12 дней назад»), если
//      важен срок, а не число календаря: длительность одинакова в любом
//      часовом поясе;
//   3) момент с ЯВНО названной зоной («9 сентября 2026, 22:14 UTC»),
//      если предмет — сам момент и умолчать нельзя.
// Машинные адресаты — параметры внешних API, операторские журналы,
// выгрузки — под правило не попадают: там полный ISO с «Z» честен сам по
// себе. Список исключений закреплён тестом, а не доверием.

const MS_PER_DAY = 24 * 60 * 60 * 1000;

/** Русская форма при числе: 1 день, 2 дня, 5 дней. */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/** Расстояние в днях назад. День считается от момента до момента, а не
 * по календарю: «сколько прошло» одинаково в любом часовом поясе, а «в
 * какой день это было» — нет. */
export function daysAgo(date: Date, now: Date = new Date()): string {
  const ms = now.getTime() - date.getTime();
  if (ms < 0) return 'ещё не наступило';
  const days = Math.floor(ms / MS_PER_DAY);
  if (days === 0) return 'меньше суток назад';
  return `${days} ${plural(days, 'день', 'дня', 'дней')} назад`;
}

/** Срок относительно «сейчас». Календарного числа здесь нет намеренно:
 * его точное значение знает только устройство человека, и оно же его
 * показывает — а модель, получив неверное число, повторит человеку
 * именно его. */
export function deadlineRelative(due: Date, now: Date = new Date()): string {
  const ms = due.getTime() - now.getTime();
  if (ms < 0) {
    const days = Math.floor(-ms / MS_PER_DAY);
    return days === 0 ? 'срок истёк менее суток назад' : `срок истёк ${days} ${plural(days, 'день', 'дня', 'дней')} назад`;
  }
  const days = Math.floor(ms / MS_PER_DAY);
  if (days === 0) return 'срок истекает в течение суток';
  return `через ${days} ${plural(days, 'день', 'дня', 'дней')}`;
}

/** Метка порядка вместо даты. `newestFirst` не по умолчанию: направление
 * надо назвать вслух, иначе модель достроит его сама — обычно неверно. */
export function orderLabel(index: number, total: number, newestFirst: boolean): string {
  const which = newestFirst ? '1 — самый недавний' : '1 — самый ранний';
  return `${index + 1} из ${total}, ${which}`;
}

/** Момент с явно названной зоной. Единственный вид записи, где серверу
 * позволено назвать число: зона стоит рядом, и человек видит, что число
 * не обязано совпадать с его собственным календарём. */
export function instantUtc(date: Date): string {
  const day = date.toLocaleDateString('ru-RU', { timeZone: 'UTC', day: 'numeric', month: 'long', year: 'numeric' });
  const time = date.toLocaleTimeString('ru-RU', { timeZone: 'UTC', hour: '2-digit', minute: '2-digit' });
  return `${day}, ${time} UTC`;
}
