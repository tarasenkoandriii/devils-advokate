// Пункт [check-then-create] 2026-09-04 — «проверил, что нет, и создал».
//
// ФОРМА ДЕФЕКТА. Метод читает, есть ли уже такая строка, и если нет —
// создаёт. Между чтением и записью проходит время, и второй такой же
// вызов (двойное нажатие, повтор при плохой связи, две вкладки) успевает
// пройти проверку до того, как первый запишет. Дальше два исхода, и они
// РАЗНЫЕ:
//
//  • если у модели есть уникальное ограничение — база отвергает вторую
//    вставку, Prisma бросает P2002, и человек получает пятисотку на
//    действии, которое на самом деле УЖЕ УДАЛОСЬ. Данные целы, но
//    сообщение врёт;
//  • если ограничения нет — обе вставки проходят, и появляется дубль,
//    о котором никто не узнает.
//
// Этот файл — про первый случай. Обе половины лечатся по-разному: там,
// где повтор ЗАДУМАН как безвредный (вступить в команду, куда уже
// вступил), правильный ответ — `upsert`, то есть отсутствие гонки по
// определению. Там, где повтор — ошибка по замыслу («разбор для этого
// проекта уже настроен»), правильный ответ не в том, чтобы гонку
// исключить, а в том, чтобы ОТВЕТ БЫЛ ОДИН И ТОТ ЖЕ независимо от того,
// кто успел раньше: человек должен прочитать «уже настроено», а не
// «внутренняя ошибка сервера».
//
// Тот же приём, что уже применён в проекте к атомарному забору права на
// отправку (напоминания, вебхук расшифровки, аренда медиа): не «сделать
// гонку невозможной усилием воли», а «сделать её исход предсказуемым».

/** Нарушение уникального ограничения. Проверяется по коду ошибки
 * Prisma, а не по тексту сообщения: текст зависит от версии и от языка
 * драйвера, код — нет. */
export function isUniqueViolation(err: unknown): boolean {
  return (err as { code?: string } | null)?.code === 'P2002';
}
