// Пункт [enum-copy-drifted] 2026-09-29 — список значений перечисления,
// переписанный руками рядом с местом проверки.
//
// ФОРМА. Валидатор ответа модели проверяет поле на принадлежность
// перечислению — и делает это СПИСКОМ ЛИТЕРАЛОВ:
//
//   ['INACCURACY', 'DISCREPANCY', 'STRONG_DISCREPANCY'].includes(item.severity)
//
// А настоящее перечисление живёт в `schema.prisma`, и связи между ними
// нет никакой. Дальше значение приводится к типу перечисления (`as
// SignalSeverity`) и уходит в запись.
//
// ЧТО ИМЕННО ЛОМАЕТСЯ, КОГДА КОПИЯ ОТСТАЁТ. Два исхода, и они разные.
//
//   Перечисление ВЫРОСЛО, копия осталась прежней. Новое значение не
//   проходит валидацию — то есть фича, ради которой его завели, не
//   работает НИ РАЗУ, и выглядит это не как «значение не принято», а как
//   испорченный ответ модели: валидация не пройдена, запрос повторяется,
//   и человек читает «модель вернула ответ, который не удалось
//   разобрать». Причина названа неверно, и искать её будут в промпте.
//
//   Из перечисления значение УБРАЛИ, копия его помнит. Валидатор
//   пропускает, приведение типа молчит (`as` ничего не проверяет), и
//   Prisma отвергает запись уже на вставке — внутренней ошибкой.
//
// ИЗМЕРЕНО перед правилом: перечислений в схеме 99, переписанных руками
// копий в коде — 25. Значений ВНЕ перечисления среди них не нашлось ни
// одного, то есть сегодня всё совпадает. Правило заводится не на
// существующий беспорядок, а на расхождение, которое ничем не
// обнаруживается: 18 копий точные, 7 намеренно УЖЕ перечисления.
//
// ПОЧЕМУ НЕ «ПРОСТО СВЕРЯТЬ ТЕСТОМ». Сверка копии со схемой тестом
// поймала бы расхождение, но оставила бы саму копию — а значит и повод
// расходиться. Значения берутся из перечисления напрямую; сверять
// становится нечего.

/** Все значения перечисления Prisma — источником служит само
 * перечисление, а не его копия рядом с проверкой. */
export function enumValues<E extends Record<string, string>>(e: E): readonly E[keyof E][] {
  return Object.values(e) as E[keyof E][];
}

// Пункт [written-for-the-person-never-delivered] 2026-09-30: здесь
// была `enumStrings` — «то же самое строкой, для проверок вида
// includes(x)». Не вызывалась нигде: её задачу решает `isEnumValue`
// ниже, и решает лучше — она СУЖАЕТ ТИП, после неё приведение `as` не
// нужно вовсе. Хелпер, который делает то же хуже, — это приглашение
// однажды выбрать его.

/** Принадлежит ли значение перечислению. Заменяет `includes` по копии и
 * СУЖАЕТ ТИП — после неё приведение `as` не нужно вовсе, а значит
 * нельзя и соврать им. */
export function isEnumValue<E extends Record<string, string>>(e: E, value: unknown): value is E[keyof E] {
  return typeof value === 'string' && (Object.values(e) as string[]).includes(value);
}

/** Часть перечисления — намеренно меньше, чем всё.
 *
 * Сужение бывает законным: разбор переломов разговора заводит ровно два
 * вида сигнала из семи, и остальные пять ему не принадлежат. Но
 * записанное СПИСКОМ ЛИТЕРАЛОВ сужение неотличимо от отставшей копии:
 * и то и другое выглядит как «здесь не все значения». Поэтому подмножество
 * объявляется явно, значения берутся из самого перечисления, а рядом
 * стоит причина — иначе следующий читатель «допишет недостающие».
 *
 * Значение не из перечисления сюда не пройдёт: типом — на сборке,
 * проверкой — на запуске, потому что `as` в вызывающем коде эту ошибку
 * молча пропустил бы. */
export function subsetOf<E extends Record<string, string>, P extends readonly E[keyof E][]>(
  e: E,
  picked: P,
  why: string,
): P {
  // Тип подмножества сохраняется НАРОЧНО: `readonly E[keyof E][]` вернул
  // бы тип всего перечисления, и `typeof SUBSET[number]` у вызывающего
  // означал бы «любое значение» — то есть сужение существовало бы только
  // на запуске, а в типах исчезало. Найдено сборкой на первом же месте,
  // где из подмножества выводится тип ключей сводки.
  const all = Object.values(e) as string[];
  const stray = picked.filter((v) => !all.includes(v));
  if (stray.length > 0) {
    throw new Error(
      `Подмножество перечисления содержит значения, которых в нём нет: ${stray.join(', ')}. ` +
        `Причина сужения: ${why}`,
    );
  }
  if (picked.length === 0 || picked.length === all.length) {
    throw new Error(
      'subsetOf() — для ЧАСТИ перечисления. Пустое подмножество и полное берутся иначе: ' +
        'полное — enumValues(), пустое не имеет смысла вовсе',
    );
  }
  return picked;
}
