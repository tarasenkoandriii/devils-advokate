/** Подпись для значения перечисления. Неизвестное значение
 * возвращается КАК ЕСТЬ, а не заменяется на «—»: документ, потерявший
 * строку, хуже документа с непереведённым словом, и молчаливая потеря
 * данных в бумаге для юриста — ровно то, чего эти сверки не допускают. */
export function labelFor(map: Record<string, string>, value: string | null | undefined): string {
  if (!value) return 'не указано';
  return map[value] ?? value;
}
