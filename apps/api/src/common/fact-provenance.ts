// Пункт [source-collapse] 2026-09-05 — происхождение факта теряется
// ровно там, где оно важнее всего.
//
// НАЙДЕНО. Продукт заставляет человека выбрать происхождение КАЖДОГО
// факта о другом человеке: 🟢 личная запись (видел/слышал сам), 🔵
// публичный факт, ⚪ моё предположение. Это одна из подписных идей
// продукта — и она держится ровно до момента, когда факт начинают
// использовать. Четыре сервиса собирали контекст так:
//
//   facts.map((f) => `- ${f.content}`).join('\n')
//   → «Известные факты о фигуранте: …»
//
// То есть ⚪ «моё предположение» уходило модели как «известный факт»,
// неотличимо от 🟢 записи со слов и 🔵 публичного факта. Модель строила
// на нём гипотезы о мотивах, портрет собеседника, стальной аргумент — и
// возвращала человеку выводы, у которых в основании лежит его же
// собственная догадка. Замкнутый круг: догадка возвращается как вывод, а
// человек, забывший, что сам её и записал, читает её как находку.
//
// ПРАВИЛО В ПРОДУКТЕ УЖЕ БЫЛО. `SchedulerAdviceService` фильтрует по
// `sourceType = PERSONAL_RECORD` прямо в SQL и называет блок «строго со
// слов пользователя», с отдельным комментарием о том, что догадки
// исключены. Снова знакомый вид: правило есть, просто не везде.
//
// ЧТО ЗДЕСЬ ВЫБРАНО И ПОЧЕМУ. Догадки НЕ выбрасываются: человек записал
// их не случайно, и терять его слова — уже разобранный изъян (пункт
// [own-input]). Они помечаются, и модели прямо сказано, чем помеченная
// строка отличается от непомеченной. Молча вырезать их значило бы
// подменить одну неправду другой.

import { FactSourceType } from '@prisma/client';

/** Как строка выглядит для модели. Формулировки не украшают: «догадка»
 * названа догадкой, а не «непроверенным наблюдением». */
export const FACT_SOURCE_PROMPT_LABEL: Record<FactSourceType, string> = {
  [FactSourceType.PERSONAL_RECORD]: 'со слов пользователя',
  [FactSourceType.PUBLIC_FACT]: 'публичный факт',
  [FactSourceType.USER_GUESS]: 'ДОГАДКА пользователя, не проверено',
};

/** Инструкция модели. Пометки без неё — украшение: модель обязана знать,
 * что с ними делать. Это тот же приём, что в пункте [partial-basis], где
 * без прямого запрета достраивать отсутствующее оговорка об усечении
 * ничего не меняла. */
export const FACT_PROVENANCE_INSTRUCTION =
  'Каждый факт помечен происхождением. Помеченное как ДОГАДКА — предположение самого пользователя, а не установленный факт: ' +
  'не опирайся на него как на факт, не выдавай его обратно как подтверждённое и, если вывод держится только на догадке, скажи об этом прямо.';

export interface ProvenancedFact {
  content: string;
  sourceType: FactSourceType;
}

/** Одна строка факта с его происхождением. */
export function factLine(fact: ProvenancedFact): string {
  return `- [${FACT_SOURCE_PROMPT_LABEL[fact.sourceType] ?? fact.sourceType}] ${fact.content}`;
}

/** Блок фактов для промпта. Пустой список — пустая строка: подставлять
 * «(фактов нет)» здесь нельзя, у вызывающих формулировки разные. */
export function factsBlock(facts: readonly ProvenancedFact[]): string {
  return facts.map(factLine).join('\n');
}

/** Есть ли среди фактов хоть одна догадка. Инструкцию про догадки не
 * стоит добавлять, когда догадок нет: лишний текст в промпте — это не
 * бесплатная осторожность, а размывание того, что модель обязана
 * прочитать. */
export function hasGuess(facts: readonly ProvenancedFact[]): boolean {
  return facts.some((f) => f.sourceType === FactSourceType.USER_GUESS);
}

/** Готовый блок вместе с инструкцией, если она нужна. */
export function factsBlockWithInstruction(facts: readonly ProvenancedFact[]): string {
  const block = factsBlock(facts);
  if (!block) return '';
  return hasGuess(facts) ? `${block}\n${FACT_PROVENANCE_INSTRUCTION}` : block;
}
