// Продолжение аудита 2026-09-02 — отставание миграции перечисления.
//
// Класс регрессии, который владелец уже ловил в проде 2026-09-02 утром
// («The column users.languageCode does not exist»): код выкатился раньше,
// чем к базе применили ручную миграцию, и штатная работа выглядела как
// сбой. Сегодня добавлено значение перечисления
// SparringVoiceReplyStatus.PROCESSING (voice_reply_processing_2026_09_02.sql),
// и до его применения любой запрос с этим значением падает в Postgres с
// 22P02 «invalid input value for enum …». Prisma не даёт этому отдельного
// кода (для DDL-расхождений у него P2021/P2022, для значений перечисления
// — нет), ошибка приходит как PrismaClientUnknownRequestError с текстом
// драйвера.
//
// Правило проекта: пробел конфигурации не должен выглядеть как отказ
// функции. Поэтому места, где новое значение используется, распознают
// это отставание и деградируют предсказуемо — с предупреждением в лог и
// с прежним поведением, — а ApiExceptionFilter называет миграцию по
// имени, если ошибка всё же дошла до ответа.

export function isUnknownEnumValueError(err: unknown): boolean {
  const message = err instanceof Error ? err.message : typeof err === 'string' ? err : '';
  return /invalid input value for enum/i.test(message) || /\b22P02\b/.test(message);
}

const activeDegradations = new Map<string, { migration: string; consequence: string }>();

/** Отметить, что место деградировало из-за неприменённой миграции.
 * Вызывается рядом с предупреждением в лог, не вместо него: лог для нас,
 * отметка — для человека. */
export function markMigrationLag(site: string, migration: string, consequence: string): void {
  activeDegradations.set(site, { migration, consequence });
}

/** Деградировало ли это место в текущем процессе. `null` — нет. */
export function migrationLagAt(site: string): { migration: string; consequence: string } | null {
  return activeDegradations.get(site) ?? null;
}

/** Только для тестов: отметки процессные, и спеки не должны протекать
 * друг в друга.
 *
 * Чистит ОБЕ памяти — отметки и выданные предупреждения. Порознь они
 * разойдутся: спек, сбросивший отметки, но не предупреждения, получит
 * место, которое деградировало и об этом молчит. Именно эту пару и
 * разбирает пункт [lag-told-only-the-log], так что оставить её
 * рассогласованной в собственном инструменте было бы смешно. */
export function resetMigrationLagForTests(): void {
  activeDegradations.clear();
  warned.clear();
}

/** Миграция, добавляющая SparringVoiceReplyStatus.PROCESSING. Имя не
 * выдумано здесь: оно сверяется с реестром ручных миграций тестом. */
export const VOICE_REPLY_MIGRATION = 'voice_reply_processing_2026_09_02.sql';

/** Одно предупреждение на процесс на каждую точку — не по строке на каждый вебхук. */
const warned = new Set<string>();

export function warnEnumMigrationLagOnce(logger: { warn(message: string): void }, site: string): void {
  if (warned.has(site)) return;
  warned.add(site);
  logger.warn(
    // Пункт [latest-migration-was-from-memory] 2026-09-24: здесь имя
    // файла ОСТАЁТСЯ дословным — эта точка знает своё перечисление
    // (SparringVoiceReplyStatus) и может назвать свою миграцию, в
    // отличие от общего фильтра ошибок, который не знает, чьё значение
    // не распозналось. Имя сверяется с реестром тестом.
    `${site}: база не знает нового значения перечисления — миграция ` +
      `apps/api/prisma/manual-migrations/${VOICE_REPLY_MIGRATION} не применена. ` +
      'Работаем в прежнем режиме (без атомарного забора / без сторожевой PROCESSING) до её применения.',
  );
}

/** Сверка вебхуков и токенов 2026-09-04 — тот же класс, но про КОЛОНКУ,
 * а не про значение перечисления. Prisma отдаёт P2022 «The column … does
 * not exist»; владелец уже ловил это в проде на `users.languageCode`. */
export function isMissingColumnError(err: unknown): boolean {
  const message = err instanceof Error ? err.message : typeof err === 'string' ? err : '';
  return /\bP2022\b/.test(message) || /column .* does not exist/i.test(message);
}

/** То же одно предупреждение на процесс, но с ИМЕНЕМ конкретной миграции:
 * прежняя функция называла один-единственный файл, и второе такое место
 * присылало бы человеку ссылку на чужую миграцию. */
export function warnMigrationLagOnce(
  logger: { warn(message: string): void },
  site: string,
  migrationFile: string,
  fallbackBehaviour: string,
): void {
  // Пункт [lag-told-only-the-log] 2026-09-24: отметка ставится ДО
  // проверки «уже предупреждали», а не после.
  //
  // ЧЕСТНО О ТОМ, ЧТО ЭТО ДАЁТ. В работающем продукте — ничего: первый
  // вызов и так проходит обе строки, а дальше отметка уже стои́т.
  // Порядок важен ровно в одном случае — когда две памяти расходятся,
  // и единственное такое место сегодня это сброс в тестах. Первая
  // редакция комментария утверждала здесь больше («раньше место
  // деградировало молча»), чего не было: обе строки написаны разом.
  // Заявление убрано — мутация показала, что оно ничем не держится, а
  // комментарий, обещающий больше, чем делает код, и есть то, что эти
  // сверки ищут.
  //
  // Расхождение двух памятей закрыто по-настоящему в
  // `resetMigrationLagForTests`: он чистит ОБЕ.
  markMigrationLag(site, migrationFile, fallbackBehaviour);
  if (warned.has(site)) return;
  warned.add(site);
  logger.warn(
    `${site}: база не знает нового поля — миграция apps/api/prisma/manual-migrations/${migrationFile} ` +
      `не применена. Работаем в прежнем режиме (${fallbackBehaviour}) до её применения.`,
  );
}

/** Только для тестов: сбросить память о выданных предупреждениях. */
export function resetEnumMigrationLagWarnings(): void {
  warned.clear();
}

// ── Пункт [lag-told-only-the-log] 2026-09-24 ──
//
// НАЙДЕНО. Механизм выше сделан правильно и по верному правилу: «пробел
// конфигурации не должен выглядеть как отказ функции» — код терпит
// неприменённую миграцию и работает в прежнем режиме. Но предупреждение
// уходит В ЛОГ СЕРВЕРА, и на этом всё.
//
// Для большинства мест это законно: отставание касается внутренней
// механики (атомарный забор вебхука, сторожевая по статусу), человек о
// ней не знает и знать не должен. Ровно одно место — исключение, и оно
// названо в собственном тексте предупреждения: снимок релевантности без
// колонки `notAssessed` теряет СПИСОК НЕПРОВЕРЕННЫХ КАНДИДАТОВ, то есть
// «пропуски снова невидимы». Экран рисует блок «Не вошли в этот снимок»
// только при непустом списке — значит при отставании миграции не рисует
// ничего, и снимок выглядит полным.
//
// Это зеркало правила, ради которого механизм и писался. Там: пробел
// конфигурации не должен выглядеть как ОТКАЗ. Здесь: он не должен
// выглядеть как ПОЛНОТА. Второе для этого продукта дороже — ровно этой
// формой дефекта заняты полтора десятка сверок подряд.
//
// ЧТО ДЕЛАЕТ РЕЕСТР НИЖЕ. Даёт месту деградации способ сказать о себе НЕ
// ТОЛЬКО В ЛОГ: отметка ставится там же, где пишется предупреждение, и
// читается тем, кто формирует ответ человеку. Процессная, не
// персистентная — отставание миграции это свойство развёрнутого
// экземпляра, а не данных; применили миграцию, перезапустили — отметки
// нет.
