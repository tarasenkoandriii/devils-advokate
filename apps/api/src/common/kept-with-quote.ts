// Пункт [dropped-quotes] 2026-09-04 — модель нашла, код отбросил, человек
// прочитал «ничего не найдено».
//
// НАЙДЕННОЕ. Восемь мест в шести сервисах устроены одинаково: модель
// возвращает список находок с цитатой, код проверяет, что цитата
// действительно есть в исходном тексте, и всё, что проверку не прошло,
// МОЛЧА исчезает через `.filter(...)`. Проверка сама по себе верна и
// обязана остаться — это и есть «только из ваших слов»: находка с
// выдуманной цитатой не находка, а утверждение продукта о человеке,
// которое нечем подкрепить. Дефект не в фильтре, а в том, что от потери
// не остаётся следа.
//
// ЧЕМ ЭТО ХУЖЕ ОБЫЧНОГО ПРОПУСКА. У четырёх детекторов ([silent-skips])
// потеря была невидима в ЛОГЕ. Здесь она невидима НА ЭКРАНЕ, и экран
// говорит утвердительно:
//   • «Compliance-флагов нет.» — на тексте вакансии,
//   • «Расхождений между источниками и досье не найдено.»,
//   • «Новых критериев в ваших словах не нашлось.»
// Если модель нашла спорную формулировку, но процитировала её неточно,
// человек читает «нарушений нет» — то есть продукт УТВЕРЖДАЕТ чистоту,
// которую не проверял. Это ровно та форма дефекта, которую проект
// называет «конфигурационные пробелы не должны выглядеть как отсутствие
// находок», только здесь пробел не конфигурационный, а свой собственный.
//
// РЕШЕНИЕ. Один способ на проект: фильтр остаётся, но возвращает ещё и
// число отброшенного, число доходит до ответа API и до экрана. «Находок
// нет» и «находки были, но без опоры на ваш текст» перестают выглядеть
// одинаково.
//
// ПОЧЕМУ НЕ ЛОГ, КАК У ДЕТЕКТОРОВ. У детекторов результат уходит в базу,
// и обратного пути к человеку в тот момент нет — предупреждение в лог
// было единственным доступным каналом. Здесь результат возвращается
// вызвавшему прямо сейчас, и число, которое читает человек, строго
// полезнее числа, которое читает только тот, у кого есть доступ к логам.
// Поэтому пять сервисов не обзаводятся `Logger` ради этого.
//
// ЧЕСТНАЯ ГРАНИЦА. Число НЕ говорит, что именно потеряно: сам текст
// отброшенной находки показывать нельзя — он опирается на цитату,
// которой в источнике нет, то есть на выдумку. Показать её значило бы
// показать человеку утверждение о нём, ничем не подкреплённое. Число
// честнее: оно сообщает, что список неполон, и не выдаёт выдумку за
// находку.

/** Результат отбора: что осталось и сколько выброшено за отсутствие опоры. */
export type KeptWithQuote<T> = {
  kept: T[];
  /** Сколько элементов ответа модели отброшено: цитаты нет в источнике. */
  skippedWithoutQuote: number;
};

/** Оставить только то, что опирается на исходный текст, ПОСЧИТАВ остальное.
 *
 * Замена голому `list.filter(предикат)` там, где предикат — это «цитата
 * из источника». Разница ровно одна и вся суть пункта в ней: `.filter()`
 * теряет число, а вместе с ним и возможность отличить «ничего не нашли»
 * от «нашли, но не смогли подтвердить». */
export function keepQuoted<T>(items: readonly T[], hasSourceQuote: (item: T) => boolean): KeptWithQuote<T> {
  const kept: T[] = [];
  let skippedWithoutQuote = 0;
  for (const item of items) {
    if (hasSourceQuote(item)) kept.push(item);
    else skippedWithoutQuote++;
  }
  return { kept, skippedWithoutQuote };
}

