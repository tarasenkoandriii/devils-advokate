// Пункт [inference-as-observation] 2026-09-05 — вывод модели,
// вернувшийся наблюдением.
//
// НАЙДЕНО. Две сущности, из которых собирается портрет человека, целиком
// создаются моделью:
//
//   • PersonCommunicationTrait — «наблюдаемый коммуникационный профиль».
//     Пишет его CommunicationProfileService по расшифровкам разговоров;
//     у каждой строки есть `observedFrom` — описание наблюдения, которого
//     §3.11 ТЗ прямо требует, — и `generatedByInferenceId`.
//   • BehaviorPrecedent — «известные прецеденты поведения». Пишет их
//     PrecedentSearchService по тем же расшифровкам; у каждой строки есть
//     `sourceDescription` и `generatedByInferenceId`.
//
// В четырёх сборщиках контекста (спарринг, взгляд глазами другого,
// мотивы, прогноз) обе сущности раскладывались голым текстом под
// заголовками, утверждающими наблюдение: «Наблюдаемый коммуникационный
// профиль: …», «Известные прецеденты поведения: …». Ни происхождения, ни
// источника — хотя и то и другое лежит в базе.
//
// ЧЕМ ЭТО ХУЖЕ ПРЕДЫДУЩЕЙ НАХОДКИ. В пункте [source-collapse] терялась
// пометка на том, что ЧЕЛОВЕК записал сам. Здесь модель получает
// СОБСТВЕННЫЙ прежний вывод, переименованный в наблюдение, и строит на
// нём следующий — а тот, сохранившись, станет «наблюдением» для
// следующего. Цепочка, в которой каждое звено считает предыдущее фактом,
// и нигде в ней нет человека, который бы это подтвердил.
//
// ПРАВИЛО В ПРОДУКТЕ УЖЕ БЫЛО — и, что важно, на стороне ЧЕЛОВЕКА: экран
// показывает прецедент с подписью «Источник: …», а черту профиля — «На
// основании: …». То есть человеку продукт честно говорит, откуда взялось
// наблюдение, а модели — нет. Ровно наоборот к тому, как должно быть:
// человек хотя бы помнит, что нажимал «найти прецеденты», модель не знает
// об этом ничего.
//
// ИСТОЧНИК НЕ ВЫБРАСЫВАЕТСЯ И НЕ СОКРАЩАЕТСЯ. Он и есть то, чем вывод
// отличается от выдумки: «по разговору 12 марта» проверяемо, «модель так
// решила» — нет.

/** Строка, целиком созданная моделью, с указанием, из чего. */
export interface DerivedItem {
  /** Сам текст — черта профиля, описание прецедента. */
  text: string;
  /** Из чего он выведен: `observedFrom` / `sourceDescription`. */
  source: string | null;
}

export function derivedLine(item: DerivedItem): string {
  const source = (item.source ?? '').trim();
  return source ? `${item.text} (вывод модели по: ${source})` : `${item.text} (вывод модели, источник не записан)`;
}

export function derivedList(items: readonly DerivedItem[], separator = '; '): string {
  return items.map(derivedLine).join(separator);
}

/** Инструкция модели. Без неё пометка — украшение: тот же урок, что в
 * [partial-basis] и [source-collapse]. Формулировка запрещает ровно то,
 * что происходит само собой: считать прошлый вывод установленным. */
export const DERIVED_CONTEXT_INSTRUCTION =
  'Строки, помеченные «вывод модели», получены разбором расшифровок, а не наблюдением человека и не его словами: ' +
  'это прежние выводы этой же системы. Не считай их установленными фактами, не ссылайся на них как на то, что человек «делает всегда», ' +
  'и, если твой вывод держится только на них, скажи об этом прямо.';

/** Нужна ли инструкция: без выведенных строк она только размывает
 * промпт. */
export function hasDerived(...lists: ReadonlyArray<readonly unknown[]>): boolean {
  return lists.some((list) => list.length > 0);
}
