// Пункт [failure-looks-empty] 2026-09-05 — сбой, неотличимый от «ничего
// не найдено».
//
// НАЙДЕНО. Продукт построен вокруг одного правила: пробел не должен
// выглядеть как полнота. Четыре предыдущие сверки закрывали его на
// ОТБРОШЕННЫХ находках — сколько выпало и почему. Осталась половина, о
// которой никто не спрашивал: сам ЗАПУСК разбора. У «пар условий»
// пустой ответ значил три разных вещи и выглядел одинаково:
//
//   • у одной из сторон нет подтверждённых пунктов — сравнивать нечего,
//     разбор вообще не запускался;
//   • модель не ответила или ответила неразборчиво — разбор не
//     состоялся;
//   • модель ответила, совпадений действительно нет.
//
// Третье — находка. Первые два — их отсутствие. Экран показывал под
// всеми тремя одно и то же, и человек уходил с выводом «система
// сравнила и ничего не нашла» там, где система не сравнивала.
//
// ПОЧЕМУ ЭТО НЕ ТО ЖЕ, ЧТО ОШИБКА. Ронять фичу целиком из-за сбоя одной
// AI-подсказки нельзя, и в коде это названо «честной деградацией» —
// верно по намерению. Нечестной её делала не деградация, а молчание:
// «продолжаем без подсказки» и «подсказка говорит, что совпадений нет» —
// разные утверждения, и второе продукт делал за модель сам.

/** Что случилось с попыткой разбора — до всякого разговора о находках. */
export type AttemptOutcome =
  /** Разбор состоялся; пустой результат означает именно пустой результат. */
  | 'ok'
  /** Разбор не запускался: не хватило входных данных. */
  | 'not-attempted'
  /** Разбор запускался и не состоялся: модель недоступна или ответ неразборчив. */
  | 'failed';

/** Подпись под результатом. `null` при `ok` — намеренно: строка «разбор
 * состоялся» под каждым списком это шум, который приучает не читать
 * подписи, и тогда пропадает та единственная, ради которой всё затеяно.
 *
 * `what` — чем разбор занимался, словами человека: «сравнение условий с
 * двух сторон». Подставляется в предложение, поэтому без точки. */
export function attemptNote(outcome: AttemptOutcome, what: string, missing?: string): string | null {
  if (outcome === 'ok') return null;
  if (outcome === 'not-attempted') {
    const because = missing ? ` — ${missing}` : '';
    return `${what}: разбор не запускался${because}. Пусто здесь не значит «совпадений нет» — их не искали.`;
  }
  return `${what}: разбор не состоялся — модель не ответила или ответила неразборчиво. Пусто здесь не значит «совпадений нет» — результата нет вовсе.`;
}

/** Состоялся ли разбор. Отдельная функция, а не сравнение со строкой на
 * месте вызова: у вызывающего кода не должно быть повода написать
 * `outcome !== 'failed'` и потерять `not-attempted`. */
export function attempted(outcome: AttemptOutcome): boolean {
  return outcome === 'ok';
}
