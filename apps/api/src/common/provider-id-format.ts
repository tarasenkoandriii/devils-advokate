// Пункт [the-identifier-reshaped-the-url] 2026-10-01 — чужой
// идентификатор, пришедший от пользователя, подставлялся в адрес
// провайдера как есть.
//
// НАЙДЕННОЕ, два места. Оба — интерполяция значения из тела запроса
// прямо в URL провайдера БЕЗ `encodeURIComponent` и без проверки
// алфавита, при DTO, где у поля нет ни одного ограничения формы:
//
//   • `google-places-client.ts#getPlaceDetails` — `place_id` в строку
//     запроса. Соседние вызовы в том же файле (`placeType`, `query`)
//     кодируются все три; этот один — нет. Значение вида `ChIJ…&key=x`
//     переписывает наш же параметр `key` или `fields`, а расход
//     квоты списывается ДО вызова — то есть единица уже потрачена, а
//     запрос ушёл не тот, который мы составили.
//
//   • `text-to-speech.service.ts#callElevenLabs` — `voiceId` в ПУТЬ.
//     Это хуже: `../../v1/history` нормализуется разборщиком URL в
//     обращение к ДРУГОМУ эндпоинту того же провайдера, и уходит оно с
//     нашим ключом в заголовке. DTO ограничивает поле `@MaxLength(100)`
//     — проверка ДЛИНЫ там, где правило провайдера про АЛФАВИТ.
//
// ПОЧЕМУ ЭТО ТА ЖЕ ПОРОДА, что сегодняшние пункты про секреты. Правило
// чужой стороны («идентификатор состоит вот из таких символов»)
// существует, продукт на него опирается — и нигде его не называет. Разница
// только в том, что здесь нарушение не отвергается провайдером, а МЕНЯЕТ
// НАШ ЗАПРОС.
//
// ЧТО СДЕЛАНО. Проверка алфавита перед вызовом плюс обязательное
// кодирование. Алфавит берётся по минимуму из документации провайдеров —
// буквы, цифры, `-` и `_`; у Google `place_id` встречается и `.`.
//
// ЧЕГО НЕ СДЕЛАНО. Значение не «чинится» вырезанием лишнего: подставить
// похожий идентификатор значит молча запросить не то, что просил человек.
// И это не замена проверке в DTO — она тоже нужна, но DTO у публичного
// маршрута может не быть вовсе, а вызов провайдера есть всегда.

/** Идентификатор места Google: буквы, цифры, `-`, `_`, `.`. */
export const PLACE_ID_ALLOWED = /^[A-Za-z0-9_.-]{1,512}$/;
/** Идентификатор голоса ElevenLabs: буквы и цифры. */
export const VOICE_ID_ALLOWED = /^[A-Za-z0-9]{1,100}$/;

export class ProviderIdFormatError extends Error {}

/** Проверяет и возвращает значение, готовое к подстановке. Бросает —
 *  значит подставлять нельзя, и причина названа по-русски. */
export function safeProviderId(value: string, allowed: RegExp, what: string): string {
  if (!allowed.test(value)) {
    throw new ProviderIdFormatError(
      `${what} имеет недопустимый вид. Такой идентификатор не запрашивается у провайдера: ` +
        'в нём есть символы, которые изменили бы сам адрес запроса.',
    );
  }
  // Кодирование остаётся даже после проверки алфавита: проверка может
  // когда-нибудь расшириться, а кодирование — вторая линия, которая от
  // этого не зависит.
  return encodeURIComponent(value);
}
