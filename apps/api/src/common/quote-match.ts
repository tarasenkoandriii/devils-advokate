// Пункт [one-quote-rule] 2026-09-06 — цитатный барьер продукта, одной
// реализацией.
//
// ЧТО ЭТО ЗА БАРЬЕР. Модель, разбирая документ, возвращает не только
// вывод, но и ЦИТАТУ — отрывок источника, на который опирается. Продукт
// проверяет цитату детерминированно: нет её в источнике — вывод не
// сохраняется. Это центральный механизм честности всего проекта
// («CV только из ваших слов», опора у каждого факта, «улучшенная»
// формулировка опорой не считается).
//
// НАЙДЕННОЕ. Барьер был написан ПЯТЬ РАЗ, и пять реализаций
// расходились:
//
//  1. `quoteIsFromSource` (terms-matching) — пробелы + регистр. Её
//     зовут шесть модулей: условия листа, чек-листы соответствия,
//     досье компании, брифы клиента;
//  2. `quoteIsFromDocument` (cv-evidence) — та же, отдельной копией;
//  3. `quoteOccursIn` (cv-variant-barriers) — пробелы, регистр, И
//     типографика (ёлочки, кавычки, длинные тире), И минимальная
//     длина 3;
//  4-5. две встроенные копии в job-search-tools (признаки
//     мошенничества по расшифровке и по тексту вакансии) — пробелы и
//     регистр БЕЗ `trim()`.
//
// Расхождения дают ошибки В ОБЕ СТОРОНЫ:
//
//  • ЛОЖНЫЙ ОТКАЗ. Модель цитирует источник верно, но подставляет
//    «ёлочки» вместо простых кавычек или длинное тире вместо дефиса —
//    для реализаций 1, 2, 4, 5 это уже другая строка. Цитата
//    отвергается, и человеку сообщается причина `withoutQuote`,
//    которая на его языке звучит как «модель сослалась на то, чего вы
//    не говорили». То есть продукт делает неверное утверждение о
//    СОБСТВЕННОМ источнике человека — ровно то, от чего барьер и
//    поставлен. И та же цитата в варианте CV проходит: барьер №3
//    типографику нормализует;
//  • ЛОЖНОЕ ПРИНЯТИЕ. Минимальной длины нет ни у 1, ни у 2, ни у 4, ни
//    у 5: цитата из одной буквы содержится в любом тексте. «Опора» в
//    один символ проходила проверку в досье компании, в брифе клиента
//    и в чек-листе соответствия — там, где цитатой утверждается, ЧТО
//    ЧЕЛОВЕК НАПИСАЛ ИЛИ СКАЗАЛ;
//  • отсутствие `trim()` у 4 и 5 — ещё один ложный отказ, на цитате с
//    ведущим пробелом.
//
// РЕШЕНИЕ: одна реализация, самая осторожная из пяти (типографика +
// минимальная длина + trim). Правило записано один раз, и проверка на
// дереве не даёт завести шестую копию.

/** Короче этого «цитата» ничего не доказывает: строка из одного-двух
 * символов содержится почти в любом тексте. Взято из самой строгой из
 * прежних реализаций, а не выдумано заново. */
export const MIN_QUOTE_CHARS = 3;

/** Регистр, пробелы и типографика расхождением не считаются; всё
 * прочее — считается. Список замен — из реализации, которая была
 * осторожнее остальных (барьер вариантов CV). */
export function normalizeForQuoteMatch(text: string): string {
  return text
    .toLowerCase()
    .replace(/[«»""'']/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Встречается ли цитата в источнике. Единственная реализация барьера
 * в проекте. */
export function quoteIsFromSource(quote: string, source: string): boolean {
  const q = normalizeForQuoteMatch(quote);
  if (q.length < MIN_QUOTE_CHARS) return false;
  return normalizeForQuoteMatch(source).includes(q);
}
