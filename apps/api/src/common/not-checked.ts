// Пункт [not-checked-looks-clean] 2026-09-06 — «не проверено» и
// «проверено, чисто» были одним и тем же ответом.
//
// ЗАЧЕМ ЭТОТ МОДУЛЬ. У продукта есть проверки, под которыми экран пишет
// утвердительно: «Compliance-флагов нет», «Расхождений не найдено»,
// «Новых критериев в ваших словах не нашлось». Проект уже дважды закрывал
// соседние дыры в этом же месте:
//
//   • [dropped-quotes] — находка была, но её цитаты нет в источнике,
//     поэтому она не сохранена: список неполон, и об этом говорится;
//   • [input-truncated] — разобран не весь текст: утверждение сделано обо
//     всём тексте по его началу, и об этом говорится.
//
// Оставался третий, самый крупный случай: ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ ВООБЩЕ —
// не настроена или не удалась. Тогда находок ноль не потому, что их нет, а
// потому, что никто не смотрел. Для продукта, чей заявленный принцип —
// «конфигурационные пробелы не должны выглядеть как отсутствие находок», —
// это ровно тот случай, ради которого принцип и написан.
//
// ПОЧЕМУ КЛЮЧ, А НЕ ФРАЗА. По уговору, сложившемуся в
// `tma/src/lib/skipped-note.ts`: сервер отдаёт ПРИЗНАК, экран решает, как о
// нём сказать. Иначе одно и то же событие человек прочитает на четырёх
// экранах четырьмя разными способами.

/** Почему проверка не выполнялась. Ноль находок при любом из этих
 * значений НЕ ЗНАЧИТ «чисто». */
export type NotCheckedReason =
  /** Механизм не настроен: нет конфигурации, нет источника, нет согласия. */
  | 'not-configured'
  /** Провайдер недоступен или вернул то, что не разобрать. */
  | 'provider-failed';

/** Признак у ответа: проверка не выполнялась, значит ноль ничего не
 * утверждает. `null` — проверка прошла, нулю можно верить. */
export type NotChecked = NotCheckedReason | null;
