// Сверка чтений без потолка 2026-09-04.
//
// Найдено: 318 вызовов `findMany` без `take`. Большинство ограничены по
// смыслу (пункты одного листа, критерии одного конфига — их число задаёт
// человек руками), но часть растёт вместе с использованием и читается
// целиком: реплики, находки, аргументы, заявки публичного обсуждения. У
// публичной ссылки это хуже всего — заявки и комментарии туда пишет любой,
// у кого есть ссылка, а читаются они все и сразу, при каждом открытии
// страницы каждым участником.
//
// И вторая половина того же дефекта, менее очевидная. Там, где потолок
// УЖЕ стоял (19 мест), он молчит: ни одного `hasMore` в ответах API не
// было. Единственное исключение — экран журнала в админке, где в шапке
// написано «отдаются последние 200 записей»; но это статичная подпись,
// она стоит и когда записей десять, и когда их тысяча, то есть не
// отвечает на вопрос «мне показали всё?». Человек видит двести строк и не
// может отличить «их всего двести» от «их тысяча, показаны последние».
// Для продукта, чьё правило — «пробел не должен выглядеть как находка», —
// обрезанный список, выглядящий полным, тот же дефект, только про объём.
//
// Поэтому здесь не «добавить take», а один механизм на оба случая: взять
// на одну строку больше запрошенного, вернуть ровно запрошенное и СКАЗАТЬ,
// что дальше есть ещё. Молчаливой обрезки не остаётся нигде.
//
// ПОПРАВКА, Пункт [ceiling-hid-inside-a-total] 2026-09-24. Последняя
// фраза была неправдой, и держалась она двадцать дней. Строка остаётся
// датированной записью того, что было заявлено; вот что было на самом
// деле.
//
// 1. МЕХАНИЗМ БЕЗ ВТОРОЙ ПОЛОВИНЫ. `takeWithProbe()` берёт на строку
//    БОЛЬШЕ потолка, и эта строка обязана быть съедена `pagedList` — на
//    то она и зонд. В выгрузке персональных данных зонд вызывался, а
//    `pagedList` нет: человек получал 201 решение о своём аккаунте, и о
//    потолке не говорилось нигде. В файле, чей ВЕСЬ смысл — полнота, и
//    который отдельным списком называет каждое исключение по имени.
//
// 2. ПОТОЛОК, СПРЯТАННЫЙ ВНУТРИ ИТОГА — и это хуже обрезанного списка.
//    Операторский обзор очередей медиа отдавал 200 строк молча, а экран
//    не показывал их по одной: он их СКЛАДЫВАЛ. «Очередей», «роликов»,
//    «доля разобранных» — итог по срезу под подписью итога по всему.
//    Обрезанный список хотя бы выглядит списком; число выглядит фактом
//    о системе. Теперь итоги считает база по всем строкам.
//
// Правило, которое из этого следует и проверяется сверкой: КТО ВЗЯЛ
// ЗОНД, ТОТ ОБЯЗАН ЕГО СЪЕСТЬ.

/** Потолок по умолчанию для списков, которые человек читает целиком.
 * Двести — столько же, сколько уже стояло у журнала аудита; менять число
 * ради единообразия смысла не было. */
export const DEFAULT_PAGE_LIMIT = 200;

export interface PagedList<T> {
  items: T[];
  /** Есть ли за пределами показанного ещё записи. Не «сколько всего»:
   * точный счёт — второй запрос к базе, и он нужен не всегда; там, где
   * нужен, вызывающий делает `count()` сам и кладёт рядом. */
  hasMore: boolean;
  /** Сколько записей запрашивалось — чтобы клиент мог сказать человеку
   * «показаны последние 200», не зашивая число у себя. */
  limit: number;
}

/** Сколько строк просить у базы, чтобы узнать про «есть ещё» без
 * отдельного `count()`. */
export function takeWithProbe(limit: number = DEFAULT_PAGE_LIMIT): number {
  return limit + 1;
}

/** Строки, полученные с `takeWithProbe`, → список с честным флагом. */
export function pagedList<T>(rows: T[], limit: number = DEFAULT_PAGE_LIMIT): PagedList<T> {
  const hasMore = rows.length > limit;
  return { items: hasMore ? rows.slice(0, limit) : rows, hasMore, limit };
}
