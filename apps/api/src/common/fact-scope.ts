// Пункт [scope-not-applied] 2026-09-06 — у факта о человеке есть
// область видимости, и её читал один сервис из одиннадцати.
//
// ЧТО ЭТО ЗА ПОЛЕ. `PersonFact.scope` объявлен в schema.prisma с
// четырьмя значениями и с объяснением у каждого:
//
//   PROJECT (по умолчанию) — «факт виден только в проекте, где получен»
//   PERSON_GLOBAL          — «явный перенос пользователем, не автоматически»
//   PRIVATE_TO_USER        — «НЕ ПУБЛИКУЕТСЯ НИ ПРИ КАКИХ ОБСТОЯТЕЛЬСТВАХ»
//   PUBLIC_DERIVED_ONLY    — «из факта можно построить Argument, сам факт не публикуется»
//
// НАЙДЕННОЕ. Читают факты одиннадцать мест. Область видимости
// соблюдал ОДИН — `SteelmanService`, и ровно так, как поле и задумано:
// `OR: [{ scope: PROJECT, projectId }, { scope: PERSON_GLOBAL }]`.
// Остальные брали `where: { personId, status: 'ACTIVE' }` и отдавали
// модели всё подряд. То есть запись, помеченная человеком как «не
// публикуется ни при каких обстоятельствах», уходила в промпт наравне
// с остальными — в поиск прецедентов, в гипотезы о мотивах, в портрет
// собеседника, в карту фигурантов, в советы планировщика.
//
// ПОЧЕМУ ЭТО ТОТ ЖЕ КЛАСС, ЧТО [source-collapse]. Тот пункт нашёл, что
// ПОМЕТКА происхождения факта терялась по дороге к модели, и починил
// её — одним общим модулем. Но он чинил, КАК факты подписаны, и не
// трогал, КАКИЕ факты выбраны. Вторая половина того же поля осталась
// неприменённой, и заголовок того самого модуля уже говорит нужные
// слова: «правило есть, просто не везде».
//
// ДВА ПРАВИЛА, А НЕ ОДНО — потому что мест два вида.
//
//  • Разбор В ПРОЕКТЕ (есть projectId): проектные факты ЭТОГО проекта
//    плюс перенесённые человеком глобальные. Дословно по полю.
//  • Разбор НА УРОВНЕ ЧЕЛОВЕКА (projectId нет по самой задаче: портрет
//    общения, поиск прецедентов, сверка фактов между собой): здесь
//    честного проектного среза не существует, и правило слабее —
//    исключается только то, что не публикуется никогда.
//
// ЧТО ОСТАЛОСЬ ОТКРЫТЫМ И НАЗВАНО, А НЕ ЗАКРЫТО МОЛЧА. В разборах
// уровня человека проектный факт из ЧУЖОГО проекта по-прежнему
// участвует. Строго по букве поля участвовать он не должен. Но
// закрыть это значило бы либо оставить такие разборы почти без
// данных, либо переписать их на «по проектам раздельно» — а это смена
// продукта, а не починка молчания, и решать её владельцу. Здесь
// закрыт тот случай, где нет спора: «не публикуется ни при каких
// обстоятельствах» значит и «не уходит в промпт».

import { FactScope } from '@prisma/client';

/** Факты, которые не участвуют ни в одном разборе. Список, а не
 * отрицание: добавить новое значение перечисления и забыть о нём
 * здесь нельзя — тип `Record` ниже не соберётся. */
export const FACT_SCOPE_IN_ANALYSIS: Record<FactScope, boolean> = {
  [FactScope.PROJECT]: true,
  [FactScope.PERSON_GLOBAL]: true,
  // «Не публикуется ни при каких обстоятельствах» — промпт это
  // обстоятельство.
  [FactScope.PRIVATE_TO_USER]: false,
  // «Из факта можно построить Argument, сам факт не публикуется»:
  // построение вывода — это и есть разрешённое использование, поэтому
  // в разбор факт идёт. Запрет касается показа факта наружу, и он
  // остаётся за теми местами, которые публикуют.
  [FactScope.PUBLIC_DERIVED_ONLY]: true,
};

export const ANALYSIS_SCOPES = (Object.keys(FACT_SCOPE_IN_ANALYSIS) as FactScope[]).filter(
  (s) => FACT_SCOPE_IN_ANALYSIS[s],
);

/** Разбор ВНУТРИ ПРОЕКТА: проектные факты этого проекта плюс
 * перенесённые человеком глобальные. Дословно по описанию поля. */
export function projectFactsScopeWhere(projectId: string) {
  return {
    OR: [
      { scope: FactScope.PROJECT, projectId },
      { scope: FactScope.PERSON_GLOBAL },
    ],
  };
}

/** Разбор НА УРОВНЕ ЧЕЛОВЕКА, где проектного среза нет по самой задаче.
 * Исключает только то, что не публикуется никогда. Открытый вопрос про
 * проектные факты чужих проектов назван в заголовке файла. */
export function personLevelFactsScopeWhere() {
  return { scope: { in: ANALYSIS_SCOPES } };
}
