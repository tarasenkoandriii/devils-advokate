// Проверка формата секрета вебхука распознавания — ОТДЕЛЬНЫМ ЧИСТЫМ
// модулем, как у телеграмовского секрета (`telegram-bot/
// webhook-secret-format.ts`). Причина та же и названа вслух: правило
// формата должно проверяться ВЫЗОВОМ в спеке, а guard тянет за собой
// сервис секретов и через него Prisma — то есть проверка формата
// оказалась бы заложницей сгенерированного клиента.

// Пункт [the-secret-travelled-as-a-header] 2026-10-01 — продолжение
// [the-provider-had-rules-nobody-wrote-down] на пути ПОЛЬЗОВАТЕЛЯ.
//
// НАЙДЕННОЕ. Этот секрет уезжает провайдеру распознавания как ЗНАЧЕНИЕ
// HTTP-ЗАГОЛОВКА (`webhook_auth_header_value` у AssemblyAI, то же у
// Soniox), а вернуться обязан байт в байт — наш guard сравнивает без
// `trim`. Ни формат, ни пробелы по краям нигде не проверялись.
//
// Чем это кончается: владелец вставляет значение с переносом строки на
// конце (самый частый способ, которым переменная окружения его
// получает) или с не-ASCII символами. Мы принимаем, провайдер
// принимает, расшифровка СЧИТАЕТСЯ И БИЛЛИТСЯ — а на обратном пути
// значение приходит обрезанным, guard отвечает 401 «Invalid webhook
// secret» по-английски, и готовый оплаченный транскрипт выбрасывается.
// Разговор остаётся в TRANSCRIBING навсегда: реапера у этого состояния
// нет, и этот же файл выше называет такой исход «разговор навсегда
// завис бы в TRANSCRIBING» — но рассуждает только про ОТСУТСТВУЮЩИЙ
// секрет, не про испорченный, хотя последствие ровно одно.
//
// ПОЧЕМУ ЭТО ХУЖЕ ТЕЛЕГРАМОВСКОГО СЛУЧАЯ. Там ломалась операторская
// команда, и владелец видел отказ сразу. Здесь ломается путь человека,
// отказ приходит через минуты, деньги уже потрачены, а симптом
// («висит») не похож на причину («в переменной перенос строки»).
//
// ЧТО СДЕЛАНО. Пробелы по краям снимаются при разрешении (значение с
// переносом строки — это почти наверняка та же строка, а не другая), а
// формат проверяется ОДИН РАЗ, при отправке задачи провайдеру, то есть
// ДО того, как деньги потрачены. Алфавит взят заведомо безопасный для
// значения HTTP-заголовка.
//
// ЧЕГО НЕ СДЕЛАНО. Продукт не переписывает секрет сам (кроме снятия
// краевых пробелов) — по той же причине, что и в телеграмовском
// пункте: это учётные данные владельца, и подмена развела бы то, что
// лежит у нас, и то, что он записал себе. И `.env.example`/`VERCEL.md`
// для этой переменной всё ещё предлагали `openssl rand -base64 32`;
// base64 как раз содержит `+`, `/` и `=` — для значения заголовка это
// допустимо, поэтому инструкция оставлена, но правило формата рядом с
// переменной теперь названо.

/** Безопасный алфавит значения HTTP-заголовка: печатные ASCII без
 *  пробелов, кавычек и управляющих символов. Шире телеграмовского
 *  (там закрытый список провайдера), но исключает ровно то, что рвёт
 *  заголовок по дороге. */
export const STT_SECRET_ALLOWED = /^[A-Za-z0-9+/=_.:-]+$/;
export const STT_SECRET_MIN = 16;

/** `null` — значение подойдёт. Иначе — что именно не так, по-русски. */
export function sttSecretProblem(secret: string): string | null {
  if (secret.length === 0) return 'значение пустое';
  if (secret !== secret.trim()) {
    return 'по краям значения есть пробелы или перенос строки — в заголовке они не доедут, и готовый транскрипт будет отброшен';
  }
  if (secret.length < STT_SECRET_MIN) {
    return `длина ${secret.length} символов — слишком коротко для общего секрета (минимум ${STT_SECRET_MIN})`;
  }
  if (!STT_SECRET_ALLOWED.test(secret)) {
    const illegal = [...new Set([...secret].filter((c) => !/[A-Za-z0-9+/=_.:-]/.test(c)))];
    return (
      `запрещённые символы: ${illegal.map((c) => `«${c}»`).join(', ')}. ` +
      'Значение уезжает провайдеру как заголовок HTTP и должно вернуться байт в байт; ' +
      'подойдёт `openssl rand -base64 32` или `openssl rand -hex 32`.'
    );
  }
  return null;
}

