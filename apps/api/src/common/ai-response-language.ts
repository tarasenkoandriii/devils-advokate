// Пункт [ai-locale] 2026-09-02 — язык ответа AI.
//
// Найдено живым прогоном: разбор украинского видео вернулся
// РУССКОЯЗЫЧНОМУ пользователю по-английски («Rhetorical commentary with
// no verifiable factual claim»). Причина не в промпте конкретной фичи:
// язык ответа не задавался НИГДЕ. Промпты написаны по-русски, но это
// инструкция МОДЕЛИ, а не требование к языку вывода — без явного
// требования модель следует языку входных данных (транскрипт) или
// отвечает по-английски.
//
// Поэтому язык задаётся централизованно в AIRouter, одинаково для всех
// шести десятков AI-фич: одна инструкция, добавляемая к системному
// промпту. Локальные правки промптов эту дыру закрывали бы по одной и
// расходились бы между собой.

/** Язык по умолчанию, когда о пользователе ничего не известно
 *  (dev-вход без initData, операторские прогоны в песочнице). Интерфейс
 *  приложения русский — этот же язык честнее всего и для ответов. */
export const DEFAULT_AI_RESPONSE_LANGUAGE = 'ru';

/** Названия на самом языке: модель точнее следует инструкции, когда
 *  язык назван так, как он называет себя сам, а не кодом. */
const LANGUAGE_NAMES: Record<string, string> = {
  ru: 'русский',
  uk: 'українська',
  en: 'English',
  pl: 'polski',
  de: 'Deutsch',
  fr: 'français',
  es: 'español',
  it: 'italiano',
  pt: 'português',
  tr: 'Türkçe',
  kk: 'қазақша',
  be: 'беларуская',
  ka: 'ქართული',
  he: 'עברית',
  ar: 'العربية',
};

/**
 * Telegram присылает как 'ru', так и 'ru-RU' / 'pt-BR'. Берём базовый
 * тег: список названий выше ведётся по нему, а региональный вариант на
 * язык ответа не влияет.
 */
export function normalizeLanguageCode(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const base = raw.trim().toLowerCase().split(/[-_]/)[0];
  if (!/^[a-z]{2,3}$/.test(base)) return null;
  return base;
}

/** Человекочитаемое имя языка; для неизвестного кода — сам код. */
export function languageName(code: string): string {
  return LANGUAGE_NAMES[code] ?? code;
}

/**
 * Инструкция, добавляемая к системному промпту.
 *
 * Отдельного внимания стоит вторая половина: почти все промпты проекта
 * требуют СТРОГОГО JSON с фиксированными enum-значениями (SUPPORTED,
 * PRO, HIGH), идентификаторами (segmentId, criterionId) и цитатами из
 * исходника. Требование «отвечай по-русски» без этой оговорки заставило
 * бы модель переводить и их — validateOutput отверг бы ответ, и фича
 * падала бы на «exhausted all attempts» вместо неправильного языка.
 * То есть оговорка тут не украшение, а условие работоспособности.
 */
export function aiResponseLanguageInstruction(code: string): string {
  const name = languageName(code);
  return (
    `ЯЗЫК ОТВЕТА: ${name} (${code}). Весь текст, предназначенный человеку — ` +
    'формулировки, пояснения, обоснования, заметки, значения текстовых полей — пиши на этом языке, ' +
    'НЕЗАВИСИМО от языка входных данных: материал может быть на другом языке, это не меняет язык ответа. ' +
    'НЕ переводи и не изменяй: ключи JSON, значения-перечисления (константы в ВЕРХНЕМ РЕГИСТРЕ вроде ' +
    'SUPPORTED, PRO, HIGH), идентификаторы (id, segmentId и подобные), URL, а также дословные цитаты из ' +
    'исходного текста — они передаются как есть.'
  );
}

/** Готовый системный промпт с требованием языка. */
export function withResponseLanguage(systemPrompt: string | undefined, code: string): string {
  const instruction = aiResponseLanguageInstruction(code);
  return systemPrompt ? `${systemPrompt}\n\n${instruction}` : instruction;
}
