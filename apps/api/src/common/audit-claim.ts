// Пункт [log-says-we-saw-it] 2026-09-24 — журнал писал утверждение
// оператора так же, как наблюдение продукта.
//
// ЧТО РАЗЛИЧАЕТСЯ. Записей в журнале шестнадцать, и они двух родов:
//
//  • НАБЛЮДЕНИЯ. Продукт сам совершил действие и потому знает, что оно
//    произошло: кандидат добавлен в проект, оффер отозван, заказ принят,
//    досье создано, экспорт для bias-аудита сформирован. Тут «произошло»
//    — факт, и записывать его как факт правильно;
//
//  • УТВЕРЖДЕНИЯ. Продукт действия НЕ совершал и наблюдать его не мог.
//    Он записал то, что ему сказал оператор, нажав кнопку. Таких две:
//    «письмо-статус отправлено» (письмо отправляет человек своей почтой
//    — так прямо и написано в рамке самого письма: «отправляет человек»)
//    и «уведомление об AI показано кандидату» (показывает человек, на
//    своём экране, вне продукта).
//
// ПОЧЕМУ ЭТО НЕ ПРИДИРКА К СЛОВАМ. Во-первых, второе из двух — ровно та
// запись, которой доказывают, что кандидата предупредили об AI. Запись
// «показано» весит здесь больше, чем запись о чём угодно другом в
// журнале, и получена она из нажатия кнопки.
//
// Во-вторых, первое из двух ЧИТАЕТСЯ ОБРАТНО КАК ФАКТ: чеклист закрытия
// вакансии собирает из этих записей множество «кому ответили» и
// показывает остальных как тех, кому не ответили. А экран под пустым
// списком пишет утвердительно: «Всем ответили.» То есть нажатие кнопки
// превращалось в утверждение продукта о том, что живой человек получил
// ответ.
//
// ПОЧЕМУ ЭТО «ПРАВИЛО БЫЛО, ПРОСТО НЕ ВЕЗДЕ». Различие уже проведено — в
// соседней паре записей того же журнала, и проведено в точности так, как
// надо: `candidate_consent.revoked_by_recruiter` против
// `candidate_consent.revoked_by_candidate`, с комментарием прямым
// текстом — «„кандидат попросил, и я записал" и „кандидат отозвал сам" —
// разные события, и складывать их нельзя», — и с обязательным
// подтверждением `candidateAskedToRevoke`, без которого запись не
// делается вовсе. У двух других утверждений о кандидате ни имени, ни
// подтверждения не было.
//
// В третьих, у продукта уже есть целый словарь на эту тему —
// `common/fact-provenance.ts`, где «со слов пользователя» и «догадка, не
// проверено» не дают выглядеть проверенным. Журнал жил мимо него.
//
// ЧЕГО ЗДЕСЬ НЕТ. Поля «род записи» в `AuditLogEntry` не появилось, и
// это решение: род читается из имени действия, а имя уже обязано быть
// стабильным (по нему ищут), тогда как новое поле у существующих строк
// было бы NULL — то есть «род неизвестен» у всей истории. Имя честнее.

/** Действия журнала, которые записаны СО СЛОВ ОПЕРАТОРА: продукт их не
 * наблюдал и наблюдать не мог. Имя каждого говорит это прямо. */
export const AUDIT_STATUS_LETTER_MARKED_SENT = 'status_letter.marked_sent_by_recruiter';
export const AUDIT_AI_NOTICE_MARKED_SHOWN = 'ai_notice.marked_shown_by_recruiter';

/** Прежние имена тех же двух действий. Читать их обязаны: строки в
 * журнале за них уже есть, они означают то же самое, и делать вид, что
 * истории нет, — это та же неправда, только в другую сторону. Писать их
 * больше нельзя. */
export const AUDIT_STATUS_LETTER_LEGACY = 'status_letter.sent';
export const AUDIT_AI_NOTICE_LEGACY = 'ai_notice.shown';

/** Оба имени для чтения — одним местом, чтобы читатель и писатель не
 * разъехались (урок [label-is-the-choice]: карта подписей и
 * перечисление уже однажды разошлись именно так). */
export const AUDIT_STATUS_LETTER_ANY = [AUDIT_STATUS_LETTER_MARKED_SENT, AUDIT_STATUS_LETTER_LEGACY];

export const SELF_REPORTED_ACTIONS = [
  AUDIT_STATUS_LETTER_MARKED_SENT,
  AUDIT_AI_NOTICE_MARKED_SHOWN,
  AUDIT_STATUS_LETTER_LEGACY,
  AUDIT_AI_NOTICE_LEGACY,
  'candidate_consent.revoked_by_recruiter',
];

export function isSelfReportedAction(action: string): boolean {
  return SELF_REPORTED_ACTIONS.includes(action);
}
