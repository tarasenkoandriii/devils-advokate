  '29 валидаторов из того же населения требуют непустоты хотя бы у одного поля, а у остальных своих полей проверяют только тип. Это следующий заход, и он назван остатком, а не закрытым: «частично проверено» — не то же, что «проверено».';

/** Есть ли в поле что читать.
 *
 * Отдельная функция, а не `x.trim().length > 0` по месту: у восьми
 * валидаторов проверка должна быть ОДНОЙ, иначе через пункт-другой
 * где-то снова окажется `!== ''`, пропускающий строку из пробелов. */
export function filled(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/** Поля, которые проверяются ПРЯМО на элементе: без скобок и без пути
 * через другой массив.
 *
 * Нужна потому, что в одном списке `required` стоят поля разной
 * природы — `note` у элемента разбора и `attentionPoints[]` у ответа
 * целиком. Отдать весь список в `allFilled` значило бы искать
 * «attentionPoints[]» среди полей элемента и не находить: валидатор
 * отвергал бы ЛЮБОЙ ответ, в том числе годный. Ровно это и случилось на
 * первом прогоне второго прохода. */
export function itemFields(fields: readonly SubstanceField[]): string[] {
  return fields.filter((f) => !f.field.includes('[')).map((f) => f.field);
}

/** Все ли перечисленные поля объекта заполнены. */
export function allFilled(item: unknown, fields: readonly string[]): boolean {
  if (typeof item !== 'object' || item === null) return false;
  const record = item as Record<string, unknown>;
  return fields.every((f) => filled(record[f]));
}

/** Массив строк, в котором КАЖДЫЙ элемент — сам по себе находка.
 *
 * Пустой массив законен: он и есть способ сказать «ничего нет», и оба
 * промпта, где это применяется, разрешают его прямо. А вот пустая строка
 * ВНУТРИ массива — пункт повестки или вопрос, у которого нечего
 * прочитать. Та же разница, что уже записана у `possibleExplanations[]`
 * в разборе противоречий. */
export function allStringsFilled(value: unknown): boolean {
  return Array.isArray(value) && value.every((item) => filled(item));
}

/** Реестр по имени валидатора — спека сверяет с ним настоящие функции. */
export function substanceSite(key: string): SubstanceSite {
  const site = CLAIM_SUBSTANCE.find((s) => s.key === key);
  if (!site) throw new Error(`Неизвестное место в реестре содержания находок: ${key}`);
  return site;
}
