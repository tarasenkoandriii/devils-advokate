// Пункт [finding-without-substance] 2026-09-25 — находка, у которой
// нечего прочитать.
//
// НАЙДЕНО. Валидаторы ответа модели проверяют поля находки на ТИП, а не
// на наличие содержимого:
//
//   typeof item.description === 'string'
//
// Пустая строка — строка. Она проходит валидацию, сохраняется в запись и
// приходит на экран как находка: приём манипуляции назван, а описания у
// него нет; «этого лучше не говорить» — а почему, не сказано; гипотеза о
// мотиве есть, а на чём она построена, пусто.
//
// МЕРА. Строковых полей, проверенных только на тип, в 33 валидаторах —
// 78. Кричать на все 78 нечестно: среди них идентификаторы (`segmentId`,
// `clauseId`, `factAId`), чья пустота обнаруживается тут же — поиск по
// Map не находит записи, и такие находки уже отбрасываются со счётчиком;
// перечисления, приходящие строкой и отображаемые в enum; и поля,
// которые сам промпт разрешает не заполнять («если есть данные о цели
// пользователя»). Правило в проекте есть и применяется: из 61
// валидатора со строковыми полями 34 уже требуют непустого значения
// хотя бы у одного поля. Это снова «правило было, просто не везде».
//
// ГРАНИЦА ЭТОГО ПУНКТА. Закрываются поля, для которых верно всё сразу:
//   1) поле несёт САМУ находку или ЕЁ ОСНОВАНИЕ — то, что человек читает
//      как содержание утверждения, а не ссылку и не категорию;
//   2) пустота не обнаруживается ниже по потоку — её никто не ищет,
//      запись создаётся как есть;
//   3) запись подаётся человеку как ГОТОВАЯ находка или готовый совет,
//      а не как черновик, который человек правит до того, как что-то
//      будет утверждено.
//
// Третий признак — это и есть линия, по которой сюда не вошли разборы
// резюме, онбординг доменов и классификация запроса: там пустое поле
// попадает в черновик, и человек видит пробел ровно как пробел, а
// заполняет его сам. Признаю прямо: у края линия — суждение, и
// «повестка разговора» с «недостающей информацией» стоят к ней ближе
// всего снаружи (см. `TODO.md`, остаток пункта).
//
// ПОЧЕМУ ВАЛИДАТОР, А НЕ ОТБРАСЫВАНИЕ СО СЧЁТЧИКОМ. У выдуманного
// идентификатора отбрасывание со счётчиком — единственный выход: повтор
// запроса выдумает его снова, а остальные находки в батче настоящие.
// Здесь иначе, и решает это сам промпт: КАЖДЫЙ из этих промптов уже
// содержит явный способ сказать «ничего нет» — «Если манипулятивных
// приёмов нет — верни пустой массив []». Значит пустая строка в поле
// находки не означает «не нашлось»: способ сказать «не нашлось» у модели
// был, и она им не воспользовалась. Это испорченный ответ того же
// класса, что невалидный JSON, и ответ проекта на испорченный ответ один
// — валидация не пройдена, запрос повторяется, а если и повтор не помог,
// человек видит честную ошибку вместо пустой находки.
//
// ЧЕГО ЗДЕСЬ НЕТ. Реестр не лезет в базу: у записей, сохранённых до
// этого пункта, пустые поля остаются пустыми. Ретроспективной чистки
// нет намеренно — удалять чужие сохранённые записи ради опрятности
// продукт не вправе, а дописать в них содержание неоткуда.

/** Поле записи и довод, почему оно попало в свой список. */
export interface SubstanceField {
  field: string;
  why: string;
}

/** Одно место, где ответ модели превращается в запись для человека. */
export interface SubstanceSite {
  /** Имя валидатора — по нему спека находит настоящую функцию. */
  key: string;
  /** Файл, чтобы не искать. */
  where: string;
  /** Что сохраняется и что человек читает. */
  record: string;
  /** Поля, пустота которых делает запись находкой без содержания, и
   * проверяется это НА УРОВНЕ ОТВЕТА: валидация не пройдена, запрос
   * повторяется. Так можно только там, где у места нет поэлементного
   * отбрасывания, — иначе один негодный элемент унёс бы соседние. */
  required: readonly SubstanceField[];
  /** Поля, пустота которых отбрасывает ОДИН ЭЛЕМЕНТ со счётчиком.
   *
   * Пункт [finding-without-substance-2] 2026-09-26, и это поправка к
   * первому проходу. Там, где место уже отбрасывает элемент с
   * посчитанной причиной (`keepQuoted`, `sanitizePositionDraft`),
   * требование существа обязано стоять В ТОМ ЖЕ МЕСТЕ: завалить весь
   * ответ значило бы потерять соседние настоящие находки И число, по
   * которому экран отличает «не найдено» от «не смогли подтвердить». */
  dropped: readonly SubstanceField[];
  /** Поля той же записи, которым пустота разрешена, и почему именно. */
  optional: readonly SubstanceField[];
}

