// Пункт [the-public-door-counted-then-crossed] 2026-10-05 — один замок
// потолков вместо двух копий.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Днём раньше Пункт
// [the-ceiling-was-counted-then-crossed] закрыл потолки РАСХОДОВ:
// «посчитать, сравнить, вставить» тремя обращениями не держит ничего, и
// это измерено на живом Postgres (двадцать одновременных попыток при
// потолке пять давали двадцать записей). Замок жил в
// `common/outward-spend.ts`, потому что там же жил счётчик расходов.
//
// Теперь та же болезнь закрывается у потолков ПУБЛИЧНОЙ ЗАПИСИ, и это
// был выбор между второй копией замка и одним местом. Проект знает,
// чем кончаются копии: «правило было, просто не везде» — самая частая
// находка его собственных сверок, и ровно она породила
// `outward-spend.ts` неделей раньше. Поэтому замок переехал сюда, а
// `withSpendLock` остался именем и шапкой на своём месте — он теперь
// один вызов.
//
// ЧТО ДЕЛАЕТ. `pg_advisory_xact_lock` по строковому ключу внутри одной
// транзакции: проверка и запись перестают быть двумя событиями. Замок
// снимается концом транзакции, а она коммитится ДО снятия — значит
// следующий ожидающий видит уже вставленную строку.
//
// ЧЕГО НЕ ДЕЛАЕТ:
//  • замок внутри ОДНОЙ базы. Два инстанса продукта на разных базах
//    считались бы порознь и без него — это свойство счёта по строкам, а
//    не этой правки;
//  • при очереди длиннее таймаута транзакции вызов упадёт. Таймаут
//    задан явно: внятный отказ лучше молчаливого перебора потолка;
//  • он не делает потолок защитой ОТ ЧЕЛОВЕКА. Потолок по обсуждению
//    по-прежнему не мешает заводить новых участников подряд — это
//    названо в `public-write-limits.ts` и замком не лечится.

import type { PrismaService } from '../prisma/prisma.service';

/** Сколько ждать своей очереди. Явно, а не умолчанием Prisma: очередь
 *  обязана кончаться отказом, а не висеть. */
export const CEILING_LOCK_TIMEOUT_MS = 10_000;

/** Проверка потолка и запись — одним событием.
 *
 *  `scopeKey` — то, ПО ЧЕМУ считается потолок: пара «кто и за что» у
 *  расходов, обсуждение или участник у публичной записи. Разные области
 *  друг друга не ждут, одна область — ждёт.
 *
 *  Внутри `body` и счёт, и запись обязаны идти по переданному `tx`:
 *  обращение мимо транзакции вернуло бы ровно ту гонку, ради которой
 *  замок и ставится. Это проверяется спеками пунктов по трассе вызовов. */
export async function withCeilingLock<T>(
  prisma: PrismaService,
  scopeKey: string,
  body: (tx: PrismaService) => Promise<T>,
): Promise<T> {
  return prisma.$transaction(
    async (tx) => {
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${scopeKey}, 0))`;
      return body(tx as unknown as PrismaService);
    },
    { timeout: CEILING_LOCK_TIMEOUT_MS },
  );
}
