// Пункт [the-provider-had-rules-nobody-wrote-down] 2026-10-01 — правило
// чужой стороны, про которое продукт молчал.
//
// НАЙДЕНО НА ЖИВОМ ДЕПЛОЕ. Владелец выставил `TELEGRAM_WEBHOOK_SECRET`
// значением `openssl rand -base64 32`, вызвал регистрацию вебхука и
// получил от Telegram:
//
//   {"ok":false,"description":"Bad Request: secret token contains
//    illegal characters"}
//
// У Telegram для `secret_token` закрытый алфавит: `A-Z`, `a-z`, `0-9`,
// `_` и `-`, длина 1..256. В base64 есть `+`, `/` и `=` — то есть самый
// очевидный способ сгенерировать секрет даёт значение, которое Telegram
// не примет. Хуже: именно `openssl rand -base64 32` и было написано в
// `.env.example` и в `VERCEL.md`, то есть СОБСТВЕННАЯ ДОКУМЕНТАЦИЯ
// ПРОЕКТА порождала нерабочее значение.
//
// ЧТО ЗДЕСЬ БЫЛО НЕ ТАК — не отсутствие проверки само по себе, а
// РАСПРЕДЕЛЕНИЕ ЗНАНИЯ. Правило чужой стороны существовало всегда; знал
// о нём только Telegram. Продукт брал значение, отдавал его провайдеру и
// пересказывал владельцу английскую строку отказа — после того, как тот
// выставил переменную, сделал редеплой и выполнил команду. Три шага до
// того места, где об ограничении можно было сказать сразу.
//
// Это та же порода, что ловили заходы про документацию, только источник
// правды внешний: «пробел не должен выглядеть как полнота» относится и к
// чужим правилам, если продукт на них опирается. Переменная, у которой
// есть неочевидный формат, обязана называть его там, где её выставляют.
//
// ЧТО СДЕЛАНО. Формат проверяется ДО обращения к провайдеру, отказ
// говорит по-русски и показывает, ЧЕМ именно значение не подошло
// (какие символы лишние), а правило записано в `.env.example` и
// `VERCEL.md` рядом с самой переменной.
//
// ЧЕГО НЕ СДЕЛАНО И ПОЧЕМУ. Продукт не генерирует секрет сам и не
// чинит чужое значение (не выкусывает лишние символы): секрет —
// учётные данные владельца, и тихо подменить их на «похожие» значило бы
// развести то, что лежит у нас, и то, что он записал себе. Отказ с
// объяснением честнее молчаливой правки.

/** Алфавит, который Telegram принимает в `secret_token`. */
export const TELEGRAM_SECRET_ALLOWED = /^[A-Za-z0-9_-]+$/;
export const TELEGRAM_SECRET_MAX = 256;

export interface SecretFormatProblem {
  /** Что не так — текст для человека, по-русски. */
  message: string;
}

/** Проверка формата. `null` — значение Telegram подойдёт.
 *
 *  Возвращается именно описание проблемы, а не булево: «не подходит» без
 *  указания, чем именно, отправляет владельца гадать — ровно то, от чего
 *  этот файл и заводится. */
export function telegramSecretProblem(secret: string): SecretFormatProblem | null {
  if (secret.length === 0) {
    return { message: 'значение пустое' };
  }
  if (secret.length > TELEGRAM_SECRET_MAX) {
    return { message: `длина ${secret.length} символов, Telegram принимает не больше ${TELEGRAM_SECRET_MAX}` };
  }
  if (!TELEGRAM_SECRET_ALLOWED.test(secret)) {
    // Лишние символы перечисляются по одному разу и в том виде, в каком
    // они есть: владелец ищет их глазами в своём значении.
    const illegal = [...new Set([...secret].filter((c) => !/[A-Za-z0-9_-]/.test(c)))];
    return {
      message:
        `запрещённые символы: ${illegal.map((c) => `«${c}»`).join(', ')}. ` +
        'Telegram принимает только латинские буквы, цифры, «_» и «-» — ' +
        'значение из `openssl rand -base64 32` не подойдёт, в нём есть «+», «/» и «=». ' +
        'Подойдёт `openssl rand -hex 32`.',
    };
  }
  return null;
}

// ── Вторая половина того же пункта, найденная ТЕМ ЖЕ ДНЁМ, НА ЖИВОМ
// ПРОДЕ, ПОСЛЕ первой правки. Она важнее первой.
//
// Владелец получил «secret token contains illegal characters», понял
// «секрет не того формата» — и поправил ТОТ СЕКРЕТ, КОТОРЫЙ ДЕРЖАЛ В
// РУКАХ: значение заголовка `x-dispatch-secret`, то есть
// SCHEDULER_DISPATCH_SECRET. Прогнал его через `tr '+/' '-_' | tr -d
// '='`, получил значение допустимого алфавита, вызвал регистрацию заново
// — и получил ТУ ЖЕ САМУЮ строку отказа. Потому что Telegram говорил о
// другой переменной, TELEGRAM_WEBHOOK_SECRET, о которой в отказе не было
// ни слова.
//
// ЧТО ЗДЕСЬ БЫЛО НЕ ТАК. Один вызов опирается на ДВА наших секрета с
// разными ролями, и ответ провайдера не называет ни одного. Продукт
// пересказал чужую английскую строку как есть и тем самым предложил
// владельцу угадать, о каком из двух речь. Угадал он разумно — и
// неверно: видимым был только тот, что он набрал в команде.
//
// Это та же порода, что и первая половина, но на уровень глубже:
// проверка формата ДО вызова спасает лишь от предсказанного нами
// случая. Любой другой отказ Telegram по-прежнему приходит чужой
// строкой — и обязан приходить с нашей припиской о том, ЧЬЁ значение
// провайдер отверг. «Пробел не должен выглядеть как полнота»
// относится и к пересказу чужих слов: пересказ без привязки к нашим
// переменным выглядит как объяснение, а объяснением не является.
//
// ЧЕГО НЕ СДЕЛАНО. Приписка не пытается разобрать все отказы Telegram
// — их список не опубликован и меняется. Неузнанный отказ получает
// приписку о том, что строка чужая и у нас ничего не изменилось; это
// честнее попытки угадать причину.

/** Переменная, значение которой уезжает в Telegram как `secret_token`. */
export const SECRET_SENT_TO_TELEGRAM = 'TELEGRAM_WEBHOOK_SECRET';
/** Переменная заголовка `x-dispatch-secret` — ДРУГАЯ, и Telegram её не
 *  видит. Названа здесь, потому что путают именно эти две. */
export const SECRET_GUARDING_THE_COMMAND = 'SCHEDULER_DISPATCH_SECRET';

/**
 * Приписка к отказу Telegram: чьё именно значение провайдер отверг.
 *
 * Возвращается всегда, когда `setWebhook` ответил `ok:false` — в том
 * числе на неузнанный отказ. Пустой приписки не бывает: отсутствие
 * пояснения и есть та беда, из-за которой этот код написан.
 */
export function telegramRefusalHint(description: string | undefined): string {
  const text = (description ?? '').toLowerCase();
  if (text.includes('secret token') || text.includes('secret_token')) {
    return (
      `Telegram отверг значение переменной ${SECRET_SENT_TO_TELEGRAM} — именно оно уходит в setWebhook. ` +
      `Это НЕ ${SECRET_GUARDING_THE_COMMAND}: тем вы подтверждаете право вызвать эту команду, и Telegram его не видит. ` +
      `Допустимый алфавит secret_token: латинские буквы, цифры, «_» и «-», длина не больше ${TELEGRAM_SECRET_MAX}; ` +
      'подойдёт `openssl rand -hex 32`. После правки переменной нужен редеплой — иначе функция читает прежнее значение.'
    );
  }
  if (text.includes('url') || text.includes('https')) {
    return (
      'Telegram отверг адрес вебхука — он складывается из переменной API_PUBLIC_BASE_URL. ' +
      'Требуется публичный https-адрес; localhost и адрес без сертификата Telegram не примет.'
    );
  }
  return (
    `Строка отказа — ответ Telegram, не наш текст. У нас ничего не изменилось: вебхук остался прежним. ` +
    `В этом вызове участвуют два наших значения: ${SECRET_SENT_TO_TELEGRAM} (уезжает в Telegram) и ` +
    `API_PUBLIC_BASE_URL (адрес). ${SECRET_GUARDING_THE_COMMAND} к ответу Telegram отношения не имеет.`
  );
}
