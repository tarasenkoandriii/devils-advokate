// Пункт [one-of-several-spoke-for-all] 2026-09-25.
//
// НАЙДЕННОЕ. Три места брали досье компании запросом
// `findFirst({ where: { projectId } })` — то есть ОДНО ИЗ, без порядка и
// без проверки, что оно единственное. А схема нескольких досье в проекте
// не запрещает: `@@unique([projectId, registryCode])` разводит только
// записи с разными кодами реестра, и это осознанно — агентский проект
// ведёт несколько компаний-заказчиков.
//
// Чем это плохо в каждом из трёх мест:
//   • уведомление кандидату о применении AI ПОДПИСЫВАЕТСЯ реквизитами
//     компании («<юрлицо, код реестра, домен> уведомляет…»). Подписать
//     его чужим юрлицом — не опечатка, а ложное утверждение о том, кто
//     обрабатывает данные человека;
//   • письмо-статус кандидату подписывается названием компании;
//   • сравнение условий «с другими проектами той же компании» выбирало
//     компанию-заказчика произвольно — и дальше весь разбор шёл про неё.
//
// ПОЧЕМУ ЛЕЧИТЬ НЕ `orderBy`. Добавить сортировку значит сделать
// произвольный выбор ВОСПРОИЗВОДИМЫМ, а не правильным: продукт всё так
// же выбирал бы за человека, просто всегда одинаково. Правило продукта
// другое — «решения принимает человек»: если компаний несколько, надо
// сказать это вслух, а не молча назначить одну.
//
// ЧТО ПРОВЕРЕНО И ОКАЗАЛОСЬ ЧИСТЫМ. Тот же разбор прошёл по всем
// `findFirst` без `orderBy`: из 223 вызовов 126 без сортировки, у 51 из
// них фильтр не выглядит уникальным, и только у 12 используется
// СОДЕРЖИМОЕ найденной строки, а не факт её существования. Девять из
// двенадцати защищены `@@unique` или уникальны по построению (идентификатор
// задачи провайдера, `sourceProjectId @unique`, песочница оператора) — их
// трогать не за что, и это записано здесь, а не опущено.

export interface DossierRow {
  id: string;
  legalName: string | null;
  registryCode: string | null;
  domain: string | null;
  jurisdiction: string | null;
}

export type DossierChoice =
  | { kind: 'one'; dossier: DossierRow }
  | { kind: 'none' }
  /** Несколько — выбирать за человека нельзя; названия нужны, чтобы
   * сказать ему, ИЗ ЧЕГО выбирать. */
  | { kind: 'many'; companies: string[] };

const SELECT = { id: true, legalName: true, registryCode: true, domain: true, jurisdiction: true } as const;

/** Досье проекта, когда оно должно быть одно. Порядок здесь нужен не для
 * выбора, а чтобы список названий в ответе не прыгал между вызовами. */
export async function dossierForProject(
  prisma: { employerDossier: { findMany: (args: unknown) => Promise<DossierRow[]> } },
  projectId: string,
  where: Record<string, unknown> = {},
): Promise<DossierChoice> {
  const rows = await prisma.employerDossier.findMany({
    where: { projectId, ...where },
    select: SELECT,
    orderBy: [{ legalName: 'asc' }, { id: 'asc' }],
    take: 25,
  });
  if (rows.length === 0) return { kind: 'none' };
  if (rows.length === 1) return { kind: 'one', dossier: rows[0] };
  return { kind: 'many', companies: rows.map((r) => r.legalName ?? r.domain ?? r.registryCode ?? r.id) };
}

/** Одна формулировка на все три места: человек читает одно и то же
 * объяснение, где бы ни столкнулся с неоднозначностью. */
export function manyCompaniesMessage(companies: string[]): string {
  return `В проекте несколько компаний (${companies.join(', ')}) — продукт не выбирает за вас, какая из них здесь имеется в виду. Оставьте в проекте одну или объедините досье.`;
}
