const BY_PROVIDER = new Map(JSON_MODE_BY_PROVIDER.map((f) => [f.provider, f]));

/** Что про формат ответа известно у этого провайдера.
 *
 * Бросает на незнакомом имени, а не возвращает 'prompt-only' по
 * умолчанию. Незнакомый провайдер с клиентом — это дыра в конфигурации,
 * и мягкий ответ выдал бы её за знание: «пробел не должен выглядеть как
 * полнота». Проверка рядом ловит такую дыру ещё на сборке. */
export function jsonModeFact(providerName: string): JsonModeFact {
  const fact = BY_PROVIDER.get(providerName);
  if (!fact) {
    throw new Error(
      `Провайдер "${providerName}" не объявлен в JSON_MODE_BY_PROVIDER — ` +
        'неизвестно, держит ли он формат ответа. Добавьте строку с причиной в json-mode.ts',
    );
  }
  return fact;
}

export function jsonModeEnforced(providerName: string): boolean {
  return jsonModeFact(providerName).support === 'enforced';
}

/** Приписка роутера о языке ответа — не просьба о формате.
 *
 * НАЙДЕНО ПЕРВЫМ ЖЕ ПРОГОНОМ проверки ниже, и это была бы главная
 * ошибка этого пункта. Роутер добавляет КАЖДОМУ запросу приписку о языке
 * ответа, и в ней есть слова «НЕ переводи и не изменяй: ключи JSON». То
 * есть наивная проверка «есть ли в промпте слово JSON» зеленела бы на
 * каждом вызове без исключения — не находила бы НИ ОДНОГО пробела и
 * выглядела бы при этом работающей. Ровно тот вид круговой проверки,
 * который уже попадался в этом проекте: «зеленеет там, где и так всё
 * хорошо».
 *
 * Приписка продукта отрезается по метке: она всегда идёт последней и
 * всегда начинается с неё. Отрезается ХВОСТ, а не строка целиком — то,
 * что вызывающий написал ДО приписки, остаётся под проверкой. */
function withoutProductAppendix(text: string): string {
  const at = text.indexOf(AI_RESPONSE_LANGUAGE_MARKER);
  return at === -1 ? text : text.slice(0, at);
}

/** Просят ли JSON СЛОВАМИ в том тексте, который написал вызывающий.
 *
 * Проверка намеренно ОДНОСТОРОННЯЯ, и это её главное свойство. Если
 * слова «json» в промпте нет вовсе — формат не просили, и это точно.
 * Если есть — промпт его по меньшей мере УПОМИНАЕТ; утверждать, что
 * упоминание является требованием, отсюда нельзя, и ниже на это ничего
 * не опирается. Все выводы делаются только на уверенной стороне. */
export function promptAsksForJson(
  systemPrompt: string | undefined,
  userPrompt: string | ContentBlock[],
): boolean {
  const parts: string[] = [];
  if (systemPrompt) parts.push(systemPrompt);
  if (typeof userPrompt === 'string') parts.push(userPrompt);
  else for (const block of userPrompt) if (block.type === 'text') parts.push(block.text);
  return parts.some((text) => /json/i.test(withoutProductAppendix(text)));
}

export interface JsonModeCheck {
  enforced: boolean;
  /** По меньшей мере упомянут в тексте запроса. */
  promptMentions: boolean;
  /** Непусто ТОЛЬКО когда формат не задан ни одним каналом. */
  gap: string | null;
  /** Одна строка оператору. Есть всегда — в том числе когда всё в
   * порядке: «формат задан жёстко» тоже диагноз. */
  note: string;
}

/** Каким каналом задан формат ответа у ЭТОГО вызова.
 *
 * Спрашивается в момент вызова, а не по коду: главный промпт приходит из
 * базы (`activePrompt?.template`), и статически он неизвестен. */
export function checkJsonMode(
  providerName: string,
  systemPrompt: string | undefined,
  userPrompt: string | ContentBlock[],
): JsonModeCheck {
  const fact = jsonModeFact(providerName);
  const enforced = fact.support === 'enforced';
  const promptMentions = promptAsksForJson(systemPrompt, userPrompt);
  const gap =
    enforced || promptMentions
      ? null
      : `провайдер ${providerName} формат ответа жёстко не задаёт (${fact.how}), ` +
        'а в самом промпте про JSON не сказано ни слова — значит формат не запрошен НИ ОДНИМ каналом. ' +
        'Допишите требование формата в шаблон промпта: это единственный канал, работающий у всех провайдеров';
  const note = enforced
    ? `формат задан жёстко (${providerName}: ${fact.how})`
    : promptMentions
      ? `формат жёстко не задан (${providerName}: ${fact.how}), но промпт про JSON упоминает`
      : `формат не задан ни одним каналом (${providerName}: ${fact.how}; в промпте про JSON ни слова)`;
  return { enforced, promptMentions, gap, note };
}

