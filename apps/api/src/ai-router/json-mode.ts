// у половины провайдеров не делает ничего, и никто об этом не узнаёт.
//
// ИЗМЕРЕНО. `jsonMode: true` стоит на 83 разобранных вызовах роутера в
// 64 сервисах. Клиентов провайдеров четыре, и флаг читает РОВНО ОДИН:
//
//   openai, xai → OpenAiCompatibleClient: body.response_format =
//                 { type: 'json_object' } — провайдер обязан вернуть JSON;
