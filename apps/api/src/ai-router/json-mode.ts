// ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕ СДЕЛАНО.
//
//   Anthropic не научен держать формат. В Messages API нет
//   `response_format`; жёсткость даётся tool-use или префиксом ответа, и
//   наивный префикс `{` сломал бы разбор там, где ждут массив верхнего
