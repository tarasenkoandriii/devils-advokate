//   молчащий флаг на молча испорченный ответ.
//
//   Подбор провайдера не изменён. «Задаче нужен JSON — отдать её только
//   тому, кто держит формат» уводит 83 задачи с Gemini и Anthropic,
//   меняя и стоимость, и задержку, и записанную позицию ТЗ §5. Это
