import { AI_RESPONSE_LANGUAGE_MARKER } from '../common/ai-response-language';
import type { ContentBlock } from './ai-provider-client';

/** Чем провайдер держит формат ответа. */
export type JsonModeSupport =
  /** Жёстко: в теле запроса есть параметр, обязывающий вернуть JSON. */
  | 'enforced'
  /** Только просьбой в тексте промпта. Ответ не гарантирован. */
  | 'prompt-only';

export interface JsonModeFact {
  provider: string;
  support: JsonModeSupport;
  /** Чем именно — конкретным параметром или его отсутствием. */
  how: string;
  /** Почему так. Для 'prompt-only' это обязательно причина, а не
   * констатация: иначе строка читается как «недоделали». */
  why: string;
}

