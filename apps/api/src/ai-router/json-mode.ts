//                 не читается ни разу. Молча;
//   google      → GeminiClient: response_mime_type не задаётся, и это
//                 записанное решение (ТЗ §5), а не забывчивость.
//
// Подбор модели про jsonMode не спрашивает ничего: кандидаты
// отсеиваются по полосе, клиенту и ключу. То есть какой провайдер
// возьмёт задачу с `jsonMode: true` — вопрос того, чей ключ задан и чья
// строка capability засеяна раньше, а не того, кто умеет держать формат.
//
// ЧТО ИЗ ЭТОГО НЕ ДЕФЕКТ, И ЭТО ВАЖНЕЕ ВСЕГО ОСТАЛЬНОГО. Требование
// JSON живёт не только во флаге: в 63 из 64 сервисов оно написано
// словами прямо в промпте («Відповідай СТРОГО валідним JSON вида …»,
// «Верни ТОЛЬКО JSON-массив …»). Для провайдера без жёсткого режима это
// не «ничего не попросили», а «попросили единственным доступным
// каналом» — ровно та позиция, которая записана у Gemini. Объявлять
// здесь аварию значило бы кричать на 63 работающих места.
//
// А ВОТ ЧТО ДЕФЕКТ.
//
//   1. Свойство невидимо. Ни одна строка кода не говорила, какие
//      провайдеры держат формат жёстко. Читающий 83 вызова читает
//      `jsonMode: true` как «провайдера попросили» — и для двух из
//      четырёх это неверно. Ровно от этого расхождения в этом же файле
//      уже заведены `lanes`, с записанным доводом: «полоса — СВОЙСТВО
//      КЛИЕНТА… забыть объявление нельзя: поле обязательное». Здесь то
//      же лечение: обязательное поле на клиенте плюс реестр рядом, и
//      проверка, что они не разъехались.
//
//   2. Главный промпт живёт В БАЗЕ. Преобладающая форма вызова —
//      `activePrompt?.template ?? SYSTEM_PROMPT`: оператор правит
//      шаблон в админке, и код видит только запасной вариант. Значит
//      статическая проверка «в промпте просят JSON» отвечает не на тот
//      вопрос: убрать требование формата из ЖИВОГО шаблона можно, ничего
//      при этом не покраснеет, а на провайдере без жёсткого режима
//      задача начнёт возвращать прозу. Единственное место, где известна
//      вся правда, — момент вызова: там есть и разрешённый промпт, и
