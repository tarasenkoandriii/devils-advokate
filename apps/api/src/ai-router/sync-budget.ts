// Пункт [the-retry-killed-the-record] 2026-09-30 — бюджет функции для
// синхронной полосы AI-роутера.
//
// НАЙДЕННОЕ, две половины одного.
//
// ПЕРВАЯ. Синхронный вызов повторяется дважды (`maxRetries` по
// умолчанию 2), у каждой попытки потолок 45 с, между ними пауза 500 мс.
// Предел одного вызова функции на платформе — 60 с
// (`apps/api/vercel.json`). Значит вторая попытка после ИСТЕКШЕЙ первой
// не может завершиться никогда: платформа обрывает функцию на 60-й
// секунде, `catch` не исполняется, запись об ошибке в базу не попадает.
// Повтор, задуманный как попытка спасти запрос, ГАРАНТИРОВАННО
// уничтожал единственное свидетельство того, что запрос был. Комментарий
// у самого потолка («обязана уложиться до maxDuration») был правдой для
// одной попытки и неправдой для двух — ровно та порода, которую этот
// проект уже ловил: утверждение о проверке, записанное внутри самой
// проверки.
//
// ВТОРАЯ. Сторожевая (`reapExpired`) ищет зависшие джобы по
// `leaseExpiresAt: { lt: now }`. Асинхронная полоса (`enqueue`) срок
// выставляет; синхронная (`execute`) — нет, поле остаётся NULL, а NULL
// не меньше никакой даты. То есть джоба, убитая пределом функции,
// оставалась `RUNNING` НАВСЕГДА: не закрывалась, не помечалась FAILED,
// человек не получал ни результата, ни отказа. Сторожевая при этом
// существовала и работала — просто не для той полосы. «Правило было,
// просто не везде».
//
// ЧТО ЗДЕСЬ ЕСТЬ. Одно число предела функции — в коде, сверенное со
// `vercel.json` отдельной проверкой (два числа в двух файлах расходятся
// молча, и расходились: ТЗ мультимодальности до сих пор пишет 10).
// Резерв на запись исхода в базу. Решение «влезет ли ещё одна попытка»,
// принимаемое ПО ОСТАТКУ, а не по номеру попытки.
//
// ЧЕГО ЗДЕСЬ НЕТ. Сокращения самих цепочек. Запрос, делающий десять
// обращений к источникам подряд (`employer-dossier`) или до пятидесяти
// перефразировок (`terms-sheets/rephrase`), в 60 с не уложится ни с
// каким бюджетом — это переход на асинхронную полосу, то есть другая
// архитектура, и он назван в `VERCEL.md` как осознанно не сделанный.
// Бюджет здесь делает другое и меньшее: не даёт ПОВТОРУ убить запись и
// даёт сторожевой увидеть то, что платформа всё-таки убила.

/** Предел одного вызова функции на платформе.
 *
 *  ОБЯЗАН совпадать с `functions["api/index.ts"].maxDuration` в
 *  `apps/api/vercel.json` (там секунды). Сверяется
 *  `audit-2026-09-30-the-retry-killed-the-record.spec.ts`: число,
 *  живущее в двух файлах, расходится молча. */
export const FUNCTION_MAX_DURATION_MS = 60_000;

/** Сколько оставить на запись исхода в базу после последнего внешнего
 *  вызова. Это и есть смысл всего бюджета: обрыв на 60-й секунде
 *  означает, что причина провала не записана НИГДЕ. */
export const OUTCOME_WRITE_RESERVE_MS = 3_000;

/** Потолок одного обращения к провайдеру LLM.
 *
 *  ОБЯЗАН совпадать с потолком в `ai-provider-client.ts`. */
export const PROVIDER_CALL_BUDGET_MS = 45_000;

/** Срок аренды для джобы СИНХРОННОЙ полосы.
 *
 *  Заведомо больше предела функции: пока функция жива, она закончит
 *  сама и снимет срок. Срок нужен ровно на случай, когда функции уже
 *  нет, — иначе сторожевая не видит такую джобу вообще. */
export const SYNC_LEASE_MS = FUNCTION_MAX_DURATION_MS + 30_000;

/** Момент, после которого записывать исход уже поздно. */
export function outcomeDeadline(startedAtMs: number): number {
  return startedAtMs + FUNCTION_MAX_DURATION_MS - OUTCOME_WRITE_RESERVE_MS;
}

/** Влезет ли ещё одно обращение к провайдеру так, чтобы его исход
 *  успел попасть в базу.
 *
 *  Считается по ОСТАТКУ, а не по номеру попытки: первая попытка,
 *  упавшая на 401 за две секунды, оставляет время на вторую — и повтор
 *  тогда осмыслен. Первая, упёршаяся в свой потолок 45 с, не
 *  оставляет: повтор в этом случае лишь доводит функцию до обрыва. */
export function fitsAnotherProviderCall(
  startedAtMs: number,
  nowMs: number,
  callBudgetMs: number = PROVIDER_CALL_BUDGET_MS,
): boolean {
  return nowMs + callBudgetMs <= outcomeDeadline(startedAtMs);
}

/** Сколько времени функции осталось до момента «записывать поздно».
 *  Отрицательное значение возможно и означает, что мы уже за ним. */
export function msLeftForOutcome(startedAtMs: number, nowMs: number): number {
  return outcomeDeadline(startedAtMs) - nowMs;
}
