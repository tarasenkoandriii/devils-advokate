/** Человеческий текст плюс операторский — в одном месте, чтобы они не
 * разъехались и чтобы нельзя было случайно отдать человеку второй. */
export function failureText(kind: FailureKind, operatorDetail: string): FailureText {
  return { person: PERSON[kind], operator: `${kind}: ${operatorDetail}` };
}

/** Незнакомый вид провала. Человеку — честное «не знаем», а не
 * придуманное объяснение: выдуманная причина уводит его чинить не то. */
export function unknownFailureText(operatorDetail: string): FailureText {
  return {
    person: 'Разбор не получился, и причину мы назвать не можем. Попробуйте ещё раз; если повторится — это на нашей стороне.',
    operator: `unknown: ${operatorDetail}`,
  };
}

