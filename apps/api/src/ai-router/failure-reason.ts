// Пункт [failure-spoke-to-the-operator] 2026-09-25.
//
// НАЙДЕННОЕ. У асинхронной полосы причина провала пишется в
// `AIJob.partialResult`, оттуда её забирают обработчики завершения и
// кладут в поля, КОТОРЫЕ РИСУЕТ ЭКРАН ЧЕЛОВЕКА:
// `Conversation.paralinguisticsError`, `MediaReviewQueueItem.
// autoAnalysisError`, `JobVacancy.matchNotes`. А написаны эти причины
// для оператора:
//
//   «воркер не поставил задачу провайдеру до истечения lease —
//    проверьте pg_cron-джобы ai_jobs»
//   «провайдер не завершил задачу за отведённый потолок ожидания
//    (EXTERNAL_INTERACTION_MAX_WAIT_MS); задача могла остаться у
//    провайдера»
//   «ответ упёрся в max_output_tokens (incomplete) — чинится
//    промптом/длительностью, не ретраем»
//
// Человек, у которого не получился разбор, читает это на своём экране.
// Продукт уже чинил ровно этот дефект в других каналах
// ([draft-spoke-machine], [machine-text], [refusal-spoke-english],
// [decisions-spoke-machine]) — и у синхронного пути даже есть общий
// шлюз (`common/ai-error-passthrough.ts`, Пункт [ai-errors]), который
// не пускает наружу внутренние формулировки. У АСИНХРОННОЙ полосы такого
// шлюза не было: правило было, просто не везде.
//
// И отдельно: в одну из причин подставлялось до полутора тысяч знаков
// СЫРОГО ТЕЛА ответа провайдера. Это диагностика, а не сообщение
// человеку; её место в логе.
//
// ПРАВИЛО. У провала два адресата и два текста. Человеку — что
// случилось и что он может сделать, без внутренних имён. Оператору —
// подробности, и они идут В ЛОГ, рядом с идентификатором задачи.
// Придумывать человеку объяснение там, где смысл неизвестен, нельзя:
// незнакомый вид провала честно называется незнакомым.

export type FailureKind =
  | 'worker-never-sent'
  | 'provider-timeout'
  | 'provider-budget'
  | 'provider-incomplete'
  | 'provider-contract'
  | 'provider-rejected'
  | 'provider-unknown-status'
  | 'schema-invalid'
  | 'schema-invalid-no-format'
  | 'consent-revoked'
  | 'project-frozen';

export interface FailureText {
  /** Что увидит человек. Без внутренних имён и без сырых ответов. */
  person: string;
  /** Что уйдёт в лог рядом с идентификатором задачи. */
  operator: string;
}

