// Пункт [the-type-we-invented-ourselves] 2026-10-01 — продукт отдавал
// провайдеру тип, которого тот не принимает, и говорил человеку, что с
// его материалами всё в порядке.
//
// НАЙДЕННОЕ. `ALLOWED_CONTENT_TYPES` при загрузке аудио допускает
// `application/octet-stream` (намеренно: часть клиентов иначе грузить не
// умеет). Паралингвистика затем строит медиа-блок так:
// `mimeType: conversation.audioBlobContentType ?? 'application/octet-stream'`
// — то есть НАШЕ ЖЕ умолчание, придуманное здесь, а не прочитанное у
// провайдера, — и Gemini получает его как `mime_type`. У медиа-поверхности
// Gemini закрытый список типов, `application/octet-stream` в него не
// входит: ответ 400, `isRetryable === false`.
//
// И вот что человек читал в итоге: «Поставщик модели отклонил запрос. Это
// наша сторона: С ВАШИМИ МАТЕРИАЛАМИ ВСЁ В ПОРЯДКЕ, повторять смысла
// нет». Обе половины неправда. Дело ровно в типе ЕГО файла, и повторная
// загрузка с настоящим типом сработала бы. Это не «неудобный текст», а
// утверждение, которое уводит человека от работающего действия, —
// худшее, что может сделать сообщение об отказе.
//
// Разбор продуктового кода: allow-list'а поддерживаемых провайдером
// типов не было НИ ОДНОГО (единственное похожее место —
// `soniox-stt.provider.ts`, и там MIME→расширение для другой задачи).
//
// ЧТО СДЕЛАНО ЗДЕСЬ. Список типов, которые принимает медиа-поверхность
// Gemini, и проверка перед постановкой задачи. Отказ называет тип,
// говорит, что дело в файле, и говорит, что делать.
//
// ЧЕГО НЕ СДЕЛАНО — И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, НЕ МОЁ. Загрузку мы НЕ
// ужесточали: `application/octet-stream` при записи остаётся разрешённым.
// Иначе сломались бы уже загруженные записи и часть клиентов, которые
// иначе грузить не умеют, — а это продуктовый выбор про поведение
// загрузки, не правка на ходу. И тип файла здесь НЕ УГАДЫВАЕТСЯ по
// содержимому: подменить `octet-stream` на «похоже, это mp3» значит
// отправить провайдеру наше предположение под видом факта. Поэтому
// отказ, а не догадка.

/** Типы, которые принимает медиа-поверхность Gemini (аудио и видео). */
export const GEMINI_MEDIA_TYPES: readonly string[] = [
  'audio/wav',
  'audio/mp3',
  'audio/mpeg',
  'audio/aiff',
  'audio/aac',
  'audio/ogg',
  'audio/flac',
  'audio/webm',
  'audio/mp4',
  'audio/m4a',
  'audio/x-m4a',
  'video/mp4',
  'video/mpeg',
  'video/mov',
  'video/quicktime',
  'video/avi',
  'video/x-flv',
  'video/mpg',
  'video/webm',
  'video/wmv',
  'video/3gpp',
];

/** `null` — тип подойдёт. Иначе — текст ДЛЯ ЧЕЛОВЕКА: что не так и что
 *  делать. Параметров провайдера в тексте нет: человек не обязан знать,
 *  как называется наша модель. */
export function geminiMediaTypeProblem(mimeType: string | null | undefined): string | null {
  const raw = (mimeType ?? '').trim().toLowerCase();
  if (!raw) {
    return (
      'У записи не указан тип файла, и поставщик модели такой запрос не принимает. ' +
      'Загрузите запись ещё раз — большинство приложений проставляют тип само́й, ' +
      'если файл сохранён как обычный mp3, m4a, wav или mp4.'
    );
  }
  // Параметры вида `; codecs=opus` отбрасываются: они законны и на
  // пригодность типа не влияют.
  const base = raw.split(';')[0].trim();
  if (GEMINI_MEDIA_TYPES.includes(base)) return null;
  return (
    `Тип файла записи — «${base}», и поставщик модели его не принимает. ` +
    'Дело именно в типе файла, а не в содержании записи: ' +
    'загрузите её ещё раз как mp3, m4a, wav или mp4, и разбор пройдёт.'
  );
}
