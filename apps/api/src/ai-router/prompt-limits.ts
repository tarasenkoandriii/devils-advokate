// Найдено сверкой DTO: у 135 DTO проекта нет ни одного декоратора
// class-validator (это осознанное решение Пункта [validation] — декораторы
// добавляются точечно), и среди них есть поля, которые уходят в промпт
// внешнего провайдера ПРЯМО ИЗ ЗАПРОСА, без единого ограничения длины:
// `transcriptWindow` у четырёх живых циклов, `text` реплики спарринга и
// чата по материалам, `situationDescription` поиска прецедентов.
//
// Почему это не «валидация ради валидации»: живые циклы клиент вызывает
// сам, каждые 15–45 секунд, и содержимое окна тоже задаёт он. Ни один
// сервер-сайд не мешал послать мегабайт текста в каждом тике — это деньги
// на счёте у владельца и нагрузка на провайдера, а не абстрактный риск.
// Часть сервисов уже резала вход (`slice(0, 24_000)` в job-search-tools),
// часть — нет: правило существовало, но не было общим.
//
// Два разных предела, потому что это два разных вопроса:
//   • MAX_USER_PROMPT_CHARS — жёсткий потолок В РОУТЕРЕ, один для всех.
//     Он не про «удобно», а про «дальше платим за чужую шалость».
//   • MAX_LIVE_WINDOW_CHARS — смысловой предел окна живого цикла: это
//     последние минуты разговора, а не архив. Стоит у самих циклов.
//
// Обрезать молча нельзя: модель ответила бы про урезанный текст, а человек
// считал бы, что она видела всё. Поэтому — отказ с прямым объяснением.

import { BadRequestException } from '@nestjs/common';

/** ~30–40 тысяч токенов на запрос: заведомо больше любого честного
 * серверного промпта проекта (самый длинный — сверка вариантов CV, 24 000
 * символов) и заведомо меньше, чем «сколько влезет». */
export const MAX_USER_PROMPT_CHARS = 120_000;

/** Окно живого цикла — «последние ~10 минут» по замыслу клиента. 20 000
 * символов это примерно час непрерывной речи: предел ловит поломку и
 * злоупотребление, а не длинный разговор. */
export const MAX_LIVE_WINDOW_CHARS = 20_000;

export function assertWithinLimit(text: string, limit: number, what: string): void {
  if (text.length > limit) {
    throw new BadRequestException(
      `${what}: слишком длинный текст (${text.length} символов при пределе ${limit}). Текст не отправлен модели — она ответила бы про урезанный фрагмент, а вы считали бы, что она видела всё.`,
    );
  }
}
