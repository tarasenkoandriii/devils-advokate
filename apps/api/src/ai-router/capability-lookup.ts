// ПОВОД. Обзорный аудит незавершённого 2026-09-29 закончил список
// строкой: «плюс мелкое, подтверждённое раньше и не закрытое: индекс под
// горячий путь `AIModelCapability(taskType + availability)`». Заход
// начался с того, чтобы этот индекс создать.
//
// ЧТО ПОКАЗАЛ ЗАМЕР. Индекс создавать НЕ НАДО, и причин две.
//
//   1. КОЛОНКИ `taskType` У ЭТОЙ МОДЕЛИ НЕТ. Она была и удалена
//      НАМЕРЕННО Пунктом [router-simplify] 2026-09-01: строка на пару
//      (модель × задача) давала 192 записи на пять моделей и 63 задачи,
//      не отвечала ни на один вопрос — все текстовые модели умеют все
//      текстовые задачи одинаково — и стоила дорого: новая фича
//      добавляла `taskType` в сервис, забывала про сид, и фича молча
//      умирала при живых ключах. Так разом легли семь доменов.
//      Составной индекс по удалённой колонке создать нельзя, и это к
//      лучшему: он вернул бы в схему намёк, что различать задачи здесь
//      нужно.
//
//   2. ТАБЛИЦА — ЧЕТЫРЕ СТРОКИ. После той же правки строка ОДНА НА
//      МОДЕЛЬ, сид заводит четыре (Google + три текстовых провайдера) и
//      деактивирует всё остальное. Индекс по `availability` на таблице
//      из четырёх строк не будет использован никогда: планировщик
//      Postgres на таких размерах читает таблицу целиком, потому что это
//      дешевле обращения к индексу. Зато индекс стоил бы: ручной
//      миграции, применяемой на проде руками, записи в реестре ручных
//      миграций со своей пробой — и строки в схеме, которая говорит
//      следующему читателю «таблица большая», хотя она крошечная.
//
// ТО ЕСТЬ ЭТО НЕ «НЕ УСПЕЛИ», А НЕВЕРНАЯ ЗАПИСЬ В ИНВЕНТАРЕ. Пункт
// попал в список как «подтверждённое раньше», и его никто не перемерял;
// к моменту записи колонки уже девятнадцать дней не существовало. Тот же
// класс, что Пункт [unclosed-list-closed-itself]: утверждение о продукте
// пережило продукт. За сессию 2026-09-30 это третья неточность моего же
// инвентаря — после «13 потолков вместо 10» и «заявок заведений», у
// которых нет маршрутов записи.
//
// КОГДА ВОПРОС ОТКРОЕТСЯ СНОВА. Если строк станет заметно больше
// четырёх — вернулось различение по задачам, или моделей стало десятки, —
// «читать целиком» перестанет быть дешевле. Сторож ниже держит именно
// это условие, а не сам факт отсутствия индекса: запрет индекса навсегда
// был бы таким же необоснованным утверждением, как требование его
// создать.

