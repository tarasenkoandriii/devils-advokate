// Пункт [cascade-took-a-stranger] 2026-09-26 — удаление уносит чужое, и
// человеку об этом не сказано.
//
// НАЙДЕНО. Раздел «Требует решения владельца» называл две цепочки
// каскадов, уносящих чужие данные. Мера по схеме нашла третью и показала
// масштаб: удаление аккаунта каскадом затрагивает **143 модели из 169**.
// Через чужие записи проходят три цепочки:
//
//   1. User → VenueApplication → ApprovedVenue → VenueBookingConfirmation
//      Человек подал заявку заведения. Заявку одобрили, заведение попало
//      в публичную витрину, другие люди отмечали у себя бронирования, и
//      у заведения появилось согласованное вознаграждение за переход.
//      Человек удаляет аккаунт — исчезает витрина, отметки ДРУГИХ людей
//      и сумма, которая числилась к оплате заведению.
//
//   2. User → LibraryEntry → LibraryExperience
//      Человек отправил разбор в публичную библиотеку. Другие люди
//      написали под ним свой опыт. Человек удаляет аккаунт — их слова
//      исчезают вместе с его разбором. При этом схема ТУТ ЖЕ, на соседней
//      строке, утверждает обратное про исходный проект: «сама запись
//      библиотеки остаётся — это уже публичная, отдельная сущность,
//      снапшот текста» (`sourceProjectId` → SetNull). Одно и то же
//      решение принято по-разному для проекта и для автора.
//
//   3. User → Project → PublicComment / PublicArgumentSubmission
//      Приглашённые по ссылке написали комментарии и предложили
//      аргументы. Они вообще не пользователи приложения — у них нет
//      аккаунта, нет уведомлений и нет способа узнать, что их слов
//      больше нет.
//
// ЧТО ЗДЕСЬ ЗАКРЫТО, А ЧТО НЕТ, И ПОЧЕМУ ИМЕННО ТАК.
//
// Закрыто: человек, нажимающий «удалить аккаунт», ДО решения видит, что
// его удаление заберёт у других, и после — что забрало. Это не политика
// хранения, а правда о последствиях: «решения принимает человек» держится
// на том, что человеку есть что взвесить.
//
// НЕ закрыто намеренно: сами каскады не переписаны. Заменить Cascade на
// SetNull значит решить, что публичная витрина заведения и разбор в
// библиотеке ОСТАЮТСЯ после просьбы об удалении. Это решение о хранении
// данных человека, у него юридический вес, и принимать его молча,
// правкой схемы, продукт не вправе — тем более что модель данных
// смешивает «заявку человека» и «публичную карточку заведения» в одной
// цепочке. Развязка этой пары — отдельная работа, и она названа в
// `TODO.md` как решение владельца, а не сделана здесь наполовину.
//
// ЧЕСТНАЯ ГРАНИЦА ЧИСЕЛ. Считается ДО каскада — после него считать
// нечего. Если между подсчётом и удалением кто-то добавит комментарий,
// число окажется меньше факта; врать в эту сторону лучше, чем в
// обратную, и это единственная сторона, в которую оно может ошибиться.

import type { PrismaService } from '../prisma/prisma.service';

/** Что удаление аккаунта забирает у других. */
export interface ThirdPartyLoss {
  key: string;
  /** Текст с числом — человеку, а не оператору. */
  text(count: number): string;
  /** Почему это уносится: цепочка каскада словами. */
  why: string;
  /** Сколько именно. Считается до удаления. */
  count(prisma: PrismaService, userId: string): Promise<number>;
}

export const DELETION_TAKES_FROM_OTHERS: readonly ThirdPartyLoss[] = [
  {
    key: 'library-experiences',
    text: (n) => `${n} рассказов о похожем опыте, написанных ДРУГИМИ людьми под вашими разборами в публичной библиотеке`,
    why: 'рассказы привязаны к разбору, а разбор удаляется вместе с вашим аккаунтом',
    count: (prisma, userId) =>
      prisma.libraryExperience.count({ where: { libraryEntry: { submittedByUserId: userId } } }),
  },
  {
    key: 'library-entries',
    text: (n) => `${n} ваших разборов исчезнут из публичной библиотеки вместе с голосами за них`,
    why: 'записи библиотеки привязаны к вашему аккаунту напрямую',
    count: (prisma, userId) => prisma.libraryEntry.count({ where: { submittedByUserId: userId } }),
  },
  {
    key: 'venue-bookings',
    text: (n) => `${n} отметок о бронировании, сделанных ДРУГИМИ людьми в заведении, заявку на которое подавали вы`,
    why: 'отметки привязаны к карточке заведения, а она — к вашей заявке',
    count: (prisma, userId) =>
      prisma.venueBookingConfirmation.count({
        where: {
          approvedVenue: { application: { submittedByUserId: userId } },
          confirmedByUserId: { not: userId },
        },
      }),
  },
  {
    key: 'venue-listings',
    text: (n) => `${n} заведений пропадут из публичной витрины, и вместе с ними — согласованное вознаграждение, которое числилось заведению к оплате`,
    why: 'публичная карточка заведения привязана к вашей заявке; сумма вознаграждения хранится на карточке',
    count: (prisma, userId) =>
      prisma.approvedVenue.count({ where: { application: { submittedByUserId: userId } } }),
  },
  {
    key: 'discussion-comments',
    text: (n) => `${n} комментариев, написанных людьми, которых вы пригласили в обсуждение по ссылке`,
    why: 'обсуждение живёт внутри вашего проекта и удаляется вместе с ним',
    count: (prisma, userId) => prisma.publicComment.count({ where: { project: { ownerId: userId } } }),
  },
  {
    key: 'discussion-submissions',
    text: (n) => `${n} аргументов, предложенных приглашёнными в обсуждение`,
    why: 'предложения живут внутри вашего проекта и удаляются вместе с ним',
    count: (prisma, userId) =>
      prisma.publicArgumentSubmission.count({ where: { project: { ownerId: userId } } }),
  },
];

export interface CountedLoss {
  key: string;
  count: number;
  text: string;
  why: string;
}

/** Что именно заберёт удаление — только то, чего действительно не ноль.
 *
 * Ноль не показывается: строка «0 комментариев исчезнет» не сообщает
 * ничего о последствиях и разбавляет то, что сообщает. Это то же
 * правило, по которому продукт не рисует подпись об усечении там, где
 * усечения не было. */
export async function thirdPartyLosses(prisma: PrismaService, userId: string): Promise<CountedLoss[]> {
  const counts = await Promise.all(DELETION_TAKES_FROM_OTHERS.map((l) => l.count(prisma, userId)));
  return DELETION_TAKES_FROM_OTHERS.map((l, i) => ({
    key: l.key,
    count: counts[i],
    text: l.text(counts[i]),
    why: l.why,
  })).filter((l) => l.count > 0);
}

