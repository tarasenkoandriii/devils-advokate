export interface DescribedDecision {
  action: string;
  what: string;
  by: string | null;
  resource: string;
  resourceId: string;
  at: string;
}

/** Подпись или честное «не расшифровано». Выдуманной подписи здесь не
 * появляется никогда: неизвестное действие человек переспросит, а
 * придуманному поверит. */
export function describeDecision(entry: {
  action: string;
  resource: string;
  resourceId: string;
  createdAt: Date;
}): DescribedDecision {
  const label = DECISION_LABELS[entry.action];
  return {
    action: entry.action,
    what: label ? label.what : `${entry.action} — название действия не расшифровано, спросите поддержку`,
    by: label ? label.by : null,
    resource: entry.resource,
    resourceId: entry.resourceId,
    at: entry.createdAt.toISOString(),
  };
}
