/** Скалярные поля модели схемы — источником служит сама схема. */
export function scalarFields(schema: string, model: string): string[] {
  const block = new RegExp(`^model ${model}\\s*\\{([\\s\\S]*?)^\\}`, 'm').exec(schema);
  if (!block) return [];
  const out: string[] = [];
  for (const raw of block[1].split('\n')) {
    const line = raw.replace(/\/\/.*$/, '').trim();
    const m = /^(\w+)\s+(\w+)(\[\])?(\?)?/.exec(line);
    if (!m) continue;
    // Связи и списки — не скаляры: у связи тип начинается с заглавной и
    // это имя модели, а список всегда обратная сторона связи.
    if (m[3]) continue;
    const isRelation = /^[A-Z]/.test(m[2]) && !/^(String|Int|Float|Boolean|DateTime|Json|Bytes|Decimal|BigInt)$/.test(m[2]);
    const enumLike = isRelation && !line.includes('@relation');
    if (isRelation && !enumLike) continue;
    out.push(m[1]);
  }
  return out;
}
