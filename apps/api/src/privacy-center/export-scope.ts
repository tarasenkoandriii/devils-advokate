//
// Реестр выше закрыл связи ПРОЕКТА — и на том остановился. У модели
// User связей шестнадцать, и про них не говорил никто: ни выгрузка, ни
// исключения, ни тест. Ровно та форма, которую эта же сверка ловит в
// продукте третий раз подряд — ПРАВИЛО БЫЛО, ПРОСТО НЕ ВЕЗДЕ.
//
// Измерено: из шестнадцати связей в выгрузке были семь. Девять молчали,
// и среди них:
//
//  • `voiceEmbedding` — ГОЛОСОВОЙ ОТПЕЧАТОК. Биометрический
//    идентификатор, который продукт хранит под отдельным согласием
//    VOICE_BIOMETRIC. В выгрузке о нём не было ни строки — ни самих
//    данных, ни упоминания, что они есть. Человек, попросивший «всё,
//    что вы обо мне храните», не узнавал о самом чувствительном.
//    Спрятался он ровно там, где проверка не смотрела: это
//    ОДИНОЧНАЯ связь (`VoiceEmbedding?`), а тест для проекта обходил
//    только списки (`Model[]`). Поэтому проверка ниже обходит и те и
//    другие;
//  • записи в общую библиотеку, заявки на площадки и подтверждения
//    бронирований — всё это тексты, написанные самим человеком;
//  • созданные им ссылки-самошеринги (журнал того, кому он отдавал
//    свои данные).
//
// Заодно выгрузка не отдавала СОБСТВЕННЫЕ ПОЛЯ АНКЕТЫ: город, страну,
