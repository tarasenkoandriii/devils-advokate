// Плюс `AIInference`: у неё нет FK ни на `Person`, ни на `Project`, ни
// на `User`, и `person.delete()` её не касается вообще, — а в `output`
// лежит сырой текст модели ровно тех трёх разборов, чей предмет —
// названный человек.
//
// ПОЧЕМУ ЭТО ОБЕЩАНИЕ, А НЕ МЕЛОЧЬ. Реестр последствий отзыва
// согласия направляет человека к этой кнопке КАК К СРЕДСТВУ:
// «Удалить данные о конкретном человеке можно отдельной кнопкой —
// здесь же, в Центре приватности» (`REVOCATION_EFFECTS.PERSON_RESEARCH`).
// Кнопка названа средством, а что она не забирает — не было названо
// нигде.
//
// ЧТО ЗДЕСЬ СДЕЛАНО И ЧТО НЕТ. Здесь закрыта ЧЕСТНОСТЬ: остаток
// назван, посчитан и уезжает человеку вместе с ответом. Вопрос «а не
// должно ли часть этого удаляться» — продуктовый, и он записан в
// TODO.md как решение владельца, а не сделан наполовину. Девять
// переживающих моделей делятся на два разных класса, и это видно по
// полю `kind` ниже: МАТЕРИАЛЫ ПОЛЬЗОВАТЕЛЯ, в которых человек лишь
// упомянут (его реальные реплики в транскрипте, аргументы, скрипты
// разговора), и СИНТЕЗ О НЁМ (симуляция его как оппонента в спарринге,
// сгенерированная реакция «за него», сырой вывод модели). Первый класс,
// вероятно, правильно оставить — это работа человека, а не данные о
// третьем лице. Второй — вопрос владельца.

