// Пункт [rate-on-one-case] 2026-09-06 — когда доля имеет право
// показаться ЧЕЛОВЕКУ.
//
// ЧТО БЫЛО. Экран «Калибровка решений» печатает фразу о самом человеке:
// «Прогноз совпал с реальным исходом в N из M случаев (X%)». Условие
// показа было одно — `classifiable !== 0`. То есть после ПЕРВОГО же
// отмеченного исхода человек читал «в 1 из 1 случаев (100%)», а при
// неудачном — «(0%)». Рядом, тем же экраном: «В 1 случаях аргументы
// склоняли действовать, но исход оказался плохим — риск был недооценён»,
// то есть утверждение о ПАТТЕРНЕ его решений, построенное на одном
// случае.
//
// ПРАВИЛО В ПРОДУКТЕ БЫЛО. Разбивка по категориям того же экрана уже
// имеет порог, и причина над ним записана прямым текстом: «один или два
// случая недостаточно, чтобы говорить о паттерне, не единичной
// случайности». К ОБЩЕЙ доле — главному числу, которое человек и
// читает, — это правило применено не было. Третий раз подряд в этом
// ряду сверок одна и та же форма: ПРАВИЛО БЫЛО, ПРОСТО НЕ ВЕЗДЕ.
//
// И ПОРОГ СМОТРЕЛ НЕ НА ТО ЧИСЛО. Категория проходила фильтр по
// `list.length` — числу ВСЕХ её исходов, — а доля считалась по
// `classifiable`: записям, где есть и взвешенный прогноз, и
// определённый исход (MIXED и «слишком рано судить» не в счёт). Пять
// отмеченных исходов, из которых классифицируется один, проходили
// порог и печатались как «1 из 1 (100%)». Порог стоял, но считал не те
// случаи.
//
// ПОЧЕМУ ЭТО ХУЖЕ, ЧЕМ ТО ЖЕ САМОЕ НА ОПЕРАТОРСКОМ ЭКРАНЕ (см.
// [uncalibrated-number]): там число внутреннее, здесь — фраза о
// человеке, которую он читает о себе. Продукт, который не выносит
// вердиктов о людях, сообщал ему «100%» о его собственном суждении по
// одному наблюдению.

/** Минимум классифицируемых случаев, при котором доля перестаёт быть
 * случайностью. То же число и та же причина, что у порога разбивки по
 * категориям, — теперь это ОДНА константа на оба места, а не две
 * независимых: разъехаться им незачем. */
export const MIN_RATE_SAMPLE_SIZE = 3;

export interface RateCounts {
  matchCount: number;
  overOptimisticCount: number;
  overCautiousCount: number;
}

export interface RateVisibility {
  /** Случаи, по которым доля вообще может считаться: есть прогноз и
   * есть определённый исход. */
  classifiable: number;
  /** null — доля не имеет права показаться. Это НЕ «ноль процентов». */
  matchRate: number | null;
  /** false — показывать долю рано; счётчики при этом показать можно,
   * они ничего не утверждают о паттерне. */
  rateShown: boolean;
  minSample: number;
}

export function rateVisibility(counts: RateCounts, minSample: number = MIN_RATE_SAMPLE_SIZE): RateVisibility {
  const classifiable = counts.matchCount + counts.overOptimisticCount + counts.overCautiousCount;
  if (classifiable < minSample) {
    return { classifiable, matchRate: null, rateShown: false, minSample };
  }
  return { classifiable, matchRate: counts.matchCount / classifiable, rateShown: true, minSample };
}

/** Что человек читает вместо доли. Формулировка не говорит ни «мало
 * данных о вас», ни «пока плохо» — она говорит, чего не хватает, и
 * прямо отделяет «ещё не измерили» от «измерили и вышло ноль». */
export function notEnoughForRateNote(v: RateVisibility): string {
  if (v.classifiable === 0) {
    return 'Пока недостаточно данных для сравнения (нужны решения со взвешенными аргументами и отмеченным исходом).';
  }
  return `Сравнимых случаев пока ${v.classifiable} из ${v.minSample} нужных. Доля здесь не показана намеренно: по такому числу случаев она сказала бы о случайности, а не о ваших решениях.`;
}
