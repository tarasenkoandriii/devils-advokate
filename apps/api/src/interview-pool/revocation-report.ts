// Пункт [the-sentence-did-not-look-at-the-fact] 2026-09-25.
//
// НАЙДЕННОЕ. Отзыв согласия кандидатом гасит цепочку копий: профиль,
// ссылки, принятые по ним копии, ссылки от копий — и так вглубь, но НЕ
// БЕСКОНЕЧНО: обход ограничен `MAX_COPY_CHAIN_DEPTH`. Когда цепочка
// длиннее, обход останавливается и честно возвращает
// `depthExhausted: true`.
//
// А человеку отдавалась ФИКСИРОВАННАЯ фраза — одна и та же в обоих
// случаях: «копии, которые уже успели принять по этим ссылкам, помечены
// отозванными тоже». При исчерпанной глубине это неправда, и неправда
// самая дорогая из возможных: человек отозвал согласие и ему сказали,
// что копии закрыты. Факт был посчитан и выброшен по дороге к тексту.
//
// Та же болезнь второй стороной: числа `sharesRevoked`/`copiesRevoked`
// считались и не назывались. «Закрыто три ссылки и две копии» и «всё
// закрыто» — разные сообщения; первое человек может проверить.
//
// ПРАВИЛО. Фраза о последствиях СТРОИТСЯ ИЗ ИСХОДА, а не стои́т рядом с
// ним. Ничего не нашлось — так и сказано; дошли не до конца — сказано
// это, и сказано, что делать дальше.

import { MAX_COPY_CHAIN_DEPTH } from './consent-revocation';

export interface RevocationOutcome {
  /** Ссылок закрыто. */
  sharesRevoked: number;
  /** Копий профиля помечено отозванными (кроме самого профиля). */
  copiesRevoked: number;
  /** Обход остановился по пределу глубины: дальше цепочку не прошли. */
  depthExhausted: boolean;
}

function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/** Что сделано — словами и числами, из фактического исхода. */
export function revocationAlsoDone(outcome: RevocationOutcome): string {
  const parts = ['Ваш профиль у получателя помечен как отозванный'];
  if (outcome.sharesRevoked > 0) {
    parts.push(
      `закрыто ${outcome.sharesRevoked} ${plural(outcome.sharesRevoked, 'ссылка', 'ссылки', 'ссылок')}, которыми его могли передать дальше`,
    );
  } else {
    parts.push('открытых ссылок, которыми его могли передать дальше, не было');
  }
  if (outcome.copiesRevoked > 0) {
    parts.push(
      `${outcome.copiesRevoked} ${plural(outcome.copiesRevoked, 'копия', 'копии', 'копий')} у принявших сторон помечены отозванными — по ним тоже ничего не формируется`,
    );
  } else {
    parts.push('копий, принятых другими сторонами, не нашлось');
  }
  return `${parts.join('; ')}.`;
}

/** Чего отзыв НЕ отменяет. К постоянной части добавляется то, что
 * зависит от исхода: недойденная вглубь цепочка. */
export function revocationDoesNotUndo(outcome: RevocationOutcome, base: string): string {
  if (!outcome.depthExhausted) return base;
  return (
    `${base} И отдельно: цепочка передач оказалась длиннее, чем продукт проходит за один раз ` +
    `(${MAX_COPY_CHAIN_DEPTH} ${plural(MAX_COPY_CHAIN_DEPTH, 'звено', 'звена', 'звеньев')}), поэтому самые дальние копии могли остаться непомеченными. ` +
    'Это не «всё закрыто» — напишите тому, кто прислал ссылку, или в поддержку, чтобы довести отзыв до конца.'
  );
}
