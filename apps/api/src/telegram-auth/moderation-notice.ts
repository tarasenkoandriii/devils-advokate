// Пункт [decision-basis] 2026-09-04 — что человек узнаёт о решении,
// принятом о нём.
//
// НАЙДЕННОЕ. Ограничение и полная блокировка сообщались человеку двумя
// строками, и обе говорили одно: «напишите в поддержку». Поддержки в
// продукте НЕТ — ни адреса, ни формы, ни обработчика в боте: поиск по
// всему монорепо находит только сами эти две строки. Продукт называл
// человеку способ, которого не существует, — та же форма, что в пункте
// [candidate-rights], где отзыв согласия был обещан и не выдан.
//
// И вторая половина: ПРИЧИНА У НАС ЕСТЬ. Оператор записывает её
// (`restrictedNote` / `blockedNote`), с этой сверки — обязательно. Но
// человеку она не показывалась никогда: он узнавал, что доступ закрыт, и
// не узнавал, за что. Решение без основания и есть то, что человек
// достраивает сам — обычно в худшую для нас сторону.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Есть: что именно ограничено, с какого
// числа, на каком основании, и что запись о решении хранится. Нет:
// выдуманного канала. Если владелец заведёт контакт поддержки
// (`SUPPORT_CONTACT`), он будет назван; пока переменной нет — молчим об
// этом, а не отправляем человека в никуда.

import { instantUtc } from '../common/server-time';

/** Дата решения в виде, понятном человеку. Пустая — если её нет: дата,
 * которой нет, лучше отсутствует, чем показана как «Invalid Date». */
function on(date: Date | null | undefined): string {
  if (!date) return '';
  const d = new Date(date);
  if (Number.isNaN(d.getTime())) return '';
  // Пункт [server-said-which-day] 2026-09-24: `toLocaleDateString` без
  // зоны форматирует по зоне КОНТЕЙНЕРА (на Vercel — UTC). Решение,
  // принятое в 01:00 по Киеву, человек читал как «от» предыдущего числа
  // — и именно это число он назовёт, если считает решение ошибкой. Зона
  // названа вслух: число может не совпасть с его календарём, и это
  // видно.
  return ` от ${instantUtc(d)}`;
}

/** Контакт для обжалования — только если он настроен. */
function appeal(env: NodeJS.ProcessEnv = process.env): string {
  const contact = (env.SUPPORT_CONTACT ?? '').trim();
  return contact ? ` Если считаете решение ошибкой, напишите: ${contact}.` : '';
}

/** Сообщение при ПОЛНОЙ блокировке: вход отклоняется целиком. */
export function blockedNotice(
  user: { blockedNote?: string | null; blockedAt?: Date | null },
  env: NodeJS.ProcessEnv = process.env,
): string {
  const reason = (user.blockedNote ?? '').trim();
  return (
    `Доступ к аккаунту закрыт решением модерации${on(user.blockedAt)}.` +
    (reason ? ` Основание: ${reason}.` : '') +
    ' Запись о решении сохраняется.' +
    appeal(env)
  );
}

/** Сообщение при ОГРАНИЧЕНИИ: вход работает, часть действий закрыта.
 *
 * Формулировка отличается от блокировки намеренно: человеку важно
 * понимать, что читать свои данные он по-прежнему может, — иначе он
 * решит, что потерял всё. */
export function restrictedNotice(
  user: { restrictedNote?: string | null; restrictedAt?: Date | null },
  env: NodeJS.ProcessEnv = process.env,
): string {
  const reason = (user.restrictedNote ?? '').trim();
  return (
    `Это действие закрыто решением модерации${on(user.restrictedAt)}: ограничены создание проектов, публикации и заявки. ` +
    'Вход, чтение и выгрузка ваших данных работают как обычно.' +
    (reason ? ` Основание: ${reason}.` : '') +
    appeal(env)
  );
}
