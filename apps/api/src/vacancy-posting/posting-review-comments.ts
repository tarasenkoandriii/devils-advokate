// Пункт [the-atomic-fix-stayed-on-one-path] 2026-10-01 — одно место
// добавления комментария вместо двух, из которых атомарным было одно.
//
// НАЙДЕННОЕ. Пункт [two-comments-one-survived] 2026-09-30 сделал запись
// комментария по ПУБЛИЧНОЙ ссылке атомарной: один `UPDATE` с
// `jsonb ||` и проверкой потолка в условии, с длинным объяснением, почему
// чтение-склейка-запись здесь теряет комментарий без следа. Всё верно —
// и ровно та же колонка `posting_review_shares.comments` пишется ВТОРЫМ
// путём, внутри продукта: `engagement.service.ts#postingReview`, которым
// комментирует работодатель. Там осталось чтение массива, склейка в
// памяти и запись целиком.
//
// Два одновременных комментария с этого пути затирали друг друга так же,
// как затирали на публичном: побеждал последний, первый ИСЧЕЗАЛ БЕЗ
// СЛЕДА — без отказа и без строки в логе. И одновременность здесь не
// теоретическая: доступ к `engagement` имеет ЛЮБОЙ участник
// `RecruitingTeam` работодателя (`interview-pool-access.ts`), то есть
// два человека или один человек в двух вкладках.
//
// ВТОРОЕ, что нашлось по дороге: у этого пути НЕ БЫЛО ПОТОЛКА ВООБЩЕ.
// `comments-per-posting-review` из реестра публичной записи проверялся
// только на публичном пути, то есть массив с внутренней стороны мог
// расти без предела — а это та же колонка и тот же экран.
//
// ЧТО СДЕЛАНО. Добавление живёт одной функцией, и оба пути зовут её.
// Разница между путями — только в содержимом записи (`from: 'employer'`
// у внутреннего), и она передаётся параметром, а не копией кода.
//
// ЧЕГО НЕ СДЕЛАНО. Потолок один на оба пути, а не по потолку на путь:
// колонка одна, и «у заказчика сто и у работодателя сто» означало бы
// двести в одном массиве при пределе сто. Если когда-нибудь понадобятся
// раздельные счёта, это отдельное решение и отдельная запись в реестре.

import type { PrismaService } from '../prisma/prisma.service';
import { publicWriteLimit } from '../common/public-write-limits';

/** Что именно добавляется. `from` опускается на публичном пути: там
 *  автор — заказчик по ссылке, и отдельного имени у него нет. */
export interface PostingReviewCommentEntry {
  text: string;
  from?: 'employer';
}

/**
 * Атомарное добавление комментария с проверкой потолка В ТОМ ЖЕ
 * операторе.
 *
 * @returns число комментариев после добавления, либо `null` — потолок не
 *          дал добавить (или строки больше нет). Решение, что сказать
 *          человеку, принимает вызывающий: у публичного пути и у
 *          внутреннего разные отказы.
 */
export async function appendPostingReviewComment(
  prisma: PrismaService,
  shareId: string,
  entry: PostingReviewCommentEntry,
): Promise<number | null> {
  // Ноль в реестре означает «не ограничивай» — как у потолков расходов.
  // В условии SQL это пришлось бы читать как «меньше нуля», то есть
  // запретить всё, поэтому ноль превращается в предел int4: условие
  // остаётся одним и тем же оператором, а смысл сохраняется.
  const configured = publicWriteLimit('comments-per-posting-review').value;
  const limit = configured === 0 ? 2_147_483_647 : configured;
  const payload = JSON.stringify([
    {
      at: new Date().toISOString(),
      text: entry.text.trim().slice(0, 2000),
      ...(entry.from ? { from: entry.from } : {}),
    },
  ]);
  // Один SQL-оператор: добавление элемента и проверка потолка вместе.
  // Postgres выполняет его под блокировкой строки, так что второй
  // запрос видит уже дополненный массив. Сырой SQL здесь — тот же
  // приём, что в `ai-router` (`SKIP LOCKED` при заборе джоб): когда
  // важна одновременность, Prisma-обёртки недостаточно (у JSON-колонки
  // оператора добавления у Prisma нет).
  const updated = await prisma.$queryRaw<Array<{ count: number }>>`
    UPDATE posting_review_shares
       SET comments = COALESCE(comments, '[]'::jsonb) || ${payload}::jsonb
     WHERE id = ${shareId}
       AND jsonb_array_length(COALESCE(comments, '[]'::jsonb)) < ${limit}
    RETURNING jsonb_array_length(comments)::int AS count
  `;
  return updated.length === 0 ? null : updated[0].count;
}
