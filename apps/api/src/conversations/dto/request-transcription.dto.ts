export interface RequestTranscriptionDto {
  // Пункт [blob-upload] 2026-08-31: поле стало ОПЦИОНАЛЬНЫМ.
  //
  // Раньше оно было единственным источником файла: клиент сначала
  // прогонял байты через `POST /conversations/:id/upload`, получал от
  // AssemblyAI временный upload_url и присылал его сюда. Этот путь
  // сохранён — он работает локально и в докере, где лимита на тело
  // запроса нет, — но на Vercel он неработоспособен (4,5 МБ на тело
  // запроса к функции), поэтому основным стал другой: файл уже лежит в
  // приватном Vercel Blob, и requestTranscription() сам делает для него
  // подписанную ссылку.
  //
  // Отсюда правило: ЛИБО передан audioUrl, ЛИБО у разговора есть
  // audioBlobPathname. Оба сразу — ошибка, а не «возьмём какой-нибудь»:
  // молчаливый выбор источника означал бы, что пользователь думает,
  // будто расшифровывается один файл, а расшифровывается другой.
  audioUrl?: string;
  languageCode?: string;
}
