// Пункт [uncalibrated-number] 2026-09-06 — когда у числа есть право
// появиться.
//
// ЧТО БЫЛО. `recomputeCalibration()` писал
// `calibratedProbability = confirmed / total` в КАЖДУЮ корзину, у
// которой нашёлся хотя бы один подтверждённый исход. Один отмеченный
// человеком исход в корзине MEDIUM — и все сценарии этой корзины
// получали «эмпирическую точность» 1.000 или 0.000.
//
// ЭТО НЕ ПРОБЕЛ В ТЗ, А НЕВЫПОЛНЕННОЕ ТРЕБОВАНИЕ. Условие записано
// буквально, в трёх местах сразу:
//
//  • devils-advocate-prompt-framework-tz.md §4.3: «`calibratedProbability`
//    не активируется, "пока датасет исходов меньше минимального
//    размера выборки". Стартовое значение минимальной выборки: 30
//    предсказаний с известным исходом — ниже этого Brier score
//    статистически ненадёжен для production-решения»;
//  • тот же инвариант в implementation-ready.md
//    («calibratedProbability: nullable»);
//  • и в schema.prisma над самим полем: «NULL до накопления
//    достаточной выборки — не "низкая вероятность", а буквально "ещё
//    не откалибровано"».
//
// Порог в коде тоже был — MIN_SAMPLE_SIZE = 30 в calibration.service.ts,
// — но держал он только ПОКАЗ статуса (`gatePassed` на операторском
// экране), а не ЗАПИСЬ числа. То есть инвариант был описан, порог был
// объявлен, и ровно между ними число проходило без проверки.
//
// Форма знакомая: ПРОБЕЛ ВЫГЛЯДИТ КАК ПОЛНОТА. Отличить «посчитано по
// сорока исходам» от «посчитано по одному» по самому числу нельзя, и
// 1.000 выглядит убедительнее, чем 0.675. NULL означал «ещё не
// откалибровано» — значит любое не-NULL означало «откалибровано», и
// один клик выдавался за калибровку.
//
// ДВА УРОВНЯ ПОРОГА, И ВТОРОЙ — РЕШЕНИЕ ЭТОЙ РЕВИЗИИ, НЕ БУКВА ТЗ.
//
//  1. По ТЗ: пока ВСЯ выборка подтверждённых исходов меньше 30, числа
//     нет ни у одной корзины. Это дословный перенос требования выше,
//     и это то, чего не хватало.
//  2. Сверх ТЗ: выборка САМОЙ КОРЗИНЫ тоже обязана дойти до порога.
//     Причина: calibratedProbability — величина корзины, а не
//     выборки. При тридцати исходах в HIGH и одном в LOW условие ТЗ
//     выполнено, а у LOW всё равно 1.000 по одному наблюдению — тот
//     же дефект, только мельче. Альтернатива была ограничиться
//     буквой ТЗ и оставить этот случай как есть; выбран более строгий
//     вариант, потому что число уходит в поле, чей NULL прямо
//     документирован как «ещё не откалибровано», и врать в нём нечем
//     оправдаться. Порог взят тот же, 30: другого обоснованного
//     значения у нас нет, а выдумывать более мягкое ради того, чтобы
//     число появилось раньше, значило бы уступить ровно там, где
//     чинится.
//
// `gatePassed` НЕ ТРОНУТ — он остаётся буквально по ТЗ §5.3, по всей
// выборке, и acceptance-тесты §6.4 продолжают держать его как был.
// Это две разные величины: «можно ли доверять Brier score для
// решения о промоуте промпта» и «имеет ли право появиться число у
// конкретной корзины».
//
// НИЖЕ ПОРОГА ПИШЕТСЯ NULL, А НЕ «ОСТАВЛЯЕМ КАК БЫЛО». Число,
// записанное прежней, негодной калибровкой, само собой не исчезнет:
// счётчики только растут, поэтому корзина, однажды получившая 1.000
// по одному исходу, унесла бы это значение до тридцатого исхода.
// Пересчёт обязан его снять — иначе починка не дошла бы до данных,
// которые уже есть.

/** Порог выборки НА КОРЗИНУ. Совпадает с порогом ТЗ численно, но это
 * отдельное решение — см. пункт 2 в обосновании выше. */
export const MIN_BUCKET_SAMPLE_SIZE = 30;

export interface BucketCounts {
  total: number;
  confirmed: number;
}

export interface BucketCalibration {
  /** Сколько подтверждённых исходов в этой корзине. */
  sampleSize: number;
  /** null — выборки не хватает (корзины или всей), число не имеет
   * права появиться. Это НЕ «точность нулевая». */
  calibratedProbability: number | null;
  /** true — число посчитано по достаточной выборке. */
  calibrated: boolean;
  /** Порог корзины, с которым сравнивали — рядом с числом, чтобы
   * экран не додумывал его сам. */
  threshold: number;
  /** false — числа нет не из-за этой корзины, а потому что вся
   * выборка продукта ещё меньше порога ТЗ. Разные причины пустоты
   * читаются по-разному, поэтому различаются в ответе. */
  datasetReady: boolean;
}

/** Считает эмпирическую точность корзины ИЛИ честно отказывается её
 * считать. Отдельная чистая функция, а не три строки внутри цикла
 * записи: правило «когда число имеет право появиться» проверяется на
 * своих данных, без базы и без планового задания.
 *
 * @param datasetSampleSize вся выборка подтверждённых исходов
 * @param datasetThreshold порог ТЗ по всей выборке (MIN_SAMPLE_SIZE)
 */
export function bucketCalibration(
  counts: BucketCounts | undefined,
  datasetSampleSize: number,
  datasetThreshold: number,
  bucketThreshold: number = MIN_BUCKET_SAMPLE_SIZE,
): BucketCalibration {
  const sampleSize = counts?.total ?? 0;
  const datasetReady = datasetSampleSize >= datasetThreshold;
  if (!datasetReady || sampleSize < bucketThreshold) {
    return { sampleSize, calibratedProbability: null, calibrated: false, threshold: bucketThreshold, datasetReady };
  }
  return {
    sampleSize,
    calibratedProbability: (counts as BucketCounts).confirmed / sampleSize,
    calibrated: true,
    threshold: bucketThreshold,
    datasetReady,
  };
}

/** Текст для оператора рядом с корзиной. Пусто здесь не значит
 * «точность нулевая» — значит «ещё не измеряли». */
export function bucketCalibrationNote(c: BucketCalibration): string {
  if (c.calibrated) return `посчитано по ${c.sampleSize} подтверждённым исходам`;
  if (!c.datasetReady) return `вся выборка продукта ещё меньше порога — числа нет ни у одной корзины`;
  if (c.sampleSize === 0) return `исходов в этой корзине пока нет (нужно ${c.threshold})`;
  return `исходов ${c.sampleSize} из ${c.threshold} — числа нет, а не «точность низкая»`;
}
