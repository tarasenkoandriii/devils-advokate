// ПОВТОРНЫЙ АУДИТ 2026-08-31 — единственный публичный эндпоинт
// проверки живости.
//
// Зачем понадобился. После деплоя первым делом хочется убедиться, что
// функция вообще поднимается, и до сих пор это было нечем сделать:
// маршрут `/health` — доменный контроллер про медицинские решения под
// TelegramAuthGuard, и запрос к нему отдаёт «Cannot GET /health», что
// одинаково выглядит и при живом API, и при сломанном роутинге.
// Docker-стенду по той же причине пришлось проверять живость TCP-
// подключением к порту, а не запросом.
//
// Почему это не расширение поверхности атаки:
// - только GET, никаких параметров и никаких побочных эффектов;
// - в базу НЕ ходит. Это осознанно: эндпоинт отвечает на вопрос
//   «процесс поднялся и маршрутизация работает», а не «здорова ли вся
//   система». Проверка БД здесь означала бы, что при недоступной базе
//   healthcheck докера/платформы считает контейнер мёртвым и
//   перезапускает его по кругу — лечение не той болезни;
// - отдаёт только факт работы и время старта. Ни версий пакетов, ни
//   переменных окружения, ни состава модулей — всё это подсказки для
//   того, кто ищет уязвимость в конкретной версии зависимости.

import { Controller, Get, UseInterceptors } from '@nestjs/common';
import { ApiResponseInterceptor } from '../common/api-response.interceptor';

// Момент запуска инстанса. На serverless он же — время холодного
// старта, поэтому uptime заодно показывает, «тёплый» инстанс отвечает
// или только что созданный.
const STARTED_AT = new Date();

@Controller('healthz')
@UseInterceptors(ApiResponseInterceptor)
export class HealthzController {
  @Get()
  check(): { status: 'ok'; startedAt: string; uptimeSeconds: number } {
    return {
      status: 'ok',
      startedAt: STARTED_AT.toISOString(),
      uptimeSeconds: Math.round((Date.now() - STARTED_AT.getTime()) / 1000),
    };
  }
}
