// Сверка 2026-09-05 — что страница обещает человеку, который продукт
// ещё не открывал.
//
// ПОЧЕМУ ЭТО ТОТ ЖЕ ВОПРОС, ЧТО И ВЕЗДЕ. Прошлый пункт
// ([consent-purpose]) мерил не код, а ОБЕЩАНИЯ: собрал пять текстов
// согласий и проверил каждый против кода — три оказались правдой, два
// нет. Лендинг — то же самое, только раньше по времени: его читают до
// первого экрана согласия, и решение «доверить ли этому разговоры, в
// которых нет права на ошибку» человек принимает здесь.
//
// НАЙДЕННОЕ. Пять проверяемых утверждений, которым код противоречит:
//
//  1. «Все записи хранятся ЛОКАЛЬНО» — записи лежат в базе на сервере.
//     Продукт — Telegram Mini App с серверным разбором; иначе он не
//     работал бы вовсе.
//  2. «ЛОКАЛЬНОЕ хранение, без утечек, по вашим правилам» — то же, плюс
//     «без утечек» это обещание, которое нельзя ни проверить, ни
//     сдержать.
//  3. «Надёжное шифрование — защита промышленного уровня» — на ЭТОЙ ЖЕ
//     странице ниже честно написано: «Сквозного шифрования у продукта
//     нет: сервер работает с текстом, чтобы его разбирать». Два
//     утверждения об одном, и первое читают раньше.
//  4. «Без слежки — без аналитики, без ПРОФИЛИРОВАНИЯ» — аналитики
//     действительно нет (проверено: ни одного счётчика во всём
//     дереве). А коммуникационный профиль собеседника продукт строит,
//     и это одна из его главных функций.
//  5. «Без третьих сторон» — рядом, в том же списке, стоит «Внешним
//     AI-сервисам данные уходят лишь после вашего явного согласия».
//     Список третьих сторон в коде: OpenAI, Anthropic, xAI, Google
//     (Gemini, Places, Vision, Fact Check), AssemblyAI, Soniox,
//     ElevenLabs, SerpApi, Vercel Blob, Open-Meteo, Nominatim, Windy.
//
// ЧТО ПРОВЕРЕНО И ОКАЗАЛОСЬ ПРАВДОЙ — и потому не тронуто: «аудиозапись
// не хранится у нас» (файл удаляется по вебхуку на обоих путях),
// «экспорт и удаление данных в один клик» (обе кнопки есть на экране
// приватности), «без аналитики» (счётчиков нет).
//
// ЧЕГО СВЕРКА НЕ ТРОГАЕТ. Расплывчатого. «Ваша информация всегда
// остаётся вашей», «Ответственность по своей природе» — это не ложь, а
// отсутствие утверждения: проверять там нечего. Правило ниже ловит
// проверяемые обещания, которым код противоречит, а не всякую
// приподнятую формулировку — иначе оно начнёт падать на вкусовщине и
// его отключат.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';

const DICT_DIR = join(__dirname, '../lib/i18n/dictionaries');
const LANGS = readdirSync(DICT_DIR).filter((f) => f.endsWith('.ts')).map((f) => f.replace(/\.ts$/, ''));

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

/** Комментарии прочь: прежние формулировки процитированы в шапке этого
 * же файла, и проверка на текст поймала бы саму себя. Урок повторялся
 * в этой сессии столько раз, что стал привычкой. */
function copy(lang: string): string {
  return readFileSync(join(DICT_DIR, `${lang}.ts`), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Запрещённые обещания. Каждое — не «слишком бодрая формулировка», а
 * утверждение, которому продукт противоречит. Список общий на все
 * языки: перевод не делает неправду правдой. */
const FORBIDDEN: Array<[RegExp, string]> = [
  [/хранятся локально|зберігаються локально|stored locally/i, 'обещание локального хранения — записи лежат на сервере'],
  [/Локальное хранение|Локальне зберігання|Local storage/i, 'обещание локального хранения во втором месте'],
  [/без утечек|без витоків|no leaks/i, '«без утечек» — обещание, которое нельзя ни проверить, ни сдержать'],
  [/без профилирования|без профілювання|no profiling/i, '«без профилирования» — продукт строит коммуникационный профиль'],
  [/Без третьих сторон|Без третіх сторін|Third-party free/i, '«без третьих сторон» — их больше десяти, и соседний пункт списка это признаёт'],
  [/промышленного уровня|промислового рівня|Industry-standard/i, 'обещание уровня защиты без сказанного ограничения'],
];

/** Обязательные оговорки. Их отсутствие — не «недостаточно скромно», а
 * возврат к тому же обещанию другими словами. */
const REQUIRED: Array<[string, RegExp]> = [
  ['сказано, что сквозного шифрования нет', /Сквозного шифрования|Наскрізного шифрування|no end-to-end encryption/i],
  ['сказано, что профиль собеседника всё-таки собирается', /Профиль собеседника|Профіль співрозмовника|profile of the person/i],
  ['третьи стороны названы, а не отрицаются', /AI-провайдеры|AI-провайдери|AI providers/i],
];

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: ни на одном языке нет обещания, которому продукт противоречит', () => {
    // Правило по дереву языков, а не по списку строк: четвёртый язык с
    // прежней формулировкой должен уронить проверку, а не проехать
    // потому, что его забыли внести.
    const offenders: string[] = [];
    for (const lang of LANGS) {
      const text = copy(lang);
      for (const [pattern, why] of FORBIDDEN) {
        if (pattern.test(text)) offenders.push(`${lang}: ${why}`);
      }
    }
    assert(offenders.length === 0, `на странице снова обещано лишнее:\n  ${offenders.join('\n  ')}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: оговорки стоят на всех языках, а не только на одном', () => {
    // Самый вероятный способ вернуть неправду — починить русский и
    // забыть украинский: тексты правятся по одному.
    const missing: string[] = [];
    for (const lang of LANGS) {
      const text = copy(lang);
      for (const [what, pattern] of REQUIRED) {
        if (!pattern.test(text)) missing.push(`${lang}: не ${what}`);
      }
    }
    assert(missing.length === 0, `оговорка потерялась при переводе:\n  ${missing.join('\n  ')}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: страница не спорит сама с собой о шифровании', () => {
    // Утверждение и его опровержение на одной странице — хуже, чем
    // любое из двух по отдельности: человек читает то, что выше.
    for (const lang of LANGS) {
      const text = copy(lang);
      const strong = /Надёжное шифрование|Надійне шифрування|Strong encryption/i.test(text);
      assert(!strong, `${lang}: заголовок обещает шифрование, а ниже сказано, что сквозного нет`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: правда, которую проверяли и не тронули, на месте', () => {
    // Сверка не только удаляет обещания. Три утверждения проверены
    // против кода и оказались верными — если их однажды вычистят
    // «за компанию», продукт станет скромнее, чем он есть.
    for (const lang of LANGS) {
      const text = copy(lang);
      // Проверка ловит УТВЕРЖДЕНИЕ, а не одну его формулировку: в
      // английском словаре стоит «deleted right after». Первая версия
      // правила падала на переводе, а не на неправде — сузить правило
      // до одной фразы значит однажды выбросить верный текст ради
      // регулярки.
      assert(/удаляется сразу|видаляється одразу|deleted (immediately|right after)|removed (immediately|right after)/i.test(text),
        `${lang}: пропало верное утверждение про удаление аудиозаписи`);
      assert(/в один клик|в один клік|one-click|One-click/i.test(text),
        `${lang}: пропало верное утверждение про экспорт и удаление в один клик`);
    }
  }],

  ['ИЗМЕРЕНИЕ: языков три, и правило меряется по каталогу', () => {
    // Точка отсчёта. Четвёртый язык не должен появиться мимо правил
    // выше — они читают каталог, а не этот список.
    assert(LANGS.length === 3, `языков должно быть 3, найдено ${LANGS.length}: ${LANGS.join(', ')}`);
    for (const lang of LANGS) assert(copy(lang).length > 5000, `${lang}: словарь подозрительно короткий`);
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nlanding-promise: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
