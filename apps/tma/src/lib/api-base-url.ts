// Пункт [green-deploy-pointed-at-localhost] 2026-09-30.
//
// НАЙДЕННОЕ. Адрес API брался так — в ВОСЬМИ местах одного приложения
// (`api.ts`, `public-api.ts` и пять раз внутри `features.ts`), плюс
// девятый раз в админке:
//
//   process.env.NEXT_PUBLIC_API_BASE_URL ?? 'http://localhost:3000'
//
// Переменная читается на СБОРКЕ (`NEXT_PUBLIC_` вкомпилируется в
// бандл), не в рантайме. Значит если её не выставить в проекте на
// платформе, в бандл уезжает `http://localhost:3000`, сборка проходит,
// деплой зелёный, страницы рисуются — и каждый запрос уходит на
// localhost БРАУЗЕРА ЧЕЛОВЕКА. Ни одной ошибки на нашей стороне: ни в
// сборке, ни в логах функции, потому что до функции ничего не доходит.
// Узнать об этом можно было только от человека, у которого «ничего не
// работает».
//
// Отдельно: дефолт был скопирован восемь раз. Проверять его в восьми
// местах — это и есть «правило было, просто не везде» наоборот: копия
// есть везде, проверки нет нигде.
//
// ПРАВИЛО. Дефолт для разработки остаётся дефолтом для РАЗРАБОТКИ. На
// платформе отсутствие адреса — не «возьми localhost», а красная
// сборка: красная сборка дешевле зелёного деплоя, который не работает,
// и обнаруживается нами, а не человеком.
//
// Признак платформы — `VERCEL`/`VERCEL_ENV`, которые платформа
// выставляет сама на всех сборках (прод и превью), а не `NODE_ENV`:
// `next build` локально и в CI тоже идёт с `NODE_ENV=production`, и по
// нему проверка роняла бы обычную локальную сборку, в которой дефолт
// как раз уместен.

/** Дефолт разработки. Используется ТОЛЬКО когда мы не на платформе. */
export const LOCAL_API_BASE_URL = 'http://localhost:3000';

/** Признак сборки на платформе. Любая из двух переменных означает, что
 *  бандл уедет пользователям. */
function onPlatform(env: NodeJS.ProcessEnv): boolean {
  return Boolean((env.VERCEL ?? '').trim() || (env.VERCEL_ENV ?? '').trim());
}

export function resolveApiBaseUrl(env: NodeJS.ProcessEnv = process.env): string {
  const raw = (env.NEXT_PUBLIC_API_BASE_URL ?? '').trim();
  if (raw) {
    // Хвостовой слэш убирается здесь, а не в восьми местах склейки:
    // `${base}${path}` с ним даёт `//conversations` — путь, которого на
    // API нет, и отказ 404 выглядел бы как «объекта не существует».
    return raw.replace(/\/+$/, '');
  }
  if (onPlatform(env)) {
    throw new Error(
      'NEXT_PUBLIC_API_BASE_URL не выставлена в проекте на платформе. ' +
        'Без неё в бандл уедет http://localhost:3000, и каждый запрос уйдёт на localhost браузера человека: ' +
        'деплой будет зелёным, а приложение — нерабочим. Выставьте адрес API в переменных проекта и пересоберите.',
    );
  }
  return LOCAL_API_BASE_URL;
}

/** Единственный адрес API приложения. */
export const API_BASE_URL = resolveApiBaseUrl();
