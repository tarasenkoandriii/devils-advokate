// Пункт [date-only] 2026-09-04 — день, который сдвигался.
//
// НАЙДЕННОЕ. Поля «к какому сроку» — это `<input type="date">`, он даёт
// строку вида `2026-09-10`. Дальше стояло `new Date('2026-09-10')`, и вот
// здесь происходит то, о чём легко не подумать: по спецификации JS
// строка ТОЛЬКО С ДАТОЙ разбирается как полночь UTC, а не как полночь
// местного времени. Дальше `.toISOString()` — и в базу уезжает
// `2026-09-10T00:00:00.000Z`.
//
// Для человека восточнее Гринвича это почти незаметно. Западнее —
// заметно сразу: в Чикаго (UTC−5) `2026-09-10T00:00:00Z` это 19:00
// ДЕВЯТОГО, и `toLocaleDateString()` показывает «09.09.2026». Человек
// выбрал десятое, приложение показывает девятое. Проверено прогоном, а
// не рассуждением.
//
// Вторая половина, менее очевидная и более неприятная: «просрочено»
// считается как `dueDate < сейчас`. При полуночи UTC обещание со сроком
// «до 10 сентября» у человека в Киеве становится просроченным в 03:00
// десятого — то есть утром того самого дня, когда срок ещё не вышел.
// Приложение УТВЕРЖДАЕТ неправду о человеке, которому оно помогает
// держать слово.
//
// РЕШЕНИЕ: дата без времени превращается в КОНЕЦ МЕСТНОГО ДНЯ.
//  • отображение: тот же день в том же часовом поясе, откуда его ввели;
//  • «просрочено»: наступает после того, как день кончился, — ровно то,
//    что означает «до 10 сентября» в обычной речи, где срок включительно.
//
// ЧЕСТНАЯ ГРАНИЦА. В базе это по-прежнему МОМЕНТ ВРЕМЕНИ (`DateTime`), а
// не календарная дата. Значит, человек, поставивший срок в Киеве и
// открывший приложение в Нью-Йорке, увидит на границе суток другой день —
// это неизбежно для момента времени и лечится только колонкой типа
// `@db.Date`, то есть ручной миграцией. Решение о ней за владельцем;
// здесь закрыт куда более частый случай — один человек, один часовой
// пояс, и число, которое ему показывают, совпадает с тем, что он ввёл.

/** `2026-09-10` → ISO-момент конца этого дня в ЧАСОВОМ ПОЯСЕ БРАУЗЕРА.
 *
 * Собирается из частей (`new Date(y, m - 1, d, …)`), а не разбором
 * строки: конструктор от чисел трактует их как местное время, разбор
 * строки — как UTC. Вся разница именно в этом. */
export function endOfLocalDay(dateOnly: string): string {
  const [year, month, day] = dateOnly.split('-').map(Number);
  if (!year || !month || !day) return dateOnly; // не наш формат — не трогаем
  return new Date(year, month - 1, day, 23, 59, 59, 999).toISOString();
}

/** ISO-момент → `2026-09-10` для подстановки обратно в `<input type="date">`.
 *
 * Раньше в этом месте стояло `.slice(0, 10)` / `.split('T')[0]` по ISO —
 * то есть ДАТА В UTC. При хранении конца местного дня она отличается от
 * той, что человек видит на экране, и форма при открытии подставляла бы
 * не тот день, который в ней записан. */
export function toDateInputValue(iso: string | null | undefined): string {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
