// Пункт [unmeasured-confidence] 2026-09-05 — проценты уверенности,
// которых никто не измерял.
//
// НАЙДЕНО. Продукт показывает человеку числа вида «уверенность 87%» и
// слова вида «высокая уверенность», и по виду это измерение продукта. Ни
// одно из них измерением не является, а происхождение у них РАЗНОЕ — и
// именно разницы человек не видел:
//
//  1. САМООЦЕНКА МОДЕЛИ. У уловок в речи, у гипотез о мотивах, у
//     сценариев прогноза и у распознавания запроса число (или слово)
//     приходит от самой модели: в промпте у неё прямо спрашивают
//     «confidence — 0..1, честная оценка уверенности». Это её слова о
//     себе, и проверить их продукту нечем. Показанные без источника, они
//     читаются как заключение продукта о надёжности вывода.
//  2. ФОРМУЛА ОТ СЧЁТЧИКА. У предупреждения о прощупывании
//     `confidence = min(0.85, 0.3 + (repeatCount − 1) · 0.2)` — то есть
//     линейная функция числа упоминаний, которое человеку показано в той
//     же строке. «Упомянуто 3 раза, уверенность 70%» — это один и тот же
//     факт дважды, второй раз в виде процента, которого никто не мерил.
//     И это утверждение О ПОВЕДЕНИИ ЧЕЛОВЕКА — ровно там, где продукт
//     запрещает себе оценки людей.
//
// ЧИСЛО НЕ УБРАНО, и это не осторожность. ТЗ прямо требует показывать
// его явно, «не скрывать за уверенной формулировкой», и правильно: тихо
// спрятать число — тоже способ соврать о надёжности. Убрана ложная
// точность и добавлено происхождение — то, чего человеку не хватало,
// чтобы понять, чему он верит.
//
// ТОЧНОСТЬ ЧЕСТНАЯ. «87%» выглядит измерением до процента. У формулы
// прощупывания всего четыре возможных значения (0.3 / 0.5 / 0.7 / 0.85),
// у самооценки модели воспроизводимости нет вовсе. Поэтому число
// округляется до десятков: не потому что так красивее, а потому что
// разряд единиц здесь ничего не означает.

/** Откуда взялось число. Разные источники — разная цена доверия, и
 * человек имеет право видеть, какая именно. */
export type ConfidenceSource = 'model-self' | 'repeat-formula';

/** До десятков: разряд единиц у этих чисел не значит ничего. */
export function roundedPercent(value: number): number {
  return Math.round(Math.max(0, Math.min(1, value)) * 10) * 10;
}

/** Подпись к числу — с происхождением. Пустая, если числа нет: писать
 * «уверенность неизвестна» там, где модель просто не вернула поле, —
 * значит сообщать о несуществующем измерении. */
export function confidenceWording(value: number | null | undefined, source: ConfidenceSource): string | null {
  if (value === null || value === undefined || Number.isNaN(value)) return null;
  const percent = roundedPercent(value);
  return source === 'model-self'
    ? `уверенность около ${percent}% — это оценка самой модели, продукт её не проверял`
    : `отметка около ${percent}% — она считается из числа упоминаний, это не измерение`;
}

/** Словесная шкала (низкая/средняя/высокая) — тоже самооценка модели, и
 * без источника читается как заключение продукта. */
export function levelWording(level: 'LOW' | 'MEDIUM' | 'HIGH' | string): string {
  const label =
    level === 'LOW' ? 'низкая уверенность' : level === 'MEDIUM' ? 'средняя уверенность' : level === 'HIGH' ? 'высокая уверенность' : level;
  return `${label} — по оценке самой модели`;
}
