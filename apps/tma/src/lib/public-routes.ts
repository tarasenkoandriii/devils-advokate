/** Буквальные страницы, которые ПОДОШЛИ БЫ под шаблон с параметром, но
 * публичными не являются.
 *
 * Next.js отдаёт статическому сегменту приоритет над динамическим, и
 * `/venues/apply` открывает форму подачи заявки — авторизованную. Первая
 * версия `isPublicRoute` этого не знала и признала её публичной: шлюз
 * открыл бы страницу, которая без Telegram всё равно не работает, и
 * человек увидел бы сломанную форму вместо честного «войдите». Поймано
 * собственной проверкой приватных маршрутов.
 *
 * Список проверяется тестом против настоящих страниц приложения: новая
 * буквальная страница под публичным шаблоном не может появиться молча. */
export const NOT_PUBLIC_LITERALS: readonly string[] = ['/venues/apply'];

/** Публичен ли путь.
 *
 * Сравнение посегментное: `[param]` в шаблоне совпадает с любым одним
 * непустым сегментом. Не `startsWith` — иначе `/library-admin` сошёл бы
 * за `/library`, и шлюз открыл бы то, чего не открывал. Буквальные
 * страницы из `NOT_PUBLIC_LITERALS` проверяются ПЕРВЫМИ, как и в самом
 * Next.js. */
export function isPublicRoute(pathname: string): boolean {
  const path = pathname.split('?')[0].replace(/\/+$/, '') || '/';
  if (NOT_PUBLIC_LITERALS.includes(path)) return false;
  const parts = path.split('/').filter(Boolean);
  return PUBLIC_ROUTES.some(({ route }) => {
    const pattern = route.split('/').filter(Boolean);
    if (pattern.length !== parts.length) return false;
    return pattern.every((seg, i) => (seg.startsWith('[') ? parts[i].length > 0 : seg === parts[i]));
  });
}
