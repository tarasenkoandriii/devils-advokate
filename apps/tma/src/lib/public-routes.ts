// где всё решается.
//
// КОГО ЭТО КАСАЕТСЯ. Не пользователей приложения — у них Telegram есть.
// Касается тех, у кого его нет и не должно быть: приглашённого в
// обсуждение по ссылке, кандидата, отвечающего на анкету и ОТЗЫВАЮЩЕГО
// согласие, коллеги, читающего черновик вакансии. Пункт
// [right-lived-in-the-tab] построил для них уведомления о правах на
// экране, который у них не открывался.
//
// МЕРА. Маршрутов TMA — 23. Страниц, чьи ДАННЫЕ приходят публичным
// клиентом, — семь (в `TODO.md` было названо три). Остальные шестнадцать
// работают с данными человека и обязаны оставаться за шлюзом: дисклеймер
// проверяется в layout'е именно потому, что прямой заход на под-страницу
// по закладке обходил проверку на главной.
//
// ГРАНИЦА. Публичным считается маршрут, чьи данные приходят
// `lib/public-api`. `/venues/[id]` в списке, хотя умеет и подтверждение
// брони: подтверждение — авторизованное действие, и страница сама
// прячет его через `isTelegramWebAppAvailable()`. Смотреть заведение
// можно без аккаунта, подтверждать бронь — нет, и это разные вопросы.
//
// ЧЕГО ЗДЕСЬ НЕТ. Дисклеймер публичным страницам не показывается. Он —
// условие пользования приложением, а пришедший по ссылке приложением не
// пользуется: он читает то, на что ему дали ссылку. Требовать от него
// согласия с условиями продукта, которым он не пользуется, значило бы
// ставить условие вместо права — тот же довод, которым публичные
// маршруты обошлись без Telegram-аутентификации на сервере.

