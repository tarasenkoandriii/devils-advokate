// по дороге.
//
// Прошлые заходы закрывали потери ОТВЕТА МОДЕЛИ. Здесь теряется другое —
// СЛОВА САМОГО ЧЕЛОВЕКА, а это в продукте, обещающем «только из ваших
// слов», дефект другого веса:
//
//  • пакет отклика резал список вопросов до восьми — молча, и не в одном
//    месте, а в двух подряд: сначала экран, потом сервер. Человек
//    вписывал двенадцать, получал ответы на восемь и отправлял пакет
//    работодателю, считая, что в нём все двенадцать;
//  • разбор письма с вакансиями отбрасывал строку, которую не удалось
//    прочитать как ссылку, и не считал её. Частый случай — строка
//    записана наоборот («Название — https://…»): тогда «ссылкой»
//    оказывается название, проверка его отвергает, и строка исчезает.
//    Человек вставил десять строк, увидел семь кандидатов и прочитал это
//    как «в письме было семь».
//
// ПОЧЕМУ РАЗБОР ЖИВЁТ ЗДЕСЬ, А НЕ В ОБРАБОТЧИКЕ. Пункт [render-guards]
// показал, чего стоит код внутри `onSubmit={async (v) => { … }}`: его
// нельзя вызвать из теста, поэтому любой инвариант о том, что уходит на
// сервер, держится чтением исходника — а такая проверка подтверждает
// наличие слова, не поведение. Мутация «вызвать помощника и выбросить
// результат» проходила её насквозь. Чистая функция вызывается и
// проверяется по-настоящему.

import { endOfLocalDay } from './date-only';

/** Многострочное поле → список непустых строк, без обрезки по потолку.
 *
 * Потолок НАМЕРЕННО не применяется здесь: резать в двух местах — способ
 * однажды получить два разных потолка и не заметить. Режет сервер, он же
 * сообщает, сколько не поместилось. */
export function splitLines(text: string): string[] {
  return text
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

/** Поле `<input type="date">` → момент, который уйдёт на сервер.
 *
 * Долг, названный пунктом [render-guards]: два экрана собирают payload
 * прямо в обработчике, и мутация «вызвать `endOfLocalDay` и выбросить
 * результат» проходила проверку по исходнику насквозь — то есть дефект
 * [date-only] мог вернуться целиком, а тест бы этого не заметил. Вынесено
 * сюда именно поэтому: одна строчка, которую можно ВЫЗВАТЬ.
 *
 * Пустое поле даёт `undefined`, а не момент: «срок не указан» и «срок
 * такой-то» — разные утверждения. */
export function dueMoment(dateOnly: string | null | undefined): string | undefined {
  const value = (dateOnly ?? '').trim();
  return value ? endOfLocalDay(value) : undefined;
}

export type LinkLine = { url: string; title: string | null };

/** Строки письма → ссылки на вакансии, и ОТДЕЛЬНО те, что прочитать не
 * удалось.
 *
 * Формат строки: `https://… — Название`. Разделитель — длинное тире с
 * пробелами, как написано в подсказке к полю.
 *
 * Нечитаемая строка возвращается человеку ЦЕЛИКОМ, а не числом: в
 * отличие от выдуманной моделью цитаты, это его собственный текст —
 * показать его безопасно и полезно, он сразу увидит опечатку или
 * перевёрнутую строку. Там, где текст принадлежит человеку, число было
 * бы менее честным, а не более. */
export function parseLinkLines(text: string): { links: LinkLine[]; unreadable: string[] } {
  const links: LinkLine[] = [];
  const unreadable: string[] = [];
  for (const line of splitLines(text)) {
    const [head, ...rest] = line.split(' — ');
    const url = head.trim();
    // Проверка ровно та же, что применит сервер: адрес должен быть
    // http(s)-ссылкой. Иначе строка молча пропала бы уже там.
    if (!/^https?:\/\/\S+$/i.test(url)) {
      unreadable.push(line);
      continue;
    }
    const title = rest.join(' — ').trim();
    links.push({ url, title: title || null });
  }
  return { links, unreadable };
}

/** Подпись под списком, если часть строк прочитать не удалось. Пустая
 * строка, когда всё разобрано: сообщение «не прочитано: 0» приучает не
 * читать сообщения. */
export function unreadableLinesNote(unreadable: string[]): string {
  if (unreadable.length === 0) return '';
  const one = unreadable.length === 1;
  return `${one ? 'Одну строку' : `${unreadable.length} строк(и)`} не удалось прочитать как ссылку, ${one ? 'она' : 'они'} не добавлен${one ? 'а' : 'ы'}: ${unreadable
    .map((l) => `«${l.slice(0, 80)}»`)
    .join(', ')}. Ссылка идёт первой, название — после « — ».`;
}
