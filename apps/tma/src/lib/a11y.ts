// Пункт [announce-failures] 2026-09-04 — клавиатура для элементов,
// которые ведут себя как кнопки, но кнопками не являются.
//
// В четырёх местах TMA обработчик клика висел на `<div>` или `<span>`:
// раскрыть сводку открытых вопросов, раскрыть строку разговора, начать
// правку защищённой заметки. Мышью это работает, а с клавиатуры до
// действия не добраться вообще — такой элемент не получает фокус и не
// реагирует на Enter. Для человека, который не пользуется мышью (а в
// Telegram это и внешняя клавиатура, и экранный диктор), функции просто
// нет: она есть на экране и недоступна.
//
// Почему не переписать всё в `<button>`: три из четырёх — контейнеры со
// своей вёрсткой (строка со статусом, сводка со счётчиками), и кнопка
// принесла бы с собой чужие отступы, шрифт и поведение переноса. Роль
// плюс фокусируемость плюс обработка клавиш дают ровно ту же
// доступность, ничего не меняя визуально; это стандартная замена, а не
// обходной путь.

import { KeyboardEvent } from 'react';

/** Enter и Пробел — те же две клавиши, которыми срабатывает настоящая
 * кнопка. Пробел гасится намеренно: иначе страница прокрутится вместе с
 * нажатием, и человек потеряет место, откуда действовал. */
export function activateOnKey(action: () => void) {
  return (event: KeyboardEvent<HTMLElement>) => {
    if (event.key !== 'Enter' && event.key !== ' ') return;
    event.preventDefault();
    action();
  };
}

// Пункт [render-guards] 2026-09-04 — почему одной `activateOnKey` мало.
//
// Проверка «у кликабельного div есть role, tabIndex и onKeyDown» читала
// ИСХОДНИК регуляркой и подтверждала наличие трёх слов в теге. Две
// мутации прошли её насквозь:
//   • `tabIndex={0}` → `tabIndex={-1}` — атрибут на месте, элемент выпал
//     из обхода табом, то есть до действия по-прежнему не добраться;
//   • `activateOnKey(() => setExpanded(…))` → `activateOnKey(() => undefined)`
//     — клавиша обрабатывается и не делает ничего.
// Разрозненные атрибуты иначе как текстом не проверить. Собранные в один
// набор — можно ВЫЗВАТЬ: тест берёт `activatable(...)`, читает значения и
// дёргает обработчик поддельным событием, убеждаясь, что действие
// выполнено. Это и есть разница между «слово в файле» и «работает».

/** Полный набор свойств для элемента, который ведёт себя как кнопка.
 *
 * Три свойства нельзя настроить по отдельности и наполовину: роль без
 * фокусируемости — подпись без доступа, фокусируемость без обработчика —
 * фокус, из которого ничего не запускается. */
export function activatable(action: () => void) {
  return {
    role: 'button' as const,
    tabIndex: 0,
    onClick: action,
    onKeyDown: activateOnKey(action),
  };
}
