// Пункт [dropped-quotes] 2026-09-04 — подпись под списком, из которого
// что-то выбросили.
//
// Сервер отдаёт `skippedWithoutQuote` — сколько находок модели отброшено
// потому, что их цитаты нет в исходном тексте. Формулировка живёт здесь,
// а не в API: это текст интерфейса, и он обязан быть одинаковым на всех
// экранах, иначе одно и то же событие человек прочитает четырьмя разными
// способами.
//
// ЗАЧЕМ ЭТО ВООБЩЕ. Под пустым списком экраны пишут утвердительно:
// «Compliance-флагов нет», «Расхождений не найдено», «Новых критериев в
// ваших словах не нашлось». Если модель что-то нашла, но процитировала
// неточно, находка не сохраняется — и правильно, показывать
// неподтверждённое нельзя, — но человек читал это как «проверено, чисто».
// Подпись превращает утверждение в то, чем оно является: список неполон.
//
// ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: самого текста отброшенной находки. Он
// опирается на цитату, которой в источнике нет, то есть на выдумку;
// показать его — значит показать человеку утверждение о нём (или о
// компании), ничем не подкреплённое. Число честнее.

/** Подпись под списком, если что-то отброшено; пустая строка, если нет.
 *
 * Ноль намеренно даёт пустую строку: строка «отброшено: 0» — это шум,
 * который приучает её не читать. */
export function skippedWithoutQuoteNote(skipped: unknown): string {
  const n = typeof skipped === 'number' && Number.isFinite(skipped) ? Math.trunc(skipped) : 0;
  if (n <= 0) return '';
  // Русские числительные: 21 находка, 22 находки, 25 находок, но 11–14 —
  // всегда «находок». Наивное `n < 5` даёт «11 находки» — мелочь, из-за
  // которой строку перестают читать как написанную для человека.
  const tens = n % 100;
  const ones = n % 10;
  const one = ones === 1 && tens !== 11;
  const few = ones >= 2 && ones <= 4 && (tens < 12 || tens > 14);
  const found = one ? 'находка' : few ? 'находки' : 'находок';
  const verb = one ? 'отброшена' : 'отброшено';
  const quote = one ? 'её цитаты' : 'их цитат';
  return `Ещё ${n} ${found} модели ${verb}: ${quote} нет в исходном тексте. Показывать неподтверждённое нельзя, но список из-за этого неполон.`;
}

// ── Пункт [draft-outcome] 2026-09-04 ──
//
// Черновики пунктов листа и позиций по ним теряются не по одной причине,
// а по четырём, и причины значат для человека РАЗНОЕ:
//   • опоры на его текст нет — модель предложила то, чего он не говорил;
//   • ссылка на пункт, которого в листе нет — модель придумала пункт;
//   • ответ не той формы — сбой разбора, к человеку отношения не имеющий;
//   • упёрлись в потолок 40 — единственная причина, где ему есть что
//     сделать: разбить текст на части.
// Свести их в одно число значило бы сказать «что-то потерялось» вместо
// «вот что и вот почему» — и отнять у него единственное действие, которое
// он мог бы предпринять.
//
// ДУБЛЬ НЕ СЧИТАЕТСЯ ПОТЕРЕЙ и в подпись не попадает: вторая позиция по
// тому же пункту отброшена, но первая сохранена — о пункте человек узнал.
// Приписать её к потерям было бы преувеличением, то есть той же неправдой,
// что и молчание, только в другую сторону.

export type DraftSkips = {
  withoutQuote?: number;
  unknownClause?: number;
  malformed?: number;
  duplicateClause?: number;
  overLimit?: number;
};

function n(v: unknown): number {
  return typeof v === 'number' && Number.isFinite(v) && v > 0 ? Math.trunc(v) : 0;
}

/** Подпись под списком черновиков: что не разобрано и почему.
 * Пустая строка, если всё предложенное моделью сохранено. */
export function draftSkipsNote(skips: DraftSkips | null | undefined): string {
  if (!skips || typeof skips !== 'object') return '';
  const parts: string[] = [];
  const withoutQuote = n(skips.withoutQuote);
  const unknownClause = n(skips.unknownClause);
  const malformed = n(skips.malformed);
  const overLimit = n(skips.overLimit);

  if (withoutQuote) parts.push(`${withoutQuote} — без опоры на ваш текст`);
  if (unknownClause) parts.push(`${unknownClause} — со ссылкой на пункт, которого в листе нет`);
  if (malformed) parts.push(`${malformed} — с неразборчивым ответом модели`);
  if (overLimit) parts.push(`${overLimit} — не поместилось в предел 40 пунктов за раз`);
  if (parts.length === 0) return '';

  const total = withoutQuote + unknownClause + malformed + overLimit;
  const tens = total % 100;
  const ones = total % 10;
  const one = ones === 1 && tens !== 11;
  const few = ones >= 2 && ones <= 4 && (tens < 12 || tens > 14);
  const word = one ? 'черновик' : few ? 'черновика' : 'черновиков';
  const verb = one ? 'не сохранён' : 'не сохранено';
  const tail = overLimit ? ' Разбейте текст на части, чтобы разобрать остальное.' : '';
  return `Ещё ${total} ${word} ${verb}: ${parts.join('; ')}.${tail}`;
}

/** Как называется поток разбора там, где их в одном ответе несколько.
 *
 * Держать их порознь, а не складывать, — решение по смыслу: «требование
 * не извлеклось из задания» оставляет неполным чеклист, а «позиция не
 * извлеклась из ответа» оставляет пункт без вывода. Для человека, который
 * читает ответ кандидата, это разные пробелы. */
const STREAM_LABEL: Record<string, string> = {
  assignment: 'В тексте задания',
  answer: 'В ответе',
  clauses: 'Условия оффера',
  positions: 'Позиции по условиям',
};

/** Ответ сервера может нести один набор потерь или несколько именованных
 * (разбор задания и разбор ответа, условия оффера и позиции по ним).
 * Возвращает готовые строки — по одной на поток, пустых нет. */
export function draftSkipsNotes(input: unknown): string[] {
  if (!input || typeof input !== 'object') return [];
  const record = input as Record<string, unknown>;
  const nested = Object.entries(record).filter(([, v]) => v && typeof v === 'object');
  if (nested.length > 0) {
    return nested
      .map(([key, value]) => {
        const note = draftSkipsNote(value as DraftSkips);
        if (!note) return '';
        return `${STREAM_LABEL[key] ?? key}: ${note.charAt(0).toLowerCase()}${note.slice(1)}`;
      })
      .filter(Boolean);
  }
  const single = draftSkipsNote(record as DraftSkips);
  return single ? [single] : [];
}

// ── Пункт [input-truncated] 2026-09-05 ──
//
// Все подписи выше — о том, что потерялось ПОСЛЕ разбора. Эта — о том,
// что до разбора не дошло: текст источника режется потолком одного
// запроса, и об этом не говорилось нигде.
//
// ФОРМУЛИРОВКА ЖИВЁТ ЗДЕСЬ, а не в API, по тому же уговору, что и
// остальные: сервер отдаёт ЧИСЛА (сколько знаков вошло из скольких),
// экран решает, как о них сказать.

export type SourceIntake = { used?: number; total?: number; limit?: number };

function readIntake(input: unknown): { used: number; total: number } | null {
  if (!input || typeof input !== 'object') return null;
  const { used, total } = input as SourceIntake;
  if (typeof used !== 'number' || typeof total !== 'number') return null;
  if (!Number.isFinite(used) || !Number.isFinite(total)) return null;
  // Не урезано — говорить не о чем. Подпись «прочитано 100%» приучает
  // не читать подписи, и тогда пропадёт та единственная, что нужна.
  if (total <= used) return null;
  return { used, total };
}

/** Подпись «разобран не весь текст». Пустая строка, если текст вошёл
 * целиком. `what` — что именно разбиралось, словами экрана. */
export function intakeNote(input: unknown, what = 'текст'): string {
  const intake = readIntake(input);
  if (!intake) return '';
  const percent = Math.max(1, Math.round((intake.used / intake.total) * 100));
  return (
    `Разобран не весь ${what}: прочитаны первые ${intake.used} знаков из ${intake.total} (${percent}%). ` +
    'О том, что дальше, продукт не сказал ничего — ни что там что-то есть, ни что там пусто. ' +
    'Разбейте текст на части и повторите разбор.'
  );
}

/** Подпись «сохранён не весь текст» — событие тяжелее предыдущего:
 * разбор можно повторить, а хвост документа в базу уже не попал. */
export function storedIntakeNote(input: unknown, what = 'текст'): string {
  const intake = readIntake(input);
  if (!intake) return '';
  return (
    `Сохранён не весь ${what}: записаны первые ${intake.used} знаков из ${intake.total}. ` +
    'Остальное не сохранилось — повторный разбор его не найдёт. Сохраните хвост документа отдельно.'
  );
}

// ── Пункт [not-checked-looks-clean] 2026-09-06 ──
//
// Подписи выше — о том, что потерялось при разборе и что до разбора не
// дошло. Эта — о случае крупнее обоих: РАЗБОРА НЕ БЫЛО ВОВСЕ. Механизм не
// настроен или провайдер не ответил — и тогда ноль находок не значит
// ничего, а экран под ним писал утвердительно: «Compliance-флагов нет».
//
// ПОЧЕМУ ФРАЗА ЗДЕСЬ, А ПРИЗНАК НА СЕРВЕРЕ — по тому же уговору, что и у
// остальных подписей: сервер отдаёт, ПОЧЕМУ не проверено, экран решает,
// КАК об этом сказать. Формулировка уже была найдена однажды — на экране
// пула, где не грузятся флаги: «Это НЕ значит, что спорных формулировок
// нет — проверка не выполнена». Здесь она же, и намеренно теми же словами.

export type NotCheckedReason = 'not-configured' | 'provider-failed';

/** Подпись «проверка не выполнялась». Пустая строка, если выполнялась —
 * тогда нулю можно верить, и говорить не о чем.
 *
 * `what` — что именно не проверено, словами экрана (родительный падеж:
 * «дебриф», «текст вакансии»). */
export function notCheckedNote(reason: unknown, what: string): string {
  if (reason !== 'not-configured' && reason !== 'provider-failed') return '';
  const why =
    reason === 'not-configured'
      ? 'проверка не настроена у этого проекта'
      : 'провайдер не ответил или вернул неразборчивое';
  return `Внимание: ${what} не проверен — ${why}. Пустой список НЕ значит «чисто»: никто не смотрел. Повторите позже или настройте проверку.`;
}

// ── Пункт [job-died-quietly] 2026-09-06 ──
//
// Паралингвистический проход — ОТДЕЛЬНАЯ фоновая задача поверх готовой
// расшифровки, и её провал записывался только в лог сервера. Экран же
// показывал блок «Подача (паралингвистика)» лишь при `signals.length >
// 0`: при провале не появлялось НИЧЕГО. Человек, включивший галочку
// «паузы, темп, несовпадение слов и интонации», не видел отметок и
// заключал, что их нет.
//
// Две подписи, а не одна: «разбор не выполнился» и «разбор выполнился,
// но часть находок отброшена» значат для человека разное — первое
// повторяют, второе нет.

/** Подписи об исходе паралингвистического прохода. Пустой массив —
 * проход прошёл целиком, говорить не о чем.
 *
 * `enabled` обязателен: у разговора без галочки отсутствие отметок
 * означает ровно то, чем выглядит, и подпись была бы шумом. */
export function paralinguisticsNotes(
  enabled: unknown,
  error: unknown,
  skipped: unknown,
): string[] {
  if (enabled !== true) return [];
  const notes: string[] = [];
  if (typeof error === 'string' && error.trim()) {
    notes.push(
      `Разбор подачи не выполнился: ${error.trim()}. Отсутствие отметок ниже НЕ значит, что в разговоре ничего не было — их не искали. Запустите разбор заново.`,
    );
  }
  const n = typeof skipped === 'number' && Number.isFinite(skipped) ? Math.trunc(skipped) : 0;
  if (n > 0) {
    const tens = n % 100;
    const ones = n % 10;
    const one = ones === 1 && tens !== 11;
    const few = ones >= 2 && ones <= 4 && (tens < 12 || tens > 14);
    const word = one ? 'отметка' : few ? 'отметки' : 'отметок';
    const verb = one ? 'отброшена' : 'отброшено';
    notes.push(
      `Ещё ${n} ${word} подачи ${verb}: модель сослалась на реплики, которых в расшифровке нет. Показывать их нельзя — привязать не к чему, — но список из-за этого неполон.`,
    );
  }
  return notes;
}
