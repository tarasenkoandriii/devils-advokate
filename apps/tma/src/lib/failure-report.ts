// Пункт [one-buzz-was-the-whole-answer] 2026-09-24 — отказ сообщался
// одной вибрацией.
//
// НАЙДЕННОЕ. В тридцати местах экранов единственным следом неудачи было
// `haptic('error')`. Человек нажимает кнопку, чувствует короткую
// вибрацию — и не узнаёт НИЧЕГО: ни что не получилось, ни почему.
//
// Это хуже молчания в трёх отношениях.
//
//  1. Сервер пишет отказы человеческими словами: «вы уже отмечались
//     сегодня», «превышен суточный лимит», «нужны оба согласия». Все
//     они превращались в один и тот же толчок.
//  2. Вибрация неразличима: успех, предупреждение и отказ отличаются
//     рисунком, которого человек не помнит и не обязан помнить, а на
//     части устройств вибрация выключена вовсе — тогда следа нет
//     никакого.
//  3. Хуже всего на экранах СОГЛАСИЙ. Человек нажимает «согласен»,
//     запрос падает, он чувствует толчок — и уходит, не зная,
//     записано согласие или нет. Вся механика согласий в продукте
//     держится на том, что состояние известно.
//
// Урок был назван раньше: пункт [false-success] и сверка
// [self-reported-money] прямо записали — «сбой сообщался ОДНОЙ
// вибрацией: человек нажал и не узнал ничего, в том числе отказа». И
// применён он был к ОДНОМУ обработчику.
//
// ПОЧЕМУ ОДИН МЕХАНИЗМ, А НЕ ТРИДЦАТЬ ПОЛЕЙ СОСТОЯНИЯ. Тридцать копий
// одной проверки — способ разъехаться, и этот проект уже дважды платил
// за такие копии. Здесь одна точка: сообщение уходит наверх и
// показывается общим объявлением, а место вызова пишет ровно одно —
// что именно не получилось.

import { haptic } from './telegram';

export interface Failure {
  /** Что не получилось — словами, от лица продукта. */
  action: string;
  /** Что сказал сервер, если сказал: его отказы написаны для человека. */
  reason: string | null;
  /** Чтобы два одинаковых отказа подряд были видны как два. */
  at: number;
}

type Listener = (failure: Failure) => void;

const listeners = new Set<Listener>();

export function subscribeFailures(listener: Listener): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Единственный способ сообщить о неудаче действия.
 *
 * `action` — что не получилось («Не удалось добавить участника»).
 * Причина берётся из ошибки, если она есть: текст отказа сервера
 * написан для человека и полезнее любой нашей формулировки. Вибрация
 * остаётся — она быстрая и уместная, — но теперь она не единственное,
 * что человек получает. */
export function reportFailure(error: unknown, action: string): void {
  haptic('error');
  const reason = error instanceof Error && error.message.trim() ? error.message.trim() : null;
  const failure: Failure = { action, reason, at: Date.now() };
  for (const listener of listeners) listener(failure);
}
