// Сверка чтений без потолка 2026-09-04 — подпись под списком, который
// показан не целиком.
//
// В проекте нашлось 318 чтений без потолка и 19 с потолком, и ни одного
// места, где человеку сказано, что список обрезан. Это тот же дефект, что
// закрывал заход [silent-failure-sweep], только про объём: экран без
// ошибки и без подписи читается как «здесь всё». Модератор решает, что
// рассмотрел все заявки; участник обсуждения — что прочитал все
// комментарии.
//
// Формулировка говорит две вещи и ни одной лишней: сколько показано и что
// показаны САМЫЕ НОВЫЕ (все такие списки отсортированы по убыванию даты —
// иначе подпись врала бы). Про «загрузить ещё» здесь не говорится: такой
// кнопки нет, и обещать её было бы хуже, чем честно назвать границу.

interface TruncatedListNoticeProps {
  /** Показывать ли подпись — прямо `hasMore` из ответа сервера. */
  hasMore: boolean;
  /** Потолок, который применил сервер, — число приходит оттуда же, а не
   * зашито здесь: разойтись они не должны. */
  limit: number;
  /** Что именно в списке, в родительном падеже: «заявок», «комментариев». */
  what: string;
  /** Где их больше. По умолчанию «в проекте» — так было у всех первых
   * мест. Пункт [right-with-no-door] 2026-09-25: решения о человеке
   * лежат не в проекте, а в журнале, и подпись обязана называть то
   * место, которое есть на самом деле, иначе она врёт в мелочи там, где
   * заведена ради точности. */
  where?: string;
}

export function TruncatedListNotice({ hasMore, limit, what, where = 'в проекте' }: TruncatedListNoticeProps) {
  if (!hasMore) return null;
  return (
    <p className="conversations-section__hint" role="note">
      Показаны {limit} самых новых {what} — {where} их больше. Этот список неполный.
    </p>
  );
}
