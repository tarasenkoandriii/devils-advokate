'use client';

// Пункт [right-lived-in-the-tab] 2026-09-25 — право забрать написанное
// названо кнопкой, а его срок не назван нигде.
//
// НАЙДЕННОЕ. Пришедший по публичной ссылке может забрать свою заявку и
// удалить свой комментарий — это право ему дали Пункты [public-name] и
// [badge-was-the-key]. Удостоверение при этом живёт ТОЛЬКО в памяти
// вкладки и намеренно не кладётся в `localStorage`: человек не заводил
// аккаунта, и оставлять его ключ на чужом устройстве продукт не вправе.
// Решение верное — а вот СКАЗАНО о нём не было ничего. На экране стояла
// кнопка «Забрать свою заявку» и больше ни слова; закрыв вкладку,
// человек терял возможность забрать написанное навсегда и узнавал об
// этом, только вернувшись и не найдя кнопки.
//
// Продукт уже знает эту форму дефекта: «механизм есть, доступа к нему
// нет». Здесь механизм есть, доступ есть, а СРОК не назван — и человек
// достраивает его в свою пользу, как достраивает любое молчание.
//
// Вторая половина того же: когда автор принимает заявку, кнопка просто
// исчезает. Сервер на попытку отвечает подробно и честно, но до сервера
// дело не доходит — кнопки уже нет. Пропавшая кнопка без объяснения
// читается как поломка или как «у меня отняли право».

interface Props {
  /** Есть ли у вкладки удостоверение участника прямо сейчас. */
  hasBadge: boolean;
}

/** Строка о сроке права — показывается там же, где человек пишет. */
export function ParticipantRightsNote({ hasBadge }: Props) {
  if (!hasBadge) {
    return (
      <p className="public-discussion-page__rights" role="note">
        Забрать написанное можно только из той вкладки, где вы присоединились: аккаунта у вас нет, и удостоверение
        участника мы не сохраняем на устройстве — чужой человек за тем же компьютером не должен получить доступ к
        вашим записям. Если вкладка закрылась, напишите тому, кто дал ссылку.
      </p>
    );
  }
  return (
    <p className="public-discussion-page__rights" role="note">
      Своё написанное можно забрать — пока открыта эта вкладка. Удостоверение участника живёт только в ней и на
      устройстве не сохраняется: аккаунта вы не заводили. Закроете вкладку — забрать уже не получится, придётся
      писать тому, кто дал ссылку.
    </p>
  );
}

/** Что показать вместо кнопки, когда забрать уже нельзя. Пропавшая
 * кнопка без слов читается как поломка. */
export function WithdrawUnavailableNote({ status }: { status: 'ACCEPTED' | 'REJECTED' }) {
  if (status === 'ACCEPTED') {
    return (
      <span className="conversations-section__hint">
        Автор принял заявку — она стала аргументом проекта и живёт отдельно; забрать её отсюда уже нельзя. Напишите
        автору, если хотите, чтобы он её убрал.
      </span>
    );
  }
  return (
    <span className="conversations-section__hint">
      Автор отклонил заявку — в проект она не попала. Забирать нечего.
    </span>
  );
}
