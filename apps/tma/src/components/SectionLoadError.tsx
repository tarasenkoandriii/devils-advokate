'use client';

// Аудит 2026-09-03 («сбой не должен выглядеть как пустота») — одна
// строка на все секции, которые до этого при ошибке загрузки просто
// исчезали со страницы.
//
// Почему это отдельный компонент, а не `return null` на месте: у
// продукта есть прямое обещание — конфигурационные и технические
// пробелы не выдаются за отсутствие находок. Секция, которая молча
// не отрисовалась, читается как «здесь ничего нет»: лог конфликта —
// как «динамики не было», открытые вопросы — как «всё закрыто»,
// юридические ориентиры — как «этот домен ничем не регулируется».
// Это ровно та ложь умолчанием, которую в других местах продукта уже
// закрывали прицельно (флаги соответствия в подборе, ошибка загрузки
// разбора). Здесь она закрыта одинаково для всех.
//
// Текст всегда говорит ДВЕ вещи: не удалось загрузить И что из этого
// НЕ следует. Второе важнее первого: пользователь по умолчанию
// достраивает молчание в свою пользу.

// Пункт [announce-failures] 2026-09-04 — здесь `role="status"`, а не
// `alert`, и разница не косметическая: `alert` перебивает то, что человек
// читает сейчас, `status` дожидается паузы. Сбой ЗАГРУЗКИ секции — не
// ответ на только что нажатую кнопку, он случается сам при открытии
// экрана, и перебивать им чтение нечего. Ошибки действия (класс
// `generation-error` вне этого компонента) приходят сразу после нажатия —
// там стоит `alert`.
export function SectionLoadError({ what, hint }: { what: string; hint?: string }) {
  return (
    <p className="generation-error section-load-error" role="status">
      Не удалось загрузить {what}. Это не значит, что {hint ?? 'здесь пусто'} — проверка не выполнена. Обновите
      страницу; если повторяется, дело на нашей стороне.
    </p>
  );
}
