// Пункт [failure-looks-empty] 2026-09-05 — пусто на экране, потому что
// не загрузилось.
//
// НАЙДЕНО. Четыре раздела TMA грузили свой список в `try`, а в `catch`
// ставили пустой список и молчали:
//
//   catch { setSessions([]); }
//   catch { setVenues([]); }
//   catch { setForecasts([]); }
//   catch { setTrackedArguments([]); }
//
// Дальше экран рисует пустое состояние — «мест пока нет», «прогнозов
// нет», а у аргументов блок просто не появляется. Человек читает это как
// ответ продукта о своих данных, хотя ответа не было вовсе.
//
// ПОЧЕМУ ЭТО НЕ ПОЙМАЛА ПРОШЛАЯ СВЕРКА. Пункт [voice-attribution]
// 2026-09-05 закрыл на этом же экране два пустых `catch` и оставил
// правило `!/\.catch\(\(\) => \{\}\)/` — оно знает ОДНУ форму записи.
// `catch { setTrackedArguments([]); }` — третий пустой обработчик на том
// же экране с тем же последствием, и он прошёл мимо правила, потому что
// написан иначе. Правило было, просто оно узнавало сбой в лицо, а не по
// последствию.
//
// ЧЕГО ЗДЕСЬ НЕТ. Автоповтора. Молчаливая перезагрузка по кругу — это
// снова решение продукта за человека, только дороже; кнопка «Повторить»
// стоит там, где перезагрузка дешёвая, а здесь человеку достаточно
// знать, что показанное неполно.

/** Строка под пустым (или отсутствующим) списком, если он пуст из-за
 * сбоя загрузки, а не потому, что данных нет.
 *
 * `what` — что именно не загрузилось, в винительном падеже: «сохранённые
 * прогнозы». `consequence` — что из-за этого не работает; ставится там,
 * где пропажа списка меняет поведение экрана, а не только его вид. */
export function NotLoadedNotice({ what, consequence }: { what: string; consequence?: string }) {
  return (
    // role="status" — человек в этот момент смотрит не сюда: на разговор,
    // на карту, на собеседника. Появление строки должно быть объявлено.
    <p role="status" className="conversations-section__hint">
      Не удалось загрузить: {what}. Пусто — из-за сбоя связи, а не потому, что здесь ничего нет.
      {consequence ? ` ${consequence}` : ''}
    </p>
  );
}
