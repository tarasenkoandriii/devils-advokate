'use client';

// Пункт [translated-adds] 2026-09-06 — что появилось в переводе.
//
// НАЙДЕНО. Обещание продукта здесь одно из самых сильных: «CV
// собирается только из ваших слов». На ПЕРЕФОРМУЛИРОВКЕ его держит
// детерминированный барьер: добавленное число не попадает в базу,
// ответ уходит на повтор. На ПЕРЕВОДЕ того же CV барьера не было
// вовсе — вместо него обратная сверка, где вторая модель сообщает о
// первой, что та дописала. Проверка и самоотчёт — разные вещи, и
// вариант сохранялся независимо от того, что самоотчёт сказал.
//
// Экран печатал одну строку: «Потеряно: … · Добавлено: …», обе
// половины из самоотчёта и обе без различения. Строка, где «ничего»
// стоит рядом с «ничего», читается как «перевод чистый» — то самое
// «пробел выглядит как полнота», вокруг которого построен продукт.
//
// ЧТО ИЗМЕНИЛОСЬ ЗДЕСЬ. Найденное деление: цифры — проверка, остальное
// — слова модели о себе. Одинаково называть их значило бы стереть
// разницу в цене доверия, ровно как в пункте [unmeasured-confidence].

export interface TranslationBackCheck {
  lost?: string[];
  added?: string[];
  addedNumbers?: string[];
}

export function TranslationCheckNote({ backCheck, unverifiable }: { backCheck: TranslationBackCheck | null | undefined; unverifiable?: number }) {
  if (!backCheck) return null;
  const lost = backCheck.lost ?? [];
  const added = backCheck.added ?? [];
  const addedNumbers = backCheck.addedNumbers ?? [];
  const dropped = typeof unverifiable === 'number' && unverifiable > 0 ? unverifiable : 0;

  return (
    <>
      <h4>Обратная сверка перевода</h4>

      {addedNumbers.length > 0 && (
        // Единственная строка здесь, которая является ПРОВЕРКОЙ, а не
        // пересказом. Потому и объявляется вслух, и стоит первой.
        <p className="dtp-status dtp-status--warn" role="status">
          В переводе есть числа, которых нет в вашем тексте: {addedNumbers.join(', ')}. Это проверка, а не мнение модели:
          цифра в резюме — это достижение, и отправлять её как своё, не написав её самому, не стоит.
        </p>
      )}

      <p className="dtp-muted">
        🟡 Ниже — слова самой модели о своём переводе, не проверка продукта.{' '}
        Потеряно: {lost.join('; ') || 'модель ничего не назвала'} · Добавлено: {added.join('; ') || 'модель ничего не назвала'}
      </p>

      {dropped > 0 && (
        <p className="dtp-status dtp-status--warn" role="status">
          Ещё {dropped} пункт(ов) обратной сверки отброшено: названного в них текста нет ни в оригинале, ни в переводе —
          обсуждать выдумку нельзя, но список из-за этого неполон.
        </p>
      )}
    </>
  );
}
