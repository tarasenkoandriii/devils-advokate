// Пункт [the-refusal-was-swallowed-midway] 2026-10-26 — срез называется
// срезом.
//
// ПОВОД. Подбор мест для встречи отдавал СТОЛЬКО заведений, сколько
// удалось, и не говорил, сколько рассматривалось. Список из одного
// заведения выглядел так же, как список из одного заведения, которое
// рядом единственное. Человек, попросивший «подобрать место рядом»,
// получал часть и не знал, что это часть.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ КОМПОНЕНТ, А НЕ СТРОКА НА ЭКРАНЕ. Решение «есть ли
// о чём говорить» должно жить в ОДНОМ месте и проверяться показом, а не
// упоминанием имени в исходнике: мутация, заменившая условие на `false`
// прямо в разделе, прошла мимо сторожа, который искал в коде раздела
// слово `skippedCount`. Теперь условие здесь, и его проверяет тест
// разметкой.
//
// Сосед по смыслу — `NotLoadedNotice` (пусто из-за сбоя загрузки) и
// `AnalysisBasisNote` (разбор не на всех данных). Тот же принцип:
// продукт не молчит там, где молчание читается как «всё в порядке».

interface PartialResultNoticeProps {
  /** Сколько в итоге показано. */
  shown: number;
  /** Сколько рассматривалось — то, чего человек без этой строки не знает. */
  considered: number;
  /** Сколько не дошло. Ноль — говорить не о чем, строки нет. */
  skipped: number;
  /** Что именно подбиралось, в родительном падеже: «найденных рядом». */
  what: string;
}

export function PartialResultNotice({ shown, considered, skipped, what }: PartialResultNoticeProps) {
  // Ноль пропущенных — это ПОЛНЫЙ ответ, и приписка к нему была бы
  // шумом. Решение одно и здесь.
  if (!(skipped > 0)) return null;
  return (
    // role="status" — человек в этот момент смотрит на список, а не
    // сюда; появление строки должно быть объявлено. См. NotLoadedNotice.
    <p role="status" className="conversations-section__hint">
      Показано {shown} из {considered} {what}: по {skipped} данные получить не удалось. Это срез, а не весь
      список — можно вернуться позже и попробовать снова.
    </p>
  );
}
