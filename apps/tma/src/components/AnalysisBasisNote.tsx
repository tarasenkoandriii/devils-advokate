'use client';

// Пункт [partial-basis] 2026-09-04 — на чём построен разбор, который
// человек сейчас читает.
//
// НАЙДЕНО: разборы о человеке строятся на срезе данных (пять последних
// прецедентов, пять самых весомых аргументов), а подаются как разборы на
// всех данных — и модели, и человеку. В промпте это называлось
// «ИЗВЕСТНЫЕ прецеденты поведения», а видно усечение было только в
// комментариях к коду. Тот же изъян, вокруг которого построен весь
// продукт: пробел не должен выглядеть как полнота.
//
// ГРАНИЦА СКАЗАНА ПРЯМО. Это свойство ЭТОГО ответа: в базе основания
// нет — колонки под него не существует ни у одной модели результата, и
// ручную миграцию ради подписи под текстом мы не заводили. Значит,
// открыв сохранённый разбор завтра, человек этой строки не увидит, и
// компонент говорит об этом сам, вместо того чтобы промолчать и дать
// подумать, будто разбор её помнит.
//
// Пустая приписка не рисуется вообще: сообщение об усечении там, где
// усечения не было, — такой же обман, только в другую сторону.

export function AnalysisBasisNote({ note }: { note: string | null | undefined }) {
  if (!note) return null;
  return (
    <p className="analysis-basis-note" role="note">
      {note} Эта пометка относится к только что построенному разбору и не сохраняется вместе с ним.
    </p>
  );
}
