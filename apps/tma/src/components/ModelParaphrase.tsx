'use client';

// Пункт [quotation-marks] 2026-09-05 — парафраз в кавычках с точной
// ссылкой на источник.
//
// НАЙДЕНО. Продукт подбирает человеку «уместную цитату» из религиозного
// первоисточника — и в промпте САМ ЖЕ требует от модели обратного
// цитированию: «quoteText — краткий ПАРАФРАЗ своими словами, НЕ
// дословное цитирование», отдельным полем «quoteSourceReference — точная
// ссылка на источник (книга, глава, стих)». То есть продукт знает, что
// это не цитата.
//
// А показывал он это тремя способами, и все три говорили «цитата»:
//
//   «{quoteText}» — {quoteSourceReference}
//
// Кавычки с атрибуцией — типографский знак дословности; на экране
// разрядки текст стоял под меткой «🔵 Цитата», где 🔵 в этом продукте
// означает ПУБЛИЧНЫЙ ФАКТ, то есть установленное; а на публичной
// странице обсуждения это читают ПОСТОРОННИЕ ЛЮДИ по ссылке — без
// аккаунта, без контекста, без возможности спросить. Человек может
// переслать такое дальше как цитату из Писания с главой и стихом.
//
// ССЫЛКА ОСТАЁТСЯ, и это не компромисс: она полезна — по ней можно
// открыть первоисточник и прочитать, как там на самом деле. Убрано
// другое — вид проверенной точности. Продукт ссылку не проверял и
// проверить не может.

export function ModelParaphrase({ text, source }: { text: string; source?: string | null }) {
  if (!text) return null;
  return (
    <div className="model-paraphrase">
      <span className="model-paraphrase__label">🟡 Пересказ смысла, не дословная цитата</span>
      <p className="model-paraphrase__text">{text}</p>
      {source && (
        <p className="model-paraphrase__source">
          Источник назван моделью: {source}. Продукт эту ссылку не проверял — откройте первоисточник, если
          собираетесь на него ссылаться.
        </p>
      )}
    </div>
  );
}

/** Текст, который целиком написала модель, а человек читает как запись о
 * состоявшемся — протокол, итог. На публичной странице это читают
 * посторонние: они видят «Протокол по итогам» и не знают, что его
 * составила модель по расшифровке. */
export function ModelWrittenNote({ what }: { what: string }) {
  return (
    <p className="model-paraphrase__label">
      🟡 {what} составлен моделью по записи разговора — это пересказ, а не подписанный документ.
    </p>
  );
}
