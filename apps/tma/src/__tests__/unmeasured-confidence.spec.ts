// Сверка 2026-09-05 — проценты уверенности, которых никто не измерял.
//
// НАЙДЕННОЕ. Продукт показывал человеку «уверенность 87%» и «Высокая
// уверенность», и по виду это было измерение продукта. Ни одно из них
// измерением не является, а происхождение у них РАЗНОЕ — и разницы
// человек не видел:
//
//  1. САМООЦЕНКА МОДЕЛИ — уловки в речи, гипотезы о мотивах, сценарии
//     прогноза, распознавание запроса. В промпте у модели прямо
//     спрашивают «confidence — 0..1, честная оценка уверенности»: это её
//     слова о себе, и проверить их продукту нечем.
//  2. ФОРМУЛА ОТ СЧЁТЧИКА — предупреждение о прощупывании:
//     `min(0.85, 0.3 + (repeatCount − 1) · 0.2)`. Процент был линейной
//     функцией числа упоминаний, показанного в той же строке: один факт
//     дважды, второй раз в виде измерения, которого не было. И это
//     утверждение О ПОВЕДЕНИИ ЧЕЛОВЕКА — там, где продукт запрещает себе
//     оценки людей.
//
// ЧИСЛО НЕ УБРАНО. ТЗ прямо требует показывать его явно, «не скрывать за
// уверенной формулировкой», и это верно: тихо спрятать число — тоже
// способ соврать о надёжности. Убрана ложная точность (разряд единиц у
// этих чисел не значит ничего) и добавлено происхождение.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { confidenceWording, levelWording, roundedPercent } from '../lib/confidence';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

/** Комментарии прочь перед разбором КОДА: за эту сессию проверки шесть
 * раз ловили собственный объяснительный текст, а старые формулировки
 * процитированы в комментариях как «было раньше». */
function code(path: string): string {
  return readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Все экраны TMA — правило меряется по дереву, а не по списку файлов:
 * новый экран с сырым процентом должен уронить проверку. */
function screens(): string[] {
  const out: string[] = [];
  (function walk(dir: string) {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === '__tests__') continue;
      const full = join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith('.tsx')) out.push(full);
    }
  })(SRC);
  return out;
}

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: у числа названо происхождение — чья это оценка', () => {
    const self = confidenceWording(0.87, 'model-self');
    assert(/оценка самой модели/.test(self ?? ''), 'не сказано, что число — самооценка модели');
    assert(/продукт её не проверял/.test(self ?? ''), 'не сказано, что проверки этому числу нет');

    const formula = confidenceWording(0.7, 'repeat-formula');
    assert(/из числа упоминаний/.test(formula ?? ''), 'не сказано, что отметка считается из счётчика');
    assert(/это не измерение/.test(formula ?? ''), 'отметка снова подана как измерение');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: самооценка и формула НЕ описываются одинаково', () => {
    // Разные источники — разная цена доверия. Одинаковый текст стирал бы
    // ровно ту разницу, ради которой сверка и затевалась.
    assert(confidenceWording(0.7, 'model-self') !== confidenceWording(0.7, 'repeat-formula'),
      'самооценка модели и формула от счётчика описаны одним текстом');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: ложная точность убрана — округление до десятков', () => {
    // «87%» выглядит измерением до процента. У формулы прощупывания всего
    // четыре возможных значения, у самооценки модели воспроизводимости
    // нет вовсе.
    assert(roundedPercent(0.87) === 90, `0.87 округлилось в ${roundedPercent(0.87)}, а не в 90`);
    assert(roundedPercent(0.3) === 30, 'нижнее значение формулы искажено');
    assert(!/\b8[0-9]%/.test(confidenceWording(0.87, 'model-self') ?? ''), 'в тексте осталась точность до процента');
    // Границы: за пределы 0..1 выходить нельзя, иначе появится «110%».
    assert(roundedPercent(1.4) === 100 && roundedPercent(-2) === 0, 'значение вне 0..1 не обрезано');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: числа НЕТ — и выдумывать его нечем', () => {
    // Модель может не вернуть поле вовсе. «Уверенность неизвестна» —
    // сообщение о несуществующем измерении, поэтому молчание.
    for (const empty of [null, undefined, NaN]) {
      assert(confidenceWording(empty as any, 'model-self') === null, `подпись построена при значении ${String(empty)}`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: словесная шкала тоже названа самооценкой', () => {
    // «Высокая уверенность» без источника читается как заключение
    // ПРОДУКТА о том, насколько надёжна гипотеза о мотивах человека.
    for (const level of ['LOW', 'MEDIUM', 'HIGH']) {
      assert(/по оценке самой модели/.test(levelWording(level)), `${level}: не сказано, чья это оценка`);
    }
    assert(/низкая уверенность/.test(levelWording('LOW')), 'сама степень потерялась — число спрятали вместо того, чтобы объяснить');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: ни один экран не печатает сырой процент уверенности сам', () => {
    // Правило меряется по всему дереву: новый экран с
    // `confidence * 100` должен уронить проверку, а не тихо повторить
    // изъян. Урок [decision-basis] — «правило было, просто не везде».
    const offenders: string[] = [];
    for (const file of screens()) {
      const src = code(file);
      if (/confidence[^\n]*\*\s*100/.test(src)) offenders.push(file.slice(SRC.length + 1));
    }
    assert(offenders.length === 0, `экраны печатают процент уверенности мимо общего текста: ${offenders.join(', ')}`);
  }],

  ['ИЗМЕРЕНИЕ: где именно продукт показывает чужую уверенность', () => {
    // Список зафиксирован, чтобы следующая сверка начинала с факта, а
    // пятый такой экран было видно.
    const users = screens().filter((f) => /confidenceWording\(|levelWording\(/.test(code(f)));
    assert(users.length === 4, `экранов с чужой уверенностью должно быть 4, найдено ${users.length}: ` +
      users.map((f) => f.slice(SRC.length + 1)).join(', '));
  }],
  ['КЛЮЧЕВОЙ ТЕСТ [voice-attribution]: разделение говорящих названо догадкой', () => {
    // Реплики попадают в разбор поведения СОБЕСЕДНИКА по результату
    // сравнения голоса с порогом, который в самом продукте назван
    // неоткалиброванным. Соседний блок на том же экране честно помечен
    // «догадка ИИ» — правило было, просто не везде.
    const src = code(join(SRC, 'components/AssistanceScreen.tsx'));
    assert(/Разделение говорящих — тоже догадка/.test(src), 'разделение говорящих подаётся как факт');
    assert(/не\s+откалиброван/.test(src), 'не сказано, что порог не откалиброван');
    // И сказано, куда попадают нераспознанные реплики: включаются
    // намеренно, и это может быть речь самого человека.
    assert(/часть ваших собственных слов может оказаться/.test(src),
      'не сказано, что свои слова могут попасть в разбор собеседника');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ [voice-attribution]: отказ сверки голоса не молчит', () => {
    // Здесь стоял пустой catch. Если сверка не отвечает вовсе, ни одна
    // реплика не помечается «моя» — весь разговор уходит в разбор как
    // речь собеседника, молча.
    const src = code(join(SRC, 'components/AssistanceScreen.tsx'));
    assert(!/\.catch\(\(\) => \{\}\)/.test(src), 'сбой сверки голоса снова проглатывается пустым catch');
    // ОБА пути отказа, а не «имя встречается в файле»: сверка на каждой
    // реплике и загрузка модели в начале сессии — разные места с
    // одинаковым последствием. Мутация показала, что проверка на
    // упоминание проходит, пока жив хоть один из них.
    assert(/voiceCheckFailuresRef\.current \+= 1;[\s\S]{0,200}setVoiceAttributionFailed\(true\)/.test(src),
      'счётчик отказов сверки больше ничего не включает');
    assert(/getVoiceEnrollmentStatus\(\)[\s\S]{0,600}setVoiceAttributionFailed\(true\)/.test(src),
      'несостоявшаяся загрузка модели голоса снова молчит');
    assert(/реплики не разделяются вовсе/.test(src), 'не сказано, что при отказе разбор идёт по всему разговору');
    // Сообщение об отказе — объявляемое: человек в этот момент смотрит
    // на разговор, а не на экран.
    const notice = src.slice(src.indexOf('Сверка голоса сейчас не отвечает') - 200, src.indexOf('Сверка голоса сейчас не отвечает'));
    assert(/role="status"/.test(notice), 'сообщение об отказе сверки не объявляется вслух');
  }],

];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nunmeasured-confidence: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
