// Сверка 2026-09-06 — правило смотрело туда, где искали, а не туда, где
// может случиться.
//
// ПОЧЕМУ ЭТА СВЕРКА О САМИХ ПРОВЕРКАХ. Три пункта подряд закончились
// одинаково: изъян закрывали там, где на него наткнулись, а правило
// оставалось узким — и тот же изъян в соседнем месте проходил насквозь.
// [landing-promise] читал каталог словарей лендинга и не дотянулся до
// экранов приложения ([device-not-yours]); [voice-attribution] знал одну
// форму записи пустого обработчика и пропустил вторую
// ([failure-looks-empty]); [silent-jurisdiction] закрыл молчание на
// сервере и не заметил второй путь к тому же молчанию на клиенте
// ([domain-not-mapped]). Три раза — это уже не случайность, а свойство
// того, как пишутся правила.
//
// МЕРИЛИ, А НЕ РАССУЖДАЛИ. 257 проверок: 35 ходят по дереву, 17
// перечисляют файлы списком, остальные — юнит-проверки поведения, где
// дерево ни при чём. Каждое подозрительное правило проверено ПРОБОЙ:
// в дерево подкладывался настоящий новый нарушитель и смотрелось,
// упадёт ли правило.
//
// НАЙДЕНО ПРОБАМИ — три слепых правила:
//
//   quotation-marks  — новый экран с «{quoteText}» прошёл насквозь;
//   partial-basis    — новый экран со срезом прошёл насквозь;
//   source-collapse  — новый экран с фактами без происхождения прошёл
//                      насквозь, ХОТЯ комментарий в самой проверке
//                      обещал: «Третье должно уронить эту проверку».
//
// Последнее — худшее из трёх: правило утверждало о себе то, чего не
// делало. Ровно тот изъян, который вся сессия ищет в продукте, только
// найденный в собственных проверках.
//
// ЧЕГО ЭТА СВЕРКА НЕ ДЕЛАЕТ. Не переводит на обход дерева все 17
// списков. Список — верный инструмент там, где изъян может жить только
// в одном месте: у публичной страницы по токену она одна, у экрана
// юридических ориентиров он один. Массовая переделка ради единообразия
// добавила бы шума в проверки, которые сегодня верны.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { screenFiles, codeOf, screensMatching } from './screen-walker';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

function spec(name: string): string {
  return readFileSync(join(__dirname, name), 'utf8');
}

/** Правила, про которые ПРОБОЙ доказано, что список их подводил. Они
 * обязаны ходить по дереву, и сузить их обратно нельзя. */
const MUST_WALK = ['quotation-marks.spec.ts', 'source-collapse.spec.ts', 'partial-basis.spec.ts'];

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: три починенных правила ходят по дереву, а не по списку', () => {
    for (const name of MUST_WALK) {
      assert(/screensMatching\(/.test(spec(name)), `${name}: правило снова смотрит в список, а не в дерево`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: общий обход существует и им пользуются починенные правила', () => {
    // ЗДЕСЬ СТОЯЛО ДРУГОЕ ПРАВИЛО — «обход дерева должен быть один на
    // всех» — и оно сразу нашло четырнадцать проверок со своим
    // `readdirSync`. Но ни одна из них не слепа: каждая ходит по дереву
    // верно, просто фильтрует по-своему. Правило требовало переделать
    // четырнадцать файлов ради единообразия, не исправляя ни одного
    // изъяна, — то есть кричало бы всегда. Такие правила отключают, а
    // вместе с ними перестаёт работать та часть, что ловила настоящее
    // (тот же довод, что в [translated-adds] про разрядные
    // разделители). Правило убрано, а не кодовая база подогнана под
    // него.
    //
    // Остаётся то, что действительно нужно: общий обход есть, и три
    // правила, которые пробой уличены в слепоте, пользуются именно им.
    const walker = readFileSync(join(__dirname, 'screen-walker.ts'), 'utf8');
    assert(/export function screenFiles/.test(walker), 'общий обход дерева пропал');
    assert(/name === '__tests__'/.test(walker), 'обход перестал исключать каталог тестов');
    for (const name of MUST_WALK) {
      assert(/from '\.\/screen-walker'/.test(spec(name)), `${name}: завёл свой обход вместо общего`);
    }
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: обход не ловит сам себя', () => {
    // За эту сессию проверки шесть раз ловили собственный
    // объяснительный текст. Обход исключает каталог тестов, а `codeOf`
    // снимает комментарии.
    const files = screenFiles(SRC);
    assert(files.every((f) => !f.includes('__tests__')), 'обход зашёл в каталог тестов');
    assert(files.length > 40, `экранов подозрительно мало: ${files.length}`);
    const withComment = codeOf(join(SRC, 'components/LaunchDisclaimer.tsx'));
    assert(!/остаются на вашем устройстве/.test(withComment), 'комментарии не снимаются — правило поймает само себя');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: правило по дереву действительно НАХОДИТ, а не возвращает пустоту всегда', () => {
    // Правило, которое никогда ничего не находит, выглядит как зелёное
    // и не проверяет ничего. Поэтому — образец, который заведомо есть.
    const found = screensMatching(SRC, /export function/);
    assert(found.length > 30, `обход почти ничего не нашёл (${found.length}) — вероятно, он холостой`);
    const none = screensMatching(SRC, /такого-текста-в-продукте-нет-\d{9}/);
    assert(none.length === 0, 'обход находит то, чего нет');
  }],

  ['ИЗМЕРЕНИЕ: сколько правил ходит по дереву и сколько смотрит в список', () => {
    // Точка отсчёта. Список сам по себе не изъян — изъян, когда класс
    // шире списка. Число здесь, чтобы следующая сверка начинала с
    // факта, а не с ощущения.
    const specs = readdirSync(__dirname).filter((f) => f.endsWith('.spec.ts'));
    const walkers = specs.filter((f) => /screensMatching\(|screenFiles\(|readdirSync\(/.test(spec(f)));
    assert(walkers.length >= 12, `правил по дереву должно быть не меньше 12, найдено ${walkers.length}`);
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nguard-scope: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
