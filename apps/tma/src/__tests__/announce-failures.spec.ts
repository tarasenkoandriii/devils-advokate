// Сверка доступности 2026-09-04 — «сбой выглядит как пустота», версия
// для человека, который экран не видит.
//
// Продукт уже принял решение и выполнил его для зрячих: аудит 2026-09-03
// («сбой загрузки не должен выглядеть как пустота») завёл `SectionLoadError`
// и заменил им десять мест, где секция при ошибке просто исчезала. Логика
// была та же, что во всём проекте: молчание человек достраивает в свою
// пользу и читает как «здесь ничего нет».
//
// НАЙДЕНО. На весь TMA — НОЛЬ живых областей: ни одного `aria-live`,
// `role="status"` или `role="alert"`, при 121 месте, где показывается
// ошибка. Значит, для человека со скринридером решение 2026-09-03 не
// сработало: текст на экране появляется, но не произносится, и «не
// удалось загрузить» звучит ровно так же, как «нечего показывать», —
// то есть никак. Это тот же дефект продукта, только он не был виден,
// потому что смотрели глазами.
//
// Плюс четыре места, где обработчик клика висел на `<div>`/`<span>`:
// раскрыть сводку открытых вопросов, раскрыть строку разговора, начать
// правку защищённой заметки (дважды). Мышью работает, с клавиатуры до
// действия не добраться вообще: элемент не получает фокус и не реагирует
// на Enter. Функция есть на экране и недоступна.
//
// ЧТО ИСПРАВЛЕНО. 118 мест показа ошибки получили `role="alert"` — это
// ответ на только что сделанное человеком действие, его и надо
// произнести сразу. `SectionLoadError` получил `role="status"`: сбой
// ЗАГРУЗКИ приходит сам при открытии экрана, перебивать им чтение
// нечего. Четыре кликабельных не-кнопки получили роль, фокусируемость и
// обработку Enter/Пробела.
//
// ЧЕСТНАЯ ПОПРАВКА К СОБСТВЕННОМУ ИЗМЕРЕНИЮ. Первый прогон «кнопок без
// доступного имени» дал 77 штук — и это была ошибка measurement'а, а не
// находка: разбор выбрасывал `{...}`-выражения, а подпись у этих кнопок
// живёт именно там (`{sending ? 'Отправляем…' : 'Ответить текстом'}`).
// После починки разбора кнопок без имени НЕ НАШЛОСЬ НИ ОДНОЙ. Записано
// здесь, потому что «нашли 77 проблем» и «сломан разбор» — разные
// утверждения, и первое звучало бы убедительнее второго.
//
// ЧЕГО ЭТОТ ЗАХОД НЕ ДЕЛАЕТ. Не проверяет контрастность, порядок фокуса
// и разметку заголовков: это требует прогона в настоящем браузере с
// настоящим скринридером, чего здесь нет, а имитировать такую проверку
// статикой — значит выдать её отсутствие за наличие.

import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';
import { SectionLoadError } from '../components/SectionLoadError';
import { activatable } from '../lib/a11y';

const SRC = join(__dirname, '..');
const ROOTS = ['components', 'app'].map((d) => join(SRC, d));

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : walk(full);
    return name.endsWith('.tsx') ? [full] : [];
  });
}

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

/** Открывающий тег целиком, от `<` до закрывающего `>`.
 *
 * Считается по глубине фигурных скобок, а не регуляркой: в атрибутах
 * живут стрелочные функции, и `=>` содержит `>`. Первая версия проверки
 * обрывала тег на первой же стрелке и объявляла недоступными как раз те
 * четыре места, которые только что были починены, — ошибка разбора,
 * выданная за находку. Внутри `{...}` любые `>` игнорируются, поэтому
 * первый `>` на нулевой глубине и есть настоящий конец тега. */
function openingTag(source: string, start: number): string {
  let depth = 0;
  for (let i = start; i < source.length; i++) {
    const ch = source[i];
    if (ch === '{') depth++;
    else if (ch === '}') depth--;
    else if (ch === '>' && depth === 0) return source.slice(start, i + 1);
  }
  return source.slice(start);
}

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: каждое место показа ошибки объявляется вслух', () => {
    // Ошибка, которую видно и не слышно, для человека со скринридером
    // не существует — ровно та же «пустота вместо сбоя», которую продукт
    // уже закрывал для зрячих.
    const offenders: string[] = [];
    for (const file of ROOTS.flatMap((r) => walk(r))) {
      const src = readFileSync(file, 'utf8');
      for (const m of src.matchAll(/<p[^>]*className="generation-error[^"]*"[^>]*>/g)) {
        if (!/role=/.test(m[0])) offenders.push(`${file.slice(file.indexOf('/src/') + 1)}: ${m[0].slice(0, 70)}`);
      }
    }
    assert(offenders.length === 0, `эти сообщения об ошибке появятся молча:\n  ${offenders.join('\n  ')}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сбой загрузки секции объявляется вежливо — и текст ВНУТРИ живой области', () => {
    // Пункт [render-guards] 2026-09-04: раньше здесь искали `role="status"`
    // в ИСХОДНИКЕ. Мутация «оставить атрибут, вынести текст в соседний
    // элемент» проходила насквозь: живая область пуста, объявлять
    // нечего, а регулярка довольна. Теперь компонент рисуется.
    const out = renderToStaticMarkup(createElement(SectionLoadError, { what: 'лог конфликта', hint: 'динамики не было' }));
    const live = /<p[^>]*role="status"[^>]*>([\s\S]*?)<\/p>/.exec(out);
    assert(live !== null, `SectionLoadError не объявляет себя вовсе: ${out}`);
    assert(/Не удалось загрузить/.test(live![1]), `текст ошибки оказался вне живой области: ${out}`);
    // Обе половины обещания продукта — что не удалось И что из этого НЕ
    // следует — должны звучать, а не только первая.
    assert(/лог конфликта/.test(live![1]), `не сказано, что именно не загрузилось: ${out}`);
    assert(/динамики не было/.test(live![1]), `не сказано, чего из сбоя НЕ следует: ${out}`);
    // Разница между `alert` и `status` — между «перебить человека» и
    // «дождаться паузы». Сбой загрузки приходит сам, не в ответ на
    // нажатие; перебивать им нечего.
    assert(!/role="alert"/.test(out), `сбой загрузки перебивает чтение: ${out}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: кликабельная строка не просто размечена, а СРАБАТЫВАЕТ с клавиатуры', () => {
    // Две мутации, которые прежняя проверка по исходнику пропускала:
    // `tabIndex={0}` → `tabIndex={-1}` (атрибут на месте, элемент выпал
    // из обхода табом) и `activateOnKey(() => setExpanded(…))` →
    // `activateOnKey(() => undefined)` (клавиша обрабатывается и ничего
    // не делает). Набор свойств собран в `activatable()`, и его можно
    // ВЫЗВАТЬ, а не искать словами.
    let fired = 0;
    const props = activatable(() => { fired += 1; });
    assert(props.role === 'button', `нет роли кнопки: ${props.role}`);
    assert(props.tabIndex === 0, `элемент вне обхода табом: tabIndex=${props.tabIndex}`);

    const press = (key: string) => {
      let prevented = false;
      props.onKeyDown({ key, preventDefault: () => { prevented = true; } } as never);
      return prevented;
    };
    assert(press('Enter') && fired === 1, 'Enter не запускает действие');
    assert(press(' ') && fired === 2, 'Пробел не запускает действие');
    // Пробел гасится: иначе страница прокрутится, и человек потеряет
    // место, откуда действовал.
    assert(press(' ') === true, 'Пробел прокрутит страницу');
    // Посторонняя клавиша не должна запускать ничего — иначе набор
    // текста рядом внезапно «нажимает» строку.
    const before = fired;
    press('a');
    assert(fired === before, 'посторонняя клавиша запустила действие');
    // Клик и клавиатура делают ОДНО И ТО ЖЕ. Раньше это были две разные
    // стрелочные функции рядом, и они умели разъехаться.
    props.onClick();
    assert(fired === before + 1, 'клик и клавиатура делают разное');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: до действия, которое делается кликом, можно добраться с клавиатуры', () => {
    // `onClick` на div/span без роли и фокусируемости — функция, которой
    // для человека без мыши просто нет.
    const offenders: string[] = [];
    for (const file of ROOTS.flatMap((r) => walk(r))) {
      const src = readFileSync(file, 'utf8');
      // Открывающий тег берётся ОКНОМ, а не регуляркой `[^>]*`: внутри
      // атрибутов живут стрелочные функции, и `=>` содержит `>` — первая
      // версия проверки обрывала тег на первой же стрелке и объявляла
      // недоступными как раз те четыре места, которые только что были
      // починены. Ошибка разбора, выданная за находку, — ровно то, чего
      // эти сверки не должны делать.
      for (const m of src.matchAll(/<(div|span|li)\b/g)) {
        const tag = openingTag(src, m.index ?? 0);
        if (!/onClick/.test(tag)) continue;
        if (/role=/.test(tag) && /tabIndex=/.test(tag) && /onKeyDown=/.test(tag)) continue;
        offenders.push(`${file.slice(file.indexOf('/src/') + 1)}: ${tag.replace(/\s+/g, ' ').slice(0, 80)}`);
      }
    }
    assert(
      offenders.length === 0,
      `эти действия недоступны с клавиатуры (нет role/tabIndex/onKeyDown):\n  ${offenders.join('\n  ')}`,
    );
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: клавиатурная активация — Enter и Пробел, и Пробел не прокручивает страницу', () => {
    // Поведение общей функции, а не наличие слова: проверка урока
    // [guard-audit] применена и здесь.
    const src = readFileSync(join(SRC, 'lib', 'a11y.ts'), 'utf8');
    assert(/'Enter'/.test(src) && /' '/.test(src), 'активация не покрывает обе клавиши настоящей кнопки');
    assert(/preventDefault\(\)/.test(src), 'Пробел прокрутит страницу, и человек потеряет место, откуда действовал');
  }],

  ['ИЗМЕРЕНИЕ: сколько живых областей и сколько мест показа ошибки', () => {
    // Было: ноль живых областей при 121 месте показа ошибки. Число живёт
    // здесь, чтобы следующая сверка начинала с факта.
    let live = 0;
    let errors = 0;
    for (const file of ROOTS.flatMap((r) => walk(r))) {
      const src = readFileSync(file, 'utf8');
      live += (src.match(/role="(alert|status)"|aria-live=/g) ?? []).length;
      errors += (src.match(/className="generation-error/g) ?? []).length;
    }
    assert(live >= errors, `живых областей ${live}, мест показа ошибки ${errors} — часть по-прежнему молчит`);
    assert(errors > 50, `мест показа ошибки всего ${errors} — проверка, похоже, смотрит не туда`);
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nannounce-failures: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
