// Сверка ложного успеха 2026-09-04 — экран сказал, что получилось.
//
// Продолжение сверки публичных страниц. Прежние заходы закрывали
// МОЛЧАНИЕ: сбой, о котором не сказано. Здесь нашлось то, что хуже
// молчания — сбой, о котором сказано НЕПРАВДУ.
//
// НАЙДЕНО НА САМОЙ ОТКРЫТОЙ СТРАНИЦЕ ПРОДУКТА (публичное обсуждение,
// которое открывает кто угодно по ссылке — репост в чат, в группу):
//
//  1. `handleJoin` при ошибке делал `setJoined(true)`. Человек вводил
//     имя, нажимал «присоединиться», получал экран участника — а на
//     сервер он не попал, и всё, что он напишет дальше, ушло бы БЕЗ
//     ЕГО ИМЕНИ. Экран не промолчал: он сказал, что получилось.
//  2. `handleVote` — пустой `catch`: голос не засчитан, число не
//     изменилось, объяснения нет. «Голосование не критично» — это про
//     продукт, а не про человека: без объяснения он нажмёт ещё раз.
//  3. В публичной библиотеке отправка СВОЕГО ОПЫТА не имела `catch`
//     вовсе — необработанное отклонение промиса. Текст его собственный,
//     и терять его молча нельзя (поле теперь намеренно не очищается).
//  4. Сообщение об ошибке на публичном обсуждении рисовалось ВНУТРИ
//     блока «добавить аргумент», то есть только после присоединения —
//     сбой присоединения показать было физически негде. Одна из причин,
//     по которым его и выдавали за успех.
//
// ПОЧЕМУ ПРЕЖНЯЯ ПРОВЕРКА ЭТО ПРОПУСКАЛА — тот же урок [guard-audit]:
// правило уровня ФАЙЛА о свойстве уровня ОПЕРАТОРА. Оно прощало любой
// молчащий `catch` в файле, где `setError` встречался хоть раз, и не
// видело формы `try { … } catch { … }` вовсе. Переписано на разбор
// каждого обработчика отдельно.
//
// ГРАНИЦА НОВОГО ПРАВИЛА НАЗВАНА ЧЕСТНО. Строго — публичные страницы:
// их открывает человек без аккаунта, которому спросить некого. По
// остальному интерфейсу измерено ~33 молчащих обработчика, почти все
// фоновые и идемпотентные; выписать им 33 объяснения «под правило»
// значило бы наплодить пустых формул — ровно то, что запретила сверка
// [guard-audit]. Оставлено измерением, а не требованием.

import { readFileSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

function read(rel: string): string {
  return readFileSync(join(SRC, rel), 'utf8');
}

/** Экраны публичных действий и то, что каждый обязан уметь сказать. */
const PUBLIC_ACTION_PAGES = [
  'app/public/[token]/page.tsx',
  'app/library/[entryId]/page.tsx',
];

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: сообщение об ошибке действительно выводится в разметку, а не только в состояние', () => {
    // Состояние, которое никто не рисует, — то же молчание, только с
    // переменной. Мутация «убрать <p> с сообщением» обязана падать.
    const unrendered: string[] = [];
    for (const rel of PUBLIC_ACTION_PAGES) {
      const src = read(rel);
      const states = [...src.matchAll(/const \[(\w*[eE]rror\w*), set/g)].map((m) => m[1]);
      assert(states.length > 0, `${rel}: на странице нет состояния ошибки вовсе`);
      for (const s of states) {
        // Именно в JSX: `{состояние && <p …>` или `{состояние}` внутри тега.
        if (!new RegExp(`\\{\\s*${s}\\s*&&`).test(src) && !new RegExp(`>\\s*\\{\\s*${s}\\s*\\}`).test(src)) {
          unrendered.push(`${rel} · ${s}`);
        }
      }
    }
    assert(unrendered.length === 0, `эти сообщения об ошибке никуда не выводятся:\n  ${unrendered.join('\n  ')}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: на публичном обсуждении сообщение видно ДО присоединения', () => {
    // Пока `{error && …}` жил внутри `{joined && …}`, сбой присоединения
    // показать было негде — и это прямо помогало выдать его за успех.
    const src = read('app/public/[token]/page.tsx');
    const joinedBlock = src.indexOf('{joined && (');
    const errorLine = src.indexOf('{error && <p');
    assert(errorLine !== -1, 'сообщение об ошибке исчезло со страницы');
    assert(
      errorLine < joinedBlock,
      'сообщение об ошибке снова живёт внутри блока для присоединившихся — сбой присоединения показать негде',
    );
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: пустой список проектов отличается от несостоявшейся загрузки', () => {
    // «У вас нет проектов» — это совет завести проект. «Не удалось
    // загрузить» — это «попробуйте позже». Выглядели одинаково: пустое
    // «— выберите —» на странице, где человек принимает ЧУЖИЕ данные.
    const src = read('app/candidate-shares/[token]/page.tsx');
    assert(/projectsFailed/.test(src), 'страница снова не отличает сбой загрузки от пустого списка');
    assert(/Пустой список не означает/.test(src), 'человеку не сказано, как читать пустой список');
    // Загрузок ДВЕ, и отметить сбой обязаны обе: мутация «вернуть тихий
    // catch одной из них» первую проверку проходила — слово
    // `projectsFailed` в файле оставалось от второй.
    const quietFallbacks = (src.match(/\.catch\(\(\) => \(\{ items: \[\] \}\)\)/g) ?? []).length;
    assert(quietFallbacks === 0, `${quietFallbacks} загрузк(и) списка проектов снова гасят сбой в пустой список`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: текст, написанный человеком, не пропадает при сбое отправки', () => {
    // Поле НЕ очищается в `catch` — иначе сбой съедал бы написанное.
    const src = read('app/library/[entryId]/page.tsx');
    const submit = src.slice(src.indexOf('async function handleAddExperience'), src.indexOf('if (loading) return null;'));
    const catchBody = submit.slice(submit.indexOf('} catch'), submit.indexOf('} finally'));
    assert(!/setExperienceText\(''\)/.test(catchBody), 'при сбое отправки поле очищается — текст человека пропадает');
    assert(/setActionError/.test(catchBody), 'сбой отправки не показывается');
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nfalse-success: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
