// Сверка своего ввода 2026-09-04 — терялись слова САМОГО ЧЕЛОВЕКА.
//
// Все предыдущие заходы про потери закрывали одно и то же: отброшенный
// ответ МОДЕЛИ. Здесь теряется другое, и в продукте, обещающем «только из
// ваших слов», это дефект другого веса.
//
// ЧТО НАЙДЕНО:
//
//  1. Пакет отклика резал список вопросов до восьми — молча, и не в одном
//     месте, а в ДВУХ подряд: сначала экран (`.slice(0, 8)`), потом
//     сервер (такой же `.slice(0, 8)`). Человек вписывал двенадцать
//     вопросов, получал ответы на восемь и отправлял пакет работодателю,
//     считая, что в нём все двенадцать. Число было вписано по месту
//     дважды — то есть два потолка, которые умели разъехаться.
//
//  2. При пустом поле продукт подставляет ТРИ СВОИХ вопроса и возвращает
//     ответы на них без всякой пометки. Сама подстановка полезна;
//     непомеченная — способ отправить работодателю ответы на вопросы,
//     которых человек не задавал.
//
//  3. Разбор письма отбрасывал строку, которую не удалось прочитать как
//     ссылку, и не считал её. Частый случай — строка записана наоборот
//     («Название — https://…»): «ссылкой» оказывается название, проверка
//     его отвергает, строка исчезает. Вставил десять — увидел семь —
//     прочитал как «в письме было семь».
//
//  4. `skippedKnown` в приёме кандидатов считался вычитанием и складывал
//     ДВА разных события: «уже есть в базе» и «упёрлись в потолок 200».
//     Для человека это противоположные вещи: первое значит «ничего не
//     потеряно», второе — «остальное не добавлено, освободите место».
//     Отчёт, называющий одним словом оба, хуже отчёта, который молчит.
//
// РАЗНИЦА С ПРЕЖНИМИ ЗАХОДАМИ, и она определила решение: там показывать
// потерянное было НЕЛЬЗЯ — выдуманная моделью цитата не подкреплена
// ничем, и число честнее текста. Здесь текст принадлежит человеку.
// Нечитаемая строка возвращается ему ЦЕЛИКОМ: он сразу увидит опечатку
// или перевёрнутую строку и починит сам. Там, где слова его, число было
// бы МЕНЕЕ честным, а не более.
//
// И ЗАОДНО ЗАКРЫТ ДОЛГ ПУНКТА [render-guards]: два экрана собирали дату
// прямо в обработчике, где её нельзя вызвать из теста. Сборка вынесена в
// `dueMoment()`; проверка про неё — в `date-only.spec.ts`, рядом с
// остальными про даты.

import { splitLines, parseLinkLines, unreadableLinesNote, dueMoment } from '../lib/form-input';

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: экран больше не режет список сам — иначе потолков два', () => {
    // Резать в двух местах — способ однажды получить два разных потолка и
    // не заметить. Экран отдаёт ВСЁ, что человек написал; режет сервер,
    // он же сообщает, сколько не поместилось.
    const twelve = Array.from({ length: 12 }, (_, i) => `Вопрос ${i + 1}`).join('\n');
    assert(splitLines(twelve).length === 12, `экран снова режет список: ${splitLines(twelve).length}`);
    // Пустые строки и пробелы человек оставляет случайно — они не вопросы.
    assert(splitLines('a\n\n   \nb').length === 2, 'пустые строки попали в список');
    assert(splitLines('').length === 0, 'пустое поле дало строку');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: нечитаемая строка не исчезает, а возвращается человеку целиком', () => {
    // Его собственный текст — показать безопасно и полезно: он сразу
    // увидит, что строка записана наоборот.
    const { links, unreadable } = parseLinkLines(
      ['https://example.com/job1 — Продажи B2B', 'Дизайнер — https://example.com/job2', 'просто заметка', 'https://example.com/job3'].join('\n'),
    );
    assert(links.length === 2, `разобрано ссылок ${links.length}, ожидалось 2`);
    assert(links[0].title === 'Продажи B2B', `название потеряно: ${links[0].title}`);
    assert(links[1].title === null, `у ссылки без названия появилось название: ${links[1].title}`);
    assert(unreadable.length === 2, `нечитаемых строк ${unreadable.length}, ожидалось 2`);
    assert(unreadable.includes('Дизайнер — https://example.com/job2'), 'перевёрнутая строка потерялась');
    assert(unreadable.includes('просто заметка'), 'строка без ссылки потерялась');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: название с длинным тире внутри не рвёт строку', () => {
    // Название вакансии само может содержать « — ». Наивный `split`
    // выбрасывал бы хвост — то есть снова терял слова человека, только
    // незаметнее.
    const { links } = parseLinkLines('https://example.com/j — Аналитик — отдел закупок');
    assert(links.length === 1, 'строка не разобрана');
    assert(links[0].title === 'Аналитик — отдел закупок', `хвост названия потерян: ${links[0].title}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: подпись о нечитаемых строках называет их и объясняет формат', () => {
    const note = unreadableLinesNote(['Дизайнер — https://example.com/j']);
    assert(note.includes('Дизайнер'), `строка не показана человеку: ${note}`);
    assert(/Ссылка идёт первой/.test(note), `не сказано, как починить: ${note}`);
    // Ноль — молчание: «не прочитано: 0» приучает не читать сообщения.
    assert(unreadableLinesNote([]) === '', 'ноль дал подпись');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: строка, похожая на ссылку, но не http — не ссылка', () => {
    // Ровно та же проверка, что применит сервер: иначе строка молча
    // пропала бы уже там, и человек снова не узнал бы почему.
    const { links, unreadable } = parseLinkLines(['ftp://example.com/x', 'example.com/x', 'https://example.com/x'].join('\n'));
    assert(links.length === 1, `пропущено лишнее: ${JSON.stringify(links)}`);
    assert(unreadable.length === 2, `нечитаемых ${unreadable.length}, ожидалось 2`);
  }],

  ['срок из формы собирается сборщиком, а не самим экраном', () => {
    // Полная проверка про часовые пояса — в `date-only.spec.ts`; здесь
    // только то, что сборщик существует и пустое поле сроком не делает.
    assert(dueMoment('') === undefined, 'пустое поле превратилось в срок');
    assert(typeof dueMoment('2026-09-10') === 'string', 'дата не превратилась в момент');
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nown-input: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
