// Сверка 2026-09-06 — первый экран обещал, что записи остаются на
// устройстве.
//
// НАЙДЕННОЕ. Блокирующий экран, который человек обязан подтвердить
// ПЕРЕД тем, как увидеть продукт, говорил:
//
//     «Ваши записи остаются на вашем устройстве
//      (подробнее — в настройках приватности).»
//
// Неправда. Записи лежат на сервере: расшифровки, аргументы, разборы,
// история — без этого разбор был бы невозможен. И неправда в самом
// дорогом месте: это условие, под которым человек соглашается
// пользоваться продуктом.
//
// Отдельно скверно, что фраза отсылала за подробностями в настройки
// приватности, а ТОТ экран говорит обратное: «данные удаляются только
// вручную», сроки хранения — «Бессрочно». Продукт спорил сам с собой, и
// первым человек читал неверное.
//
// ПРАВИЛО БЫЛО, ПРОСТО НЕ ВЕЗДЕ. Ту же фразу («Все записи хранятся
// локально») пункт [landing-promise] нашёл и убрал с лендинга тремя
// сверками раньше, вместе с правилом. Правило читало КАТАЛОГ СЛОВАРЕЙ
// ЛЕНДИНГА — и до экранов приложения не дотянулось. Проверка ниже
// покрывает обе стороны.
//
// ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ: не запрещает слова «на устройстве». В
// продукте есть ЧЕТЫРЕ места, где это чистая правда и важная: разбор
// файла переписки, извлечение текста из .md/PPTX, подсчёт голосового
// отпечатка, индикатор накала. Вычистить их «за компанию» значило бы
// сделать продукт скромнее, чем он есть, — тот же довод, что в
// [landing-promise]. Запрещается конкретное ложное утверждение, а не
// тема.

import { readdirSync, readFileSync, statSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

/** Комментарии прочь: прежняя формулировка процитирована и здесь, и в
 * комментарии самого компонента. */
function copy(path: string): string {
  return readFileSync(path, 'utf8')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function screens(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === '__tests__' ? [] : screens(full);
    return /\.tsx?$/.test(name) ? [full] : [];
  });
}

/** Ложные обещания о хранении. Каждое — утверждение, которому
 * противоречит устройство продукта, а не просто бодрая формулировка. */
const FORBIDDEN: Array<[RegExp, string]> = [
  [/записи\s+остаются\s+на\s+(вашем\s+)?устройстве/i, 'обещание, что записи остаются на устройстве'],
  [/(хранятся|хранится)\s+локально/i, 'обещание локального хранения'],
  [/не\s+покидают\s+(ваше\s+)?устройств/i, 'обещание, что данные не покидают устройство'],
  [/без\s+утечек/i, '«без утечек» — обещание, которое нельзя ни проверить, ни сдержать'],
];

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: ни один экран приложения не обещает хранение на устройстве', () => {
    const offenders: string[] = [];
    for (const file of screens(SRC)) {
      const text = copy(file);
      for (const [pattern, why] of FORBIDDEN) {
        if (pattern.test(text)) offenders.push(`${file.slice(SRC.length + 1)}: ${why}`);
      }
    }
    assert(offenders.length === 0, `обещание вернулось:\n  ${offenders.join('\n  ')}`);
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: первый экран говорит, где записи на самом деле', () => {
    // Убрать неправду мало: экран, который просто промолчит о хранении,
    // человек достроит в свою пользу — это и есть ложь умолчанием.
    const text = copy(join(SRC, 'components/LaunchDisclaimer.tsx'));
    assert(/хранятся на нашем сервере/.test(text), 'не сказано, где хранятся записи');
    assert(/Аудиофайл\s+удаляется сразу после расшифровки/.test(text), 'не сказано про единственное, что действительно удаляется само');
    // И выход: честность без выхода — просто плохая новость.
    assert(/настройках приватности/.test(text), 'не сказано, где удалить и выгрузить');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: первый экран не спорит с экраном приватности', () => {
    // Раньше он отсылал «подробнее — в настройках приватности», а тот
    // экран говорил обратное.
    const privacy = copy(join(SRC, 'app/privacy/page.tsx'));
    assert(/удаляются только вручную/.test(privacy), 'экран приватности перестал говорить, что удаление ручное');
    const first = copy(join(SRC, 'components/LaunchDisclaimer.tsx'));
    assert(/пока вы сами не удалите/.test(first), 'первый экран снова обещает больше, чем экран приватности');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: верные упоминания «на устройстве» НЕ вычищены', () => {
    // Сверка о честности, а не о скромности. Все шесть — правда, и
    // важная: человек по ним понимает, что именно НЕ уходит на сервер.
    const truthful = [
      ['components/ChatImportSection.tsx', /обрабатывается на устройстве/],
      ['components/CooldownNudgeSession.tsx', /полностью на устройстве, на сервер уходят только числа/],
      ['components/UserVoiceRecordingSection.tsx', /Обрабатываем запись на устройстве/],
      ['components/WorkingMaterialsSection.tsx', /на устройстве извлекается только текст/],
      ['components/VoiceBiometricConsentPrompt.tsx', /посчитанный\s+на вашем устройстве числовой отпечаток/],
      ['components/AssistanceScreen.tsx', /считается на устройстве/],
      // Пункт [right-lived-in-the-tab] 2026-09-25: утверждение
      // ОБРАТНОГО знака — «на устройстве НЕ сохраняется». Оно такое же
      // проверяемое, как остальные: удостоверение участника держится
      // только в памяти вкладки, и это отдельно закреплено сверкой
      // badge-was-the-key (запрет на localStorage/sessionStorage).
      ['components/ParticipantRights.tsx', /на\s+устройстве\s+не\s+сохраняет/i],
    ] as const;
    for (const [rel, pattern] of truthful) {
      assert(pattern.test(copy(join(SRC, rel))), `${rel}: пропало ВЕРНОЕ утверждение про работу на устройстве`);
    }
  }],

  ['ИЗМЕРЕНИЕ: где продукт вообще говорит о хранении на устройстве', () => {
    // Точка отсчёта. Пятое такое место должно быть осмотрено глазами:
    // правда это или очередное «локально».
    const mentions = screens(SRC).filter((f) => /на\s+(вашем\s+)?устройстве/i.test(copy(f)));
    // Ожидалось четыре, оказалось шесть: два места (нудж охлаждения и
    // запись образца голоса) в первый обход не попали. Ошиблось
    // ИЗМЕРЕНИЕ, а не код — оба утверждения верны и остаются.
    // Пункт [right-lived-in-the-tab] 2026-09-25: 6 → 7. Седьмое место
    // осмотрено глазами, как и требует эта проверка: это утверждение
    // «удостоверение участника на устройстве НЕ сохраняется», и оно
    // верно — запрет на хранение закреплён отдельной сверкой. Равенство
    // здесь оставлено намеренно: смысл проверки в том, чтобы КАЖДОЕ
    // новое такое утверждение кто-то прочитал.
    assert(mentions.length === 7, `мест с «на устройстве» должно быть 7, найдено ${mentions.length}: ` +
      mentions.map((f) => f.slice(SRC.length + 1)).join(', '));
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\ndevice-not-yours: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
