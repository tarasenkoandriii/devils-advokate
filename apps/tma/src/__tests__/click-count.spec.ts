// Сверка 2026-09-05, экранная половина — доля, которая росла от нажатий.
//
// НАЙДЕНО на сервере (подробности — в серверной сверке): повторный поиск
// прецедентов создавал записи заново, а доля «X из Y раз вёл себя схожим
// образом» считалась по ВСЕЙ таблице человека, накопленной разными
// поисками по разным ситуациям.
//
// Здесь проверяется, что экран не молчит о втором следствии: когда
// повторы отсекаются, человек видит «ничего не добавилось». Без
// объяснения это читается как «не сработало» — и он жмёт снова, ровно то
// поведение, из-за которого числа и росли. Тот же изъян, что разобран в
// пунктах [silent-destruction] и [dropped-quotes]: отброшенное должно
// быть названо.

import { readFileSync } from 'fs';
import { join } from 'path';

const SRC = join(__dirname, '..');

function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
}

/** Комментарии прочь перед разбором КОДА: за эту сессию проверки шесть
 * раз ловили собственный объяснительный текст. */
function code(rel: string): string {
  return readFileSync(join(SRC, rel), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const scenarios: Array<[string, () => void]> = [
  ['КЛЮЧЕВОЙ ТЕСТ: отсечённые повторы названы человеку', () => {
    const src = code('components/PeopleSection.tsx');
    assert(/setDuplicatesSkipped\(outcome\.duplicatesSkipped\)/.test(src),
      'число отсечённых повторов не берётся из ответа сервера');
    // Условие на ПЕРЕМЕННОЙ, а не на константе: мутация `{false && …}`
    // проходила мимо проверки на упоминание текста — тот же способ
    // обмануть проверку, что ловился в [decision-basis].
    assert(/\{duplicatesSkipped > 0 && \(/.test(src),
      'сообщение о повторах отключено или привязано к константе');
    assert(/Повторов отсечено/.test(src), 'повторы отсекаются молча');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: сказано, ПОЧЕМУ повтор не записан', () => {
    // «Отсечено 3» без причины — просто число. Человеку важно, что
    // случай не потерян, а уже учтён, и что второй раз он не считался бы
    // как отдельный.
    const src = code('components/PeopleSection.tsx');
    assert(/уже были найдены для той же ситуации/.test(src), 'не сказано, почему повтор не записан');
    assert(/не считаться дважды/.test(src), 'не сказано, чем плох был бы двойной счёт');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ [shown-not-all]: карточка разговора говорит, что показано не всё', () => {
    // Карточку человек уносит В РАЗГОВОР. «Ключевые аргументы» там —
    // пять самых весомых, и он уносил пятёрку, считая её своей позицией
    // целиком.
    const src = code('app/projects/[id]/card/page.tsx');
    assert(/\{card\.topArgumentsNote && /.test(src), 'карточка снова молчит об усечении');
    // Приписка идёт из ответа сервера, а не собирается на экране: своя
    // арифметика однажды разойдётся с серверной, и разойдётся молча.
    //
    // Правило запрещает сравнение с ЛИМИТОМ, а не с нулём: `length > 0`
    // это проверка пустого списка, и она законна. Первая версия
    // запрещала любое сравнение и объявила нарушением честную строку —
    // седьмая за сессию ошибка в самой проверке, пойманная прогоном.
    assert(!/topArguments\.length\s*[<>=]+\s*[1-9]/.test(src), 'экран сам решает, было ли усечение');
  }],

  ['КЛЮЧЕВОЙ ТЕСТ: экран не считает долю сам', () => {
    // Доля осмысленна только внутри одной ситуации, и считает её сервер.
    // Собственная арифметика на экране разошлась бы с серверной — и
    // разошлась бы молча.
    const src = code('components/PeopleSection.tsx');
    assert(!/precedentResult\.analogousCount\s*\/|\/\s*precedentResult\.total/.test(src),
      'экран делит числа сам — доля может разойтись с серверной');
  }],
];

const results: Array<{ name: string; error?: string }> = [];
for (const [name, fn] of scenarios) {
  try {
    fn();
    results.push({ name });
  } catch (err: any) {
    results.push({ name, error: err.message });
  }
}

const failed = results.filter((r) => r.error);
console.log(`\nclick-count: ${results.length - failed.length}/${results.length} passed\n`);
for (const r of results) {
  console.log(`${r.error ? '✗' : '✓'} ${r.name}`);
  if (r.error) console.log(`  ${r.error}`);
}
if (failed.length > 0) process.exit(1);
